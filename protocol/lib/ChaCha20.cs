//ChaCha20 stream-cipher stages for org.unirail.AdHoc streams (RFC 8439). A pluggable inner stage between the
//outer framer (Receiver/Transmitter.Chunked) and what it wraps: the transmit side XOR-encrypts freshly-written
//plaintext in place, the receive side XOR-decrypts each de-framed chunk into a scratch buffer. Compose it like
//any other stage; for compress-then-encrypt place it OUTSIDE (toward the wire) of the Zstd stage.
//
//─ Properties ───────────────────────────────────────────────────────────────
//  • Length-preserving — encrypt and decrypt are the same keystream XOR, so the stage neither adds nor removes
//    bytes and is valid under the `File` framer (which declares its size at Init) as well as `Chunked`.
//  • The keystream and the AEAD lie in the native library, adhoc-crypto: see Chain.cs.
//  • Key material is folded into the state on Init and not retained.
//
//─ SECURITY (read this) ──────────────────────────────────────────────────────
//  • Pairing is mandatory and symmetric: both ends MUST use the SAME 32-byte key
//    and 12-byte nonce (and the default counter 0). The sender's keystream is the
//    receiver's keystream.
//  • NEVER reuse a (key, nonce) pair for two different streams. Re-using a nonce
//    under the same key is catastrophic (XOR of two plaintexts leaks). Use a fresh
//    random/counter nonce per stream and convey it out-of-band, or derive a unique
//    nonce per stream from a session value.
//  • ChaCha20 provides CONFIDENTIALITY ONLY — no integrity/authentication. A
//    tampered ciphertext decrypts to garbage without detection. If you need
//    authenticated encryption, add a MAC stage (e.g. Poly1305) or terminate the
//    stream into an authenticated container.
//
