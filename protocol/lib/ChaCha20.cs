public interface ChaCha20
{
    ///<summary>
    ///ChaCha20 keystream engine (RFC 8439): 256-bit key, 96-bit nonce, 32-bit block counter, 20 rounds.
    ///Encryption and decryption are the same operation — XOR of the data with the keystream. The keystream
    ///position (block counter + offset into the current 64-byte block) is retained across <see cref="Process(Span{byte})"/>
    ///calls, so a single keyed stream spans any number of chunks and socket fills.
    ///</summary>
    sealed unsafe class Core
    {
        //The Stream of adhoc_crypto.c: key | nonce | counter | position in the keystream | the keystream made and not used yet
        const int NONCE = 32, COUNTER = 44, POS = 48;

        readonly byte[] _s = new byte[Crypto.adhoc_stream_size()];

        ///<summary>(Re)key for a fresh stream. <paramref name="key"/> = 32 bytes, <paramref name="nonce"/> = 12 bytes.
        ///Both ends must pass identical values (and the same <paramref name="counter"/>, normally 0).</summary>
        public void Init(ReadOnlySpan<byte> key, ReadOnlySpan<byte> nonce, uint counter = 0)
        {
            if (key.Length != 32)
                throw new ArgumentException("ChaCha20 key must be 32 bytes, got " + key.Length, nameof(key));
            if (nonce.Length != 12)
                throw new ArgumentException("ChaCha20 nonce must be 12 bytes, got " + nonce.Length, nameof(nonce));
            key.CopyTo(_s);
            nonce.CopyTo(_s.AsSpan(NONCE));
            BinaryPrimitives.WriteUInt32LittleEndian(_s.AsSpan(COUNTER), counter);
            BinaryPrimitives.WriteUInt32LittleEndian(_s.AsSpan(POS), 64);
        }

        ///<summary>Right after <see cref="Init"/>: the stream's nonce becomes <c>nonce XOR (0⁴ ‖ seq)</c>, little-endian - the
        ///per-record nonce of TLS 1.3 and QUIC.</summary>
        public void Nonce(ulong seq)
        {
            var at = _s.AsSpan(NONCE + 4);
            BinaryPrimitives.WriteUInt64LittleEndian(at, BinaryPrimitives.ReadUInt64LittleEndian(at) ^ seq);
        }

        ///<summary>
        ///The sequence of the next stream that carries its own nonce. Every process starts at a random point of the 64-bit
        ///space and counts up: two streams under one key never share a nonce within a process, and across processes and
        ///restarts only if two ranges drawn at random in 2⁶⁴ overlap. A thread counts in a block of its own ( <see cref="SEQ_BLOCK"/>
        ///sequences taken from the process at once ): every pack of every thread on one cache line cost ~120 ns at 8 threads.
        ///The receiver decrypts each pack alone - no order of the sequences is relied on.
        ///</summary>
        public static ulong NextSeq()
        {
            if (_left != 0)
            {
                _left--;
                return _next++;
            }
            var start = (ulong)System.Threading.Interlocked.Add(ref _seq, SEQ_BLOCK) - SEQ_BLOCK;
            _next = start + 1;
            _left = SEQ_BLOCK - 1;
            return start;
        }

        const long SEQ_BLOCK = 1 << 16;

        [ThreadStatic]
        static ulong _next;
        [ThreadStatic]
        static long _left;

        static long _seq = BitConverter.ToInt64(System.Security.Cryptography.RandomNumberGenerator.GetBytes(8));

        ///<summary>In-place XOR (encrypt == decrypt).</summary>
        public void Process(Span<byte> data)
        {
            if (data.IsEmpty)
                return;
            fixed(byte *s = _s, d = data)
                Crypto.adhoc_stream_xor((long)s, (long)d, data.Length);
        }

        ///<summary>XOR <paramref name="src"/> with the keystream into <paramref name="dst"/>
        ///(<paramref name="dst"/> may alias <paramref name="src"/>). Advances the keystream by the data length.</summary>
        public void Process(ReadOnlySpan<byte> src, Span<byte> dst)
        {
            src.CopyTo(dst);
            Process(dst.Slice(0, src.Length));
        }
    }

    ///<summary>
    ///ChaCha20-Poly1305 AEAD (RFC 8439) under one key, a message at a time: <see cref="Seal"/> and <see cref="Open"/> work in
    ///place and take the 64-bit message number the nonce is made of - 32 zero bits, then the number little-endian, as
    ///the Noise protocol forms it. A number must never be used twice under one key. In the native library: its context lies in
    ///memory that does not move; of a handshake, in the memory of that handshake.
    ///</summary>
    sealed unsafe class Aead
    {
        public const int TAG = 16;

        static readonly int size = Crypto.adhoc_aead_size();

        internal readonly long ctx;
        readonly object? owner; //the handshake whose memory it lies in; null - its own

        public Aead(ReadOnlySpan<byte> key)
        {
            ctx = (long)NativeMemory.AlignedAlloc((nuint)size, 16);
            Rekey(key);
        }

        internal Aead(long ctx, object owner)
        {
            this.ctx = ctx;
            this.owner = owner;
        }

        ~Aead()
        {
            if (owner == null)
            {
                NativeMemory.Clear((void *)ctx, (nuint)size);
                NativeMemory.AlignedFree((void *)ctx);
            }
        }

        public void Rekey(ReadOnlySpan<byte> key)
        {
            if (key.Length < 32)
                throw new ArgumentException("A key is 32 bytes.");
            fixed(byte *k = key) if (Crypto.adhoc_aead_init(0, (void *)ctx, k, 32) == 0) throw new ArgumentException("A key is 32 bytes.");
        }

        public void Wipe() => NativeMemory.Clear((void *)ctx, (nuint)size);

        //The library wants the tag right behind the text: what is not there goes through a place where it is.
        static bool together(ReadOnlySpan<byte> data, ReadOnlySpan<byte> tag) => Unsafe.AreSame(ref Unsafe.Add(ref MemoryMarshal.GetReference(data), data.Length), ref MemoryMarshal.GetReference(tag));

        ///<summary>Encrypts <paramref name="data"/> in place and writes the tag of it and <paramref name="ad"/>.</summary>
        public void Seal(ulong n, ReadOnlySpan<byte> ad, Span<byte> data, Span<byte> tag)
        {
            Span<byte> nonce = stackalloc byte[12];
            nonce.Slice(0, 4).Clear();
            BinaryPrimitives.WriteUInt64LittleEndian(nonce.Slice(4), n);
            Seal(nonce, ad, data, tag);
        }

        ///<summary>As <see cref="Seal(ulong, ReadOnlySpan{byte}, Span{byte}, Span{byte})"/>, with the whole 12-byte nonce given.</summary>
        public void Seal(ReadOnlySpan<byte> nonce, ReadOnlySpan<byte> ad, Span<byte> data, Span<byte> tag)
        {
            var ok = 0;
            if (together(data, tag))
                fixed(byte *no = nonce, a = ad, d = &MemoryMarshal.GetReference(data))
                    ok = Crypto.adhoc_seal_nonce(ctx, no, a, ad.Length, d, data.Length);
            else
            {
                var whole = System.Buffers.ArrayPool<byte>.Shared.Rent(data.Length + TAG);
                data.CopyTo(whole);
                fixed(byte *no = nonce, a = ad, d = whole)
                    ok = Crypto.adhoc_seal_nonce(ctx, no, a, ad.Length, d, data.Length);
                whole.AsSpan(0, data.Length).CopyTo(data);
                whole.AsSpan(data.Length, TAG).CopyTo(tag);
                System.Buffers.ArrayPool<byte>.Shared.Return(whole);
            }
            if (ok == 0)
                throw new InvalidOperationException("seal");
        }

        ///<summary>Checks the tag of <paramref name="data"/> and <paramref name="ad"/>, and only then decrypts in place.</summary>
        ///<returns><c>false</c> - forged or damaged: <paramref name="data"/> is not to be read.</returns>
        public bool Open(ulong n, ReadOnlySpan<byte> ad, Span<byte> data, ReadOnlySpan<byte> tag)
        {
            Span<byte> nonce = stackalloc byte[12];
            nonce.Slice(0, 4).Clear();
            BinaryPrimitives.WriteUInt64LittleEndian(nonce.Slice(4), n);
            return Open(nonce, ad, data, tag);
        }

        ///<summary>As <see cref="Open(ulong, ReadOnlySpan{byte}, Span{byte}, ReadOnlySpan{byte})"/>, with the whole 12-byte nonce given.</summary>
        public bool Open(ReadOnlySpan<byte> nonce, ReadOnlySpan<byte> ad, Span<byte> data, ReadOnlySpan<byte> tag)
        {
            if (together(data, tag))
                fixed(byte *no = nonce, a = ad, d = &MemoryMarshal.GetReference(data)) return Crypto.adhoc_open_nonce(ctx, no, a, ad.Length, d, data.Length) != 0;
            var whole = System.Buffers.ArrayPool<byte>.Shared.Rent(data.Length + TAG);
            data.CopyTo(whole);
            tag.Slice(0, TAG).CopyTo(whole.AsSpan(data.Length));
            int ok;
            fixed(byte *no = nonce, a = ad, d = whole)
                ok = Crypto.adhoc_open_nonce(ctx, no, a, ad.Length, d, data.Length);
            if (ok != 0)
                whole.AsSpan(0, data.Length).CopyTo(data);
            System.Buffers.ArrayPool<byte>.Shared.Return(whole);
            return ok != 0;
        }

        ///<summary>All the records at <paramref name="at"/>, sealed in place in one call: the next number, -1 - a failure.</summary>
        internal long SealRecords(long n, byte[] buf, int at, int bytes)
        {
            fixed(byte *b = buf) return Crypto.adhoc_seal_records(ctx, n, (long)b + at, bytes);
        }

        ///<summary>All the whole records at <paramref name="at"/>, opened in place in one call: opened bytes &lt;&lt; 32 | records; -1 - forged.</summary>
        internal long OpenRecords(long n, byte[] buf, int at, int have, int max)
        {
            fixed(byte *b = buf) return Crypto.adhoc_open_records(ctx, n, (long)b + at, have, max);
        }
    }

    ///<summary>Decrypting receive-side stage.</summary>
    interface Receiver
    {
        ///<summary>
        ///ChaCha20-decrypting inner stage for <see cref="AdHoc.Connection.Receiver.Chunked"/>: XOR-decrypts each
        ///de-framed chunk IN PLACE, in the receive buffer it came in, and hands the recovered plaintext to a downstream
        ///<see cref="AdHoc.Connection.Receiver.BytesDst"/> (a <c>Terminal</c> sink, or another stage) from there - no
        ///staging, no copy. Pair with <see cref="Transmitter.Stage"/>.
        ///<para>What the downstream does not take stays where it lies, decrypted already: the framer offers it again from
        ///the same place, and <see cref="_open"/> - how many bytes at the front of the next offer are plaintext already -
        ///keeps them from going through the keystream twice. As a pure-byte inner stage it never touches the slot and never
        ///self-completes — the outer framer's <c>0x0000</c> terminator is the sole end-authority, so
        ///<see cref="__put_bytes"/> always returns <c>false</c>.</para>
        ///</summary>
        class Stage : AdHoc.Connection.Receiver.BytesDst, AdHoc.BytesDst
        {
            readonly Core _c = new();
            int _open;      //bytes at the front of the next offer that are decrypted already: the refused tail
            bool _inFlight; //re-entrancy guard: a nested downstream consumer must not re-drive this stage mid-read (ports Java's inFlight)

            AdHoc.Connection.Receiver.BytesDst dst = null!; //inner stage — another IStream (Chunked/File) or a Terminal leaf

            ///<summary>Chain builder: swap the inner next-stage <see cref="dst"/> — set it (null to detach), return the previous.</summary>

            public int __id { get; set; } //unused for an inner stage (the outer framer carries the dispatch id)

            ///<summary>(Re)configure: inner dst + a fresh ChaCha20 keystream (<paramref name="key"/> 32 B, <paramref name="nonce"/> 12 B). Returns <c>this</c> for chaining.</summary>
            public Stage Init(AdHoc.Connection.Receiver.BytesDst dst, byte[] key, byte[] nonce)
            {
                this.dst = dst;
                dst_ = null; //INNER role — the two roles are mutually exclusive per instance
                _c.Init(key, nonce);
                _open = 0;
                _hdrGot = HDR;
                _discard = false;
                return this;
            }

            ///<summary>
            ///(Re)configure for a pack, the pair of <see cref="Transmitter.Stage.InitExplicit"/>: its first 12 bytes, in clear,
            ///are the id of the key it was encrypted with (4) and the sequence its nonce is made of (8). The stage holds no key:
            ///it takes the one of that id from the keys of the Receiver that drives it (<see cref="AdHoc.Connection.Receiver.keys"/>).
            ///Each pack is decrypted alone: after a loss, as a duplicate, out of a replayed journal. A pack whose key the session
            ///does not have - of a session this side has lost - is dropped whole (<c>drop_received</c>).
            ///</summary>
            public Stage InitExplicit(AdHoc.Connection.Receiver.BytesDst dst)
            {
                this.dst = dst;
                dst_ = null;
                _open = 0;
                _hdrGot = 0;
                _discard = false;
                return this;
            }

            const int HDR = 12;
            readonly byte[] _hdr = new byte[HDR];
            int _hdrGot = HDR; //bytes of the header read so far; HDR - all, or none to read
            bool _discard;     //the pack's key is unknown: its bytes are taken and thrown away

            //The header in front of the ciphertext: false while more of it is to come.
            bool readSeq(AdHoc.Connection.Receiver src, byte[] buf, ref int pos, int max)
            {
                for (; _hdrGot < HDR; _hdrGot++, pos++)
                {
                    if (pos == max)
                        return false;
                    _hdr[_hdrGot] = buf[pos];
                }
                var k = src.keys.Find(BinaryPrimitives.ReadUInt32LittleEndian(_hdr));
                if (k == null)
                {
                    _discard = true;
                    src.drop_received = true; //not dispatched when it ends
                    return true;
                }
                _c.Init(k.key, k.iv);
                _c.Nonce(BinaryPrimitives.ReadUInt64LittleEndian(_hdr.AsSpan(4)));
                return true;
            }
#region TRANSPORT role
            //Length-preserving, so nothing to flush and no frame. Decrypted in place: the transport re-offers a refused tail
            //from where it stopped, and _open says how much of it went through the keystream already.

            AdHoc.BytesDst? dst_; //TRANSPORT role: the connection's own Receiver (null ⇒ inner role)
            bool _closed;

            ///<summary>Ciphertext bytes consumed off the transport so far.</summary>
            public long wire_bytes;

            ///<summary>Plaintext bytes delivered to <see cref="dst_"/> so far.</summary>
            public long plain_bytes;

            ///<summary>Arm as the connection's transport-level decryptor: takes ciphertext off the socket and feeds the
            ///recovered protocol bytes to <paramref name="dst_"/> (normally <c>Connection.receiver</c>).
            ///Pair with <see cref="Transmitter.Stage.Init_"/>.</summary>
            public Stage Init_(AdHoc.BytesDst dst_, byte[] key, byte[] nonce)
            {
                this.dst_ = dst_;
                dst = null!; //TRANSPORT role
                _c.Init(key, nonce);
                _open = 0;
                _hdrGot = HDR;
                _discard = false;
                _closed = false;
                return this;
            }

            public bool isOpen() => !_closed && (dst_?.isOpen() ?? true);

            public void Close()
            {
                if (_closed)
                    return;
                _closed = true;
                _open = 0;
                dst_?.Close();
            }

            ///<summary>Transport entry: decrypt <paramref name="src"/> in place - only what went not through the keystream
            ///yet - and hand it to <see cref="dst_"/> from there. What it does not take stays in <paramref name="src"/>,
            ///decrypted, for the transport to offer again.
            ///<para>ATTENTION! <paramref name="src"/> is borrowed and must not be referenced after this returns.</para></summary>
            ///<returns>The bytes <see cref="dst_"/> took; negative - it gave up on the stream.</returns>
            public int Write(byte[] src, int src_byte, int src_bytes)
            {
                if (_closed || dst_ == null || src_bytes < 0)
                    return 0;
                if (_open < src_bytes)
                {
                    _c.Process(src.AsSpan(src_byte + _open, src_bytes - _open)); //XOR in place: only the bytes not decrypted yet
                    wire_bytes += src_bytes - _open;
                    _open = src_bytes; //decrypted, all of them: a sink that throws leaves them to the next offer as they are
                }
                var n = dst_.Write(src, src_byte, src_bytes);
                if (n < 0)
                    return n;
                plain_bytes += n;
                _open = src_bytes - n; //the refused tail: plaintext already
                return n;
            }
#endregion

            ///<summary>
            ///Framework entry. Decrypts the available (chunk-clamped) ciphertext in place - only what went not through the
            ///keystream yet - and hands it to <see cref="dst"/> from there; what <see cref="dst"/> does not take stays,
            ///decrypted, for the framer to offer again. Always returns <c>false</c>: a codec stage never self-completes — the
            ///outer Chunked framer's <c>0x0000</c> terminator ends the stream.
            ///</summary>
            public bool __put_bytes(AdHoc.Connection.Receiver src)
            {
                //A deeply-nested downstream consumer could, on its own park/resume, re-enter and re-drive THIS stage mid-read.
                //Refuse the re-entrant refill: park; the outer (non-re-entrant) drive refills after the framer's clamped feed.
                if (_inFlight)
                    return false;
                var inBuf = src.buffer!; //ciphertext input window (already clamped to the current chunk by the framer)
                var inPos = src.byte_;
                var inMax = src.byte_max;
                if (_hdrGot < HDR)
                {
                    var ok = readSeq(src, inBuf, ref inPos, inMax);
                    src.byte_ = inPos;
                    if (!ok)
                        return false; //the rest of the header comes with the next chunk
                }
                if (_discard)
                {
                    src.byte_ = inMax; //a pack of a key this session does not have: taken, and thrown away
                    return false;
                }
                if (inPos + _open < inMax)
                {
                    _c.Process(inBuf.AsSpan(inPos + _open, inMax - inPos - _open)); //XOR in place: only the bytes not decrypted yet
                    _open = inMax - inPos;                                          //decrypted, all of them: a sink that throws leaves them to the next offer as they are
                }
                _inFlight = true;
                try
                {
                    dst.__put_bytes(src); //the inner stage takes what it can; its return is ignored (terminator is end-authority)
                }
                finally
                {
                    _inFlight = false;
                }
                _open = inMax - src.byte_; //the refused tail: plaintext already
                return false;              //a codec never self-completes; the framer's 0x0000 terminator is the end-authority
            }
        }
    }

    ///<summary>Encrypting transmit-side stage.</summary>
    interface Transmitter
    {
        ///<summary>
        ///ChaCha20-encrypting inner stage for <see cref="AdHoc.Connection.Transmitter.Chunked"/>: lets an upstream
        ///<see cref="AdHoc.Connection.Transmitter.BytesSrc"/> (a <c>Terminal</c> source, or another stage) write plaintext
        ///straight into the transmit window, XOR-encrypts it <b>in place</b> (the cipher is length-preserving, so no
        ///scratch buffer is needed), and hands the ciphertext back to the framer for chunk framing. Pair with
        ///<see cref="Receiver.Stage"/>.
        ///<para>Because it is length-preserving, a ChaCha20 stage over a known-size source is valid under the <c>File</c>
        ///framer (which declares its size at Init) as well as <c>Chunked</c>. <see cref="__get_bytes"/> relays the inner stage's completion verbatim.</para>
        ///</summary>
        class Stage : AdHoc.Connection.Transmitter.BytesSrc, AdHoc.BytesSrc
        {
            readonly Core _c = new();

            AdHoc.Connection.Transmitter.BytesSrc src = null!; //inner stage — another IStream (Chunked/File) or a Terminal leaf

            ///<summary>Chain builder: swap the inner next-stage <see cref="src"/> — set it (null to detach), return the previous.</summary>

            public int __id { get; set; } //unused for an inner stage (the outer framer carries the dispatch id)

            ///<summary>(Re)configure: inner src + a fresh ChaCha20 keystream (<paramref name="key"/> 32 B, <paramref name="nonce"/> 12 B). Returns <c>this</c> for chaining.</summary>
            public Stage Init(AdHoc.Connection.Transmitter.BytesSrc src, byte[] key, byte[] nonce)
            {
                this.src = src;
                src_ = null; //INNER role — the two roles are mutually exclusive per instance
                _c.Init(key, nonce);
                _hdrPut = HDR;
                return this;
            }

            ///<summary>
            ///(Re)configure for a pack. The stage holds no key: at the pack's first bytes it takes the newest key of the
            ///Transmitter that drives it (<see cref="AdHoc.Connection.Transmitter.keys"/>) and encrypts under that key's base
            ///nonce XOR-ed with the next <see cref="Core.NextSeq"/>. 12 bytes go in clear ahead of the ciphertext - the key's
            ///id (4) and the sequence (8): each pack is decrypted alone, with the key it names. The stream is no longer
            ///length-preserving: not for the <c>File</c> framer. Pair with <see cref="Receiver.Stage.InitExplicit"/>.
            ///</summary>
            public Stage InitExplicit(AdHoc.Connection.Transmitter.BytesSrc src)
            {
                this.src = src;
                src_ = null;
                _hdrPut = -1; //the key is taken at the first bytes
                return this;
            }

            //The key of the pack: the newest of the Transmitter's session.
            void keyed(AdHoc.Connection.Transmitter dst)
            {
                var k = dst.keys.Current ?? throw new InvalidOperationException("A pack chain with ChaCha20 on a connection without keys: encrypt the connection (a host key, a pinned server key), or add a key to its Transmitter's and Receiver's keys.");
                _c.Init(k.key, k.iv);
                var seq = Core.NextSeq();
                _c.Nonce(seq);
                BinaryPrimitives.WriteUInt32LittleEndian(_hdr, k.id);
                BinaryPrimitives.WriteUInt64LittleEndian(_hdr.AsSpan(4), seq);
                _hdrPut = 0;
            }

            const int HDR = 12;
            readonly byte[] _hdr = new byte[HDR];
            int _hdrPut = HDR; //bytes of the header written so far; HDR - all, or none to write
#region TRANSPORT role
            //Length-preserving: fill the transport buffer from the upper layer, XOR it in place, relay -1/0 verbatim.

            AdHoc.BytesSrc? src_; //TRANSPORT role: the connection's own Transmitter (null ⇒ inner role)
            bool _closed;

            ///<summary>Plaintext bytes pulled from <see cref="src_"/> so far (== ciphertext bytes: length-preserving).</summary>
            public long wire_bytes;

            ///<summary>Arm as the connection's transport-level encryptor: pulls protocol bytes from
            ///<paramref name="src_"/> (normally <c>Connection.transmitter</c>) and hands the socket ciphertext.
            ///Pair with <see cref="Receiver.Stage.Init_"/>.</summary>
            public Stage Init_(AdHoc.BytesSrc src_, byte[] key, byte[] nonce)
            {
                this.src_ = src_;
                src = null!; //TRANSPORT role
                _c.Init(key, nonce);
                _hdrPut = HDR;
                _closed = false;
                return this;
            }

            public bool isOpen() => !_closed && (src_?.isOpen() ?? true);

            public void Close()
            {
                if (_closed)
                    return;
                _closed = true;
                src_?.Close();
            }

            ///<summary>Transport entry: let the upper layer fill <paramref name="dst"/>, then XOR-encrypt exactly the
            ///freshly written bytes in place. Return value is relayed verbatim (<c>-1</c> dry, <c>0</c> nothing now).</summary>
            public int Read(byte[] dst, int dst_byte, int dst_bytes)
            {
                if (_closed || src_ == null)
                    return -1;
                var n = src_.Read(dst, dst_byte, dst_bytes);
                if (n < 1)
                    return n;
                _c.Process(dst.AsSpan(dst_byte, n)); //XOR in place; the keystream is continuous across calls
                wire_bytes += n;
                return n;
            }
#endregion

            //Transparent to length: a stream cipher neither adds nor removes bytes, so it forwards the inner stage's
            //declared payload size unchanged (-1 if the inner source's size is unknown). Valid under File and Chunked.

            ///<summary>
            ///Framework entry. Lets <see cref="src"/> write plaintext into the transmit window, then XOR-encrypts exactly
            ///those freshly-written bytes in place. The keystream advances continuously across fills. Relays the inner
            ///stage's completion verbatim: <c>true</c> at source EOF (the framer then writes the <c>0x0000</c> terminator),
            ///<c>false</c> to park when the buffer fills.
            ///</summary>
            public bool __get_bytes(AdHoc.Connection.Transmitter dst)
            {
                if (_hdrPut < 0)
                    keyed(dst);
                for (; _hdrPut < HDR; _hdrPut++) //the key id and the sequence, in clear, ahead of the ciphertext
                {
                    if (dst.byte_max <= dst.byte_)
                        return false;
                    dst.buffer![dst.byte_++] = _hdr[_hdrPut];
                }
                var from = dst.byte_;
                var done = src.__get_bytes(dst); //inner produces plaintext into dst.buffer[from .. dst.byte_]
                var n = dst.byte_ - from;
                if (0 < n)
                    _c.Process(dst.buffer.AsSpan(from, n)); //XOR-encrypt the new bytes in place; keystream is continuous
                return done;
            }
        }
    }
