            public long accept_retry = 1000;

            ///<summary>
            ///How many connections this server serves at once; <c>0</c> - as many as the machine allows. Past the
            ///limit an accepted socket is closed at once: the peer learns immediately instead of waiting in the
            ///backlog for a server that will not come, and the descriptors that are left stay for those already
            ///served. <see cref="refused"/> counts them.
            ///</summary>
            public int max_connections;

            ///<summary>
            ///How many connections one address may open per <see cref="accept_window"/>; <c>0</c> - as many as it likes.
            ///<para>A fixed window, not a sliding one: what every address has knocked is thrown away when the window
            ///turns, so an address can spend its budget at the end of one window and again at the start of the next.
            ///That is what makes it cost nothing to keep - one map that is emptied, not a queue of stamps per address -
            ///and against a storm it is enough.</para>
            ///</summary>
            public int accept_rate;

            ///<summary>The window <see cref="accept_rate"/> is counted in, in milliseconds.</summary>
            public long accept_window = 1000;

            ///<summary>
            ///How many connections one address may hold at once; <c>0</c> - as many as it likes. Unlike the rate, this
            ///is counted down again when a connection of that address goes.
            ///</summary>
            public int max_per_address;

            ///<summary>
            ///The peer as both limits know it - its address, not its port: <c>1.2.3.4:5000</c> and <c>1.2.3.4:5001</c>
            ///are the same peer. Nothing is hashed, so no two peers ever share a budget by accident:
            ///<list type="bullet">
            ///<item><b>IPv4</b> - the four bytes as they are, exactly;</item>
            ///<item><b>IPv6</b> - the first eight, the <c>/64</c> the peer sits in. That is the unit an address belongs
            ///to: one host there has as many addresses as it likes inside its own <c>/64</c>, so counting them one by
            ///one would limit nothing.</item>
            ///</list>
            ///A bit of its own marks each family, which also keeps the answer from being <c>0</c> - the value that
            ///means "not counted". An IPv4 peer arriving on a dual-stack listener is unmapped first, so it is counted
            ///with the other IPv4 peers and not with the whole of <c>::ffff:0:0/96</c>.
            ///</summary>
            public static long address_of(Socket socket)
            {
                try
                {
                    if (socket.RemoteEndPoint is not IPEndPoint end)
                        return 0;
                    var a = end.Address;
                    if (a.IsIPv4MappedToIPv6)
                        a = a.MapToIPv4();
                    Span<byte> b = stackalloc byte[16];
                    if (!a.TryWriteBytes(b, out var n))
                        return 0;
                    long v = 0;
                    for (int i = 0, k = Math.Min(n, 8); i < k; i++)
                        v = v << 8 | b[i];
                    return n == 4 ? v | 1L << 32 : v | 1L << 63;
                }
                catch (Exception gone) when (gone is SocketException or ObjectDisposedException)
                {
                    return 0; //оно закрылось само; путь приёма узнает об этом сам
                }
            }

            ///<summary>
            ///Who knocked in this window and how often, and how many connections each address holds right now. An
            ///accept completes on whatever thread the kernel gives it and a connection dies on another, so one lock
            ///guards both; it is touched twice per connection of a limited server, never per message. Made on the
            ///first accept while the limit that needs it is on.
            ///</summary>
            readonly object gate_lock = new();
            PrimitiveKeyMap<long, int>? knocks, held;
            long window_from;

            long _refused, _throttled, _crowded;

            ///<summary>How many connections were turned away at <see cref="max_connections"/>.</summary>
            public long refused() => Interlocked.Read(ref _refused);

            ///<summary>How many were turned away at <see cref="accept_rate"/> - one address knocking too often.</summary>
            public long throttled() => Interlocked.Read(ref _throttled);

            ///<summary>How many were turned away at <see cref="max_per_address"/> - one address holding too many at once.</summary>
            public long crowded() => Interlocked.Read(ref _crowded);

            bool full()
            {
                if (max_connections <= 0 || connections_live() < max_connections)
                    return false;
                Interlocked.Increment(ref _refused);
                return true;
            }

            ///<summary>
            ///Both limits of one address, asked at once. <c>0</c> back means "take it" - and that is the whole cost
            ///while both are off: two comparisons of an int with zero, no address looked up, no map made. <c>-1</c>
            ///means "turn it away"; anything else is the address itself, for <see cref="ExternalConnection.address"/>
            ///to hold onto and <see cref="release"/> to give back.
            ///</summary>
            long gate(Socket accepted)
            {
                if (accept_rate <= 0 && max_per_address <= 0)
                    return 0;
                var who = address_of(accepted);
                if (who is 0 or - 1)
                    return 0;
                lock (gate_lock)
                {
                    if (0 < accept_rate)
                    {
                        var now = Environment.TickCount64;
                        if (knocks == null)
                        {
                            knocks = new PrimitiveKeyMap<long, int>(256);
                            window_from = now;
                        }
                        else if (window_from + Math.Max(1L, accept_window) <= now)
                        {
                            knocks.Clear(); //окно сменилось: все начинают заново
                            window_from = now;
                        }
                        knocks.TryGetValue(who, out var knocked);
                        knocks[who] = ++knocked;
                        if (accept_rate < knocked)
                        {
                            Interlocked.Increment(ref _throttled);
                            return -1;
                        }
                    }
                    if (max_per_address <= 0)
                        return 0; //частота пропустила, а считать обратно нечего: адрес можно и не помнить
                    held ??= new PrimitiveKeyMap<long, int>(256);
                    held.TryGetValue(who, out var holds);
                    if (max_per_address < ++holds)
                    {
                        Interlocked.Increment(ref _crowded);
                        return -1;
                    }
                    held[who] = holds;
                }
                return who;
            }

            ///<summary>
            ///A connection of <paramref name="address"/> is gone - one less it holds. Called only for a connection that
            ///was admitted under <see cref="max_per_address"/>.
            ///</summary>
            protected internal override void release(long address)
            {
                if (address == 0)
                    return;
                lock (gate_lock)
                {
                    if (held == null || !held.TryGetValue(address, out var holds))
                        return;
                    if (--holds < 1)
                        held.Remove(address); //адрес не держит ничего: вон из карты, чтобы та не росла вечно
                    else
                        held[address] = holds;
                }
            }

            ///<summary>
            ///An accepted socket at the door. Past a limit it is closed at once - the peer learns immediately instead
            ///of waiting in the backlog for a server that will not come. A factory that throws, or a REMOTE_CONNECT
            ///handler that throws, must not stop the server from accepting; a slot already taken is aborted, not
            ///dropped - its state would stay ACTIVE for ever.
            ///</summary>
            internal void admit(Socket accepted)
            {
                long who;
                if (full() || (who = gate(accepted)) < 0)
                {
                    closeQuietly(accepted);
                    return;
                }
                ExternalConnection? con = null;
                try
                {
                    con = allocate();
                    con.address = who;
                    con.receiver_connected(accepted);
                }
                catch (Exception ex)
                {
                    if (con == null)
                    {
                        release(who); //никто не принял адрес на себя
                        closeQuietly(accepted);
                    }
                    else if (con.IsActive)
                        con.Abort(); //слот уже занят - его надо закрыть, иначе он навсегда останется ACTIVE
                    onFailure(this, ex);
                }
            }

            static void closeQuietly(Socket socket)
            {
                try
                {
                    socket.Close();
                }
                catch
                { /* уже нет */
                }
            }

            ///<summary>
            ///One listening socket and the accepts it drives. It issues one <see cref="Socket.AcceptAsync(SocketAsyncEventArgs)"/>
            ///at a time and re-issues it as each one reports - synchronous completions in a loop, asynchronous ones
            ///from the completion handler.
            ///</summary>
            public sealed class Acceptor
            {
                readonly Server server;
                public readonly Socket listener;
                readonly SocketAsyncEventArgs args = new();

                internal Acceptor(Server server, Socket listener)
                {
                    this.server = server;
                    this.listener = listener;
                    args.Completed += (_, _) => drive();
                }

                ///<summary>Issues the next accept, and drives the loop when it is already done.</summary>
                internal void arm()
                {
                    if (!issue())
                        drive();
                }

                ///<summary><c>true</c> - the accept was taken and will report later; <c>false</c> - it is already done.</summary>
                bool issue()
                {
                    try
                    {
                        return listener.AcceptAsync(args);
                    }
                    catch (ObjectDisposedException)
                    {
                        return true; //deafen() closed the listener: there is nothing left to accept
                    }
                    catch (Exception why)
                    {
                        pause(why);
                        return true;
                    }
                }

                void drive()
                {
                    do
                    {
                        var accepted = args.AcceptSocket;
                        args.AcceptSocket = null; //снимаем до следующего приёма: SAEA пойдёт в него чистым
                        var err = args.SocketError;
                        if (err == SocketError.Success)
                        {
                            if (accepted != null)
                                server.admit(accepted);
                        }
                        else if (err is SocketError.OperationAborted or SocketError.Interrupted or SocketError.Shutdown)
                            return; //слушающий сокет закрыт: deafen() или shutdown()
                        else
                        {
                            pause(new SocketException((int)err));
                            return;
                        }
                    } while (!issue());
                }

                ///<summary>
                ///An accept failed - out of descriptors, most of the time ("Too many open files"). The peer is still in
                ///the backlog and the listener is still ready, so accepting on would mean this same failure again, and
                ///again, for as long as it lasts: measured on Linux, 998 ms of a core out of 1000 and 454 823 reports in
                ///a second, with nothing else getting served.
                ///<para>So the listener goes deaf for <see cref="accept_retry"/> milliseconds - the backlog holds the
                ///peers meanwhile, and the descriptors have that long to come back - and what happened is reported
                ///once, not once per attempt.</para>
                ///</summary>
                void pause(Exception why)
                {
                    server.onFailure(server, why);
                    Task.Delay((int)Math.Max(1L, server.accept_retry)).ContinueWith(
                        _ => arm());
                }
            }

            ///<summary>The accept loops, one per bound address.</summary>
            public readonly List<Acceptor> acceptors = new();

            ///<summary>
            ///No more listening: the bound addresses are given up, what is already accepted is untouched. What a
            ///<see cref="TCP.shutdown(TimeSpan)"/> does first, and on its own the way to stop taking new peers while
            ///the server goes on serving the ones it has.
            ///</summary>
            public override void deafen()
            {
                foreach (var listener in tcp_listeners)
                    try
                    {
                        listener.Close();
                    }
                    catch (Exception ex)
                    {
                        onFailure(this, ex);
                    }
                tcp_listeners.Clear();
                acceptors.Clear();
            }

            ///<summary>
            ///Binds the server to the specified IP endpoints and begins listening for incoming connections.
            ///For each endpoint, it starts an asynchronous accept loop.
            ///</summary>
            ///<param name="Backlog">The maximum length of the pending connections queue.</param>
            ///<param name="socketBuilder">An optional factory function to create custom listener sockets. If null, a standard TCP socket is used.</param>
            ///<param name="ips">An array of <see cref="IPEndPoint"/>s to bind the server to.</param>
            public void bind(int Backlog, Func<IPEndPoint, Socket>? socketBuilder, params IPEndPoint[] ips)
            {
                var sb = new StringBuilder(50).Append("Server ").Append(name);
                socketBuilder ??= ip => new Socket(ip.AddressFamily, SocketType.Stream, ProtocolType.Tcp);
                foreach (var ip in ips)
                {
                    sb.Append('\n').Append("\t\t : ").Append(ip);
                    var tcp_listener = socketBuilder(ip);
                    tcp_listeners.Add(tcp_listener);
                    if (0 < socket_receive_buffer)
                        try
                        {
                            //до bind: только тогда верен масштаб окна в рукопожатии, и только тогда его наследует принятый сокет
                            tcp_listener.ReceiveBufferSize = socket_receive_buffer;
                        }
                        catch (Exception ex) when (ex is SocketException or NotSupportedException)
                        {
                            onFailure(this, ex);
                        }
                    tcp_listener.Bind(ip);
                    tcp_listener.Listen(Backlog < 1 ? listen_backlog : Backlog);
                    var acceptor = new Acceptor(this, tcp_listener);
                    acceptors.Add(acceptor);
                    acceptor.arm();
                }

                toString = sb.ToString();
            }
