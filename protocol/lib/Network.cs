#region waiting
        ///<summary>
        ///How a loop sleeps: until a socket of it has a datagram, <see cref="wake"/> is called, or the time runs out.
        ///<c>Socket.Poll</c> cannot do it - measured on Windows it sleeps 15.6 ms at least, and a wakeup through a
        ///datagram to itself takes 80 us.
        ///</summary>
        internal abstract class Waiter
        {
            internal abstract void add(Socket socket);
            internal abstract void remove(Socket socket);

            ///<summary>Sleeps up to <paramref name="ticks"/> clock ticks: <c>0</c> - not at all, <see cref="long.MaxValue"/> - until woken.</summary>
            internal abstract void wait(long ticks);

            internal abstract void wake();
            internal abstract void close();

            ///<summary>
            ///One datagram off <paramref name="ep"/>'s socket into <paramref name="buffer"/>, its sender into
            ///<see cref="Endpoint.from"/>: the length, or <c>-1</c> when there is none. The system's <c>recvfrom</c>, not
            ///<c>Socket.ReceiveFrom</c>: that one reports "nothing more" as an exception - 10 to 20 us for every wakeup - and
            ///checking <c>Available</c> first stops at a datagram of length 0, which leaves the socket unreadable for good.
            ///</summary>
            internal abstract int receive(Endpoint ep, byte[] buffer);

            internal static Waiter make() => OperatingSystem.IsWindows() ? new Windows() : new Linux();

            ///<summary>
            ///One event for the sockets (<c>WSAEventSelect</c>), one to be woken by, and a high-resolution waitable
            ///timer: measured, it sleeps 1 ms as 1.5 ms and wakes on <c>SetEvent</c> in 8 us, without changing the timer
            ///resolution of the process the way <c>timeBeginPeriod</c> does.
            ///</summary>
            sealed class Windows : Waiter
            {
                readonly IntPtr sockets = WSACreateEvent(), woken = CreateEventW(IntPtr.Zero, false, false, IntPtr.Zero), timer;
                readonly IntPtr[] handles;

                internal Windows()
                {
                    timer = CreateWaitableTimerExW(IntPtr.Zero, IntPtr.Zero, 2 /*HIGH_RESOLUTION*/, 0x1F0003 /*TIMER_ALL_ACCESS*/);
                    if (timer == IntPtr.Zero) //before Windows 10 1803: an ordinary timer, 15.6 ms
                        timer = CreateWaitableTimerExW(IntPtr.Zero, IntPtr.Zero, 0, 0x1F0003);
                    handles = new[] { sockets, woken, timer };
                }

                internal override void add(Socket socket)
                {
                    if (WSAEventSelect(socket.Handle, sockets, 1 /*FD_READ*/) != 0)
                        throw new SocketException(Marshal.GetLastPInvokeError());
                }

                internal override void remove(Socket socket) => WSAEventSelect(socket.Handle, IntPtr.Zero, 0);

                internal override void wait(long ticks)
                {
                    if (0 < ticks)
                        if (ticks == long.MaxValue)
                            WaitForMultipleObjects(2, handles, false, 0xFFFFFFFF);
                        else
                        {
                            var due = -Math.Max(1, ticks * 10_000_000 / Stopwatch.Frequency); //relative, in 100 ns
                            SetWaitableTimer(timer, ref due, 0, IntPtr.Zero, IntPtr.Zero, false);
                            WaitForMultipleObjects(3, handles, false, 0xFFFFFFFF);
                        }
                    //Before the sockets are read, not after: a datagram that arrives while they are read sets it again.
                    WSAResetEvent(sockets);
                }

                internal override void wake() => SetEvent(woken);

                internal override void close()
                {
                    CloseHandle(timer);
                    CloseHandle(woken);
                    WSACloseEvent(sockets);
                }

                //The socket is non-blocking: WSAEventSelect made it so.
                internal override int receive(Endpoint ep, byte[] buffer)
                {
                    for (;;)
                    {
                        var size = ep.fromCap;
                        var n = recvfrom(ep.handle, buffer, buffer.Length, 0, ep.fromBytes, ref size);
                        if (0 <= n)
                        {
                            ep.from.Size = size;
                            return n;
                        }
                        switch (Marshal.GetLastPInvokeError())
                        {
                            case 10040: //WSAEMSGSIZE: longer than any packet of ours, dropped
                            case 10054: //WSAECONNRESET: an ICMP of an earlier send, where SIO_UDP_CONNRESET is not honoured
                                continue;
                            default: //WSAEWOULDBLOCK, or the socket is gone
                                return -1;
                        }
                    }
                }

                [DllImport("ws2_32.dll", SetLastError = true)]
                static extern int recvfrom(IntPtr socket, byte[] buffer, int length, int flags, byte[] from, ref int fromLength);

                [DllImport("ws2_32.dll")]
                static extern IntPtr WSACreateEvent();
                [DllImport("ws2_32.dll")]
                static extern bool WSACloseEvent(IntPtr ev);
                [DllImport("ws2_32.dll")]
                static extern bool WSAResetEvent(IntPtr ev);
                [DllImport("ws2_32.dll", SetLastError = true)]
                static extern int WSAEventSelect(IntPtr socket, IntPtr ev, int events);
                [DllImport("kernel32.dll")]
                static extern IntPtr CreateEventW(IntPtr attributes, bool manual, bool initial, IntPtr name);
                [DllImport("kernel32.dll")]
                static extern bool SetEvent(IntPtr ev);
                [DllImport("kernel32.dll")]
                static extern bool CloseHandle(IntPtr handle);
                [DllImport("kernel32.dll")]
                static extern IntPtr CreateWaitableTimerExW(IntPtr attributes, IntPtr name, uint flags, uint access);
                [DllImport("kernel32.dll")]
                static extern bool SetWaitableTimer(IntPtr timer, ref long due, int period, IntPtr routine, IntPtr arg, bool resume);
                [DllImport("kernel32.dll")]
                static extern uint WaitForMultipleObjects(uint count, IntPtr[] handles, bool all, uint ms);
            }

            ///<summary><c>ppoll</c> over the sockets and an <c>eventfd</c> to be woken by.</summary>
            sealed class Linux : Waiter
            {
                readonly int woken = eventfd(0, 0x800 /*EFD_NONBLOCK*/ | 0x80000 /*EFD_CLOEXEC*/);
                PollFd[] fds = new PollFd[4];
                int n = 1;

                internal Linux()
                {
                    if (woken < 0)
                        throw new SocketException(Marshal.GetLastPInvokeError());
                    fds[0] = new PollFd { fd = woken, events = 1 /*POLLIN*/ };
                }

                internal override void add(Socket socket)
                {
                    if (n == fds.Length)
                        Array.Resize(ref fds, n * 2);
                    fds[n++] = new PollFd { fd = (int)socket.Handle, events = 1 };
                }

                internal override void remove(Socket socket)
                {
                    var fd = (int)socket.Handle;
                    for (var i = 1; i < n; i++)
                        if (fds[i].fd == fd)
                        {
                            fds[i] = fds[--n];
                            return;
                        }
                }

                internal override void wait(long ticks)
                {
                    if (ticks <= 0)
                        return; //the sockets are read anyway; a wake left in the eventfd costs one early return later
                    if (ticks == long.MaxValue)
                        ppoll(fds, (ulong)n, IntPtr.Zero, IntPtr.Zero);
                    else
                    {
                        var ns = ticks * 1_000_000_000 / Stopwatch.Frequency;
                        var ts = new TimeSpec { sec = ns / 1_000_000_000, nsec = ns % 1_000_000_000 };
                        ppoll(fds, (ulong)n, ref ts, IntPtr.Zero);
                    }
                    if ((fds[0].revents & 1) != 0)
                    {
                        ulong v = 0;
                        read(woken, ref v, 8);
                    }
                }

                internal override void wake()
                {
                    ulong v = 1;
                    write(woken, ref v, 8);
                }

                internal override void close() => close(woken);

                internal override int receive(Endpoint ep, byte[] buffer)
                {
                    uint size = (uint)ep.fromCap;
                    //MSG_DONTWAIT; a datagram longer than the buffer comes truncated, and a truncated packet is dropped by its parse
                    var n = recvfrom((int)ep.handle, buffer, buffer.Length, 0x40, ep.fromBytes, ref size);
                    if (n < 0)
                        return -1; //EAGAIN, or the socket is gone
                    ep.from.Size = (int)size;
                    return (int)n;
                }

                [DllImport("libc", SetLastError = true)]
                static extern nint recvfrom(int fd, byte[] buffer, nint length, int flags, byte[] from, ref uint fromLength);

                [StructLayout(LayoutKind.Sequential)]
                struct PollFd
                {
                    public int fd;
                    public short events, revents;
                }
                [StructLayout(LayoutKind.Sequential)]
                struct TimeSpec
                {
                    public long sec;
                    public long nsec;
                }

                [DllImport("libc", SetLastError = true)]
                static extern int eventfd(uint initial, int flags);
                [DllImport("libc")]
                static extern int ppoll(PollFd[] fds, ulong n, ref TimeSpec timeout, IntPtr sigmask);
                [DllImport("libc")]
                static extern int ppoll(PollFd[] fds, ulong n, IntPtr timeout, IntPtr sigmask);
                [DllImport("libc")]
                static extern nint read(int fd, ref ulong value, nint count);
                [DllImport("libc")]
                static extern nint write(int fd, ref ulong value, nint count);
                [DllImport("libc")]
                static extern int close(int fd);
            }
        }
