            ///<summary>
            ///Handles the completion of asynchronous socket operations such as Connect, Disconnect, and Send.
            ///</summary>
            ///<param name="_transmit">The <see cref="SocketAsyncEventArgs"/> instance for the completed operation.</param>
            protected override void OnCompleted(SocketAsyncEventArgs _transmit)
            {
                //Wait if maintenance is in progress to prevent race conditions. The rescheduled item carries
                //this operation's pending reference with it — it is released when the handler actually runs.
                if (locked_for_maintenance())
                {
                    //Immediately release this IOCP thread back to the pool.
                    //The rescheduled item runs on a regular ThreadPool thread, which
                    //can block without starving I/O completions.
                    reschedule_transmit(_transmit);
                    return;
                }

                //The reference this operation holds on pending is released in the finally — at the END of the
                //handling, not on entry. While the handler runs it is what keeps FinishDispose() from returning
                //the buffers to the pool under our feet when another thread calls Abort() mid-fill.
                //A completed send is the transmit runner coming back: whatever happened to the socket, the runner turns
                //once more — to send on, or to release the counter.
                var send = _transmit.LastOperation == SocketAsyncOperation.Send;
                try
                {
                    if (!IsActive)
                    {
                        if (send)
                            transmit();
                        return; //an operation of a session that is already gone
                    }

                    Event eventType;
                    switch (_transmit.SocketError)
                    {
                        case SocketError.Success:
                            if (send)
                            {
                                transmit_time = DateTimeOffset.UtcNow.ToUnixTimeMilliseconds();
                                transmit_due = 0; //записанное ушло: ожидание снято
                                transmit();       //Continue sending if more data is available.
                            }

                            return;
                        case SocketError.TimedOut:
                            timed_out_transmit(); //вопрос приложению, а не приговор
                            if (send)
                                transmit();
                            return;
                        case SocketError.ConnectionReset:
                        case SocketError.ConnectionAborted:
                        case SocketError.NetworkReset:
                            eventType = Event.REMOTE_CLOSE_ABRUPTLY;
                            break;
                        default:
                            host.onFailure(this, new SocketException((int)_transmit.SocketError));
                            eventType = Event.REMOTE_CLOSE_ABRUPTLY;
                            break;
                    }

                    Disconnected(eventType);
                    if (send)
                        transmit();
                }
                finally
                {
                    pending_send_receive_completed();
                    ReleaseOp();
                }
            }

            ///<summary>
            ///Configures the connection for transmission after a successful connection, setting up buffers and starting I/O loops.
            ///</summary>
            ///<param name="ext">The newly connected socket.</param>
            internal void transmitterConnected(Socket? ext)
            {
                isClosingGracefully = false;

                this.ext = ext;
                noise = serverKey == null ? null : NoiseStream.Client(serverKey, () => Internal?.BytesSrc, () => ActiveDst, WakeTransmit, k => AdHoc.Connection.Keyring.Seat(Internal, k));
                if (ext != null)
                    host.configure(ext);
                transmit_time = DateTimeOffset.UtcNow.ToUnixTimeMilliseconds();

                //Setup custody — see receiver_connected.
                Interlocked.Increment(ref pending);
                try
                {
                    var before = id;
                    Internal.OnExternalEvent(this, Event.THIS_CONNECT);
                    if (IsActive)
                        SessionOpened();

                    if (!IsActive)
                        return; //the handler tore the connection down

                    if (before != 0 && id == before)
                        Internal.resume(this); //an identity kept across sockets that the handler did not re-identify

                    if (Buffer == null)
                        host.buffers(this);
                    else
                        SetBuffer(0, Buffer.Length);
                    //Backfill: a runner that ran during OnExternalEvent above found no buffer and left; a wake that
                    //landed while one ran is counted. Either way this one serves them.
                    WakeTransmit();
                    if (Internal.BytesDst == null)
                        return;
                    if (ReceiveMate.Buffer == null)
                        host.buffers(ReceiveMate);
                    //Start the receive loop. If ReceiveAsync completes synchronously, call receive() immediately.
                    if (!IssueReceive())
                        receive();
                }
                finally
                {
                    ReleaseOp();
                }
            }

            ///<summary>The write timeout in milliseconds.
            ///Getter: positive while open normally; negative once a graceful close is in progress (magnitude = the write
            ///timeout that still bounds draining the send queue) — the sign is a read-only "closing" indicator.
            ///Setter: value&gt;=0 sets the write timeout and leaves the graceful flag untouched; value&lt;0 enters graceful
            ///close — the queue drains, then OnTransmitterDrained sends the FIN. This is the trigger the generated
            ///LastTransmission uses.</summary>
            public virtual int TransmitTimeout
            {
                get => isClosingGracefully ? -_transmit_timeout : //Return as negative to signal closing state
                           _transmit_timeout;
                set {
                    _transmit_timeout = value < 0 && (isClosingGracefully = true) ? -value : value;
                    if (IsActive)
                        arm_transmit();
                }
            }

            ///<summary>
            ///The two waits, in milliseconds; <see cref="int.MaxValue"/> - no deadline, which is where a connection
            ///starts. Plain fields, not <c>Socket.ReceiveTimeout</c> / <c>SendTimeout</c>: .NET applies those to
            ///SYNCHRONOUS calls only, so they would time nothing here - and reading one is a <c>getsockopt</c>, which
            ///on the path of every message is a price nothing pays for. A slot handed to a new tenant keeps them, the
            ///same as the Java runtime.
            ///</summary>
            int _receive_timeout = int.MaxValue, _transmit_timeout = int.MaxValue;

            ///<summary>
            ///Manages the asynchronous sending of data. It repeatedly reads from the source transmitter
            ///and issues non-blocking send operations until the transmitter is empty.
            ///</summary>
            void transmit()
            {
                //The runner. Whoever turned the wake counter 0->1 handed it to the pool; a send completion continues it on
                //the completion's own pool thread. It is the only code that pulls the transmitter: ACTIVE fills the socket,
                //any other state has nothing to fill for. Eventcount release: the counter is snapshotted BEFORE a turn; a
                //wake that lands during the turn makes the CAS(observed, 0) fail and the runner turn again, so no work is
                //stranded and no second runner ever starts — nothing resets the counter, ever.
                for (;;)
                {
                    var observed = Volatile.Read(ref TransmitLock);
                    switch (conn_state)
                    {
                        case ACTIVE:
                            //The retain covers the fill: a concurrent teardown cannot hand Buffer to the pool — and on to
                            //another connection — while this thread is still writing packs into it. A null buffer means the
                            //socket has not been handed the transmitter yet: transmitterConnected wakes again.
                            if (Buffer != null && TryRetain())
                            {
                                try
                                {
                                    //Guard the fill: transmit(Buffer!) runs the serializer — and for a tunnel Relay it re-enters
                                    //the PEER connection's receive path, so a malformed inbound stream can throw ACROSS the
                                    //connection boundary into THIS runner; a File/Chunked EndPoint source can throw here too.
                                    //Unhandled, it would crash the ThreadPool worker. Treat it like a genuine SendAsync error:
                                    //report + Abort; the counter is released below once the state has left ACTIVE.
                                    bool more;
                                    try
                                    {
                                        more = transmit(Buffer!);
                                    }
                                    catch (Exception e)
                                    {
                                        host.onFailure(this, e);
                                        Abort();
                                        more = false;
                                    }
                                    while (more)
                                    {
                                        //Capture once per send attempt. If Abort() runs between iterations,
                                        //the next capture will see null and exit cleanly without an exception.
                                        var socket = Volatile.Read(ref ext);
                                        if (socket == null)
                                            break; //connection was aborted; no send possible

                                        //The send's own reference — released by OnCompleted's finally, or right below on a
                                        //synchronous completion. A blind increment is safe: the entry retain keeps the count
                                        //above zero for this whole scope.
                                        Interlocked.Increment(ref pending);
                                        bool async;
                                        try
                                        {
                                            arm_transmit(); //ожидание, пока собеседник заберёт записанное
                                            async = socket.SendAsync(this);
                                        }
                                        catch (ObjectDisposedException)
                                        {
                                            //Socket was closed by Abort() in the gap between the Volatile.Read above and
                                            //SendAsync. Expected and benign — the teardown owns the rest.
                                            ReleaseOp();
                                            break;
                                        }
                                        catch (Exception e)
                                        {
                                            ReleaseOp();
                                            host.onFailure(this, e);
                                            Abort();
                                            break;
                                        }
                                        if (async)
                                            return;  //completing asynchronously; OnCompleted owns the reference and continues the runner
                                        ReleaseOp(); //completed synchronously — no callback will fire

                                        //Refill for the next send attempt — same guard as the initial fill above.
                                        try
                                        {
                                            more = transmit(Buffer!);
                                        }
                                        catch (Exception e)
                                        {
                                            host.onFailure(this, e);
                                            Abort();
                                            more = false;
                                        }
                                    }
                                }
                                finally
                                {
                                    ReleaseOp();
                                }
                                if (!IsActive)
                                    break; //torn down mid-turn: the counter is released below
                                //Nothing produced. Release to idle ONLY if no wake arrived since `observed`; otherwise a producer
                                //raced the fill — turn again so its work is not stranded (and no second runner can start).
                                if (Interlocked.CompareExchange(ref TransmitLock, 0, observed) == observed)
                                {
                                    OnTransmitterDrained();
                                    return;
                                }
                                continue;
                            }
                            break;
                    }
                    if (Interlocked.CompareExchange(ref TransmitLock, 0, observed) == observed)
                        return;
                }
            }

            ///<summary>
            ///A hook method invoked when the internal transmitter has been fully drained of pending data.
            ///</summary>
            ///<remarks>
            ///This method is called by the <code>transmit()</code> loop after it has sent all available data from the
            ///transmitter. It serves as an extension point for derived classes to implement
            ///protocol-specific final actions.
            ///<para>
            ///For example, the <see cref="WebSocket"/> class overrides this method to send a CLOSE frame if a
            ///graceful shutdown was previously requested.
            ///</para>
            ///The default implementation handles the raw TCP graceful close sequence by calling
            ///<see cref="Close"/> if a graceful close was initiated.
            ///</remarks>
            protected virtual void OnTransmitterDrained()
            {
                if (isClosingGracefully)
                    Close();
            }

            ///<summary>
            ///Loads a chunk of data from the internal transmitter into the specified buffer for sending.
            ///</summary>
            ///<param name="dst">The destination buffer for the data.</param>
            ///<returns><c>true</c> if data was loaded into the buffer; <c>false</c> if no data was available.</returns>
            protected virtual bool transmit(byte[] dst)
            {
                var src = TxSrc;
                if (src == null)
                    return false;
                var bytes = src.Read(dst, 0, dst.Length);

                if (bytes < 1)
                    return false;
                SetBuffer(0, bytes);
                return true;
            }
