            ///<summary>Dialing side: the first read of a socket to a multiplexed port. Puts the Internal back in place, then
            ///the byte naming the connection and whatever the Internal has to send behind it - one send. Listening side:
            ///nothing to send before the caller is named.</summary>
            int AdHoc.BytesSrc.Read(byte[] dst, int dst_byte, int dst_bytes)
            {
                if (host.internals != null)
                    return 0;
                var @out = outgoing!;
                if (Internal != this)
                    return @out.BytesSrc?.Read(dst, dst_byte, dst_bytes) ?? 0; //a late call through the stand-in: pass on
                Internal = @out;
                dst[dst_byte] = (byte) @out.id;
                var n = @out.BytesSrc?.Read(dst, dst_byte + 1, dst_bytes - 1) ?? 0;
                return n < 0 ? 1 : 1 + n;
            }

