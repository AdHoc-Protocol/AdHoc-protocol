        public int lingerTimeout = 5000;

        ///<summary>The default minimum interval in milliseconds between maintenance passes.</summary>
        public uint maintenance_duty_cycle = 5000;

        ///<summary>
        ///When the maintenance pass means to look again, in milliseconds since the epoch; <c>0</c> - it has not said
        ///yet. Published by the pass right before it sleeps.
        ///</summary>
        long _nextDeadline;

        ///<summary>
        ///A wait that runs out at <paramref name="at"/> has been armed: the maintenance pass must not sleep past it.
        ///<para>It wakes the pass only when the new deadline falls EARLIER than the pass already means to look - so in
        ///a steady stream, where every message pushes its connection's deadline further away, arming one costs a read
        ///and a comparison and wakes nobody.</para>
        ///</summary>
        protected internal void deadline_at(long at)
        {
            while (true)
            {
                var planned = Volatile.Read(ref _nextDeadline);
                if (planned != 0 && planned <= at)
                    return; //обход и так проснётся раньше
                if (Interlocked.CompareExchange(ref _nextDeadline, at, planned) == planned)
                {
                    TriggerMaintenance();
                    return;
                }
            }
        }

        ///<summary>The pass means to look again at <paramref name="at"/>: what an arming deadline compares itself with.</summary>
        protected void deadline_planned(long at) => Volatile.Write(ref _nextDeadline, at);

        ///<summary>
        ///The sleep between maintenance passes, and the way to cut it short. A token already waiting IS the signal, so
        ///a second wake adds nothing.
        ///</summary>
        protected readonly SemaphoreSlim maintenance_wake = new(0, 1);

        ///<summary>Ends the maintenance pass's sleep now.</summary>
        protected void wake()
        {
            if (maintenance_wake.CurrentCount != 0)
                return;
            try
            {
                maintenance_wake.Release();
            }
            catch (SemaphoreFullException)
            { /* кто-то успел первым - сигнал уже подан */
            }
        }

        ///<summary>
        ///Takes nothing new in. A <see cref="Server"/> closes its listeners; a client has nothing to close.
        ///</summary>
        public virtual void deafen() {}

        ///<summary>
        ///Stops at once: every connection is torn down where it stands. Whatever was in a send queue stays there.
        ///</summary>
        public virtual void shutdown() => shutdown(TimeSpan.Zero);

        ///<summary>
        ///Stops, giving the sessions <paramref name="grace"/> to finish what they were saying.
        ///<list type="number">
        ///<item>nothing new is taken in - a <see cref="Server"/> closes its listeners here;</item>
        ///<item>every connection is asked to close the polite way: the send queue drains, then the FIN goes out - and
        ///a <see cref="WebSocket"/> sends its CLOSE frame first and waits for the peer's;</item>
        ///<item>the sessions have <paramref name="grace"/> to end on their own; whoever is still there when it runs
        ///out is torn down.</item>
        ///</list>
        ///Blocking - not to be called from a completion handler, which is one of the threads it waits for.
        ///</summary>
        ///<param name="grace">How long to wait; zero is <see cref="shutdown()"/>.</param>
        ///<returns><c>true</c> if every session ended on its own inside <paramref name="grace"/>.</returns>
        public bool shutdown(TimeSpan grace)
        {
            deafen(); //a server stops listening; a client has nothing to stop
            var ms = (long)grace.TotalMilliseconds;
            var quiet = true;
            if (0 < ms)
            {
                each(true); //close, the polite way
                quiet = false;
                for (var until = Environment.TickCount64 + ms; Environment.TickCount64 < until;)
                {
                    if (connections_live() == 0)
                    {
                        quiet = true;
                        break;
                    }
                    Thread.Sleep(5);
                }
            }
            each(false); //whoever is left
            return quiet;
        }

        ///<summary>Every connection of this host that still holds a socket: closed the polite way, or torn down.</summary>
        void each(bool politely)
        {
            var registry = _connections;
            for (int i = 0, n = Math.Min(Volatile.Read(ref _connectionsSize), registry.Length); i < n; i++)
            {
                var con = registry[i];
                if (con == null || !con.IsActive)
                    continue;
                if (politely)
                    con.Close();
                else
                    con.Abort();
            }
        }

