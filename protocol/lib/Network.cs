            public ExternalConnection? next;

            ///<summary>
            ///How deep this thread is inside the application on this connection - its event handler, its receiver.
            ///While it is above zero a slot freed by <see cref="reclaim"/> waits in <see cref="_departed"/> instead of
            ///going back to the pool, because the <c>Internal</c> that rode it home is still on the stack.
            ///</summary>
            int _appCall;

            ExternalConnection? _departed;

            void app_enter() => _appCall++;

            void app_leave()
            {
                if (0 < --_appCall)
                    return;
                var gone = _departed;
                if (gone == null)
                    return;
                _departed = null;
                host.ReturnToFreePool(gone); //стек раскручен: теперь слот можно отдавать кому угодно
            }
#region session and deadlines
            ///<summary>
            ///1 while the <see cref="AdHoc.Connection.Internal"/> sitting on this connection has heard
            ///<see cref="AdHoc.Connection.Internal.OnOpen"/> and not yet <see cref="AdHoc.Connection.Internal.OnClose"/>.
            ///<para>Events are the detail - every socket, every cause; the two hooks are the opposite: no detail, and
            ///exactly once each. Their unit is the CONNECTION: whoever sits on a usable one hears OnOpen once, and
            ///hears OnClose once when it leaves - torn down, parked, or displaced by a <see cref="reclaim"/>. So the
            ///two always alternate for any one <c>Internal</c>, and an OnClose never comes without an OnOpen.</para>
            ///<para>An int, not a bool: receive and transmit complete on different completion-port threads and can
            ///reach the teardown together, so the flag is claimed, not tested.</para>
            ///</summary>
            protected int sessionOpen;

            ///<summary>
            ///The connection can be used: <see cref="AdHoc.Connection.Internal.OnOpen"/>, once. Raw TCP calls it with
            ///the socket; <see cref="WebSocket"/> holds it back until the upgrade is done, so a peer that never became
            ///one opens nothing and closes nothing.
            ///</summary>
            protected internal virtual void SessionOpened()
            {
                if (Internal == null || Interlocked.Exchange(ref sessionOpen, 1) != 0)
                    return;
                Internal.OnOpen();
            }

            ///<summary>
            ///When the waits run out, in milliseconds since the epoch; 0 - nothing is waited for.
            ///<para>.NET applies <c>Socket.ReceiveTimeout</c> / <c>SendTimeout</c> to SYNCHRONOUS calls only - an
            ///overlapped receive issued through <see cref="SocketAsyncEventArgs"/> is never timed by the OS. So the
            ///deadlines are kept here and looked at by the maintenance pass, which is this transport's clock: the same
            ///contract as the Java runtime, on the mechanism .NET gives.</para>
            ///</summary>
            protected long receive_due, transmit_due;

            static long now_ms() => DateTimeOffset.UtcNow.ToUnixTimeMilliseconds();

            ///<summary>
            ///Starts the receive wait: from now, for as long as <see cref="ReceiveTimeout"/> says - or, while our own
            ///graceful close waits for the peer's FIN, no longer than <see cref="TCP.lingerTimeout"/>.
            ///</summary>
            protected void arm_receive()
            {
                var t = isClosingGracefully ? Math.Min(_receive_timeout, host.lingerTimeout) : _receive_timeout;
                receive_due = t is <= 0 or int.MaxValue ? 0 : now_ms() + t;
                if (receive_due != 0)
                    host.deadline_at(receive_due); //обход не должен проспать этот срок
            }

            ///<summary>Starts the transmit wait: the peer has this long to take what was written.</summary>
            protected void arm_transmit()
            {
                var t = _transmit_timeout;
                transmit_due = t is <= 0 or int.MaxValue ? 0 : now_ms() + t;
                if (transmit_due != 0)
                    host.deadline_at(transmit_due);
            }

            ///<summary>
            ///A wait ran out. A timeout is a question before it is a verdict: the application is asked how long it
            ///still waits - it may have answered the silence with a heartbeat - and only its 0 closes the connection.
            ///The answer holds for this one wait; the next runs on <see cref="ReceiveTimeout"/> again.
            ///</summary>
            void timed_out_receive()
            {
                if (isClosingGracefully) //the peer never answered our FIN: that was never a timeout
                {
                    Disconnected(Event.REMOTE_CLOSE_ABRUPTLY);
                    return;
                }
                var more = Internal?.OnReceiveTimeout() ?? 0;
                if (!IsActive)
                    return; //the handler ended it
                if (isClosingGracefully)
                    arm_receive(); //the handler began a graceful close: from here it is the wait for the peer's FIN
                else if (more <= 0)
                    Disconnected(Event.RECEIVE_TIMEOUT);
                else
                {
                    receive_due = more == int.MaxValue ? 0 : now_ms() + more;
                    if (receive_due != 0)
                        host.deadline_at(receive_due);
                }
            }

            void timed_out_transmit()
            {
                var more = Internal?.OnTransmitTimeout() ?? 0;
                if (!IsActive)
                    return;
                if (more <= 0)
                    Disconnected(Event.TRANSMIT_TIMEOUT);
                else
                {
                    transmit_due = more == int.MaxValue ? 0 : now_ms() + more;
                    if (transmit_due != 0)
                        host.deadline_at(transmit_due);
                }
            }

            ///<summary>
            ///How long, in milliseconds, until one of this connection's waits runs out; <see cref="uint.MaxValue"/> when
            ///neither is armed. Called by the maintenance pass, which asks the application when a wait is over.
            ///</summary>
            protected internal uint deadlines()
            {
                var now = now_ms();
                var next = uint.MaxValue;
                if (receive_due != 0)
                {
                    if (receive_due <= now)
                    {
                        timed_out_receive();
                        if (!IsActive)
                            return uint.MaxValue;
                    }
                    if (receive_due != 0)
                        next = (uint)Math.Max(1, Math.Min(receive_due - now_ms(), uint.MaxValue - 1));
                }
                if (transmit_due != 0)
                {
                    if (transmit_due <= now)
                    {
                        timed_out_transmit();
                        if (!IsActive)
                            return uint.MaxValue;
                    }
                    if (transmit_due != 0)
                        next = Math.Min(next, (uint)Math.Max(1, Math.Min(transmit_due - now_ms(), uint.MaxValue - 1)));
                }
                return next;
            }
#endregion
#region maintenance
            ///<summary>
            ///A lock variable used to synchronize connection maintenance with active send/receive operations. Its value represents the connection's I/O state:
            ///<list type="bullet">
            ///<item><term>&lt; 0</term><description>Maintenance is in progress or scheduled. The connection is locked for new I/O.</description></item>
            ///<item><term>== int.MinValue</term><description>The connection has no active I/O and is ready for maintenance processing.</description></item>
            ///<item><term>&gt; 0</term><description>The count of active, pending I/O operations.</description></item>
            ///<item><term>== 0</term><description>The connection is idle (no pending I/O).</description></item>
            ///</list>
            ///</summary>
            volatile int maintenance_lock = 0;

            ///<summary>
            ///When overridden in a derived class, performs connection-specific maintenance tasks, such as handling timeouts.
            ///This method requires exclusive access to the connection, which is ensured by the maintenance lock.
            ///</summary>
            ///<returns>The time in milliseconds until the next maintenance task is due, or <see cref="uint.MaxValue"/> if none.</returns>
            protected internal virtual uint maintenance() => uint.MaxValue;

            ///<summary>
            ///Checks if maintenance is currently scheduled or in progress.
            ///</summary>
            ///<returns><c>true</c> if the maintenance lock is active; otherwise, <c>false</c>.</returns>
            protected internal bool waiting_for_maintenance() => maintenance_lock < 0;

            ///<summary>
            ///Checks if the connection is ready for maintenance (i.e., no active I/O operations).
            ///</summary>
            ///<returns><c>true</c> if ready for maintenance; otherwise, <c>false</c>.</returns>
            protected internal bool ready_for_maintenance() => maintenance_lock == int.MinValue;

            ///<summary>
            ///Resets the maintenance lock, allowing normal I/O operations to resume after maintenance is complete.
            ///</summary>
            protected internal void maintenance_completed() => Interlocked.Exchange(ref maintenance_lock, 0);

            ///<summary>
            ///Decrements the active I/O operation counter upon completion of a send or receive operation.
            ///</summary>
            protected void pending_send_receive_completed() => Interlocked.Decrement(ref maintenance_lock);

            ///<summary>
            ///Attempts to acquire a lock for a new I/O operation. It fails if maintenance is in progress.
            ///</summary>
            ///<returns><c>true</c> if the connection is locked for maintenance (preventing I/O); <c>false</c> if the I/O operation can proceed.</returns>
            protected bool locked_for_maintenance()
            {
                int t;
                do
                    t = maintenance_lock;
                while (Interlocked.CompareExchange(ref maintenance_lock, t < 0 ? t : t + 1, t) != t);
                return t < 0;
            }

            ///<summary>
            ///Schedules maintenance by setting the maintenance lock, which prevents new I/O operations from starting.
            ///</summary>
            protected internal void schedule_maintenance()
            {
                int t;
                do
                    t = maintenance_lock;
                while (Interlocked.CompareExchange(ref maintenance_lock, t < 0 ? t : int.MinValue + t, t) != t);
            }
#endregion

