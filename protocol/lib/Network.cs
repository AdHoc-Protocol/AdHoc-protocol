                if (0 < socket_transmit_buffer)
                    socket.SendBufferSize = socket_transmit_buffer;
            }
            catch (Exception ex) when (ex is SocketException or ObjectDisposedException or NotSupportedException)
            {
                onFailure(this, ex);
            }
        }

        ///<summary>
        ///How many connections of this host hold a socket right now: up when a slot goes ACTIVE, down when the socket
