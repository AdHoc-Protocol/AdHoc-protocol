        ///<summary>
        ///Represents a single communication connection over a TCP connection.
        ///This class extends <see cref="SocketAsyncEventArgs"/> to manage the state and buffers for asynchronous I/O operations on a dedicated socket.
        ///</summary>
        public class ExternalConnection : SocketAsyncEventArgs, AdHoc.Connection.External, IThreadPoolWorkItem, AdHoc.Connection.Internal, AdHoc.BytesDst, AdHoc.BytesSrc
        {
            ///<summary>
            ///The position of this connection's slot in the host's registry. Stamped once, at allocation.
            ///</summary>
            internal int index_;
            public int id { get; internal set; } //the identity the session was given: what the token a returning peer hands to reclaim is matched against

            public int index() => index_;

            ///<summary>
            ///An <see cref="AdHoc.Connection.Transmitter.Resumable.now"/> deadline, in minutes: until it passes, this parked
            ///connection's session survives the loss of its socket and waits to be reclaimed. 0 — not parked. Stamped when
            ///the connection is lost, from <see cref="AdHoc.Connection.Internal.resumable_minutes"/>, cleared when the
            ///session really ends.
            ///</summary>
            public int resumable { get; set; }

            ///<summary>The minutes a parked session still waits for its peer, 0 when its deadline has passed but it has not
            ///been reaped, or -1 when there is no parked session.</summary>
            public int parked => resumable == 0 ? -1 : Math.Max(0, resumable - AdHoc.Connection.Transmitter.Resumable.now());

            ///<summary>
            ///Sets this connection's identity to <paramref name="id"/> and tells its <see cref="Internal"/> to
            ///<see cref="AdHoc.Connection.Internal.resume"/>. Nothing moves: no parked session is claimed.
            ///</summary>
            ///<returns>This connection's <see cref="index()"/>.</returns>
            public long identify(int id)
            {
                if (this.id == id)
                    return session(); //already this identity: the resume that went with it is not repeated
                this.id = id;
                if (IsActive)
                {
                    Internal.resume(this);
                    WakeTransmit();
                }
                return session();
            }

            ///<summary>The session id of this connection: the slot and the identity, packed as <see cref="identify"/> returns them.</summary>
            public long session() => ((long)index_ << 32) | (uint)id;

            ///<summary>
            ///The peer sends back the token a former connection of this host gave it: the slot that connection sat on and
            ///the identity it proved. That slot is not this one — this connection is a new socket on a new slot — so it is
            ///looked up on the parked list. When it still holds the parked session under that identity, the session takes
            ///this connection over: its <see cref="Internal"/> moves here, this connection's <see cref="Internal"/> goes
            ///to the freed slot, and the slot returns to the pool. When the token points at this very slot, or the parked
            ///session is gone, only the identity is left to apply. Either way the connection ends up
            ///<see cref="identify">identified</see>.
            ///</summary>
            ///<param name="session_id">The peer's token: what <see cref="session"/> returned on the connection it came from.</param>
            ///<returns>This connection's <see cref="session"/>: the slot the session lives on from now on.</returns>
            public long reclaim(long session_id)
            {
                var id = (int)session_id;
                if ((int)(session_id >> 32) != index_)
                {
                    var slot = host.parked(session_id);
                    if (slot != null)
                    {
                        //Сессии меняются местами: припаркованная переезжает сюда, здешняя уезжает на освобождённый
                        //слот. Один Internal сходит с этого подключения, другой на него садится - значит одному
                        //OnClose, другому OnOpen, и у каждого скобки по-прежнему чередуются.
                        var left = Internal;
                        (slot.Internal, Internal) = (Internal, slot.Internal);
                        AdHoc.Connection.Keyring.Seat(Internal, noise?.PackKey); //the session moved here: this connection's key too
                        if (Volatile.Read(ref sessionOpen) == 1)
                        {
                            left?.OnClose();
                            Internal?.OnOpen();
                        }
                        slot.sessionOpen = 0;
                        slot.id = 0;
                        slot.resumable = 0;
                        //Приёмник ушедшего Internal может быть ещё на стеке этого вызова - он и привёл сюда. Слот,
                        //отданный в общий стек сейчас, мог бы достаться другому потоку и начать на том же Internal
                        //новую сессию. Поэтому он уходит домой, когда стек раскрутится.
                        if (0 < _appCall)
                            _departed = slot;
                        else
                            host.ReturnToFreePool(slot);
                    }
                }
                return identify(id);
            }

            ///<summary>
            ///Returns a string representation of the connection, including the host name and endpoint details.
            ///</summary>
            ///<returns>A string describing the connection's state and connection endpoints.</returns>
            public override string ToString() => IsActive ? $"[{index_}] {host.name} {ext!.LocalEndPoint}:{ext.RemoteEndPoint}" : $"[{index_}] {host.name} : closed";

            ///<summary>
            ///Gets the underlying <see cref="Socket"/> for this connection's connection. It is null if the connection is not connected.
            ///</summary>
            public Socket? ext;

            ///<summary>
            ///Address and port of this side of the socket, <c>null</c> when there is no socket. Nothing is kept and
            ///nothing is made: it is the object .NET holds for its socket - so it is gone the moment the socket is,
            ///which is the point. An application that needs the peer's address after the close takes it while the
            ///connection is up, in <see cref="AdHoc.Connection.Internal.OnOpen"/>, and keeps it where it needs it.
            ///</summary>
            public IPEndPoint local()
            {
                var s = ext;
                try
                {
                    return s == null ? null : s.LocalEndPoint as IPEndPoint;
                }
                catch (Exception closed) when (closed is SocketException or ObjectDisposedException)
                {
                    return null;
                }
            }

            ///<summary>Address and port of the peer, <c>null</c> when there is no socket - or none connected yet.</summary>
            public IPEndPoint remote()
            {
                var s = ext;
                try
                {
                    return s == null ? null : s.RemoteEndPoint as IPEndPoint;
                }
                catch (Exception closed) when (closed is SocketException or ObjectDisposedException)
                {
                    return null;
                }
            }

            ///<summary>
            ///Gets or sets the internal connection that provides data sources, destinations, and event handling logic.
            ///This property must be set via the <see cref="Init"/> method before communication can begin.
            ///</summary>
            public AdHoc.Connection.Internal Internal { get; set; }

            ///<summary>
            ///Initializes the external connection with its internal counterpart, linking it to the application logic.
            ///</summary>
            ///<param name="_internal">The internal connection implementation.</param>
            public void Init(AdHoc.Connection.Internal _internal) => Internal = _internal;

            ///<summary>
            ///The peer's address as <see cref="Server.max_per_address"/> knows it, or <c>0</c> while that limit is
            ///off - the teardown then costs one comparison. It is remembered here because by teardown time the socket
            ///is gone and nobody could ask it any more.
            ///</summary>
            protected internal long address;

            ///<summary>
            ///The timestamp (in Unix milliseconds) of the last successful data reception. A plain timestamp —
            ///the lifecycle lives in <see cref="conn_state"/>.
            ///</summary>
            public long receive_time;

            ///<summary>
            ///The timestamp (in Unix milliseconds) of the last successful data transmission.
            ///</summary>
            public long transmit_time;

            ///<summary>
            ///The lifecycle of this pooled connection object, and the reason a completion that arrives after a
            ///teardown cannot be mistaken for a live one:
            ///<list type="bullet">
            ///<item><see cref="FREE"/> — on the host's free stack, waiting to be handed out.</item>
            ///<item><see cref="ACTIVE"/> — a session is running on it.</item>
            ///<item><see cref="CLEANING"/> — the session is over and the socket is closed, but the kernel has
            ///not reported every operation it was given yet. The connection is NOT on the free stack, so it
            ///cannot be handed out; the buffers are NOT in the pool and the SAEAs may not be re-armed, because
            ///an operation may still be using them. <see cref="FinishDispose"/> releases everything and moves
            ///to <see cref="FREE"/> when the last operation reports — see <see cref="pending"/>.</item>
            ///</list>
            ///That draining state is the whole answer to "a completion of a session that is already gone":
            ///while it lasts, no new session can start here, so a late callback has nothing to damage — it
            ///just drops its reference and leaves.
            ///</summary>
            protected internal volatile int conn_state;

            protected internal const int FREE = 0, ACTIVE = 1, CLEANING = 2, PARKED = 3;

            ///<summary>
            ///<c>true</c> while this slot holds a session whose socket is gone and whose deadline has not passed: no socket,
            ///no buffers, on no stack, waiting for <see cref="activate"/> from the peer's next connection.
            ///</summary>
            public bool IsParked => conn_state == PARKED;

            ///<summary>
            ///Attempts to atomically take a <see cref="FREE"/> connection for a new session. On success the
            ///state is <see cref="ACTIVE"/>, <see cref="pending"/> holds the activation reference and both
            ///timestamps are stamped.
            ///</summary>
            ///<returns><c>true</c> if this caller won the connection.</returns>
            public bool IsActivateDeactivated()
            {
                var s = conn_state;
                if (s != FREE && s != PARKED || Interlocked.CompareExchange(ref conn_state, ACTIVE, s) != s)
                    return false;
                Interlocked.Increment(ref host._connectionsLive);
                pending = 1; //the activation reference — see pending
                receive_time = transmit_time = DateTimeOffset.UtcNow.ToUnixTimeMilliseconds();
                return true;
            }

            ///<summary>
            ///The <see cref="ACTIVE"/> → <see cref="CLEANING"/> transition: exactly one teardown wins it.
            ///</summary>
            protected bool TryDeactivate() => Interlocked.CompareExchange(ref conn_state, CLEANING, ACTIVE) == ACTIVE;

            ///<summary>
            ///Ends a parked session for good: its state is already CLEANING (set under the parked lock by
            ///<see cref="TCP.ReapParked"/>, or by a client before a stale reconnect). The close event the loss withheld is
            ///delivered now — the peer did not return in time — then the codecs are closed and the slot returns to the free stack.
            ///</summary>
            internal void Reap()
            {
                id = 0;
                resumable = 0;
                if (Internal != null)
                {
                    //Закрывающее событие ждало здесь: собеседник не вернулся, сессия кончилась. OnClose ему не
                    //положен - подключение кончилось ещё тогда, когда сессию парковали, там он и прозвучал.
                    Internal.OnExternalEvent(this, Event.REMOTE_CLOSE_ABRUPTLY);
                    Internal.BytesSrc?.Close();
                    Internal.BytesDst?.Close();
                    AdHoc.Connection.Keyring.Clear(Internal);
                }
                host.ReturnToFreePool(this);
            }

            ///<summary>
            ///The connection is gone. A loss that is not our own doing — a peer FIN, an error, or a timeout while we were
            ///not closing — parks the session for <see cref="AdHoc.Connection.Internal.resumable_minutes"/> when the peer is
            ///identified, and the close event is withheld until the wait runs out (see <see cref="Reap"/>). Our own graceful
            ///close, an <see cref="Abort"/>, or an unidentified peer end the session at once, delivering <paramref name="event"/> now.
            ///</summary>
            void Disconnected(Event @event)
            {
                if (Interlocked.Exchange(ref closing, 1) != 0)
                    return; //разрыв уже идёт: приём и передача завершаются на разных потоках и приходят сюда оба
                var loss = !isClosingGracefully && (@event.IsRemote() || @event.IsTimeout());
                var minutes = loss && id != 0 && Internal != null ? Internal.resumable_minutes(this, @event) : 0;
                resumable = minutes == 0 ? 0 : AdHoc.Connection.Transmitter.Resumable.now() + minutes;
                if (resumable == 0 && Internal != null)
                    Internal.OnExternalEvent(this, @event);
                CloseAndDispose(); //OnClose - там, под выигранным CAS: это единственная точка, общая всем путям разрыва
            }

            ///<summary>
            ///A teardown has begun: the closing event and <see cref="AdHoc.Connection.Internal.OnClose"/> belong to
            ///whoever raised this from 0, and to nobody else. Cleared in <see cref="FinishDispose"/>, so the slot -
            ///and a parked session that comes back to it - starts over.
            ///</summary>
            int closing;

            ///<summary>
            ///The connection is over for whoever sat on it: <see cref="AdHoc.Connection.Internal.OnClose"/>, once.
            ///Called where the ACTIVE -&gt; CLEANING race is already won, so every way a connection can end passes here
            ///exactly once - including the ones that never went through <see cref="Disconnected"/>, like an accepted
            ///socket found dead or a half-built client session.
            ///<para>A session being PARKED ends its connection too: the socket is gone and the peer will come back on
            ///a new one, which opens again. The close EVENT is a different matter - it is withheld until the wait runs
            ///out (<see cref="Reap"/>), because it says the session is finished, and that is not yet known.</para>
            ///</summary>
            void SessionClosed()
            {
                if (Interlocked.Exchange(ref sessionOpen, 0) != 1)
                    return;
                Internal?.OnClose();
            }

            ///<summary>
            ///<c>true</c> while a session is running on this connection.
            ///</summary>
            public bool IsActive => conn_state == ACTIVE;

            ///<summary>
            ///<c>true</c> while the connection is closed but still waiting for outstanding operations to
            ///report, so it can be neither handed out nor connected again yet.
            ///</summary>
            public bool IsCleaning => conn_state == CLEANING;

            ///<summary>
            ///How many things still hold this connection: one reference for the session itself, taken at
            ///activation, one for every socket operation handed to the kernel that has not reported back, and
            ///one for every thread currently inside an entry point that touches the buffers. Whoever brings it
            ///to zero runs <see cref="FinishDispose"/> — the <see cref="CLEANING"/> → <see cref="FREE"/>
            ///transition. That is what keeps the buffers out of the pool, and the SAEAs unarmed, while the
            ///kernel may still be writing into one of them.
            ///</summary>
            private protected volatile int pending;

            ///<summary>
            ///Takes one more reference on <see cref="pending"/> — but only if the connection still holds any:
            ///a count that reached zero has run <see cref="FinishDispose"/>, and incrementing it back would run
            ///the release a second time, pushing this connection onto the free stack twice. The one legal way
            ///to revive a zeroed counter is a fresh activation.
            ///</summary>
            ///<returns><c>true</c> if the reference was taken and must later be dropped via <see cref="ReleaseOp"/>.</returns>
            private protected bool TryRetain()
            {
                for (int p; (p = pending) != 0;)
                    if (Interlocked.CompareExchange(ref pending, p + 1, p) == p)
                        return true;
                return false;
            }

            private protected void ReleaseOp()
            {
                if (Interlocked.Decrement(ref pending) == 0)
                    FinishDispose();
            }

            ///<summary>
            ///Gets a reference to the parent <see cref="TCP"/> instance that manages this connection.
            ///</summary>
            public readonly TCP host;

            ///<summary>
            ///Initializes a new instance of the <see cref="ExternalConnection"/> class.
            ///</summary>
            ///<param name="host">The parent <see cref="TCP"/> instance that owns this connection.</param>
            public ExternalConnection(TCP host)
            {
                this.host = host;
                //This SAEA instance is primarily for sends, while ReceiveMate is for receives.
                //Both can trigger the same completion handler because SAEA operations are distinct.
                ReceiveMate.Completed += OnCompleted;
                DisconnectReuseSocket = true;
            }

            ///<summary>
            ///Implements <see cref="AdHoc.Connection.External.WakeTransmit"/>: activates the
            ///transmitter and runs the transmit loop. Called by the owning
            ///<see cref="AdHoc.Connection.Transmitter"/> on the queue-empty→non-empty edge of
            ///<c>sending_put</c>, by a backpressure-aware nested <see cref="AdHoc.BytesSrc"/>
            ///that has just deposited bytes into an armed slot, locally for WebSocket urgent
            ///frames (CLOSE/PING), and at backfill points in <see cref="receiver_connected"/>
            ///and <see cref="transmitterConnected"/>.
            ///</summary>
            ///<remarks>
            ///Volatile.Read ensures we see the write from Abort() on any CPU architecture.
            ///The null check is a fast exit only — transmit() performs its own per-call capture,
            ///which is the actual safety guarantee.
            ///</remarks>
            public void WakeTransmit()
            {
                if (IsActivateDeactivatedTransmitter())
                    ThreadPool.UnsafeQueueUserWorkItem(this, preferLocal: false); //the runner is taken: it runs on the pool, never on the caller
            }

            void IThreadPoolWorkItem.Execute() => transmit();

            ///<summary>
            ///Bytes from the last receive that <see cref="AdHoc.BytesDst.Write"/> refused.
            ///While <c>_pendingTailLength &gt; 0</c> the receive loop is paused —
            ///no further <c>ReceiveAsync</c> is issued until the destination signals space
            ///via <see cref="WakeReceive"/>. The tail lives in <see cref="ReceiveMate"/>'s
            ///buffer (untouched while paused).
            ///</summary>
            int _pendingTailOffset;
            int _pendingTailLength;

            //--- lost-wakeup-safe receive park/resume -------------------------------------------------------------
            //WakeReceive can fire from another thread (a downstream-aware sink signals it has space again)
            //and race the receive loop publishing its park. _flushing is a CAS gate making the tail-flush a single
            //flusher (guards against both a concurrent cross-thread flush and a reentrant one — Write →
            //WakeReceive). _rxParked is the published "loop has parked" state; exactly one of {receive loop,
            //WakeReceive} claims it (Interlocked.Exchange) and performs the single re-arm.
            int _flushing;          //0 = free, 1 = a DrainTail is in progress
            volatile int _rxParked; //1 = receive loop parked awaiting a wake; claimed → 0 by the re-armer
            //Eventcount for the single-flusher: every DrainTail bumps this BEFORE contending for _flushing. A caller
            //that loses the _flushing CAS still leaves its bump behind; the active flusher re-loops until the counter
            //is stable, so a wake is never dropped in the gap between a losing CAS and the owner releasing (e.g. a
            //cross-thread WakeReceive racing the receive's own retry).
            int _rxReq;

            ///<summary>Single-flusher drain of the stashed receive tail (still in <see cref="ReceiveMate"/>'s
            ///buffer). CAS-guards against a concurrent (cross-thread) or reentrant (Write→WakeReceive)
            ///second flush. Returns <c>true</c> iff the tail is now empty.</summary>
            bool DrainTail()
            {
                Interlocked.Increment(ref _rxReq); //register intent first — a concurrent owner observes it and re-loops
                if (Interlocked.CompareExchange(ref _flushing, 1, 0) != 0)
                    return false; //another flush owns the tail right now — it will carry our bumped request
                var drained = true;
                try
                {
                    for (;;)
                    {
                        var seen = Volatile.Read(ref _rxReq);
                        if (Volatile.Read(ref ext) == null)
                            drained = false;
                        else
                            for (;;)
                            {
                                var dst = noise != null ? noise : ActiveDst;
                                if (dst == null)
                                {
                                    drained = false;
                                    break;
                                }
                                var len = Volatile.Read(ref _pendingTailLength);
                                if (len == 0)
                                {
                                    drained = true;
                                    break;
                                }
                                var n = deliver(dst, ReceiveMate.Buffer!, _pendingTailOffset, len);
                                if (n == 0)
                                {
                                    drained = false;
                                    break;
                                } //still refusing — stay parked
                                if (n < 0)
                                {
                                    //The destination gave up on the stream: a parse error, or its handler reset it
                                    //mid-pack. Nothing after this point can be parsed any more, so these bytes are never
                                    //offered again, and the transport goes too — the destination usually tore it down
                                    //already; Abort is a no-op then. A negative count is not a length: added to the
                                    //offset it would re-offer the bytes shifted by one.
                                    Volatile.Write(ref _pendingTailLength, 0);
                                    Abort();
                                    drained = false;
                                    break;
                                }
                                _pendingTailOffset += n;
                                Volatile.Write(ref _pendingTailLength, len - n);
                            }
                        if (Interlocked.CompareExchange(ref _rxReq, 0, seen) == seen)
                            break; //no new request arrived during this drain → settled
                        //else a wake landed mid-drain → loop and drain again (the gate may now be open)
                    }
                }
                finally
                {
                    Volatile.Write(ref _flushing, 0);
                }
                if (Volatile.Read(ref _rxReq) != 0)
                    return DrainTail(); //a request raced our release → re-drive so it is not stranded
                return drained;
            }

            ///<summary>
            ///Hands the next receive to the kernel under its own <see cref="pending"/> reference.
            ///</summary>
            ///<returns><c>false</c> if the operation completed synchronously and the caller should process it
            ///inline (under its own custody); <c>true</c> if a completion callback owns the continuation — or
            ///nothing could be issued at all.</returns>
            bool IssueReceive()
            {
                if (!TryRetain())
                    return true; //the connection is gone
                var s = Volatile.Read(ref ext);
                if (s == null)
                {
                    ReleaseOp();
                    return true;
                }
                bool async;
                arm_receive(); //ожидание данных пошло: срок ведём сами, ОС асинхронную операцию не считает
                try
                {
                    async = s.ReceiveAsync(ReceiveMate);
                }
                catch (ObjectDisposedException)
                {
                    ReleaseOp();
                    return true; //closed in the gap — the teardown owns the rest
                }
                catch
                {
                    ReleaseOp();
                    throw;
                }
                if (async)
                    return true; //the completion callback owns the reference taken above
                ReleaseOp();     //completed synchronously — no callback will fire; continue inline
                return false;
            }

            void ReArmReceive()
            {
                receive_time = DateTimeOffset.UtcNow.ToUnixTimeMilliseconds();
                try
                {
                    if (!IssueReceive())
                        receive();
                }
                catch (Exception e)
                {
                    if (ext != null)
                        host.onFailure(this, e);
                }
            }

            ///<summary>
            ///Resumes the receive loop after a downstream-aware nested <see cref="AdHoc.BytesDst"/>
            ///signals space available. Drains the pending tail; if it fully drains AND the receive loop
            ///had committed to park, this call claims the (single-owner) re-arm. If the loop hasn't parked
            ///yet it re-arms itself; if the tail still refuses, stays paused for the next wake.
            ///</summary>
            public void WakeReceive()
            {
                if (Volatile.Read(ref _pendingTailLength) == 0)
                    return; //not paused (or nothing pending)
                if (!TryRetain())
                    return; //the connection is gone — nothing left to drain into
                try
                {
                    //The retain above is what lets this thread — often the OUTBOUND side of a relay — touch
                    //ReceiveMate.Buffer at all: it blocks FinishDispose() until the drain is out of it.
                    if (!DrainTail())
                        return; //still refusing, or another flush is carrying it — a later wake resumes
                    //Tail drained. Re-arm iff the loop had parked; the Exchange makes it single-owner against the
                    //loop's own re-check (so ReceiveAsync is never issued twice).
                    if (Interlocked.Exchange(ref _rxParked, 0) == 1)
                        ReArmReceive();
                }
                finally
                {
                    ReleaseOp();
                }
            }

            ///<summary>
            ///Gets a value indicating whether the communication connection is currently open and connected.
            ///Returns false if the connection has been deactivated or if the underlying socket is disconnected.
            ///</summary>
            ///<remarks>
            ///Snapshot <c>ext</c> once: <c>Abort()</c> may null the field between the null-check
            ///and the <c>Connected</c> property access, producing a NullReferenceException.
            ///</remarks>
            public bool IsOpen
            {
                get {
                    var s = ext;
                    return s != null && IsActive && s.Connected;
                }
            }
#region close
            ///<summary>
            ///Initiates a graceful shutdown of the connection.
            ///This method shuts down the send connection, signaling the remote peer that no more data will be sent.
            ///The connection remains open to receive data until the peer also closes its end, which is detected by a zero-byte read.
            ///</summary>
            public virtual void Close()
            {
                if (!IsActive)
                    return;
                isClosingGracefully = true;
                try
                {
                    ext?.Shutdown(SocketShutdown.Send);
                }
                catch (ObjectDisposedException)
                {
                    //a teardown on another thread disposed the socket after the IsActive check: it is closed already
                }
                catch (Exception e)
                {
                    host.onFailure(this, e);
                    Abort();
                }
            }

            ///<summary>
            ///A flag indicating whether a graceful shutdown has been initiated by this host.
            ///</summary>
            bool isClosingGracefully;

            ///<summary>
            ///Forcibly closes the socket connection by shutting down both send and receive streams and closing the socket.
            ///This is an internal helper for abrupt shutdowns that suppresses exceptions.
            ///</summary>
            protected void CloseInt()
            {
                isClosingGracefully = false; //Reset the flag, as this is an abrupt closure.
                try
                {
                    ext?.Shutdown(SocketShutdown.Both);
                }
                catch (Exception)
                { /* Ignored */
                }

                try
                {
                    ext?.Close();
                }
                catch (Exception)
                { /* Ignored */
                }
            }

            ///<summary>
            ///Abruptly terminates the connection and releases associated resources.
            ///Unlike a graceful close, this method does not wait for pending data and immediately closes the socket.
            ///</summary>
            public virtual void Abort()
            {
                isClosingGracefully = false;
                if (!IsActive)
                    return;
                //The event first, while the state is still ACTIVE — the completions our own socket close then
                //aborts arrive with the session already deactivated, so they are discarded instead of being
                //reported as a second teardown.
                Disconnected(Event.THIS_CLOSE_ABRUPTLY);
            }

            public void lost()
            {
                isClosingGracefully = false;
                if (!IsActive)
                    return;
                Disconnected(Event.REMOTE_CLOSE_ABRUPTLY); //a loss, not our close: the session parks when it may
            }

            ///<summary>
            ///Tears the session down: closes the socket, drops the per-session state and closes the codecs.
            ///The single teardown path — <see cref="Abort"/>, a failed operation, a peer FIN and the
            ///application all end here, and the CAS in <see cref="TryDeactivate"/> lets exactly one of them
            ///through.
            ///<para/>
            ///The buffers are NOT released and the SAEAs are NOT re-armed here: an operation the kernel has
            ///not reported yet may still be using them. That happens in <see cref="FinishDispose"/>, run by
            ///whoever drops the last <see cref="pending"/> reference.
            ///<para/>
            ///Internal teardown detail, not part of the public <see cref="AdHoc.Connection.External"/> contract
            ///(which exposes only <see cref="Close"/> and <see cref="Abort"/>) — matches the Java lib.
            ///</summary>
            internal void CloseAndDispose()
            {
                if (!TryDeactivate())
                    return;

                SessionClosed();
                Interlocked.Decrement(ref host._connectionsLive); //ровно один раз за сессию: ACTIVE -> CLEANING выигрывает только один
                var who = Interlocked.Exchange(ref address, 0);
                if (who != 0) //предел на адрес включён, и это подключение в нём считалось
                    host.release(who);

                CloseInt();
                ext = null;

                //A tunnel swap override (_swapDst) stays until FinishDispose: a receive the kernel has not reported yet
                //may still deliver the rest of a promoted body, and that belongs to the relay, not to the deserializer.

                OnDispose();

                ReleaseOp(); //drop the activation reference; the last holder runs FinishDispose()
            }

            ///<summary>
            ///Protocol-specific teardown, run inside <see cref="CloseAndDispose"/> while the buffers are still
            ///owned by this connection. <see cref="WebSocket"/> resets its framing state here.
            ///</summary>
            protected virtual void OnDispose() {}

            ///<summary>
            ///The last step of a teardown: returns the I/O buffers to the pool, restores the SAEAs and the
            ///transmit/receive scratch state to their freshly-constructed shape and hands the connection back
            ///to the free stack. Runs exactly once, on whichever thread drops the last <see cref="pending"/>
            ///reference — only then is it certain no operation and no thread is still using any of it.
            ///</summary>
            void FinishDispose()
            {
                if (Buffer != null)
                {
                    ArrayPool<byte>.Shared.Return(Buffer);
                    SetBuffer(null, 0, 0);
                }

                if (ReceiveMate.Buffer != null)
                {
                    ArrayPool<byte>.Shared.Return(ReceiveMate.Buffer);
                    ReceiveMate.SetBuffer(null, 0, 0);
                }

                RemoteEndPoint = null;

                _pendingTailOffset = 0;
                _pendingTailLength = 0;
                _rxParked = 0;
                _rxReq = 0;
                closing = 0; //слот снова чист: и для нового арендатора, и для вернувшегося собеседника
                _flushing = 0;
                maintenance_lock = 0; //a maintenance scheduled on the dead session is void

                //No receive runs any more: a relay promoted to take a whole body is told its packet was abandoned
                //(a relay still dispatched by id hears it from the receiver's reset, in the Close below).
                if (_swapDst is AdHoc.Connection.Tunnel.Relay relay)
                    relay.InboundLost();
                _swapDst = null;

                Internal?.BytesSrc?.Close();
                Internal?.BytesDst?.Close();

                if (resumable != 0)
                {
                    host.ParkConnection(this); //onto the parked list: the session waits for its peer to return
                    return;
                }
                AdHoc.Connection.Keyring.Clear(Internal); //the session is over: its pack keys go
                id = 0;
                host.ReturnToFreePool(this);
            }
