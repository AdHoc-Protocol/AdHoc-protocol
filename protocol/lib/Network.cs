                ///<summary>
                ///Asynchronously connects to a WebSocket server with a specified timeout.
                ///</summary>
                ///<param name="server">The URI of the WebSocket server.</param>
                ///<param name="connectingTimeout">The maximum time to wait for the connection to be established.</param>
                ///<returns>A task that represents the asynchronous connect operation. The task completes with the internal connection instance on success, or null on failure.</returns>
                ///<exception cref="InvalidOperationException">Thrown if a connection is already in progress or established.</exception>
                ///<example>
                ///<code>
                ///var client = new Client&lt;MyInternalConnection&gt;(
                ///    name: "MyClient",
                ///    newInternal: (ext) => new MyInternalConnection(ext),
                ///    onFailure: (sender, ex) => Console.WriteLine($"Failed: {ex.Message}")
                ///);
                ///
                ///var serverUri = new Uri("ws://localhost:8080");
                ///var timeout = TimeSpan.FromSeconds(5);
                ///try
                ///{
                ///    var internalConnection = await client.ConnectAsync(serverUri, timeout);
                ///    if (internalConnection != null)
                ///    {
                ///        Console.WriteLine($"Connected to {serverUri}");
                ///        // Use the internalConnection for communication
                ///    }
                ///}
                ///catch (Exception ex)
                ///{
                ///    Console.WriteLine($"Connection failed: {ex.Message}");
                ///}
                ///</code>
                ///</example>
                ///<param name="serverKey">The server's static public key, 32 bytes: the connection is encrypted end to end
                ///inside the WebSocket - over ws:// and wss:// alike. null - not encrypted.</param>
                public Task<INT> ConnectAsync(Uri server, TimeSpan connectingTimeout, byte[]? serverKey = null)
                {
                    if (serverKey != null && serverKey.Length != X25519.KEY)
                        throw new ArgumentException("A server key is 32 bytes.", nameof(serverKey));
                    this.serverKey = serverKey?.ToArray();
                    //Use Interlocked to prevent race conditions on the connection flag
                    if (Interlocked.CompareExchange(ref _isConnecting, 1, 0) == 1 || ws?.State == WebSocketState.Open)
                    {
                        var ex = new InvalidOperationException("Connection already in progress or established.");
                        _onFailure(this, ex);
                        throw ex;
                    }

                    var connectionTcs = new TaskCompletionSource<INT?>();

                    //Start the actual connection logic in a background task so this method can return the Task immediately.
                    _ = ConnectInternalAsync(server, connectingTimeout, connectionTcs);

                    return connectionTcs.Task;
                }

                ///<summary>
                ///Asynchronously connects to a WebSocket server with a default 5-second timeout.
                ///</summary>
                ///<param name="server">The URI of the WebSocket server.</param>
                ///<returns>A task that represents the asynchronous connect operation. The task completes with the internal connection instance on success, or null on failure.</returns>
                public Task<INT?> ConnectAsync(Uri server) => ConnectAsync(server, TimeSpan.FromSeconds(5));

                ///<summary>
                ///This connection's <see cref="AdHoc.Connection.Internal"/> has heard
                ///<see cref="AdHoc.Connection.Internal.OnOpen"/> and not yet <see cref="AdHoc.Connection.Internal.OnClose"/>.
                ///Events are the detail - every socket, every cause; the two hooks are the opposite: no detail, exactly
                ///once each per session. Here the session is the upgrade, so it opens with the 101 and ends when the
                ///receive loop does.
                ///</summary>
                int _sessionOpen;

                void SessionOpened()
                {
                    if (Interlocked.Exchange(ref _sessionOpen, 1) == 0)
                        Internal.OnOpen();
                }

                void SessionClosed()
                {
                    if (Interlocked.Exchange(ref _sessionOpen, 0) == 1)
                        Internal.OnClose();
                }

                ///<summary>
                ///Waits for <paramref name="operation"/>, asking the application when the wait runs out instead of
                ///ending the session on the spot: a timeout is a question before it is a verdict - the silence may
                ///already have been answered with a heartbeat - and only an answer of 0 or less closes the connection.
                ///The answer holds for this one wait; the next starts from <see cref="ReceiveTimeout"/> again.
                ///<para>The operation itself is never cancelled by the deadline. Cancelling a
                ///<see cref="ClientWebSocket"/> operation aborts the socket, and then no answer could keep the session
                ///alive - the question would be a formality.</para>
                ///</summary>
                ///<returns><c>false</c> - the wait ran out and the application would wait no longer.</returns>
                async Task<bool> await_within(Task operation, bool receiving)
                {
                    var ms = receiving ? _receiveTimeout : _transmitTimeout;
                    while (true)
                    {
                        if (ms <= 0 || ms == int.MaxValue)
                        {
                            await operation; //ничего не ждём - ждём сколько угодно
                            return true;
                        }
                        using var beat = new CancellationTokenSource();
                        if (operation == await Task.WhenAny(operation, Task.Delay(ms, beat.Token)))
                        {
                            beat.Cancel(); //убрать таймер, чтобы он не дожил до своего срока впустую
                            await operation;
                            return true;
                        }
                        var more = receiving ? Internal!.OnReceiveTimeout() : Internal!.OnTransmitTimeout();
                        if (0 < more)
                        {
                            ms = more;
                            continue;
                        }
                        Internal!.OnExternalEvent(this, receiving ? Event.WEBSOCKET_RECEIVE_TIMEOUT : Event.WEBSOCKET_TRANSMIT_TIMEOUT);
                        _ = operation.ContinueWith(t => _ = t.Exception, TaskContinuationOptions.OnlyOnFaulted | TaskContinuationOptions.ExecuteSynchronously);
                        return false;
                    }
                }

                ///<summary>
                ///Internal method to handle the actual connection logic and manage the TaskCompletionSource.
                ///</summary>
                async Task ConnectInternalAsync(Uri server, TimeSpan connectingTimeout, TaskCompletionSource<INT?> tcs)
                {
                    try
                    {
                        _transmitLock = 1;

                        using var connectCts = new CancellationTokenSource(connectingTimeout);
                        using var linkedConnectCts = CancellationTokenSource.CreateLinkedTokenSource(_cts.Token, connectCts.Token);

                        PeerIp = server;
                        await ws!.ConnectAsync(server, linkedConnectCts.Token);
                        noise = serverKey == null ? null : NoiseStream.Client(serverKey, () => Internal?.BytesSrc, () => Internal?.BytesDst, WakeTransmit, k => AdHoc.Connection.Keyring.Seat(Internal, k));

                        _toString = null; //built on demand: finding the local end walks every TCP connection of the machine

                        //Signal success BEFORE starting I/O so caller's await
                        //completes before background tasks fire
                        tcs.SetResult(inner);

                        Internal.OnExternalEvent(this, Event.WEBSOCKET_THIS_CONNECT);
                        SessionOpened();

                        Interlocked.Exchange(ref _transmitLock, 0);

                        //Backfill: anything enqueued during the connect handshake kicked
                        //WakeTransmit() while _transmitLock held the loop down.
                        //Drain it now.
                        WakeTransmit();
                        _ = Task.Run(ReceiveToInternal, _cts.Token);
                    }
                    catch (Exception ex)
                    {
                        _onFailure(this, ex);
                        _toString = $"{_name} : connection failed";
                        ws?.Dispose();
                        ws = null;

                        tcs.SetException(ex);
                    }
                    finally
                    {
                        Interlocked.Exchange(ref _isConnecting, 0);
                    }
                }

                ///<summary>
                ///Helper to find the local endpoint of a TCP connection. This is a best-effort attempt.
                ///</summary>
                string GetLocalEndpoint(Uri server)
                {
                    try
                    {
                        var remoteIPs = Dns.GetHostAddresses(server.DnsSafeHost);
                        var properties = IPGlobalProperties.GetIPGlobalProperties();
                        var localEndPoint = properties.GetActiveTcpConnections()
                                                .FirstOrDefault(c => c.RemoteEndPoint.Port == server.Port && remoteIPs.Contains(c.RemoteEndPoint.Address))
                                                ?.LocalEndPoint;
                        return localEndPoint?.ToString() ?? "local:unknown";
                    }
                    catch
                    {
                        return "local:unknown";
                    }
                }

                ///<summary>The buffer used for sending data.</summary>
                byte[] transmitBuffer;

                ///<summary>
                ///Implements <see cref="AdHoc.Connection.External.WakeTransmit"/>: the transmitter
                ///loop that reads from the internal source and sends data over the WebSocket.
                ///Called by the owning <see cref="AdHoc.Connection.Transmitter"/> when new bytes
                ///are ready.
                ///</summary>
                public async void WakeTransmit()
                {
                    //Acquire lock to ensure only one send loop runs at a time.
                    if (Interlocked.Exchange(ref _transmitLock, 1) == 1)
                    {
                        return;
                    }

                    try
                    {
                        if (ws?.State != WebSocketState.Open)
                            return;

                        int bytesRead;
                        while (0 < (bytesRead = (noise != null ? noise : Internal.BytesSrc!).Read(transmitBuffer, 0, transmitBuffer.Length)))
                        {
                            try
                            {
                                if (!await await_within(ws.SendAsync(new ReadOnlyMemory<byte>(transmitBuffer, 0, bytesRead), WebSocketMessageType.Binary, true, _cts.Token).AsTask(), false))
                                    break; //ожидание вышло, и приложение решило больше не ждать
                            }
                            catch (OperationCanceledException) when (!_cts.IsCancellationRequested)
                            {
                                break; //Exit the while loop
                            }
                        }
                    }
                    catch (WebSocketException ex) //Catches specific network/protocol errors
                    {
                        //This is the most likely exception for a genuine network failure or
                        //if the remote peer closes the connection without a proper WS close handshake.
                        //The event system is the correct way to signal this state change.
                        Internal!.OnExternalEvent(this, Event.WEBSOCKET_REMOTE_CLOSE_ABRUPTLY);

                        //Optionally, you might still want to log this for diagnostics.
                        //_onFailure(this, ex);
                    }
                    catch (Exception e) //Catch-all for truly unexpected application errors
                    {
                        //This indicates a potential bug or unexpected state (e.g., NullReferenceException).
                        //Report this specific failure for logging/debugging.
                        _onFailure(this, e);

                        //Also signal that the connection is no longer viable.
                        Internal!.OnExternalEvent(this, Event.WEBSOCKET_THIS_CLOSE_ABRUPTLY);
                    }
                    finally
                    {
                        Interlocked.Exchange(ref _transmitLock, 0); //Release lock
                        if (_isClosingGracefully)
                            Close();
                    }
                }

                ///<summary>The buffer used for receiving data.</summary>
                byte[] receiveBuffer;

                ///<summary>
                ///Bytes from the last <c>ws.ReceiveAsync</c> that <see cref="AdHoc.BytesDst.Write"/>
                ///refused. Stashed in <see cref="_tailStash"/> while <c>_pendingTailLength &gt; 0</c>,
                ///the receive loop is paused at <see cref="_receiveResume"/> until
                ///<see cref="WakeReceive"/> drains the tail.
                ///</summary>
                byte[]? _tailStash;
                int _pendingTailOffset;
                int _pendingTailLength;
                TaskCompletionSource<bool>? _receiveResume;
                ///<summary>Serializes the drains of the tail: the receive loop and the destination's wakes may offer it at once.</summary>
                readonly object _tailLock = new();
                bool _draining, _drainAgain; //under _tailLock

                ///<summary>
                ///The receiver loop that reads from the WebSocket and writes data to the internal destination.
                ///Honors short writes from a backpressure-aware <see cref="AdHoc.BytesDst"/>: when the
                ///destination refuses some bytes, the unwritten tail is stashed and the loop awaits
                ///<see cref="WakeReceive"/> before continuing.
                ///</summary>
                async Task ReceiveToInternal()
                {
                    try
                    {
                        await ReceiveLoop();
                    }
                    finally
                    {
                        SessionClosed(); //поток приёма кончился - кончилась и сессия
                    }
                }

                async Task ReceiveLoop()
                {
                    while (!_cts.Token.IsCancellationRequested && ws?.State == WebSocketState.Open)
                        try
                        {
                            //If a previous iteration left a pending tail, await WakeReceive before
                            //pulling more bytes off the socket.
                            while (Volatile.Read(ref _pendingTailLength) > 0)
                            {
                                var tcs = new TaskCompletionSource<bool>(TaskCreationOptions.RunContinuationsAsynchronously);
                                Volatile.Write(ref _receiveResume, tcs);
                                //The destination may have made room between refusing the bytes and the tail being published:
                                //its WakeReceive then found nothing pending and nobody would ever wake this loop. Offer the
                                //tail once more now that it is published; a later refusal is woken by the destination.
                                WakeReceive();
                                if (Volatile.Read(ref _pendingTailLength) > 0)
                                    await tcs.Task.WaitAsync(_cts.Token);
                                Volatile.Write(ref _receiveResume, null);
                            }

                            var pending = ws.ReceiveAsync(new ArraySegment<byte>(receiveBuffer), _cts.Token);
                            if (!await await_within(pending, true))
                                break; //ожидание вышло, и приложение решило больше не ждать
                            var result = await pending;
                            if (result.MessageType == WebSocketMessageType.Close)
                            {
                                await ws.CloseAsync(WebSocketCloseStatus.NormalClosure, "Peer closed connection", CancellationToken.None);
                                Internal!.OnExternalEvent(this, Event.WEBSOCKET_REMOTE_CLOSE_GRACEFUL);
                                return;
                            }

                            var accepted = (noise != null ? noise : Internal!.BytesDst!).Write(receiveBuffer, 0, result.Count);
                            if (accepted < 0) //the destination gave up on the stream: nothing that follows can be parsed
                            {
                                Internal!.OnExternalEvent(this, Event.WEBSOCKET_THIS_CLOSE_ABRUPTLY); //the application hears the end, as after any abort
                                Abort();
                                break;
                            }

                            if (accepted < result.Count)
                            {
                                //Stash the unwritten tail in a dedicated buffer so the next
                                //ReceiveAsync can reuse receiveBuffer once we resume.
                                var remaining = result.Count - accepted;
                                if (_tailStash == null || _tailStash.Length < remaining)
                                    _tailStash = new byte[Math.Max(remaining, receiveBuffer.Length)];
                                Array.Copy(receiveBuffer, accepted, _tailStash, 0, remaining);
                                _pendingTailOffset = 0;
                                Volatile.Write(ref _pendingTailLength, remaining);
                            }
                        }
                        catch (OperationCanceledException)
                        {
                            break; //сроки ожиданий сюда больше не приходят - только отмена всего подключения
                        }
                        catch (ObjectDisposedException)
                        {
                            break; //the client was torn down under the loop: its end, not a failure
                        }
                        catch (Exception e)
                        {
                            if (!_cts.IsCancellationRequested)
                                Internal!.OnExternalEvent(this, Event.WEBSOCKET_REMOTE_CLOSE_ABRUPTLY);

                            _onFailure(this, e);
                        }
                }

                ///<summary>
                ///Implements <see cref="AdHoc.Connection.External.WakeReceive"/>: drains the stashed
                ///tail into the destination; if fully drained, unblocks <see cref="ReceiveToInternal"/>.
                ///</summary>
                public void WakeReceive()
                {
                    if (Volatile.Read(ref _pendingTailLength) == 0)
                        return;
                    lock (_tailLock)
                    {
                        //The lock is re-entrant: a destination that wakes the receive from inside its Write, on this
                        //thread, only asks for another round - the tail is never offered twice at once.
                        if (_draining)
                        {
                            _drainAgain = true;
                            return;
                        }
                        _draining = true;
                        try
                        {
                            do
                            {
                                _drainAgain = false;
                                DrainTail();
                            } while (_drainAgain && Volatile.Read(ref _pendingTailLength) > 0);
                        }
                        finally
                        {
                            _draining = false;
                        }
                    }
                }

                ///<summary>Offers the stashed tail to the destination; under <see cref="_tailLock"/>.</summary>
                void DrainTail()
                {
                    var len = Volatile.Read(ref _pendingTailLength);
                    if (len == 0 || _tailStash == null)
                        return;
                    var dst = noise != null ? noise : Internal?.BytesDst;
                    if (dst == null)
                        return;
                    var n = dst.Write(_tailStash, _pendingTailOffset, len);
                    if (n < 0) //the destination gave up on the stream: drop the tail, end the connection, release the loop
                    {
                        Volatile.Write(ref _pendingTailLength, 0);
                        Internal?.OnExternalEvent(this, Event.WEBSOCKET_THIS_CLOSE_ABRUPTLY);
                        Abort();
                        Volatile.Read(ref _receiveResume)?.TrySetResult(true);
                        return;
                    }

                    _pendingTailOffset += n;
                    var remaining = len - n;
                    Volatile.Write(ref _pendingTailLength, remaining);
                    if (remaining > 0)
                        return; //still refusing — stay paused
                    Volatile.Read(ref _receiveResume)?.TrySetResult(true);
                }

                ///<summary>
                ///Asynchronously disconnects the client and releases resources.
                ///</summary>
                ///<returns>A task that represents the asynchronous disconnect operation.</returns>
                public async Task DisconnectAsync()
                {
                    if (_cts.IsCancellationRequested)
                        return;
                    _cts.Cancel();
                    _toString = $"{_name} : disconnected";
                    if (ws?.State == WebSocketState.Open)
                    {
                        try
                        {
                            using var closeTimeoutCts = new CancellationTokenSource(TimeSpan.FromSeconds(5));
                            await ws.CloseAsync(WebSocketCloseStatus.NormalClosure, "Client disconnecting", closeTimeoutCts.Token);
                        }
                        catch (Exception)
                        {
                            //Ignore exceptions during close, as the goal is to disconnect.
                        }
                    }

                    ws?.Dispose();
                    ws = null;
                    SessionClosed(); //если поток приёма так и не запускался
                }

                ///<summary>
                ///Returns a string representing the current state of the client.
                ///</summary>
                ///<returns>A string with the client's name and connection status.</returns>
                public override string ToString() => _toString ??= $"{_name} {GetLocalEndpoint(PeerIp)} : {PeerIp}";
            }

            ///<summary>
            ///Defines bitmasks for parsing the first two bytes of a WebSocket frame header, as specified in RFC 6455.
            ///</summary>
            internal enum Mask
            {
                ///<summary>Bitmask for the FIN flag, indicating the final fragment of a message.</summary>
                FIN = 0b1000_0000,

                ///<summary>Bitmask to extract the opcode from the first byte of a frame.</summary>
                OPCODE = 0b0000_1111,

                ///<summary>Bitmask for the MASK flag, indicating if the payload is masked.</summary>
                MASK = 0b1000_0000,

                ///<summary>Bitmask to extract the initial payload length from the second byte of a frame.</summary>
                LEN = 0b0111_1111
            }

            ///<summary>
            ///Defines the standard WebSocket frame opcodes as specified in RFC 6455.
            ///</summary>
            public enum OPCode
            {
                ///<summary>Denotes a continuation frame for a fragmented message.</summary>
                CONTINUATION = 0x00,

                ///<summary>Denotes a text frame containing UTF-8 encoded data.</summary>
                TEXT_FRAME = 0x01,

                ///<summary>Denotes a binary frame containing arbitrary binary data.</summary>
                BINARY_FRAME = 0x02,

                ///<summary>Denotes a connection close frame.</summary>
                CLOSE = 0x08,

                ///<summary>Denotes a ping frame for heartbeat/keep-alive.</summary>
                PING = 0x09,

                ///<summary>Denotes a pong frame, typically a response to a ping.</summary>
                PONG = 0x0A
            }

            ///<summary>
            ///Defines the states for the WebSocket frame parsing state machine.
            ///</summary>
            internal enum State
            {
                ///<summary>Initial state, processing the HTTP handshake before WebSocket framing begins.</summary>
                HANDSHAKE = 0,

                ///<summary>Ready to parse the first byte of a new WebSocket frame.</summary>
                NEW_FRAME = 1,

                ///<summary>Parsing the second byte, which contains the MASK flag and initial payload length.</summary>
                PAYLOAD_LENGTH_BYTE = 2,

                ///<summary>Parsing the 2 or 8 extended payload length bytes (if initial length is 126 or 127).</summary>
                PAYLOAD_LENGTH_BYTES = 3,

                ///<summary>Parsing the first byte of the 4-byte masking key.</summary>
                XOR0 = 4,

                ///<summary>Parsing the second byte of the 4-byte masking key.</summary>
                XOR1 = 5,

                ///<summary>Parsing the third byte of the 4-byte masking key.</summary>
                XOR2 = 6,

                ///<summary>Parsing the fourth byte of the 4-byte masking key.</summary>
                XOR3 = 7,

                ///<summary>Unmasking the payload of a data frame (BINARY, TEXT, CONTINUATION).</summary>
                DATA = 8,

                ///<summary>Collecting the payload of a PING or CLOSE, answered once it is complete.</summary>
                CONTROL = 9,

                ///<summary>Skipping the payload of a PONG.</summary>
                DISCARD = 10
            }
        }

