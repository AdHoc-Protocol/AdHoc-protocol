    ///<summary>
    ///Defines the base action types for events.
    ///</summary>
    ///<summary>
    ///WHAT happened: one BIT per kind, in the low 16 bits - so an event may be two things at once, and every question
    ///about it is a single AND. <see cref="CONNECT"/> and <see cref="CLOSE"/> are the lifecycle; the rest is
    ///information that changes nothing.
    ///<para>The stream of one connection:</para>
    ///<code>
    ///CONNECT   [READY]   { PING | PONG | EMPTY_FRAME }*   [HANDSHAKE_FAILURE | PROTOCOL_ERROR]   [CLOSING]   CLOSE
    ///</code>
    ///CONNECT comes first and once per socket; CLOSE comes last and once per connection, whatever ended it - the
    ///<see cref="Mask"/> bits say what did. Whatever must be undone when a connection ends hangs on CLOSE alone.
    ///</summary>
    public static class Action
    {
        ///<summary>The socket is up: the first event of a connection.</summary>
        public const int CONNECT = 1;

        ///<summary>The end: the last event of a connection, whatever ended it - a timeout included.</summary>
        public const int CLOSE = 1 << 1;

        ///<summary>The protocol above the socket is up - the WebSocket upgrade is done.</summary>
        public const int READY = 1 << 2;

        ///<summary>A closing handshake is under way; the connection is still there.</summary>
        public const int CLOSING = 1 << 3;
        public const int PING = 1 << 4;
        public const int PONG = 1 << 5;
        public const int EMPTY_FRAME = 1 << 6;
        public const int HANDSHAKE_FAILURE = 1 << 7;
        public const int PROTOCOL_ERROR = 1 << 8;

        ///<summary>Gets a human-readable description of the base action part of an event code.</summary>
        ///<returns>A string describing the action.</returns>
        public static string GetDescription(int evenT)
        {
            if ((evenT & Mask.TIMEOUT) != 0)
                return "Closed by timeout";
            if ((evenT & CONNECT) != 0)
                return "Connection established";
            if ((evenT & CLOSE) != 0)
                return "Connection terminated";
            if ((evenT & READY) != 0)
                return "Upgrade done";
            if ((evenT & CLOSING) != 0)
                return "Closing handshake";
            if ((evenT & PING) != 0)
                return "Ping received";
            if ((evenT & PONG) != 0)
                return "Pong received";
            if ((evenT & EMPTY_FRAME) != 0)
                return "Empty frame received";
            if ((evenT & HANDSHAKE_FAILURE) != 0)
                return "Handshake failure";
            if ((evenT & PROTOCOL_ERROR) != 0)
                return "Protocol error";
            return "Unknown action";
        }
    }

    ///<summary>
    ///Defines the bitmasks used to encode event properties.
    ///</summary>
    public static class Mask
    {
        //--- Source Flags (Bits 31-30) ---
        public const int THIS = 0;
        public const int REMOTE = 1 << 31;

        //--- Manner Flags (Bits 29-28) ---
        public const int GRACEFUL = 1 << 30;
        public const int ABRUPT = 1 << 29;

        //--- I/O Direction Flags (Bits 27-26) ---
        public const int TRANSMIT = 1 << 28;
        public const int RECEIVE = 1 << 27;

        //--- Protocol/Context Flags (Bit 25) ---
        public const int WEBSOCKET = 1 << 26;

        ///<summary>A deadline ran out and nobody extended it: the reason of an <see cref="Action.CLOSE"/>.</summary>
        public const int TIMEOUT = 1 << 25;

        //--- Action Mask ---
        public const int ACTION = 0xFFFF;
    }
