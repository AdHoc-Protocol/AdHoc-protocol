        ///<summary>
        ///Implements a TCP client for establishing a single outgoing connection.
        ///This client uses the high-performance SocketAsyncEventArgs pattern internally but exposes a modern async/await (TAP) interface.
        ///</summary>
        public class Client<INT> : TCP
            where INT : class, AdHoc.Connection.Internal
        {
            readonly ExternalConnection connection; //Single persistent connection for client

            ///<summary>The Internal of the one connection: what ConnectAsync answers with.</summary>
            readonly INT inner;

            ///<summary>The server port is multiplexed: the connection rests standing in for its Internal, so every socket
            ///opens with the byte naming the connection.</summary>
            readonly bool mux;

            ///<summary>
            ///The client's single connection is never pooled — a finished teardown just marks it reusable.
            ///</summary>
            protected internal override void ReturnToFreePool(ExternalConnection conn)
            {
                if (mux && conn.Internal != conn)
                { //the next socket opens with the byte naming the connection: the connection stands in again
                    conn.outgoing = conn.Internal;
                    conn.Internal = conn;
                }
                conn.conn_state = ExternalConnection.FREE;
                Interlocked.Exchange(ref released, null)?.TrySetResult(); //a reconnect waiting for this slot goes on
            }

            ///<summary>A reconnect that found the previous session still being released waits here for the slot's return.</summary>
            TaskCompletionSource? released;

            ///<summary>What ToString() says: a constant phase and the server - formatted only on demand.</summary>
            string? phase;

            IPEndPoint? peer;

            volatile bool _isConnecting;

            ///<summary>Gets a value indicating whether a connection attempt is currently in progress.</summary>
            public bool isConnecting => _isConnecting;

            ///<summary>Gets a value indicating whether the client is currently connected to the server.</summary>
            public bool isConnected => connection.IsActive;

            ///<summary>
            ///Initializes a new instance of the <see cref="Client{INT}"/> class.
            ///</summary>
            ///<param name="name">The name of the client for identification.</param>
            ///<param name="newInternal">A factory that creates the internal connection implementation for the client's connection.</param>
            ///<param name="onFailure">A callback for handling failures during network operations.</param>
            ///<param name="bufferSize">The buffer size for socket operations.</param>
            public Client(string name,
                          Func<AdHoc.Connection.External, INT> newInternal,
                          Action<object, Exception> onFailure, int bufferSize = 1024, bool mux = false)
                : base(name, host => new ExternalConnection(host), onFailure, bufferSize)
            {
                //In client mode, we initialize only the first slot of the registry
                //1. Manually create the connection
                connection = NewConnection(this);

                //2. Put it in the registry so Shutdown and Maintenance can see it
                _connections[0] = connection;
                Volatile.Write(ref _connectionsSize, 1);

                //3. Link the internal logic
                connection.Init(inner = newInternal(connection));
                inner.External(connection); //the Internal learns its connection: a generated one has no constructor for it
                if (this.mux = mux)
                { //the port is multiplexed: the connection stands in for its Internal until the first byte is out
                    connection.outgoing = inner;
                    connection.Internal = connection;
                }

                //4. The maintenance pass of one connection: its deadlines, and the parked session waiting for its peer.
                //   Without it nothing would ever ask the clock on this side.
                Task.Run(async () =>
                         {
                             while (true)
                                 try
                                 {
                                     var wait = (long)maintenance_duty_cycle;
                                     if (connection.IsActive)
                                         wait = Math.Min(wait, connection.deadlines());
                                     wait = Math.Max(1, Math.Min(wait, ReapParked()));
                                     deadline_planned(DateTimeOffset.UtcNow.ToUnixTimeMilliseconds() + wait);
                                     await maintenance_wake.WaitAsync((int)wait);
                                 }
                                 catch (Exception ex)
                                 {
                                     onFailure(this, ex);
                                 }
                         });
            }

            ///<summary>Wakes this client's maintenance pass.</summary>
            public override void TriggerMaintenance() => wake();

            ///<summary>
            ///Initializes a new instance of the <see cref="Client{INT}"/> class with a default failure handler.
            ///</summary>
            ///<param name="name">The name of the client for identification.</param>
            ///<param name="newInternal">A factory that creates the internal connection implementation for the client's connection.</param>
            ///<param name="bufferSize">The buffer size for socket operations.</param>
            public Client(string name, Func<AdHoc.Connection.External, INT> newInternal, int bufferSize = 1024) : this(name, newInternal, onFailurePrintConsole, bufferSize) {}

            ///<summary>
            ///Asynchronously connects to a TCP server with a configurable timeout and cancellation support.
            ///</summary>
            ///<param name="server">The remote server's IP endpoint.</param>
            ///<param name="connectingTimeout">The timeout duration for the connection attempt.</param>
            ///<param name="cancellationToken">A token to cancel the connection attempt.</param>
            ///<returns>A task that returns the internal connection implementation on a successful connection.</returns>
            ///<exception cref="InvalidOperationException">Thrown if a connection is already active or in progress.</exception>
            ///<exception cref="SocketException">Thrown if the connection fails due to a socket error.</exception>
            ///<exception cref="OperationCanceledException">Thrown if the operation is canceled by the token or if it times out.</exception>
            ///<example>
            ///<code>
            ///var client = new Client&lt;MyInternalConnection&gt;(
            ///    name: "MyClient",
            ///    newInternal: (ext) => new MyInternalConnection(ext),
            ///    onFailure: (sender, ex) => Console.WriteLine($"Failed: {ex.Message}")
            ///);
            ///
            ///var server = new IPEndPoint(IPAddress.Loopback, 8080);
            ///var timeout = TimeSpan.FromSeconds(5);
            ///try
            ///{
            ///    var internalConnection = await client.ConnectAsync(server, timeout);
            ///    Console.WriteLine($"Connected to {server}");
            ///    // Use the internalConnection for communication
            ///}
            ///catch (Exception ex)
            ///{
            ///    Console.WriteLine($"Connection failed: {ex.Message}");
            ///}
            ///</code>
            ///</example>
            ///<param name="serverKey">The server's static public key, 32 bytes: the connection is encrypted, and only the
            ///server holding its secret can talk on it. null - not encrypted.</param>
            public async Task<INT> ConnectAsync(IPEndPoint server, TimeSpan connectingTimeout,
                                                CancellationToken cancellationToken = default, byte[]? serverKey = null)
            {
                if (isConnected)
                    throw new InvalidOperationException("Connection already established.");
                if (serverKey != null && serverKey.Length != X25519.KEY)
                    throw new ArgumentException("A server key is 32 bytes.", nameof(serverKey));
                connection.serverKey = serverKey?.ToArray();
                if (connection.IsCleaning)
                {
                    //Прошлая сессия закрыта, но ядро отчиталось ещё не по всем её операциям: отдать новой сессии
                    //буферы, которые кто-то, может быть, ещё заполняет, нельзя. Ждём разрыва, а не отказываем -
                    //приложению естественно звать connect() прямо из своего OnClose. Ждём сигнала возврата слота
                    //(ReturnToFreePool), а не таймера: Task.Delay(1) на Windows - это тик в ~15.6 мс.
                    var waiter = new TaskCompletionSource(TaskCreationOptions.RunContinuationsAsynchronously);
                    Volatile.Write(ref released, waiter);
                    if (connection.IsCleaning) //FREE is published before the waiter is signalled: no wake-up is lost
                        try
                        {
                            await waiter.Task.WaitAsync(TimeSpan.FromSeconds(5), cancellationToken);
                        }
                        catch (TimeoutException)
                        {
                            throw new InvalidOperationException("The previous connection is still being released. Retry once it is done.");
                        }
                    Volatile.Write(ref released, null);
                }
                if (isConnecting)
                    throw new InvalidOperationException("A connection attempt is already in progress.");
                if (connection.IsParked)
                {
                    parked(connection.session()); //off the parked list: the reconnect owns it now
                    if (connection.resumable <= AdHoc.Connection.Transmitter.Resumable.now())
                    {
                        //The wait elapsed while we were away: drop the stale session and reconnect fresh.
                        connection.conn_state = ExternalConnection.CLEANING;
                        connection.Reap();
                    }
                    //else: the parked session is kept — the ACTIVE flip on connect continues it.
                }

                _isConnecting = true;
                try
                {
                    ResetConnectionState();
                    phase = " : connecting to ";
                    peer = server;

                    var socket = new Socket(server.AddressFamily, SocketType.Stream, ProtocolType.Tcp);

                    try
                    {
                        using var cts = CancellationTokenSource.CreateLinkedTokenSource(cancellationToken);
                        cts.CancelAfter(connectingTimeout);

                        await socket.ConnectAsync(server, cts.Token);

                        //The socket is up: take the session — the state goes ACTIVE and with it the reference
                        //that keeps the buffers and this connection held until every operation has reported.
                        if (!connection.IsActivateDeactivated())
                            throw new InvalidOperationException("The connection was not free when its socket connected.");

                        try
                        {
                            connection.transmitterConnected(socket);
                        }
                        catch
                        {
                            connection.CloseAndDispose(); //full teardown of the half-built session
                            throw;
                        }
                        phase = " : connected to ";
                        return inner;
                    }
                    catch (Exception ex)
                    {
                        socket.Close(); //Ensure socket is closed on any failure.
                        ResetConnectionState();
                        if (connection.resumable != 0)
                            ParkConnection(connection); //a parked session whose peer is still unreachable goes back on the parked list: the reaper keeps its deadline
                        phase = " : connection failed to ";
                        onFailure(this, ex); //Report the failure.
                        throw;               //Re-throw the exception to the caller.
                    }
                }
                finally
                {
                    _isConnecting = false;
                }
            }

            ///<summary>
            ///Abruptly disconnects the client from the server (TCP RST may be sent; pending data is dropped).
            ///For a graceful close that flushes pending bytes and waits for the peer's FIN, use
            ///<see cref="DisconnectGracefully"/> instead.
            ///</summary>
            public void Disconnect()
            {
                if (isConnected)
                {
                    connection.Abort();
                    ResetConnectionState();
                    phase = " : disconnected";
                    peer = null;
                }
            }

            ///<summary>
            ///Asynchronously, abruptly disconnects the client from the server. Counterpart of
            ///<see cref="Disconnect"/>. For graceful, see <see cref="DisconnectGracefullyAsync"/>.
            ///</summary>
            ///<returns>A completed task after disconnection.</returns>
            public Task DisconnectAsync()
            {
                Disconnect();
                return Task.CompletedTask;
            }

            ///<summary>
            ///Initiates a graceful disconnect: sends TCP FIN (or WebSocket CLOSE for WebSocket subclasses)
            ///and lets the receive loop drain until the peer acknowledges. Pending application data is
            ///flushed before the FIN. The connection's state machine cleans up via the normal
            ///OnCompleted → CloseAndDispose path; <see cref="ResetConnectionState"/> is NOT called here
            ///so that the connection can finish draining before being recycled.
            ///</summary>
            public void DisconnectGracefully()
            {
                if (isConnected)
                {
                    connection.Close();
                    phase = " : graceful close in progress";
                    peer = null;
                }
            }

            ///<summary>
            ///Asynchronous counterpart to <see cref="DisconnectGracefully"/>.
            ///</summary>
            ///<returns>A completed task after the graceful close has been initiated (not necessarily completed).</returns>
            public Task DisconnectGracefullyAsync()
            {
                DisconnectGracefully();
                return Task.CompletedTask;
            }

            ///<summary>
            ///Resets the connection state to prepare for a new connection attempt.
            ///</summary>
            void ResetConnectionState()
            {
                if (connection.ext != null)
                {
                    connection.ext.Dispose();
                    connection.ext = null;
                }

                connection.AcceptSocket = null; //SAEA property
                connection.RemoteEndPoint = null;
            }

            ///<summary>
            ///Returns the string representation of the client's current state.
            ///</summary>
            ///<returns>A string with the client's name and connection status.</returns>
            public override string ToString() => phase == null ? base.ToString()! : $"Client {name}{phase}{peer}";
        }
    }

    ///<summary>
    ///An in-process pipe that directly connects a <see cref="AdHoc.BytesSrc"/> (source)
    ///to a <see cref="AdHoc.BytesDst"/> (destination), facilitating data flow within the
    ///same process without a network socket. Stateless after construction — call
    ///<see cref="Drain"/> to move all currently-available bytes from source to destination.
    ///</summary>
    public class Wire
    {
        readonly byte[] buffer;
        readonly AdHoc.BytesSrc src;
        readonly AdHoc.BytesDst dst;

        ///<summary>
        ///Initializes a new instance of the <see cref="Wire"/> class.
        ///</summary>
        ///<param name="src">The source of bytes.</param>
        ///<param name="dst">The destination for bytes.</param>
        ///<param name="buffer_size">The size of the internal buffer for data transfer.</param>
        public Wire(AdHoc.BytesSrc src, AdHoc.BytesDst dst, int buffer_size)
        {
            this.src = src;
            this.dst = dst;
            buffer = new byte[buffer_size];
        }

        ///<summary>
        ///Reads everything currently available from <c>src</c> and writes it to <c>dst</c>,
        ///looping until <c>src.Read</c> returns 0. Synchronous; caller invokes when ready.
        ///</summary>
        public void Drain()
        {
            for (int len; 0 < (len = src.Read(buffer, 0, buffer.Length));)
                dst.Write(buffer, 0, len);
        }
    }

    ///<summary>
    ///Connections over UDP: the same <see cref="AdHoc.Connection.External"/> the TCP transport gives the generated code,
    ///with a handshake, connection ids and timers of its own. The wire format is described in <c>UDP.md</c>.
    ///<para>
    ///The threads are the Java runtime's: an <see cref="Engine"/> runs loops, each loop is one thread that owns its sockets
    ///and every connection on them - their state is plain fields, and the only door in from other threads is a request
    ///(<see cref="Peer.request"/>) or a task (<see cref="Loop.submit"/>). A loop sleeps until the earliest deadline of its
    ///connections or until a datagram or a request arrives, and reads the clock once per pass.
    ///</para>
    ///<para>
    ///Nothing of this runs until a <see cref="Host"/> binds or connects: the TCP transport does not know it exists.
    ///</para>
    ///</summary>
    public class UDP
    {
#region wire
        internal const byte LONG = 0x80, SHORT = 0x40, VERSION = 1;
        internal const byte INITIAL = 0, RETRY = 1, ACCEPT = 2;
        internal const byte PADDING = 0x00, PING = 0x01, PONG = 0x02, ACK = 0x03, DATA = 0x08, CLOSE = 0x1C;
        internal const int MIN_INITIAL = 1200, TOKEN = 16, TOKEN_SECONDS = 10;
        internal const int SHORT_HEADER = 1 + 4 + 4; //type, dcid, a 4-byte packet number

        ///<summary>The Poly1305 tag that ends an encrypted short packet.</summary>
        internal const int TAG = ChaCha20.Aead.TAG;

        ///<summary>
        ///What the Noise handshake of a connection is bound to: the protocol, its version, and the client's connection id -
        ///so a first message is good for that connection only.
        ///</summary>
        static byte[] prologue(uint clientCid)
        {
            var p = new byte["AdHoc UDP".Length + 1 + 4];
            System.Text.Encoding.ASCII.GetBytes("AdHoc UDP", 0, 9, p, 0); //not the u8 suffix: a formatter parts it from the string
            p[9] = VERSION;
            u32(p, 10, clientCid);
            return p;
        }

        ///<summary>The low bits of a connection id are the slot of the connection in its loop, the high ones are random.</summary>
        internal const int SLOT_BITS = 20, SLOT_MASK = (1 << SLOT_BITS) - 1;

        static uint u32(byte[] b, int i) => System.Buffers.Binary.BinaryPrimitives.ReadUInt32LittleEndian(b.AsSpan(i));
        static void u32(byte[] b, int i, uint v) => System.Buffers.Binary.BinaryPrimitives.WriteUInt32LittleEndian(b.AsSpan(i), v);
#endregion
#region time
        ///<summary>Clock ticks per millisecond, and per microsecond.</summary>
        internal static readonly long TICKS_MS = Math.Max(1, Stopwatch.Frequency / 1000), TICKS_US = Math.Max(1, Stopwatch.Frequency / 1_000_000);

        ///<summary>The clock in microseconds, the low 32 bits: what a PING carries and its PONG echoes. Wraps every 71 minutes.</summary>
        static uint micros(long ticks) => (uint)(ticks / TICKS_US);

        ///<summary>
        ///Deadlines are filed rounded up to a beat - the largest power of two of clock ticks not over a millisecond. The
        ///Java runtime files TCP timeouts with a beat of 16.8 ms; the timers of a datagram transport are a few milliseconds
        ///long, so theirs is finer.
        ///</summary>
        internal static readonly long BEAT = (long)System.Numerics.BitOperations.RoundUpToPowerOf2((ulong)TICKS_MS + 1) >> 1;

        static long beat(long due) => (due | BEAT - 1) + 1;
#endregion

        ///<summary>
        ///The threads of the UDP transport: <see cref="threads"/> loops. A connection lives on one loop for its life. One
        ///engine can serve several hosts.
        ///</summary>
        public sealed class Engine : IDisposable
        {
            internal readonly Loop[] loops;
            int next;
            internal readonly Action<object, Exception> onFailure;

            ///<param name="threads">how many loops; capped at the processor count. On Windows a listening port is read by
            ///one loop - the kernel has no <c>SO_REUSEPORT</c> there; on Linux every loop reads a socket of its own on the
            ///port, and the kernel keeps each peer on one of them.</param>
            public Engine(string name, int threads = 1, Action<object, Exception>? onFailure = null)
            {
                if (!OperatingSystem.IsWindows() && !OperatingSystem.IsLinux() && !OperatingSystem.IsAndroid())
                    throw new PlatformNotSupportedException("The UDP transport runs on Windows and Linux.");
                this.onFailure = onFailure ?? TCP.onFailurePrintConsole;
                loops = new Loop[Math.Max(1, Math.Min(threads, Environment.ProcessorCount))];
                for (var i = 0; i < loops.Length; i++)
                    loops[i] = new Loop(this, name + "-udp-" + i, i);
            }

            public int threads() => loops.Length;

            ///<summary>Round-robin, a plain field: a race hands two connections to one loop, which is harmless.</summary>
            internal Loop pick()
            {
                var i = next;
                next = i + 1 == loops.Length ? 0 : i + 1;
                return loops[i];
            }

            ///<summary>Stops the loops. What is still connected is dropped without a word.</summary>
            public void Dispose()
            {
                foreach (var loop in loops)
                    loop.shutdown();
            }
        }

        ///<summary>One socket on one loop, and the host it serves.</summary>
        internal sealed class Endpoint
        {
            internal readonly Socket socket;
            internal readonly Host host;
            internal readonly bool listening;
            internal readonly SocketAddress from; //where the datagram in hand came from: rewritten by every receive
            internal readonly byte[] fromBytes;   //the array behind it, for recvfrom
            internal readonly int fromCap;
            internal readonly IntPtr handle;

            ///<summary>
            ///Listening: the accepted connections by the address and the connection id of their peer, for a repeated
            ///INITIAL. Both: one socket of a client carries many connections, so an address alone names none.
            ///</summary>
            internal readonly Dictionary<(SocketAddress, uint), Peer>? accepted;

            internal Endpoint(Socket socket, Host host, bool listening)
            {
                this.socket = socket;
                this.host = host;
                this.listening = listening;
                handle = socket.Handle;
                from = new SocketAddress(socket.AddressFamily, SocketAddress.GetMaximumAddressSize(socket.AddressFamily));
                if (!MemoryMarshal.TryGetArray<byte>(from.Buffer, out var array) || array.Offset != 0)
                    throw new PlatformNotSupportedException("SocketAddress is not backed by an array.");
                fromBytes = array.Array!;
                fromCap = array.Count;
                if (listening)
                    accepted = new Dictionary<(SocketAddress, uint), Peer>();
            }
        }
#region deadlines
        ///<summary>
        ///One kind of wait of the connections of a loop - the Java runtime's deadline list: singly linked through the
        ///connections themselves, sorted as it is filled, the head the next to look at. A connection is filed under the
        ///deadline it had when it was filed (<see cref="Due.at"/>) and the key does not change while it is in the list: a
        ///busy connection renews its wait with two field writes and a compare, and is filed again only when its key comes
        ///up. A cancelled wait is not taken out - it is dropped when it comes up. Each kind has a list of its own, so the
        ///waits in one list are alike and a new one goes behind the tail.
        ///</summary>
        internal sealed class Deadlines
        {
            readonly int k;
            Peer? head, tail, finger;

            internal Deadlines(int k) => this.k = k;

            internal void arm(Peer p, long due)
            {
                ref var d = ref p.dues[k];
                d.due = due;
                d.armed = true;
                if (d.linked)
                {
                    if (d.at <= beat(due))
                        return; //comes up no later than this deadline, and is filed under the one it has then
                    unfile(p);  //the wait got shorter than its key
                }
                file(p, due);
            }

            internal void disarm(Peer p) => p.dues[k].armed = false;

            void file(Peer p, long due)
            {
                ref var d = ref p.dues[k];
                var at = beat(due);
                d.at = at;
                d.linked = true;
                if (tail == null)
                {
                    d.next = null;
                    head = tail = p;
                    return;
                }
                if (tail.dues[k].at <= at) //the common case: the newest deadline is the latest
                {
                    d.next = null;
                    tail.dues[k].next = p;
                    tail = p;
                    return;
                }
                if (at < head!.dues[k].at)
                {
                    d.next = head;
                    head = p;
                    return;
                }
                var q = finger != null && finger.dues[k].at <= at ? finger : head; //the finger is in the list, always
                while (q.dues[k].next!.dues[k].at <= at)                           //behind its equals; stops before the tail, whose key is later
                    q = q.dues[k].next!;
                d.next = q.dues[k].next;
                q.dues[k].next = p;
                finger = p;
            }

            ///<summary>Out of the middle: a walk with the previous in hand. Rare - a wait shorter than the one it is filed under.</summary>
            void unfile(Peer p)
            {
                Peer? prev = null;
                for (var c = head; c != null; prev = c, c = c.dues[k].next)
                    if (c == p)
                    {
                        if (prev == null)
                            head = c.dues[k].next;
                        else
                            prev.dues[k].next = c.dues[k].next;
                        if (tail == c)
                            tail = prev;
                        if (finger == c)
                            finger = prev;
                        break;
                    }
                p.dues[k].next = null;
                p.dues[k].linked = false;
            }

            void pop()
            {
                var h = head!;
                if ((head = h.dues[k].next) == null)
                    tail = null;
                if (finger == h)
                    finger = null;
                h.dues[k].next = null;
                h.dues[k].linked = false;
            }

            ///<summary>The key of the head; heads nobody waits on any more are dropped on the way.</summary>
            internal long next()
            {
                while (head != null && !head.dues[k].armed)
                    pop();
                return head == null ? long.MaxValue : head.dues[k].at;
            }

            ///<summary>Every key that has come up: a wait that is over times out, one that is later by now is filed again.</summary>
            internal void expire(long now)
            {
                for (Peer? c; (c = head) != null && c.dues[k].at <= now;)
                {
                    pop();
                    ref var d = ref c.dues[k];
                    if (!d.armed)
                        continue;
                    if (now < d.due)
                        file(c, d.due);
                    else
                    {
                        d.armed = false;
                        c.timedOut(k, now);
                    }
                }
            }
        }

        ///<summary>The place of a connection in one <see cref="Deadlines"/> list.</summary>
        internal struct Due
        {
            internal Peer? next;
            internal long at, due;
            internal bool armed, linked;
        }

        ///<summary>The kinds of wait: nothing received, nothing sent, the handshake, the close.</summary>
        internal const int RECEIVE = 0, KEEPALIVE = 1, HANDSHAKE = 2, LINGER = 3, PROBE = 4, PARK = 5, PACE = 6;
