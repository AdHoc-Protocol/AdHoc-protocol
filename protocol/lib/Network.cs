            ///(<c>host =&gt; new ExternalConnection(host)</c>, <c>new WebSocket(host)</c>) and this names the connection by the
            ///first byte a caller sends; <c>null</c> - an ordinary port.</param>
            public Server(string name,
                          Func<TCP, ExternalConnection> newConnection,
                          Func<int, AdHoc.Connection.Internal?>? internals,
                          Action<object, Exception> onFailure,
                          int bufferSize,
                          int Backlog,
                          Func<IPEndPoint, Socket>? socketBuilder,
                          params IPEndPoint[] ips) : base(name, newConnection, onFailure, bufferSize)
            {
                this.internals = internals; //before the first caller can arrive
                //Start a background task for periodic connection maintenance.
                Task.Run(async () =>
                         {
                             while (true)
                             {
                                 await maintenance_lock.WaitAsync();
                                 try
                                 {
                                     StartMaintenance();
                                     var waitTime = await MaintenanceAsync(DateTime.UtcNow.Ticks);
                                     deadline_planned(DateTimeOffset.UtcNow.ToUnixTimeMilliseconds() + waitTime);
                                     if (RestartMaintenance())
                                         continue;                               //If re-run was requested, loop immediately.
                                     await maintenance_wake.WaitAsync(waitTime); //до срока - или пока новый срок не окажется раньше
                                 }
                                 catch (Exception ex)
                                 {
                                     onFailure(this, ex);
                                 }
                                 finally
                                 {
                                     maintenance_lock.Release();
                                 }
                             }
                         });
                bind(Backlog, socketBuilder, ips);
            }

