            ///<summary>
            ///A dedicated <see cref="SocketAsyncEventArgs"/> instance used exclusively for receive operations
            ///to avoid conflicts with send operations on the primary instance.
            ///</summary>
            internal readonly SocketAsyncEventArgs ReceiveMate = new();

            ///<summary>
            ///Hands a completion that landed during maintenance to a regular pool thread, which may block without
            ///starving I/O completions.
            ///<para>Its own method on purpose: a lambda that captures parameters makes the compiler allocate the
            ///closure object AT THE ENTRY of the method that contains it - on every completion, whether the branch
            ///runs or not. Measured: 36 B per message on the receive path, against 0 for a bare
            ///<see cref="SocketAsyncEventArgs"/> receiver. Here the closure is made only by the caller that actually
            ///got in the way of a maintenance pass.</para>
            ///</summary>
            void reschedule_transmit(SocketAsyncEventArgs saea) => ThreadPool.QueueUserWorkItem(
                _ => OnCompleted(saea), null);

            ///<summary>The receive side of <see cref="reschedule_transmit"/>, kept apart for the same reason.</summary>
            void reschedule_receive(object? src, SocketAsyncEventArgs saea) => ThreadPool.QueueUserWorkItem(
                _ => OnCompleted(src, saea), null);

            ///<summary>
            ///Handles the completion of asynchronous receive operations.
            ///</summary>
            ///<param name="src">The object that raised the event.</param>
            ///<param name="_receive">The <see cref="SocketAsyncEventArgs"/> instance for the completed operation.</param>
            protected void OnCompleted(object? src, SocketAsyncEventArgs _receive)
            {
                //Wait if maintenance is in progress to prevent race conditions. The rescheduled item carries
                //this operation's pending reference with it — it is released when the handler actually runs.
                if (locked_for_maintenance())
                {
                    reschedule_receive(src, _receive);
                    return;
                }

                //This operation's pending reference is released in the finally — at the END of the handling.
                //While the handler runs it is what keeps FinishDispose() from returning ReceiveMate.Buffer to
                //the pool under our feet when another thread calls Abort() mid-parse.
                try
                {
                    if (!IsActive)
                        return; //an operation of a session that is already gone

                    receive_time = DateTimeOffset.UtcNow.ToUnixTimeMilliseconds();

                    Event eventType;
                    switch (_receive.SocketError)
                    {
                        case SocketError.Success:
                            if (_receive.BytesTransferred == 0)
                            {
                                //A zero-byte read signifies that the remote peer has gracefully closed its end of the connection.
                                //The event type depends on whether this host initiated the close sequence.
                                var evenT = isClosingGracefully ? Event.THIS_CLOSE_GRACEFUL : Event.REMOTE_CLOSE_GRACEFUL;
                                Disconnected(evenT);
                                return;
                            }

                            if (_receive.LastOperation != SocketAsyncOperation.Receive)
                                return;

                            receive_due = 0; //данные пришли: ожидание снято до следующего
                            receive();       //Process the received data and start the next receive operation.
                            return;
                        case SocketError.TimedOut:
                            timed_out_receive(); //вопрос приложению, а не приговор
                            return;
                        case SocketError.ConnectionReset:
                        case SocketError.ConnectionAborted:
                        case SocketError.NetworkReset:
                            eventType = Event.REMOTE_CLOSE_ABRUPTLY;
                            break;
                        default:
                            host.onFailure(this, new SocketException((int)_receive.SocketError));
                            eventType = Event.REMOTE_CLOSE_ABRUPTLY;
                            break;
                    }

                    Disconnected(eventType);
                }
                finally
                {
                    pending_send_receive_completed();
                    ReleaseOp();
                }
            }

            ///<summary>
            ///Configures the connection for receiving data from a new external connection, setting up buffers and starting I/O loops.
            ///</summary>
            ///<param name="ext">The newly accepted socket.</param>
            internal void receiver_connected(Socket ext)
            {
                this.ext = ext;
                noise = host.key == null ? null : NoiseStream.Server(host.key, () => Internal?.BytesSrc, () => ActiveDst, WakeTransmit, k => AdHoc.Connection.Keyring.Seat(Internal, k));
                host.configure(ext);
                receive_time = DateTimeOffset.UtcNow.ToUnixTimeMilliseconds();

                //Setup custody: the REMOTE_CONNECT handler below may Abort() synchronously, which releases the
                //session's own reference — this extra one keeps the connection from being recycled to a new
                //tenant while the rest of this method is still on the stack.
                Interlocked.Increment(ref pending);
                app_enter();
                try
                {
                    var before = id;
                    Internal.OnExternalEvent(this, Event.REMOTE_CONNECT);
                    if (IsActive)
                        SessionOpened();

                    if (!IsActive)
                        return; //the handler tore the connection down

                    if (before != 0 && id == before)
                        Internal.resume(this); //an identity kept across sockets that the handler did not re-identify

                    if (!ext.Connected)
                    {
                        CloseAndDispose(); //the accept handed over a socket that is already dead
                        return;
                    }
                    if (ReceiveMate.Buffer == null)
                        host.buffers(ReceiveMate);
                    if (Internal.BytesSrc != null)
                    {
                        if (Buffer == null)
                            host.buffers(this);
                        SetBuffer(0, 0);
                        //Backfill — see transmitterConnected for rationale.
                        WakeTransmit();
                    }

                    //Start the receive loop. If ReceiveAsync completes synchronously, call receive() immediately.
                    if (!IssueReceive())
                        receive();
                }
                finally
                {
                    app_leave();
                    ReleaseOp();
                }
            }

            ///<summary>
            ///Stops receiving data on this connection by shutting down the receive direction of the socket.
            ///</summary>
            public void StopReceiving() => ext?.Shutdown(SocketShutdown.Receive);

            ///<summary>The read timeout in milliseconds; in a graceful close, the deadline for the peer's FIN.
            ///Getter: positive while open normally; negative once a graceful close is in progress (magnitude = the
            ///FIN-wait deadline) — the sign the generated sending_put reads to reject new outbound packets; MinValue
            ///when not active. Setter: value&gt;=0 sets the read timeout; value&lt;0 enters graceful close, identical
            ///to a negative <see cref="TransmitTimeout"/> — the queue drains, then OnTransmitterDrained sends the FIN.</summary>
            public virtual int ReceiveTimeout
            {
                get => IsActive ? isClosingGracefully ? -_receive_timeout : _receive_timeout : int.MinValue;
                set {
                    if (value < 0)
                    {
                        //Enter graceful close, identical to a negative TransmitTimeout: the send queue drains first,
                        //then OnTransmitterDrained sends the FIN; the magnitude -value becomes the FIN-wait deadline.
                        isClosingGracefully = true;
                        _receive_timeout = -value;
                    }
                    else
                        _receive_timeout = value;
                    if (IsActive)
                        arm_receive();
                }
            }

            ///<summary>
            ///Processes received data and immediately initiates the next asynchronous receive
            ///operation. Exits without re-arming when the destination has refused bytes
            ///(backpressure pause): the kernel buffer will fill, the TCP window closes, the
            ///sender stalls naturally, and <see cref="WakeReceive"/> resumes the loop once
            ///downstream signals space.
            ///</summary>
            void receive()
            {
                app_enter();
                try
                {
                    do
                    {
                        if (ReceiveMate.BytesTransferred == 0)
                        {
                            //A zero-byte read is the peer's graceful close. On the async path OnCompleted
                            //handles it; on a SYNCHRONOUS completion (ReceiveAsync returned false) we land
                            //here instead, and must run the SAME full teardown — event + CloseAndDispose —
                            //not just close the socket, or the session stays ACTIVE forever holding its
                            //activation reference.
                            var ev = isClosingGracefully ? Event.THIS_CLOSE_GRACEFUL : Event.REMOTE_CLOSE_GRACEFUL;
                            Disconnected(ev);
                            return;
                        }

                        receive(ReceiveMate.Buffer!, ReceiveMate.Offset + ReceiveMate.BytesTransferred);

                        //If receive() left an unwritten tail the destination is paused. Lost-wakeup guard: a
                        //cross-connection WakeReceive (outbound send completion freeing the downstream buffer) can
                        //fire between the refusing Write and the park below, and would have no-op'd. Retry the tail
                        //once (re-samples the now-possibly-freed downstream); if still refused, publish the park
                        //(_rxParked) and re-check — a wake that landed in the gap is claimed here so it's not lost.
                        if (Volatile.Read(ref _pendingTailLength) > 0)
                        {
                            if (!DrainTail())
                            {
                                Interlocked.Exchange(ref _rxParked, 1); //publish "parked" (full barrier)
                                if (Volatile.Read(ref _pendingTailLength) > 0)
                                    return; //genuinely parked → WakeReceive re-arms
                                if (Interlocked.Exchange(ref _rxParked, 0) != 1)
                                    return; //a WakeReceive drained the gap & claimed the re-arm
                                //else: we reclaimed the park → fall through and re-arm via the loop
                            }
                        }
                    }
                    //Loop as long as ReceiveAsync completes synchronously.
                    while (!IssueReceive());
                }
                catch (Exception e)
                {
                    if (ext != null)
                        host.onFailure(this, e);
                }
                finally
                {
                    app_leave();
                }
            }

            ///<summary>
            ///Delivers the received data from the buffer to the internal receiver.
            ///Honors short writes by stashing the unwritten tail (held in <see cref="ReceiveMate"/>'s
            ///buffer) so the receive loop declines to re-arm. A downstream-aware nested
            ///<see cref="AdHoc.BytesDst"/> calls <see cref="WakeReceive"/> when it becomes
            ///acceptable again, which flushes the tail.
            ///</summary>
            ///<param name="src">The source buffer containing the received data.</param>
            ///<param name="src_bytes">The number of bytes received in the buffer.</param>
            protected virtual void receive(byte[] src, int src_bytes)
            {
                //Stash the FRESH buffer and let the single-flusher (DrainTail, called by the receive loop) write it —
                //the SAME path a cross-thread WakeReceive uses. Writing directly here would let a downstream-aware
                //BytesDst's Write run on two threads at once (this inbound completion AND a WakeReceive → DrainTail)
                //→ framing corruption. (src is ReceiveMate.Buffer, data at offset 0.)
                received(0, src_bytes);
            }

            ///<summary>
            ///Hands <paramref name="length"/> just-received bytes at <paramref name="offset"/> of the receive buffer to
            ///the drain. From here on they are offered through <see cref="deliver"/> only: the receive loop does not read
            ///the socket again until every one of them is consumed — that pause is the whole flow control.
            ///</summary>
            protected void received(int offset, int length)
            {
                _pendingTailOffset = offset;
                Volatile.Write(ref _pendingTailLength, length);
            }

            ///<summary>
            ///One step of the drain: offers <paramref name="length"/> received bytes at <paramref name="offset"/> to
            ///<paramref name="dst"/> and returns how many of them are consumed; 0 means "refused right now", and the
            ///receive loop parks until <see cref="WakeReceive"/>. A framing transport overrides it to decode its frames
            ///here, so the same pause/resume holds for the payload it extracts.
            ///<para>Runs only under the drain's single-flusher gate, never concurrently with itself.</para>
            ///</summary>
            protected virtual int deliver(AdHoc.BytesDst dst, byte[] buffer, int offset, int length) => dst.Write(buffer, offset, length);
#endregion

