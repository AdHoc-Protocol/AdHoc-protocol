        ///<summary>
        ///Whether every socket this host serves gets <see cref="Socket.NoDelay"/>. On by default: the transmit runner
        ///already coalesces in user space - it fills the send buffer from the queue and issues one send - so Nagle's
        ///algorithm buys no packets here, it only holds a segment smaller than the MSS until the peer acknowledges the
        ///previous one. Against a peer with delayed ACK that stalls a request/response exchange for tens of
        ///milliseconds. Turn it off only for bulk one-way streaming, where fewer packets are worth more than the delay.
        ///</summary>
        public bool NoDelay = true;

        ///<summary>
        ///Keeps a link that carries nothing from being forgotten by whatever sits between: the kernel sends a probe
        ///after a couple of hours of silence and drops the connection when nobody answers. The timing is the operating
        ///system's business - a session that wants its own has <see cref="ExternalConnection.ReceiveTimeout"/> and
        ///<see cref="AdHoc.Connection.Internal.OnReceiveTimeout"/>, which cost nothing while data flows.
        ///</summary>
        public bool KeepAlive = false;

        ///<summary>
        ///What the kernel is asked to keep for a socket, in bytes; <c>0</c> leaves whatever the system gives. These
        ///are not this transport's buffers but the windows the kernel fills and drains by itself, and on a link with a
        ///long round trip they are the ceiling of one connection's throughput: window / round trip.
        ///<para>The receive one is set on the listening socket as well, <b>before it binds</b> - only then is the
        ///window scaling of the handshake right, and only then do accepted sockets inherit it.</para>
        ///</summary>
        public int socket_receive_buffer, socket_transmit_buffer;

        ///<summary>
        ///Applies this host's socket options to a socket that is about to serve a connection: called for an accepted
