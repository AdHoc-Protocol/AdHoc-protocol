        ///</summary>
        public int connections_live() => Volatile.Read(ref _connectionsLive);

        ///<summary>
        ///How many connection slots this host has ever made. Slots are reused, so this is the high-water mark of them
        ///all - and what the host costs in memory.
        ///</summary>
        public int connections_size() => Volatile.Read(ref _connectionsSize);

        ///<summary>
        ///Counts the slots of this host by the state they are in, into <paramref name="into"/> - indexed by the state
        ///itself: FREE 0, ACTIVE 1, CLEANING 2, PARKED 3. The four add up to <see cref="connections_size"/>.
        ///<para>Nothing is counted while the transport runs: the states are read off the slots when asked, which is a
        ///walk of one array and a snapshot of a moving thing - a census, not a lock. Free for the path of a message.</para>
        ///</summary>
        ///<param name="into">An array of at least 4; it is zeroed first.</param>
        ///<returns><paramref name="into"/></returns>
        public int[] census(int[] into)
        {
            Array.Clear(into, 0, 4);
            var registry = _connections;
            for (int i = 0, n = Math.Min(Volatile.Read(ref _connectionsSize), registry.Length); i < n; i++)
            {
                var con = registry[i];
                if (con != null)
                    into[con.conn_state]++;
            }
            return into;
        }

        ///<summary>The census as one line, for a log: <c>"free 12, active 300, cleaning 0, parked 4, slots 316"</c>.</summary>
        public string censusText()
        {
            var n = census(new int[4]);
            return $"free {n[ExternalConnection.FREE]}, active {n[ExternalConnection.ACTIVE]}, cleaning {n[ExternalConnection.CLEANING]}, parked {n[ExternalConnection.PARKED]}, slots {connections_size()}";
        }

