            ///<summary>Listening side: reached while this connection stands in for the Internal - a multiplexed port before
            ///the caller named its connection. Reads that one byte, seats the Internal it names, hands it the connect and the
            ///open this connection took for it, and the rest of the bytes.</summary>
            int AdHoc.BytesDst.Write(byte[] src, int offset, int length)
            {
                if (Internal != this)
                { //a frame loop fetched the destination once, before the caller was named: pass on
                    var dst = ActiveDst;
                    return dst == null ? 0 : dst.Write(src, offset, length);
                }
                if (length < 1)
                    return 0;
                var named = src[offset];
                var @in = incumbent;
                if (@in == null || @in.id != named)
                {
                    var fresh = host.internals!(named);
                    if (fresh == null)
                    {
                        host.onFailure(this, new System.Net.ProtocolViolationException($"A multiplexed port has no connection for the host uid {named}"));
                        return -1; //the drain aborts the socket; the incumbent stays with the slot
                    }
                    @in?.External(null); //unseated and back to its pool
                    @in = fresh;
                }
                incumbent = null;
                Internal = @in;
                AdHoc.Connection.Keyring.Seat(@in, noise?.PackKey);
                @in.External(this);

                var before = id;
                @in.OnExternalEvent(this, Event.REMOTE_CONNECT);
                if (held_ws_connect)
                {
                    held_ws_connect = false;
                    if (IsActive)
                        @in.OnExternalEvent(this, Event.WEBSOCKET_REMOTE_CONNECTED);
                }
                if (Volatile.Read(ref sessionOpen) == 1 && IsActive)
                    @in.OnOpen(); //the session was opened on this connection standing in: now the Internal hears it
                if (!IsActive)
                    return 1;
                if (before != 0 && id == before)
                    @in.resume(this); //an identity kept across sockets that the handler did not re-identify
                if (!IsActive)
                    return 1;
                if (@in.BytesSrc != null)
                    WakeTransmit();
                if (length == 1)
                    return 1;
                var rest = ActiveDst;
                if (rest == null)
                    return 1;
                var n = rest.Write(src, offset + 1, length - 1);
                return n < 0 ? n : 1 + n;
            }
