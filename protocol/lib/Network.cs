        ///<summary>
        ///One thread: its sockets, the connections on them, their deadlines. Each pass: sleep until the earliest deadline
        ///or a datagram or a request, read what the sockets hold, serve the requests and the tasks, time out what is due.
        ///</summary>
        internal sealed class Loop
        {
            internal readonly Engine engine;
            internal readonly int index;
            readonly Thread thread;
            volatile bool running = true;
            readonly Waiter waiter = Waiter.make();

            internal Endpoint[] endpoints = Array.Empty<Endpoint>();

            ///<summary>Every connection this loop ever made, by slot: what the low bits of a connection id point at.</summary>
            internal Peer?[] slots = new Peer?[64];
            internal int slotsN;

            internal readonly byte[] rx = new byte[2048], tx = new byte[2048];

            internal readonly Deadlines[] deadlines = { new(RECEIVE), new(KEEPALIVE), new(HANDSHAKE), new(LINGER), new(PROBE), new(PARK), new(PACE) };

            internal Loop(Engine engine, string name, int index)
            {
                this.engine = engine;
                this.index = index;
                thread = new Thread(run) { Name = name, IsBackground = true };
                thread.Start();
            }

            internal bool inLoop => Thread.CurrentThread == thread;
#region clock
            long now;
            bool stale = true;

            ///<summary>The clock, read once per pass: everything served in a pass stamps and arms from the same reading.</summary>
            internal long Now()
            {
                if (stale)
                {
                    now = Stopwatch.GetTimestamp();
                    stale = false;
                }
                return now;
            }
#endregion
#region the doors in
            ///<summary>
            ///Connections with requests, a Treiber stack threaded through <see cref="Peer.nextRequest"/>. A connection is on
            ///it at most once - it is pushed by whoever raises its <see cref="Peer.requests"/> from zero - so the stack
            ///allocates nothing and cannot overflow.
            ///</summary>
            Peer? requested;

            readonly System.Collections.Concurrent.ConcurrentQueue<Action> tasks = new();

            ///<summary>
            ///Raised right before the loop sleeps. Each side writes first and reads second, through full barriers - the
            ///push, the <see cref="Interlocked.Exchange(ref int,int)"/> here - so either the loop sees the work and does
            ///not sleep, or the producer sees the flag and wakes it. An awake loop is not woken: that is a system call saved.
            ///</summary>
            int asleep;

            internal void post(Peer p)
            {
                for (Peer? h;;)
                {
                    p.nextRequest = h = Volatile.Read(ref requested);
                    if (Interlocked.CompareExchange(ref requested, p, h) == h)
                        break;
                }
                if (Volatile.Read(ref asleep) != 0)
                    waiter.wake();
            }

            ///<summary>Runs <paramref name="task"/> on this loop. For the rare things - a bind, a connect, a shutdown - not per message.</summary>
            internal void submit(Action task)
            {
                tasks.Enqueue(task);
                if (Volatile.Read(ref asleep) != 0)
                    waiter.wake();
            }

            ///<summary>Runs <paramref name="task"/> on this loop and waits for it.</summary>
            internal void call(Action task)
            {
                if (inLoop)
                {
                    task();
                    return;
                }
                Exception? error = null;
                using var done = new ManualResetEventSlim();
                submit(() =>
                       {
                           try
                           {
                               task();
                           }
                           catch (Exception e)
                           {
                               error = e;
                           }
                           finally
                           {
                               done.Set();
                           }
                       });
                done.Wait();
                if (error != null)
                    System.Runtime.ExceptionServices.ExceptionDispatchInfo.Throw(error);
            }

            bool idle => Volatile.Read(ref requested) == null && tasks.IsEmpty;
#endregion

            void run()
            {
                var more = false; //a socket was left with datagrams: no sleep this pass
                while (running)
                    try
                    {
                        var sleep = !more && idle;
                        if (sleep)
                        {
                            Interlocked.Exchange(ref asleep, 1); //written first...
                            sleep = idle;                        //...read second
                        }
                        waiter.wait(sleep ? until(nextDeadline()) : 0);
                        if (asleep != 0)
                            Volatile.Write(ref asleep, 0);
                        stale = true;
                        more = receive();
                        serve();
                        acks();
                        expire();
                    }
                    catch (Exception e)
                    {
                        if (running)
                            engine.onFailure(this, e);
                    }
                foreach (var ep in endpoints)
                    ep.socket.Dispose();
                waiter.close();
            }

            static long until(long at) => at == long.MaxValue ? long.MaxValue : Math.Max(1, at - Stopwatch.GetTimestamp());

            long nextDeadline()
            {
                var at = long.MaxValue;
                foreach (var d in deadlines)
                    at = Math.Min(at, d.next());
                return at;
            }

            void expire()
            {
                var t = Now();
                foreach (var d in deadlines)
                    d.expire(t);
            }

            ///<summary>Connections that received DATA this pass and owe an ACK: a stack threaded through <see cref="Peer.nextAck"/>, this loop only.</summary>
            Peer? ackers;

            internal void ackLater(Peer p)
            {
                if (p.ackListed)
                    return; //an ACK that rode along reset its count, and DATA came again in the same pass
                p.ackListed = true;
                p.nextAck = ackers;
                ackers = p;
            }

            ///<summary>One ACK per connection that received DATA this pass - unless a DATA it sent meanwhile carried it already.</summary>
            void acks()
            {
                var now = Now();
                for (var p = ackers; p != null;)
                {
                    var next = p.nextAck;
                    p.nextAck = null;
                    p.ackListed = false;
                    p.sendAck(now);
                    p = next;
                }
                ackers = null;
            }

            void serve()
            {
                while (tasks.TryDequeue(out var task))
                    try
                    {
                        task();
                    }
                    catch (Exception e)
                    {
                        engine.onFailure(this, e);
                    }
                for (var p = Interlocked.Exchange(ref requested, null); p != null;)
                {
                    var next = p.nextRequest;
                    p.nextRequest = null;
                    var what = Interlocked.Exchange(ref p.requests, 0); //from here a new request pushes it again
                    try
                    {
                        p.serve(what);
                    }
                    catch (Exception e)
                    {
                        p.host.onFailure(p, e);
                    }
                    p = next;
                }
            }
#region receiving
            ///<summary>Reads what the sockets hold, a bounded burst per socket. <c>true</c>: one was left with more.</summary>
            bool receive()
            {
                var more = false;
                foreach (var ep in endpoints)
                    for (var burst = 0;; burst++)
                    {
                        if (burst == 256)
                        {
                            more = true;
                            break;
                        }
                        var n = waiter.receive(ep, rx);
                        if (n < 0)
                            break;
                        try
                        {
                            dispatch(ep, n);
                        }
                        catch (Exception e)
                        {
                            ep.host.onFailure(ep.host, e);
                        }
                    }
                return more;
            }

            void dispatch(Endpoint ep, int n)
            {
                if (n < 2)
                    return;
                var b0 = rx[0];
                if ((b0 & 0xC0) == SHORT)
                {
                    if (n < 6)
                        return;
                    var p = find(ep, u32(rx, 1));
                    if (p == null)
                        return;
                    if (p.rxKey != null && (n = p.unseal(n)) < 0)
                        return; //forged, damaged or replayed: as if it never came
                    if (p.state == Peer.CONNECTING)
                    {
                        if (!p.accepting)
                            return;
                        p.confirmed(); //the ACCEPT arrived: the handshake is complete, as a TCP accept is
                        if (p.state != Peer.ACTIVE)
                            return;
                    }
                    else if (p.state < Peer.ACTIVE)
                        return;
                    var pos = 5 + (b0 & 3) + 1;
                    if (n < pos)
                        return;
                    p.received(Now(), pos, n);
                    return;
                }
                if ((b0 & LONG) == 0 || rx[1] != VERSION)
                    return;
                switch (b0 & 0x7F)
                {
                    case INITIAL:
                        if (ep.listening && MIN_INITIAL <= n)
                            initial(ep);
                        return;
                    case RETRY:
                        if (22 <= n)
                            find(ep, u32(rx, 2))?.retry();
                        return;
                    case ACCEPT:
                        if (11 <= n)
                            find(ep, u32(rx, 2))?.accepted(u32(rx, 6), n);
                        return;
                }
            }

            ///<summary>The connection a packet names, if it came through the right socket from the right address.</summary>
            Peer? find(Endpoint ep, uint cid)
            {
                var slot = (int)(cid & SLOT_MASK);
                if (slotsN <= slot)
                    return null;
                var p = slots[slot]!;
                return p.cid == cid && p.state is Peer.CONNECTING or Peer.ACTIVE or Peer.CLOSING && p.ep == ep && p.address!.Equals(ep.from) ? p : null;
            }

            ///<summary>An INITIAL on a listening socket: a RETRY for one without a valid token, a connection for one with it.</summary>
            void initial(Endpoint ep)
            {
                var host = ep.host;
                var scid = u32(rx, 2);
                if (rx[6] != TOKEN || !host.valid(rx.AsSpan(7, TOKEN), ep.from, scid))
                {
                    tx[0] = LONG | RETRY;
                    tx[1] = VERSION;
                    u32(tx, 2, scid);
                    host.token(tx.AsSpan(6, TOKEN), ep.from, scid);
                    send(ep, ep.from, 22);
                    return;
                }
                if (ep.accepted!.TryGetValue((ep.from, scid), out var p))
                {
                    if (p.state is Peer.CONNECTING or Peer.ACTIVE)
                        p.sendAccept(); //the first ACCEPT was lost
                    return;
                }
                if (0 < host.max_connections && host.max_connections <= host.connections_live())
                    return;
                //The handshake: a server with a key reads the client's first message before it gives the connection a slot -
                //one not written for this server's key, or not written at all, gets nothing. A server without a key serves
                //only clients that do not encrypt.
                var hsAt = 7 + TOKEN;
                var hsLen = rx[hsAt];
                NoiseNK? hs = null;
                if (host.key != null)
                {
                    if (hsLen != NoiseNK.OVERHEAD)
                        return;
                    hs = NoiseNK.Responder(host.key, prologue(scid));
                    if (hs.ReadMessage(rx.AsSpan(hsAt + 1, hsLen), Span<byte>.Empty) < 0)
                        return;
                }
                else if (hsLen != 0)
                    return;
                p = allocate(host, ep);
                p.address = copy(ep.from);
                p.rcid = scid;
                ep.accepted[(p.address, scid)] = p;
                if (hs != null)
                    p.keyed(hs);
                p.accept();
            }

            static SocketAddress copy(SocketAddress a)
            {
                var c = new SocketAddress(a.Family, a.Size);
                a.Buffer.Span[..a.Size].CopyTo(c.Buffer.Span);
                return c;
            }
#endregion

            ///<summary>A connection slot of <paramref name="host"/> on this loop: a free one of that host, or a new one.</summary>
            internal Peer allocate(Host host, Endpoint ep)
            {
                var p = host.free[index];
                if (p != null)
                    host.free[index] = p.nextFree;
                else
                {
                    if (slotsN == SLOT_MASK + 1)
                        throw new InvalidOperationException("A loop holds 1 048 576 UDP connections at most.");
                    if (slotsN == slots.Length)
                        Array.Resize(ref slots, slotsN * 2);
                    slots[slotsN] = p = new Peer(this, host, slotsN);
                    slotsN++;
                    var inner = host.newInternal(p);
                    p.Internal = inner;
                    inner.External(p);
                }
                p.nextFree = null;
                p.ep = ep;
                p.cid = (uint)p.slot | (uint)RandomNumberGenerator.GetInt32(1 << 32 - SLOT_BITS) << SLOT_BITS;
                return p;
            }

            internal void release(Peer p)
            {
                p.nextFree = p.host.free[index];
                p.host.free[index] = p;
            }

            internal void send(Endpoint ep, SocketAddress to, int length)
            {
                try
                {
                    ep.socket.SendTo(tx.AsSpan(0, length), SocketFlags.None, to);
                }
                catch (SocketException e) when (e.SocketErrorCode is SocketError.WouldBlock or SocketError.NoBufferSpaceAvailable or SocketError.ConnectionReset)
                {
                    //a datagram lost on this side: the same as one lost on the way
                }
            }

            internal void add(Endpoint ep)
            {
                waiter.add(ep.socket);
                var a = new Endpoint[endpoints.Length + 1];
                endpoints.CopyTo(a, 0);
                a[^1] = ep;
                endpoints = a;
            }

            internal void remove(Endpoint ep)
            {
                waiter.remove(ep.socket);
                endpoints = Array.FindAll(endpoints, e => e != ep);
                ep.socket.Dispose();
            }

            internal void shutdown()
            {
                running = false;
                waiter.wake();
                if (!inLoop)
                    thread.Join();
            }
        }

        ///<summary>
        ///The server and the client side at once: <see cref="bind"/> takes connections in, <see cref="ConnectAsync"/> makes
        ///them. Every connection gets an <see cref="AdHoc.Connection.Internal"/> from <see cref="newInternal"/> when its slot
        ///is made and keeps it for the life of the slot, the way a pooled TCP connection does.
        ///</summary>
        public class Host
        {
            public readonly string name;
            internal readonly Engine engine;
            internal readonly Func<AdHoc.Connection.External, AdHoc.Connection.Internal> newInternal;
            internal readonly Action<object, Exception> onFailure;

            ///<summary>Nothing received for this long, in milliseconds, asks <see cref="AdHoc.Connection.Internal.OnReceiveTimeout"/>:
            ///the initial <see cref="Peer.ReceiveTimeout"/>. A datagram transport has no FIN - silence is how a peer is lost.</summary>
            public int idle_timeout = 30_000;

            ///<summary>A PING after this long without sending anything, in milliseconds: keeps the NAT binding and the peer's idle timer.</summary>
            public int keepalive = 15_000;

            ///<summary>The largest datagram sent, in bytes of UDP payload: 1200, the QUIC minimum, passes every path.</summary>
            public int mtu = 1200;

            ///<summary>
            ///This server's static X25519 secret key, 32 bytes (<see cref="X25519.KeyPair"/>). Set, its connections are
            ///encrypted: the Noise NK handshake (<see cref="NoiseNK"/>) in the INITIAL and the ACCEPT, then ChaCha20-Poly1305 on
            ///every packet, forged, damaged and replayed ones dropped. A client pins the matching public key in
            ///<see cref="ConnectAsync"/>, and cannot connect without it. null - no encryption, at no cost.
            ///</summary>
            public byte[]? key;

            ///<summary>
            ///How many bytes of the journal may be out unacknowledged, per connection: the send window until congestion control
            ///has a say. An ask for an acknowledgement, re-sent by the timer, goes out past it.
            ///</summary>
            public int window = 256 << 10;

            ///<summary>
            ///Congestion control - NewReno with pacing - on the connections of this host. Off, a sender goes as fast as the
            ///window lets it: for a LAN or a link of its own, never for the Internet.
            ///</summary>
            public bool congestion = true;

            ///<summary>The first repeat of an INITIAL, in milliseconds; it doubles, up to a second.</summary>
            public int handshake_retry = 250;

            ///<summary>How long an accepted connection waits for its client to show it got the ACCEPT, in milliseconds.</summary>
            public int accept_timeout = 10_000;

            ///<summary>How long a closing side answers the peer's packets with CLOSE again, in milliseconds.</summary>
            public int close_linger = 1_000;

            ///<summary>The kernel buffers of a socket, in bytes; <c>0</c> - what the system gives.</summary>
            public int socket_buffer = 1 << 20;

            ///<summary>How many connections this host holds at once; <c>0</c> - no limit. An INITIAL past it is not answered.</summary>
            public int max_connections;

            internal readonly Peer?[] free;        //per loop
            internal readonly Endpoint?[] clients; //per loop: the socket connections are made through
            readonly byte[] secret = RandomNumberGenerator.GetBytes(32);
            int live;

            public Host(string name, Engine engine, Func<AdHoc.Connection.External, AdHoc.Connection.Internal> newInternal, Action<object, Exception>? onFailure = null)
            {
                this.name = name;
                this.engine = engine;
                this.newInternal = newInternal;
                this.onFailure = onFailure ?? engine.onFailure;
                free = new Peer?[engine.loops.Length];
                clients = new Endpoint?[engine.loops.Length];
            }

            public int connections_live() => Volatile.Read(ref live);

            internal void opened() => Interlocked.Increment(ref live);
            internal void closed() => Interlocked.Decrement(ref live);

            public override string ToString() => $"UDP {name}";
#region tokens
            ///<summary>4 bytes of time and 12 of HMAC-SHA256(secret, time, address, scid): proof that the address answered.</summary>
            internal void token(Span<byte> dst, SocketAddress from, uint scid) => token(dst, from, scid, (uint)(Stopwatch.GetTimestamp() / Stopwatch.Frequency));

            void token(Span<byte> dst, SocketAddress from, uint scid, uint seconds)
            {
                Span<byte> src = stackalloc byte[8 + from.Size];
                System.Buffers.Binary.BinaryPrimitives.WriteUInt32LittleEndian(src, seconds);
                System.Buffers.Binary.BinaryPrimitives.WriteUInt32LittleEndian(src[4..], scid);
                from.Buffer.Span[..from.Size].CopyTo(src[8..]);
                Span<byte> mac = stackalloc byte[32];
                HMACSHA256.HashData(secret, src, mac);
                System.Buffers.Binary.BinaryPrimitives.WriteUInt32LittleEndian(dst, seconds);
                mac[..(TOKEN - 4)].CopyTo(dst[4..]);
            }

            internal bool valid(ReadOnlySpan<byte> token, SocketAddress from, uint scid)
            {
                var seconds = System.Buffers.Binary.BinaryPrimitives.ReadUInt32LittleEndian(token);
                if ((uint)(Stopwatch.GetTimestamp() / Stopwatch.Frequency) - seconds > TOKEN_SECONDS)
                    return false;
                Span<byte> expected = stackalloc byte[TOKEN];
                this.token(expected, from, scid, seconds);
                return CryptographicOperations.FixedTimeEquals(expected, token);
            }
#endregion

            Socket socket(AddressFamily family)
            {
                var s = new Socket(family, SocketType.Dgram, ProtocolType.Udp);
                try
                {
                    if (family == AddressFamily.InterNetworkV6)
                        s.DualMode = true;
                    if (0 < socket_buffer)
                    {
                        s.ReceiveBufferSize = socket_buffer;
                        s.SendBufferSize = socket_buffer;
                    }
                    if (OperatingSystem.IsWindows()) //an ICMP "port unreachable" must not fail the next receive of the socket
                        s.IOControl(unchecked((int)0x9800000C) /*SIO_UDP_CONNRESET*/, new byte[4], null);
                    return s;
                }
                catch
                {
                    s.Dispose();
                    throw;
                }
            }

            ///<summary>
            ///Takes connections in on <paramref name="ips"/>. On Linux every loop gets a socket of its own on each address
            ///(<c>SO_REUSEPORT</c>); elsewhere one loop reads the one socket.
            ///</summary>
            public void bind(params IPEndPoint[] ips)
            {
                var reuse = OperatingSystem.IsLinux() || OperatingSystem.IsAndroid();
                foreach (var address in ips)
                {
                    var ip = address;
                    var loops = reuse ? engine.loops : new[] { engine.pick() };
                    foreach (var loop in loops)
                    {
                        var s = socket(ip.AddressFamily);
                        try
                        {
                            if (reuse)
                                s.SetRawSocketOption(1 /*SOL_SOCKET*/, 15 /*SO_REUSEPORT*/, BitConverter.GetBytes(1));
                            s.Bind(ip);
                            if (ip.Port == 0)
                                ip = (IPEndPoint)s.LocalEndPoint!; //the other loops take the same port
                        }
                        catch
                        {
                            s.Dispose();
                            throw;
                        }
                        var ep = new Endpoint(s, this, true);
                        loop.call(() => loop.add(ep));
                        bound.Add(ip);
                    }
                }
            }

            ///<summary>The addresses this host listens on, as bound: a port 0 is the port the system chose.</summary>
            public readonly List<IPEndPoint> bound = new();

            ///<summary>
            ///Connects to <paramref name="server"/>. Completes with the connection's Internal once the server accepted, or
            ///fails with a <see cref="TimeoutException"/>.
            ///</summary>
            ///<param name="serverKey">The server's static public key, 32 bytes: the connection is encrypted, and only the
            ///server holding the secret of this key can accept it. null - no encryption: only a server without a key accepts.</param>
            public Task<AdHoc.Connection.Internal> ConnectAsync(IPEndPoint server, TimeSpan timeout, byte[]? serverKey = null)
            {
                if (serverKey != null && serverKey.Length != X25519.KEY)
                    throw new ArgumentException("A server key is 32 bytes.", nameof(serverKey));
                var loop = engine.pick();
                var tcs = new TaskCompletionSource<AdHoc.Connection.Internal>(TaskCreationOptions.RunContinuationsAsynchronously);
                var to = new IPEndPoint(server.Address.AddressFamily == AddressFamily.InterNetwork ? server.Address.MapToIPv6() : server.Address, server.Port).Serialize();
                loop.submit(() =>
                            {
                                try
                                {
                                    var ep = clients[loop.index];
                                    if (ep == null)
                                    {
                                        var s = socket(AddressFamily.InterNetworkV6);
                                        s.Bind(new IPEndPoint(IPAddress.IPv6Any, 0));
                                        loop.add(clients[loop.index] = ep = new Endpoint(s, this, false));
                                    }
                                    var p = loop.allocate(this, ep);
                                    p.address = to;
                                    p.pinned = serverKey?.ToArray();
                                    p.connect(tcs, loop.Now() + (long)timeout.TotalMilliseconds * TICKS_MS);
                                }
                                catch (Exception e)
                                {
                                    tcs.TrySetException(e);
                                }
                            });
                return tcs.Task;
            }

            ///<summary>
            ///Continues the parked session of <paramref name="peer"/> over a new handshake - to <paramref name="server"/>, or
            ///to where it was. The slot, its Internal and its journal stay what they were; the identity is kept, so the transport
            ///tells the Internal to resume on its own, as the TCP client does on a reconnect. A failed attempt parks the
            ///session again, for what is left of its wait.
            ///</summary>
            public Task<AdHoc.Connection.Internal> ReconnectAsync(Peer peer, TimeSpan timeout, IPEndPoint? server = null)
            {
                var tcs = new TaskCompletionSource<AdHoc.Connection.Internal>(TaskCreationOptions.RunContinuationsAsynchronously);
                var to = server == null ? null : new IPEndPoint(server.Address.AddressFamily == AddressFamily.InterNetwork ? server.Address.MapToIPv6() : server.Address, server.Port).Serialize();
                var loop = peer.loop;
                loop.submit(() =>
                            {
                                try
                                {
                                    if (peer.host != this || peer.state != Peer.PARKED)
                                        throw new InvalidOperationException("The connection holds no parked session.");
                                    var ep = clients[loop.index];
                                    if (ep == null)
                                    {
                                        var s = socket(AddressFamily.InterNetworkV6);
                                        s.Bind(new IPEndPoint(IPAddress.IPv6Any, 0));
                                        loop.add(clients[loop.index] = ep = new Endpoint(s, this, false));
                                    }
                                    loop.deadlines[PARK].disarm(peer);
                                    peer.ep = ep;
                                    peer.cid = (uint)peer.slot | (uint)RandomNumberGenerator.GetInt32(1 << 32 - SLOT_BITS) << SLOT_BITS; //the old one's late packets name nobody
                                    if (to != null)
                                        peer.address = to;
                                    peer.connect(tcs, loop.Now() + (long)timeout.TotalMilliseconds * TICKS_MS);
                                }
                                catch (Exception e)
                                {
                                    tcs.TrySetException(e);
                                }
                            });
                return tcs.Task;
            }

            ///<summary>Drops every connection of this host - each peer gets a CLOSE - and closes its sockets.</summary>
            public void shutdown()
            {
                foreach (var loop in engine.loops)
                    loop.call(() =>
                              {
                                  for (var i = 0; i < loop.slotsN; i++)
                                  {
                                      var p = loop.slots[i]!;
                                      if (p.host == this && p.state != Peer.FREE)
                                          p.end(TCP.ExternalConnection.Event.THIS_CLOSE_ABRUPTLY, 1);
                                  }
                                  foreach (var ep in loop.endpoints)
                                      if (ep.host == this)
                                          loop.remove(ep);
                                  clients[loop.index] = null;
                              });
                bound.Clear();
            }
        }

        ///<summary>
        ///One connection. It lives on its <see cref="Loop"/>: every field is the loop's, and a call from another thread is
        ///a request (<see cref="request"/>) the loop serves on its next pass.
        ///</summary>
        public sealed class Peer : AdHoc.Connection.External
        {
            internal readonly Loop loop;
            internal readonly Host host;
            internal readonly int slot;

            internal Endpoint? ep;
            internal SocketAddress? address;

            ///<summary>This side's connection id - what the peer's packets carry - and the peer's.</summary>
            internal uint cid, rcid;

            ///<summary>The next packet number.</summary>
            ulong pn; //the low 32 bits go on the wire; all 64 make the nonce

            internal const int FREE = 0, CONNECTING = 1, ACTIVE = 2, CLOSING = 3, PARKED = 4;
            internal volatile int state;

            internal readonly Due[] dues = new Due[7];

            internal Peer? nextFree, nextRequest;

            internal Peer(Loop loop, Host host, int slot)
            {
                this.loop = loop;
                this.host = host;
                this.slot = slot;
            }

            public AdHoc.Connection.Internal Internal { get; set; }

            public bool IsOpen => state == ACTIVE;

            ///<summary>The loop this connection lives on, and its slot there.</summary>
            public int index() => loop.index << SLOT_BITS | slot;

            public override string ToString() => $"[{index()}] {host.name} {state switch { ACTIVE => " active ", CONNECTING => accepting ? " accepting " : " connecting ", CLOSING => " closing ", PARKED => " parked ", _ => " free " }}";
#region requests
            internal const int CLOSE_ = 1, ABORT_ = 2, TIMEOUT_ = 4, TX_ = 8;

            internal int requests;

            ///<summary>From any thread: the loop serves <paramref name="what"/> on its next pass. No allocation, no lock.</summary>
            internal void request(int what)
            {
                if (Interlocked.Or(ref requests, what) == 0)
                    loop.post(this);
            }

            internal void serve(int what)
            {
                if ((what & ABORT_) != 0)
                {
                    end(TCP.ExternalConnection.Event.THIS_CLOSE_ABRUPTLY, 1);
                    return;
                }
                if (state != ACTIVE)
                    return;
                if ((what & CLOSE_) != 0)
                    closePending = true; //the CLOSE goes out once everything sent is acknowledged: see transmit()
                if ((what & TIMEOUT_) != 0)
                    armReceive();
                if ((what & (TX_ | CLOSE_)) != 0)
                    transmit();
            }
#endregion
#region timeouts
            int _receive_timeout = int.MaxValue, _transmit_timeout = int.MaxValue;
            bool closingGracefully;

            ///<summary>Nothing received for this long, in milliseconds, asks the Internal. Negative: a graceful close.</summary>
            public int ReceiveTimeout
            {
                get => closingGracefully ? -_receive_timeout : _receive_timeout;
                set {
                    if (value < 0)
                    {
                        _receive_timeout = -value;
                        closingGracefully = true;
                        request(CLOSE_);
                    }
                    else
                    {
                        _receive_timeout = value;
                        request(TIMEOUT_);
                    }
                }
            }

            ///<summary>Kept for the contract; negative asks a graceful close.</summary>
            public int TransmitTimeout
            {
                get => closingGracefully ? -_transmit_timeout : _transmit_timeout;
                set {
                    if (value < 0)
                    {
                        _transmit_timeout = -value;
                        closingGracefully = true;
                        request(CLOSE_);
                    }
                    else
                        _transmit_timeout = value;
                }
            }

            void armReceive()
            {
                var ms = _receive_timeout;
                if (ms == int.MaxValue)
                    loop.deadlines[RECEIVE].disarm(this);
                else
                    loop.deadlines[RECEIVE].arm(this, receivedAt + ms * TICKS_MS);
            }

            long receivedAt;

            internal void timedOut(int kind, long now)
            {
                switch (kind)
                {
                    case RECEIVE:
                        if (state != ACTIVE)
                            return;
                        var ms = Internal.OnReceiveTimeout();
                        if (state != ACTIVE)
                            return; //the handler closed it
                        if (ms == 0)
                            end(TCP.ExternalConnection.Event.RECEIVE_TIMEOUT, 1);
                        else if (ms != int.MaxValue)
                            loop.deadlines[RECEIVE].arm(this, now + ms * TICKS_MS);
                        return;
                    case KEEPALIVE:
                        if (state == ACTIVE)
                            sendFrame(PING, micros(now));
                        return;
                    case PROBE:
                        if (state != ACTIVE)
                            return;
                        if (r == null || r.next <= r.acked)
                        { //the journal is acknowledged, but datagrams are in flight: an ACK for them was lost, and they hold the window
                            if (0 < inFlight)
                            {
                                flightLost(now);
                                transmit();
                            }
                            return;
                        }
                        //Nothing acknowledged for a probe timeout: ask again, measure the path again, and back off.
                        probing = true;
                        flightLost(now);
                        if (!r.probe())
                        { //the transmitter queue is full: the ask could not be queued - again in a moment, not later
                            loop.deadlines[PROBE].arm(this, now + TICKS_MS);
                            transmit();
                            return;
                        }
                        sendFrame(PING, micros(now));
                        backoff = Math.Min(backoff + 1, 3); //acknowledgements are asked for rarely: a long silence is not the path dying
                        loop.deadlines[PROBE].arm(this, now + (pto() << backoff));
                        transmit();
                        return;
                    case HANDSHAKE:
                        if (state == ACTIVE && confirming)
                        { //the server has not heard this client since its ACCEPT: say so again
                            sendFrame(PING, micros(now));
                            loop.deadlines[HANDSHAKE].arm(this, now + Math.Min((long)host.handshake_retry * TICKS_MS << Math.Min(attempts++, 16), 1000 * TICKS_MS));
                            return;
                        }
                        if (state != CONNECTING)
                            return;
                        if (accepting)
                        { //the client never showed that it got the ACCEPT
                            accepting = false;
                            free();
                            return;
                        }
                        if (connectUntil <= now)
                        {
                            failed(new TimeoutException($"No answer from {address} in time."));
                            return;
                        }
                        sendInitial();
                        //doubling, but not past a second: a server hears the repeats as the client being alive, and it waits only so long
                        loop.deadlines[HANDSHAKE].arm(this, now + Math.Min(connectUntil - now, Math.Min((long)host.handshake_retry * TICKS_MS << Math.Min(attempts++, 16), 1000 * TICKS_MS)));
                        return;
                    case PARK:
                        if (state == PARKED)
                            reap();
                        return;
                    case PACE:
                        if (state == ACTIVE)
                            transmit();
                        return;
                    case LINGER:
                        if (state != CLOSING)
                            return;
                        if (lingerUntil <= now || 3 <= closeRepeats)
                        {
                            free();
                            return;
                        }
                        //A lost CLOSE would leave the peer waiting for its idle timeout: said again, a few times, within the linger.
                        closeRepeats++;
                        sendFrame(CLOSE, 0);
                        loop.deadlines[LINGER].arm(this, Math.Min(lingerUntil, now + (pto() << closeRepeats)));
                        return;
                }
            }
#endregion
#region handshake
            TaskCompletionSource<AdHoc.Connection.Internal>? connecting;
            long connectUntil;
            int attempts;
            readonly byte[] token = new byte[TOKEN];
            bool tokened;
            long initialAt; //the first INITIAL: the handshake is the client's first round trip

            internal void connect(TaskCompletionSource<AdHoc.Connection.Internal> tcs, long until)
            {
                connecting = tcs;
                connectUntil = until;
                attempts = 0;
                tokened = false;
                dropKeys(); //a reconnect: a new handshake, new keys
                state = CONNECTING;
                initialAt = loop.Now();
                sendInitial();
                loop.deadlines[HANDSHAKE].arm(this, loop.Now() + host.handshake_retry * TICKS_MS);
            }

            void sendInitial()
            {
                var tx = loop.tx;
                tx[0] = LONG | INITIAL;
                tx[1] = VERSION;
                u32(tx, 2, cid);
                var pos = 7;
                if (tokened)
                {
                    tx[6] = TOKEN;
                    token.CopyTo(tx, 7);
                    pos += TOKEN;
                }
                else
                    tx[6] = 0;
                if (pinned != null)
                { //the first message of the handshake, written once: every repeat of the INITIAL sends the same bytes
                    if (noise == null)
                    {
                        noise = NoiseNK.Initiator(pinned, prologue(cid));
                        hsLen = noise.WriteMessage(hs, ReadOnlySpan<byte>.Empty);
                    }
                    tx[pos++] = (byte)hsLen;
                    Array.Copy(hs, 0, tx, pos, hsLen);
                    pos += hsLen;
                }
                else
                    tx[pos++] = 0;
                Array.Clear(tx, pos, MIN_INITIAL - pos); //the padding
                loop.send(ep!, address!, MIN_INITIAL);
            }

            internal void retry()
            {
                if (state != CONNECTING)
                    return;
                loop.rx.AsSpan(6, TOKEN).CopyTo(token);
                tokened = true;
                sendInitial();
            }

            ///<summary>
            ///The server side of the handshake: the ACCEPT is out, but the connection opens only when the client shows it got it -
            ///with its first short packet, <see cref="confirmed"/>. Until then there is no REMOTE_CONNECT and no idle timeout of
            ///the application: a lost ACCEPT is sent again for every repeated INITIAL, and the slot waits the connect timeout.
            ///</summary>
            internal void accept()
            {
                accepting = true;
                state = CONNECTING;
                sendAccept();
                loop.deadlines[HANDSHAKE].arm(this, loop.Now() + host.accept_timeout * TICKS_MS);
            }

            internal void confirmed()
            {
                accepting = false;
                loop.deadlines[HANDSHAKE].disarm(this);
                open(TCP.ExternalConnection.Event.REMOTE_CONNECT);
            }

            ///<summary>The server accepted, and the client has not yet shown it got the ACCEPT.</summary>
            internal bool accepting;

            ///<summary>The client got the ACCEPT, and has not yet heard the server since: it says so until it does.</summary>
            bool confirming;

            internal void accepted(uint server, int n)
            {
                if (state != CONNECTING || accepting)
                    return;
                var rx = loop.rx;
                var len = rx[10];
                if (pinned != null)
                { //the second message: only the server holding the pinned key can write it; it names the server's connection id
                    if (len != NoiseNK.OVERHEAD + 4 || n < 11 + len)
                        return;
                    Span<byte> payload = stackalloc byte[4];
                    if (noise!.ReadMessage(rx.AsSpan(11, len), payload) != 4 || System.Buffers.Binary.BinaryPrimitives.ReadUInt32LittleEndian(payload) != server)
                        return; //forged: the real ACCEPT may still come
                    keyed(noise);
                    noise = null;
                }
                else if (len != 0)
                    return; //a server that encrypts, and this client does not know its key
                rcid = server;
                loop.deadlines[HANDSHAKE].disarm(this);
                var tcs = connecting;
                connecting = null;
                var a = attempts;
                open(TCP.ExternalConnection.Event.THIS_CONNECT);
                if (a == 0 && state == ACTIVE) //no INITIAL repeated: the round trip is the one measured
                    sample(loop.Now() - initialAt);
                if (state == ACTIVE)
                { //the server opens the connection on its first short packet: that is this PING, repeated until the server is heard
                    confirming = true;
                    attempts = 0;
                    sendFrame(PING, micros(loop.Now()));
                    loop.deadlines[HANDSHAKE].arm(this, loop.Now() + host.handshake_retry * TICKS_MS);
                }
                if (state == ACTIVE)
                    tcs!.TrySetResult(Internal);
                else
                    tcs!.TrySetException(new InvalidOperationException("The connection was closed while it was being opened."));
            }

            internal void sendAccept()
            {
                var tx = loop.tx;
                tx[0] = LONG | ACCEPT;
                tx[1] = VERSION;
                u32(tx, 2, rcid);
                u32(tx, 6, cid);
                tx[10] = (byte)hsLen; //the second message of the handshake, written once, sent again for a repeated INITIAL
                Array.Copy(hs, 0, tx, 11, hsLen);
                loop.send(ep!, address!, 11 + hsLen);
            }
#region encryption
            ///<summary>The client: the server's static public key it pinned; null - no encryption.</summary>
            internal byte[]? pinned;

            ///<summary>The client's handshake in progress.</summary>
            NoiseNK? noise;

            ///<summary>This side's handshake message - the client's first, the server's second - kept for the repeats.</summary>
            readonly byte[] hs = new byte[NoiseNK.OVERHEAD + 4];

            int hsLen;

            ///<summary>The keys of this connection, one per direction; null - not encrypted.</summary>
            internal ChaCha20.Aead? txKey, rxKey;

            ///<summary>The key this connection's handshake gives the pack stages of the session it carries; null - not encrypted.</summary>
            AdHoc.Connection.Keyring.Key? packKey;

            //The replay window, as WireGuard's and DTLS's: the largest packet number opened, and which of the 64 below it were.
            ulong rxLargest, rxWindow;
            bool rxAny;

            ///<summary>Short packets dropped: their tag did not match - forged or damaged - or their number was seen already.</summary>
            public long forged, replayed;

            ///<summary>The handshake is done: the keys of the two directions. The server writes its reply here, the second message.</summary>
            internal void keyed(NoiseNK h)
            {
                if (!h.Done)
                { //the server: its reply names its connection id, authenticated
                    Span<byte> payload = stackalloc byte[4];
                    System.Buffers.Binary.BinaryPrimitives.WriteUInt32LittleEndian(payload, cid);
                    hsLen = h.WriteMessage(hs, payload);
                }
                packKey = h.PackKey();
                h.Split(out var send, out var receive);
                h.Wipe();
                txKey = send;
                rxKey = receive;
                rxLargest = rxWindow = 0;
                rxAny = false;
            }

            void dropKeys()
            {
                txKey?.Wipe();
                rxKey?.Wipe();
                txKey = rxKey = null;
                noise?.Wipe();
                noise = null;
                hsLen = 0;
                packKey = null;
            }

            ///<summary>A short packet out: sealed when the connection is encrypted - the header authenticated, the frames encrypted, the tag appended.</summary>
            void sendShort(int length)
            {
                var tx = loop.tx;
                if (txKey != null)
                {
                    txKey.Seal(pn - 1, tx.AsSpan(0, SHORT_HEADER), tx.AsSpan(SHORT_HEADER, length - SHORT_HEADER), tx.AsSpan(length, TAG));
                    length += TAG;
                }
                loop.send(ep!, address!, length);
            }

            ///<summary>What a short packet can carry of frames: the MTU, less the tag of an encrypted connection.</summary>
            int payloadMax => txKey == null ? host.mtu : host.mtu - TAG;

            ///<summary>
            ///Opens a short packet of an encrypted connection in the receive buffer: the full packet number from its low 32
            ///bits (RFC 9000, A.3), then the replay window, then the tag.
            ///</summary>
            ///<returns>The length without the tag; -1 - dropped.</returns>
            internal int unseal(int n)
            {
                var rx = loop.rx;
                if (n < SHORT_HEADER + TAG || (rx[0] & 3) != 3)
                {
                    forged++;
                    return -1;
                }
                var expected = rxAny ? rxLargest + 1 : 0;
                var candidate = expected & ~0xFFFF_FFFFUL | u32(rx, 5);
                if (candidate + 0x8000_0000UL <= expected)
                    candidate += 0x1_0000_0000UL;
                else if (expected + 0x8000_0000UL < candidate && 0x1_0000_0000UL <= candidate)
                    candidate -= 0x1_0000_0000UL;
                if (rxAny && candidate <= rxLargest && (64 <= rxLargest - candidate || (rxWindow >> (int)(rxLargest - candidate) & 1) != 0))
                {
                    replayed++;
                    return -1;
                }
                if (!rxKey!.Open(candidate, rx.AsSpan(0, SHORT_HEADER), rx.AsSpan(SHORT_HEADER, n - SHORT_HEADER - TAG), rx.AsSpan(n - TAG, TAG)))
                {
                    forged++;
                    return -1;
                }
                if (!rxAny || rxLargest < candidate)
                { //the window moves up; only an authentic packet moves it
                    var d = rxAny ? candidate - rxLargest : 64;
                    rxWindow = d < 64 ? rxWindow << (int)d | 1 : 1;
                    rxLargest = candidate;
                    rxAny = true;
                }
                else
                    rxWindow |= 1UL << (int)(rxLargest - candidate);
                return n - TAG;
            }
#endregion

            void failed(Exception e)
            {
                var tcs = connecting;
                connecting = null;
                if (resumable != 0 && AdHoc.Connection.Transmitter.Resumable.now() < resumable)
                    park(); //a reconnect of a parked session: it waits on, for what is left of its time
                else
                {
                    if (resumable != 0)
                        reap();
                    else
                        free();
                }
                tcs?.TrySetException(e);
            }
#endregion
#region session
            int sessionOpen;

            internal void open(TCP.ExternalConnection.Event @event)
            {
                state = ACTIVE;
                pn = 0;
                closingGracefully = false;
                _receive_timeout = host.idle_timeout <= 0 ? int.MaxValue : host.idle_timeout;
                var t = loop.Now();
                receivedAt = t;
                armReceive();
                sentAt(t);
                tx_dseq = rx_dseq = 0;
                resync = false;
                closePending = probing = drained = false;
                backoff = 0;
                lastAcked = -1;
                pingAt = 0;
                hasRtt = false;
                resetCongestion(t);
                resumable = 0; //live again, if it was parked
                accepting = false;
                rebind();
                host.opened();
                var before = id;
                Internal.OnExternalEvent(this, @event); //a handler may reclaim a parked session here: the Internal changes
                if (state != ACTIVE)
                    return;
                sessionOpen = 1;
                Internal.OnOpen();
                if (state != ACTIVE)
                    return;
                if (before != 0 && id == before)
                    Internal.resume(this); //an identity kept across the handshakes that the handler did not re-identify
                request(TX_);              //whatever the handlers queued
            }

            ///<summary>The ends of the Internal this connection pulls from and pushes to: again whenever the Internal changes.</summary>
            void rebind()
            {
                src = Internal.BytesSrc;
                dst = Internal.BytesDst;
                r = src as AdHoc.Connection.Transmitter.Resumable;
                tr = src as AdHoc.Connection.Transmitter;
                AdHoc.Connection.Keyring.Seat(Internal, packKey); //the session on this connection encrypts its packs with this connection's key
            }

            ///<summary>Something came from the peer: the idle wait starts over. On a busy connection: two field writes.</summary>
            internal void heard(long now)
            {
                if (confirming)
                {
                    confirming = false;
                    loop.deadlines[HANDSHAKE].disarm(this);
                }
                receivedAt = now;
                if (_receive_timeout != int.MaxValue)
                    loop.deadlines[RECEIVE].arm(this, now + _receive_timeout * TICKS_MS);
            }

            ///<summary>A short packet of this connection, the frames at <paramref name="pos"/>..<paramref name="end"/> of the loop's receive buffer.</summary>
            internal void received(long now, int pos, int end)
            {
                if (state == CLOSING)
                {
                    sendFrame(CLOSE, 0); //it has not heard our CLOSE
                    return;
                }
                heard(now);
                var rx = loop.rx;
                while (pos < end)
                    switch (rx[pos++])
                    {
                        case PADDING:
                            continue;
                        case PING:
                            if (end < pos + 4)
                                goto default;
                            sendFrame(PONG, u32(rx, pos)); //the echo, at once: the round trip is all it measures
                            pos += 4;
                            continue;
                        case PONG:
                            if (end < pos + 4)
                                goto default;
                            sample((long)(uint)(micros(now) - u32(rx, pos)) * TICKS_US);
                            pos += 4;
                            continue;
                        case ACK:
                            if (end < pos + ACK_SIZE - 1)
                                goto default;
                            ack(now, u32(rx, pos), System.Buffers.Binary.BinaryPrimitives.ReadUInt64LittleEndian(rx.AsSpan(pos + 4)), System.Buffers.Binary.BinaryPrimitives.ReadUInt16LittleEndian(rx.AsSpan(pos + 12)));
                            pos += ACK_SIZE - 1;
                            continue;
                        case DATA:
                            data(pos, end, now);
                            return;
                        case CLOSE:
                            var code = varint(rx, ref pos, end);
                            this.end(code == 0 ? TCP.ExternalConnection.Event.REMOTE_CLOSE_GRACEFUL : TCP.ExternalConnection.Event.REMOTE_CLOSE_ABRUPTLY, -1);
                            return;
                        default:
                            host.onFailure(this, new ProtocolViolationException($"An unknown frame 0x{rx[pos - 1]:X2}"));
                            this.end(TCP.ExternalConnection.Event.REMOTE_CLOSE_ABRUPTLY, 1);
                            return;
                    }
            }

            ///<summary>
            ///The session is over: <paramref name="event"/> and <see cref="AdHoc.Connection.Internal.OnClose"/> to the
            ///Internal, the codecs closed. <paramref name="close"/> is the code of the CLOSE the peer is sent, <c>-1</c> -
            ///none; a graceful close lingers to repeat it, anything else frees the slot now.
            ///</summary>
            internal void end(TCP.ExternalConnection.Event @event, long close)
            {
                switch (state)
                {
                    case FREE:
                        return;
                    case CONNECTING:
                        failed(new OperationCanceledException("The connection was closed while connecting."));
                        return;
                    case CLOSING:
                        free();
                        return;
                    case PARKED:
                        reap();
                        return;
                }
                if (0 <= close)
                    sendFrame(CLOSE, close);
                //A loss that is not our own doing - the peer closing, or its silence - parks an identified session for the
                //minutes the Internal names, as over TCP; the close event is withheld until the wait runs out (reap).
                var loss = !closingGracefully && (@event.IsRemote() || @event.IsTimeout());
                var minutes = loss && id != 0 ? Internal.resumable_minutes(this, @event) : 0;
                resumable = minutes <= 0 ? 0 : AdHoc.Connection.Transmitter.Resumable.now() + minutes;
                state = CLOSING; //before the handlers: a call from them finds the connection closed
                host.closed();
                if (resumable == 0)
                    Internal.OnExternalEvent(this, @event);
                if (Interlocked.Exchange(ref sessionOpen, 0) == 1)
                    Internal.OnClose();
                Internal.BytesSrc?.Close(); //parked: the journal stays, and so does the receive position
                Internal.BytesDst?.Close();
                if (resumable != 0)
                {
                    park();
                    return;
                }
                if (close == 0 && state == CLOSING)
                {
                    loop.deadlines[RECEIVE].disarm(this);
                    loop.deadlines[KEEPALIVE].disarm(this);
                    var at = loop.Now();
                    lingerUntil = at + host.close_linger * TICKS_MS;
                    closeRepeats = 0;
                    loop.deadlines[LINGER].arm(this, Math.Min(lingerUntil, at + pto()));
                }
                else if (state == CLOSING)
                    free();
            }

            ///<summary>The slot goes back to its host's free list; the stale entries in the deadline lists are dropped when they come up.</summary>
            void free()
            {
                foreach (var d in loop.deadlines)
                    d.disarm(this);
                if (ep != null && ep.listening && address != null)
                    ep.accepted!.Remove((address, rcid));
                AdHoc.Connection.Keyring.Clear(Internal); //the session is over, or was moved away and this Internal waits for the next
                state = FREE;
                address = null;
                ep = null;
                id = 0;
                dropKeys();
                pinned = null;
                resumable = 0;
                accepting = confirming = false;
                loop.release(this);
            }
#region parking
            ///<summary>
            ///An <see cref="AdHoc.Connection.Transmitter.Resumable.now"/> deadline, in minutes: until it passes, the session of
            ///this slot survives the loss of its connection and waits for its peer; 0 - not parked.
            ///</summary>
            internal int resumable;

            ///<summary>The minutes a parked session still waits for its peer, 0 once its time is up, -1 - no parked session.</summary>
            public int parked => resumable == 0 ? -1 : Math.Max(0, resumable - AdHoc.Connection.Transmitter.Resumable.now());

            ///<summary><c>true</c> while this slot holds a parked session.</summary>
            public bool IsParked => state == PARKED;

            ///<summary>The slot keeps its Internal, its journal and its receive position; nothing is sent or received for it.</summary>
            void park()
            {
                state = PARKED;
                foreach (var d in loop.deadlines)
                    d.disarm(this);
                if (ep != null && ep.listening && address != null)
                    ep.accepted!.Remove((address, rcid)); //a repeated INITIAL of the old handshake starts a new connection
                var left = Math.Max(0, resumable - AdHoc.Connection.Transmitter.Resumable.now());
                loop.deadlines[PARK].arm(this, loop.Now() + left * 60_000L * TICKS_MS);
            }

            ///<summary>The wait is over and the peer did not come back: the close event withheld at the loss, the codecs closed - the journal dropped - and the slot freed.</summary>
            internal void reap()
            {
                resumable = 0;
                state = CLOSING;
                Internal.OnExternalEvent(this, TCP.ExternalConnection.Event.REMOTE_CLOSE_ABRUPTLY);
                Internal.BytesSrc?.Close();
                Internal.BytesDst?.Close();
                free();
            }

            ///<summary>
            ///The peer hands back the token a former connection of this host gave it (<see cref="session"/>): when that slot
            ///still holds the parked session under that identity, the session moves onto this connection - the Internals are
            ///swapped, the parked slot is freed on its own loop - and this connection is identified with it. Otherwise only the
            ///identity is applied. Either way it runs on this connection's loop, so no packet of it is parsed half by one
            ///Internal and half by the other.
            ///</summary>
            ///<returns>This connection's <see cref="session"/>.</returns>
            public long reclaim(long session_id)
            {
                long ret = 0;
                loop.call(() => ret = reclaim_(session_id));
                return ret;
            }

            long reclaim_(long session_id)
            {
                var id = (int)session_id;
                var at = (int)(session_id >> 32);
                if (at != index() && (uint)(at >> SLOT_BITS) < (uint)host.engine.loops.Length)
                {
                    var other = host.engine.loops[at >> SLOT_BITS];
                    var slots = Volatile.Read(ref other.slots);
                    var n = at & SLOT_MASK;
                    var p = n < slots.Length ? slots[n] : null;
                    if (p != null && p.host == host && p.id == id && Interlocked.CompareExchange(ref p.state, CLOSING, PARKED) == PARKED)
                    { //claimed: the reaper of its loop finds it no longer parked
                        var left = Internal;
                        (p.Internal, Internal) = (Internal, p.Internal);
                        if (Volatile.Read(ref sessionOpen) == 1)
                        {
                            left.OnClose();
                            Internal.OnOpen();
                        }
                        Internal.External(this);
                        p.Internal.External(p); //the fresh one stays with the freed slot, seated there for its next session
                        rebind();
                        this.id = 0; //the identity is applied again below, and with it the resume
                        other.submit(p.free);
                    }
                }
                return identify(id);
            }
#endregion
#endregion
#region sending
            void sentAt(long t) => loop.deadlines[KEEPALIVE].arm(this, t + host.keepalive * TICKS_MS);

            ///<summary>A short packet with one frame: <paramref name="frame"/> and, for a CLOSE, its code, for a PING or a PONG, the timestamp.</summary>
            void sendFrame(byte frame, long code)
            {
                var tx = loop.tx;
                tx[0] = SHORT | 3; //a 4-byte packet number
                u32(tx, 1, rcid);
                u32(tx, 5, (uint)pn++);
                var pos = SHORT_HEADER;
                tx[pos++] = frame;
                if (frame == CLOSE)
                    varint(tx, ref pos, code);
                else if (frame is PING or PONG)
                {
                    u32(tx, pos, (uint)code); //the timestamp
                    pos += 4;
                }
                sendShort(pos);
                if (state == ACTIVE)
                    sentAt(loop.Now());
            }
#endregion
#region the stream
            //The bytes of the connection are the ones its Internal pulls and pushes, as over TCP; what TCP gave for free - that
            //a lost byte is sent again - comes from the Resumable stage of the generated connection, which journals the packs.
            //What is left here: numbering the datagrams of the stream, telling the receiver where a pack starts when one is
            //lost before it, a window, and a timer for the silence that no pack behind a loss can break.

            AdHoc.BytesSrc? src;
            AdHoc.BytesDst? dst;
            AdHoc.Connection.Transmitter.Resumable? r; //the stage that journals, when the connection has one
            AdHoc.Connection.Transmitter? tr;          //the transmitter itself, when it has not

            ///<summary>The DATA frames, each way, numbered on their own: a lost PING must not look like lost data.</summary>
            uint tx_dseq, rx_dseq;

            ///<summary>A DATA frame was lost: the receiver dropped its half-read pack and waits for the start of one.</summary>
            bool resync;

            ///<summary>A graceful close waits for everything sent to be acknowledged; the transmitter is dry.</summary>
            bool closePending, drained;

            ///<summary>An ask for an acknowledgement is out after a probe timeout: it may go past the window.</summary>
            bool probing;

            int backoff;
            long lastAcked, pingAt;

            ///<summary>A graceful close: until when the slot answers the peer with CLOSE, and how often it said it on its own.</summary>
            long lingerUntil;

            int closeRepeats;

            ///<summary>The round trip, RFC 6298: smoothed and its variation, in clock ticks.</summary>
            long srtt, rttvar;

            bool hasRtt;

            ///<summary>Received DATA: gaps, frames skipped for want of a pack start, bytes refused by the receiver.</summary>
            public long gaps, skipped, refused;

            ///<summary>For a log line: the stream state of the connection.</summary>
            public string streamText => $"{this} id={id} dseq tx={tx_dseq} rx={rx_dseq} lost={lostDatagrams} rewinds={rewinds} cwnd={cwnd / 1024}KB inflight={inFlight} tokens={tokens:F0} oldest={oldest} srtt={(double)srtt / TICKS_MS:F1}ms pace={(dues[PACE].armed ? "armed" : "-")} drained={drained} gaps={gaps} skipped={skipped} refused={refused}{(resync ? " resync" : "")}{(probing ? " probing" : "")} backoff={backoff} pto={(double)pto() / TICKS_MS:F1}ms probe={(dues[PROBE].armed ? $"in {(double)(dues[PROBE].due - Stopwatch.GetTimestamp()) / TICKS_MS:F0}ms" : "-")} {r}";

            ///<summary>The round trip smoothed, in milliseconds; <c>-1</c> while nothing was measured.</summary>
            public double rtt => hasRtt ? (double)srtt / TICKS_MS : -1;

            const int DATA_HEADER = SHORT_HEADER + 1 + 4 + 2; //the packet header, the frame type, the number, the first pack
            const int NO_PACK = 0xFFFF;

            internal void sample(long ticks)
            {
                if (ticks <= 0 || 60_000 * TICKS_MS < ticks)
                    return; //a PONG of an earlier session, or a clock step
                if (!hasRtt)
                {
                    srtt = ticks;
                    rttvar = ticks / 2;
                    hasRtt = true;
                    return;
                }
                rttvar = (3 * rttvar + Math.Abs(srtt - ticks)) / 4;
                srtt = (7 * srtt + ticks) / 8;
            }

            ///<summary>The probe timeout, RFC 9002 without the ack delay: the receiver answers an ask at once.</summary>
            long pto() => Math.Max(hasRtt ? srtt + Math.Max(4 * rttvar, TICKS_MS) : 250 * TICKS_MS, 2 * TICKS_MS);

            ///<summary>The journal moved up: the silence is over.</summary>
            void progress(long now)
            {
                if (r == null || r.acked == lastAcked)
                    return;
                lastAcked = r.acked;
                backoff = 0;
                probing = false;
                if (r.next <= r.acked)
                    loop.deadlines[PROBE].disarm(this);
                else
                    loop.deadlines[PROBE].arm(this, now + pto());
            }

            ///<summary>
            ///Fills datagrams from the source until it is dry or the window is full, a bounded burst per call. The first pack
            ///that starts in each datagram is named in it; a PING rides along every 100 ms to keep the round trip measured.
            ///</summary>
            void transmit()
            {
                if (state != ACTIVE)
                    return;
                var tx = loop.tx;
                var now = loop.Now();
                drained = src == null; //nothing to send, ever
                for (var burst = 0; !drained; burst++)
                {
                    if (burst == 64)
                    {
                        request(TX_); //the other connections of the loop first
                        break;
                    }
                    if (r != null && !probing && host.window <= r.sent - r.acked)
                    {
                        r.Read(tx, DATA_HEADER, 0); //applies what acknowledgements were posted: they may make room
                        progress(now);
                        if (host.window <= r.sent - r.acked)
                            break;
                    }
                    if (!mayTransmit(now, host.mtu))
                        break; //the window, the ring or the pacing: an ACK or the PACE deadline goes on
                    var pos = SHORT_HEADER;
                    var ack = 0 < ackPending;
                    if (ack)
                        pos = putAck(tx, pos, now); //what this side owes the peer rides along
                    tx[pos] = DATA;
                    var at = pos + 1;
                    pos += 7;
                    var n = src.Read(tx, pos, payloadMax - pos);
                    progress(now);
                    if (n <= 0)
                    {
                        drained = true;
                        if (ack)
                            ackPending = 1; //it did not go out: the loop sends it on its own at the end of the pass
                        break;
                    }
                    drained = false;
                    var f = r != null ? r.first : tr?.first_pack ?? -1;
                    tx[0] = SHORT | 3;
                    u32(tx, 1, rcid);
                    u32(tx, 5, (uint)pn++);
                    sent(tx_dseq, now, pos + n, r != null && r.readAt < r.sent ? r.readAt : -1);
                    u32(tx, at, tx_dseq++);
                    System.Buffers.Binary.BinaryPrimitives.WriteUInt16LittleEndian(tx.AsSpan(at + 4), f < pos || pos + n <= f ? (ushort)NO_PACK : (ushort)(f - pos));
                    sendShort(pos + n);
                    sentAt(now);
                    loop.deadlines[PROBE].arm(this, now + (pto() << backoff)); //in flight now: a busy sender, two field writes
                }
                if ((0 < inFlight || r != null && r.acked < r.next) && !dues[PROBE].armed)
                    loop.deadlines[PROBE].arm(this, now + (pto() << backoff)); //also when nothing could go out: a journal waiting for the peer to name its position. Only when not armed: a pass that sent nothing must not push the probe back
                if (closePending && drained && (r == null || r.next <= r.acked))
                    end(TCP.ExternalConnection.Event.THIS_CLOSE_GRACEFUL, 0);
            }

            ///<summary>
            ///A DATA frame at <paramref name="pos"/>, to <paramref name="end"/>: the next one - its bytes go on where the
            ///last left off; a later one - one or more were lost, so the pack half-read is dropped and parsing starts again
            ///at the first pack that starts here; an earlier one - late, or a duplicate: dropped.
            ///</summary>
            void data(int pos, int end, long now)
            {
                if (end < pos + 6 || dst == null)
                    return;
                var rx = loop.rx;
                var dseq = u32(rx, pos);
                var first = System.Buffers.Binary.BinaryPrimitives.ReadUInt16LittleEndian(rx.AsSpan(pos + 4));
                pos += 6;
                received(dseq, now); //arrived - even a late one: to congestion control it was not lost
                if ((int)(dseq - rx_dseq) < 0)
                    return;
                if (dseq != rx_dseq && !resync)
                {
                    (dst as AdHoc.Connection.Receiver)?.Abandon();
                    resync = true;
                    gaps++;
                }
                rx_dseq = dseq + 1;
                if (resync)
                {
                    if (first == NO_PACK || end - pos <= first)
                    {
                        skipped++;
                        return; //all of it continues a pack whose start is lost
                    }
                    pos += first;
                    resync = false;
                }
                var n = dst.Write(rx, pos, end - pos);
                if (n < end - pos)
                { //refused, or a parse error: what is left is lost, as a datagram would be
                    refused++;
                    (dst as AdHoc.Connection.Receiver)?.Abandon();
                    resync = true;
                }
            }
#endregion
#region congestion control
            //NewReno as RFC 9002 has it (appendix B), with pacing (7.7). What it needs from the peer is which datagrams arrived:
            //the ACK frame - the largest DATA number received, a bitmap of the 64 below it, and how long the receiver held it.
            //That is all an ACK is for here: nothing is sent again on it, the journal replays what the packs lost.

            ///<summary>What is in flight, by DATA number: when it went out, how many bytes it took - 0: not in flight - and the
            ///journal position of its first journalled byte - -1: none.</summary>
            readonly long[] flightAt = new long[FLIGHT];
            readonly int[] flightSize = new int[FLIGHT];
            readonly long[] flightPos = new long[FLIGHT];

            //Fast retransmit, as TCP's: a DATA frame taken for lost rewinds the journal to the pack that holds its first byte, at
            //once - a gap costs the receiver everything after it, and its Resume_ a round trip, or a probe timeout when it is lost.
            //Once per round: the losses of frames sent before the last rewind are behind it already, unless they are further back.
            long lostFrom = long.MaxValue, rewoundAt, rewoundTo = long.MaxValue;

            void rewind(long now)
            {
                if (lostFrom == long.MaxValue)
                    return;
                var at = r!.rewind(lostFrom);
                lostFrom = long.MaxValue;
                if (at < 0)
                    return;
                rewoundAt = now;
                rewoundTo = at;
                rewinds++;
            }

            ///<summary>How many times the journal went back on a loss the transport saw.</summary>
            public long rewinds;

            const int FLIGHT = 1024; //a power of two: the ring is indexed by the number's low bits

            ///<summary>The oldest DATA number that may still be in flight; everything below it is acknowledged or lost.</summary>
            uint oldest;

            long inFlight, cwnd, ssthresh = long.MaxValue, recoveryStart, latestRtt;

            ///<summary>Pacing: bytes that may go out now, and when they were counted.</summary>
            double tokens;

            long tokensAt;

            void resetCongestion(long now)
            {
                Array.Clear(flightSize);
                oldest = 0;
                inFlight = 0;
                lostFrom = rewoundTo = long.MaxValue;
                rewoundAt = now;
                cwnd = 10L * host.mtu;
                ssthresh = long.MaxValue;
                recoveryStart = now;
                latestRtt = 0;
                tokens = cwnd;
                tokensAt = now;
                ackLargest = 0;
                ackBits = 0;
                ackHas = false;
                ackPending = 0;
            }

            ///<summary>Room for <paramref name="size"/> more bytes: the congestion window, the ring, and the pacing budget. A probe goes past all three.</summary>
            bool mayTransmit(long now, int size)
            {
                if (FLIGHT <= (int)(tx_dseq - oldest))
                    return false;
                if (!host.congestion)
                    return true;
                if (cwnd < inFlight + size)
                    return probing && inFlight < cwnd + 2L * host.mtu; //a probe may go a couple of datagrams past the window, no more
                if (hasRtt)
                {
                    var rate = 1.25 * cwnd / srtt; //bytes a tick
                    tokens = Math.Min(tokens + (now - tokensAt) * rate, Math.Max(10.0 * host.mtu, rate * 2 * TICKS_MS));
                    tokensAt = now;
                    if (tokens < size)
                    {
                        loop.deadlines[PACE].arm(this, now + (long)((size - tokens) / rate) + 1);
                        return false;
                    }
                }
                return true;
            }

            void sent(uint dseq, long now, int size, long pos)
            {
                var i = (int)(dseq & FLIGHT - 1);
                flightAt[i] = now;
                flightSize[i] = size;
                flightPos[i] = pos;
                inFlight += size;
                tokens -= size;
            }

            ///<summary>An ACK frame at <paramref name="pos"/>: 4 bytes the largest DATA number, 8 the bitmap below it, 2 the delay in microseconds.</summary>
            void ack(long now, uint largest, ulong bits, int delay)
            {
                if ((int)(largest - tx_dseq) >= 0)
                    return; //acknowledges what was never sent: of an earlier session
                var i = (int)(largest & FLIGHT - 1);
                if (0 < flightSize[i] && (int)(largest - oldest) >= 0)
                {
                    var rtt = now - flightAt[i] - delay * TICKS_US;
                    if (0 < rtt)
                    {
                        latestRtt = rtt;
                        sample(rtt);
                    }
                }
                acked(largest);
                for (var b = 0; bits != 0; b++, bits >>= 1)
                    if ((bits & 1) != 0)
                        acked(largest - 1 - (uint)b);

                //Lost: three numbers behind what arrived, or sent 9/8 of a round trip before it.
                var late = now - Math.Max(srtt, latestRtt) * 9 / 8;
                for (; (int)(oldest - largest) < 0; oldest++)
                {
                    var j = (int)(oldest & FLIGHT - 1);
                    if (flightSize[j] == 0)
                        continue;
                    if ((int)(largest - oldest) < 3 && late < flightAt[j])
                        break; //may still arrive
                    lost(j, now);
                }
                while (oldest != tx_dseq && flightSize[oldest & FLIGHT - 1] == 0)
                    oldest++;
                rewind(now);
                request(TX_); //room was made
            }

            void acked(uint dseq)
            {
                if ((int)(dseq - oldest) < 0 || (int)(dseq - tx_dseq) >= 0)
                    return;
                var i = (int)(dseq & FLIGHT - 1);
                var size = flightSize[i];
                if (size == 0)
                    return;
                flightSize[i] = 0;
                inFlight -= size;
                if (flightAt[i] <= recoveryStart)
                    return; //sent before the last reduction: it tells nothing of the window now
                if (cwnd < ssthresh)
                    cwnd += size; //slow start
                else
                    cwnd += (long)host.mtu * size / cwnd; //congestion avoidance
            }

            void lost(int i, long now)
            {
                var size = flightSize[i];
                flightSize[i] = 0;
                inFlight -= size;
                lostDatagrams++;
                var pos = flightPos[i];
                if (0 <= pos && (rewoundAt < flightAt[i] || pos < rewoundTo) && pos < lostFrom)
                    lostFrom = pos;
                if (flightAt[i] <= recoveryStart)
                    return; //one reduction for a whole round of losses
                recoveryStart = now;
                ssthresh = cwnd = Math.Max(cwnd / 2, 2L * host.mtu);
            }

            ///<summary>The probe timeout found nothing acknowledged: what is in flight is taken for lost, so it holds the window no more.</summary>
            void flightLost(long now)
            {
                for (; oldest != tx_dseq; oldest++)
                    if (flightSize[oldest & FLIGHT - 1] != 0)
                        lost((int)(oldest & FLIGHT - 1), now);
                rewind(now);
            }

            ///<summary>Datagrams taken for lost; congestion control counts them, the journal replays their packs.</summary>
            public long lostDatagrams;

            ///<summary>The congestion window, in bytes.</summary>
            public long congestionWindow => cwnd;

            //The receiving side of the ACK: the largest DATA number received, the 64 below it, and when the largest came.
            uint ackLargest;
            ulong ackBits;
            bool ackHas;
            long ackAt;

            ///<summary>DATA received since the last ACK went out; the loop sends the ACK at the end of its pass, or at 32.</summary>
            internal int ackPending;

            internal Peer? nextAck;
            internal bool ackListed;

            void received(uint dseq, long now)
            {
                if (!ackHas)
                {
                    ackHas = true;
                    ackLargest = dseq;
                    ackBits = 0;
                    ackAt = now;
                }
                else
                {
                    var d = (int)(dseq - ackLargest);
                    if (0 < d)
                    {
                        ackBits = d < 64 ? ackBits << d | 1UL << d - 1 : d == 64 ? 1UL << 63
                                                                                 : 0;
                        ackLargest = dseq;
                        ackAt = now;
                    }
                    else if (d < 0 && -d <= 64)
                        ackBits |= 1UL << -d - 1;
                }
                if (ackPending++ == 0)
                    loop.ackLater(this);
                else if (32 <= ackPending)
                    sendAck(now);
            }

            ///<summary>The ACK frame into <paramref name="tx"/> at <paramref name="pos"/>.</summary>
            int putAck(byte[] tx, int pos, long now)
            {
                tx[pos] = ACK;
                u32(tx, pos + 1, ackLargest);
                System.Buffers.Binary.BinaryPrimitives.WriteUInt64LittleEndian(tx.AsSpan(pos + 5), ackBits);
                System.Buffers.Binary.BinaryPrimitives.WriteUInt16LittleEndian(tx.AsSpan(pos + 13), (ushort)Math.Min(ushort.MaxValue, (now - ackAt) / TICKS_US));
                ackPending = 0;
                return pos + ACK_SIZE;
            }

            const int ACK_SIZE = 15;

            internal void sendAck(long now)
            {
                if (ackPending == 0 || state != ACTIVE)
                    return;
                var tx = loop.tx;
                tx[0] = SHORT | 3;
                u32(tx, 1, rcid);
                u32(tx, 5, (uint)pn++);
                sendShort(putAck(tx, SHORT_HEADER, now));
            }
#endregion
#region External(the stream)
            ///<summary>Queued packs are there to send: the loop pulls them on its next pass. From any thread.</summary>
            public void WakeTransmit() => request(TX_);

            ///<summary>The identity the session was given - see <see cref="identify"/>; 0 while it has none. Before it the packs
            ///travel unguarded: a journal belongs to a session, and there is no session before the peer is known.</summary>
            public int id { get; private set; }

            ///<summary>This connection is the session of <paramref name="id"/>: the Internal is told to <see cref="AdHoc.Connection.Internal.resume"/>,
            ///which names the receive position to the peer and opens the journal.</summary>
            ///<returns>The session id: the loop, the slot and the identity.</returns>
            public long identify(int id)
            {
                if (this.id == id)
                    return session(); //already this identity: the resume that went with it is not repeated
                this.id = id;
                if (state == ACTIVE)
                {
                    Internal.resume(this);
                    WakeTransmit();
                }
                return session();
            }

            public long session() => (long)index() << 32 | (uint)id;
#endregion
#region varint
            ///<summary>The QUIC variable-length integer: the top two bits of the first byte are the length 1/2/4/8, big-endian.</summary>
            static long varint(byte[] b, ref int pos, int end)
            {
                if (end <= pos)
                    return -1;
                var len = 1 << (b[pos] >> 6);
                if (end < pos + len)
                    return -1;
                long v = b[pos++] & 0x3F;
                for (var i = 1; i < len; i++)
                    v = v << 8 | b[pos++];
                return v;
            }

            static void varint(byte[] b, ref int pos, long v)
            {
                if (v < 1 << 6)
                    b[pos++] = (byte)v;
                else if (v < 1 << 14)
                {
                    b[pos++] = (byte)(0x40 | v >> 8);
                    b[pos++] = (byte)v;
                }
                else if (v < 1 << 30)
                {
                    b[pos++] = (byte)(0x80 | v >> 24);
                    b[pos++] = (byte)(v >> 16);
                    b[pos++] = (byte)(v >> 8);
                    b[pos++] = (byte)v;
                }
                else
                {
                    b[pos++] = (byte)(0xC0 | v >> 56);
                    for (var s = 48; 0 <= s; s -= 8)
                        b[pos++] = (byte)(v >> s);
                }
            }
#endregion
#region External
            ///<summary>A graceful close: the peer gets a CLOSE, repeated while it keeps sending, for <see cref="Host.close_linger"/>.</summary>
            public void Close() => request(CLOSE_);

            ///<summary>An abrupt close: the peer gets one CLOSE with a non-zero code, the slot is freed at once.</summary>
            public void Abort() => request(ABORT_);
#endregion
        }
    }
}

