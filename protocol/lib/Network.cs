        ///<summary>
        ///The registry of all allocated connections. This array only expands and is never shrunk
        ///to ensure O(1) access by connection ID.
        ///</summary>
        protected volatile ExternalConnection[] _connections = new ExternalConnection[64];

        ///<summary>
        ///The number of connections currently instantiated in the <see cref="_connections"/>.
        ///</summary>
        protected int _connectionsSize = 0;

        ///<summary>
        ///Parked sessions, one singly linked list per host, kept ascending by <see cref="ExternalConnection.resumable"/>
        ///deadline and linked through the same <see cref="ExternalConnection.next"/> field the free stack uses (a slot is
        ///on exactly one of the two, or active). One lock guards the three operations — a park inserts, a reclaim or a
        ///reconnect removes, the reaper pops the expired head.
        ///</summary>
        readonly object parked_lock = new();
        ExternalConnection? parked_head;

        ///<summary>
        ///Claims the parked session of <paramref name="id"/> on the slot at <paramref name="index"/>: found on the parked
        ///list, taken off it, and returned FREE. Such a slot keeps its <see cref="ExternalConnection.Internal"/> and holds
        ///neither socket nor buffers. Exactly one caller wins it against the reaper.
        ///</summary>
        ///<returns>The slot, FREE and off the list, or null.</returns>
        public ExternalConnection? parked(long session_id)
        {
            int index = (int)(session_id >> 32), id = (int)session_id;
            if (index < 0)
                return null;
            lock (parked_lock)
            {
                ExternalConnection? prev = null;
                for (var c = parked_head; c != null; prev = c, c = c.next)
                    if (c.index_ == index && c.id == id && Interlocked.CompareExchange(ref c.conn_state, ExternalConnection.FREE, ExternalConnection.PARKED) == ExternalConnection.PARKED)
                    {
                        if (prev == null)
                            parked_head = c.next;
                        else
                            prev.next = c.next;
                        c.next = null;
                        return c;
                    }
            }
            return null;
        }

        ///<summary>
        ///Puts a lost session on the parked list, sorted by its deadline. Most sessions on a host share the same wait, so
        ///the common case lands at the tail. A new earliest deadline wakes the maintenance loop to re-arm its timer.
        ///</summary>
        protected void ParkConnection(ExternalConnection con)
        {
            lock (parked_lock)
            {
                con.conn_state = ExternalConnection.PARKED;
                if (parked_head == null || con.resumable < parked_head.resumable)
                {
                    con.next = parked_head;
                    parked_head = con;
                    TriggerMaintenance();
                }
                else
                {
                    var p = parked_head;
                    while (p.next != null && p.next.resumable <= con.resumable)
                        p = p.next;
                    con.next = p.next;
                    p.next = con;
                }
            }
        }

        ///<summary>
        ///Ends every parked session whose deadline has passed and returns the milliseconds until the earliest deadline
        ///still on the list (<see cref="long.MaxValue"/> when empty). The expired heads are unlinked under the lock and
        ///closed outside it, so the reaper never holds the lock across application close callbacks.
        ///</summary>
        protected long ReapParked()
        {
            var now = AdHoc.Connection.Transmitter.Resumable.now();
            ExternalConnection? expired = null;
            lock (parked_lock)
            {
                while (parked_head != null && parked_head.resumable <= now)
                {
                    var c = parked_head;
                    parked_head = c.next;
                    if (Interlocked.CompareExchange(ref c.conn_state, ExternalConnection.CLEANING, ExternalConnection.PARKED) == ExternalConnection.PARKED)
                    {
                        c.next = expired;
                        expired = c;
                    }
                    else
                        c.next = null; //a returning peer claimed it
                }
            }
            for (var c = expired; c != null;)
            {
                var nx = c.next;
                c.next = null;
                c.Reap();
                c = nx;
            }
            lock (parked_lock) return parked_head == null ? long.MaxValue : Math.Max(0L, (long)(parked_head.resumable - now)) * 60_000L;
        }

        ///<summary>
        ///A lock-free stack of available (inactive) connections ready for reuse.
        ///Uses the <see cref="ExternalConnection.next"/> field as the stack pointer.
        ///</summary>
        protected ExternalConnection? _freeConnections = null;

        ///<summary>
        ///Retrieves a connection by its unique ID in O(1) time.
        ///</summary>
        public ExternalConnection? GetConnection(int id)
        {
            //1. Thread-safe read of the current count
            var currentSize = Volatile.Read(ref _connectionsSize);
            if (id < 0 || id >= currentSize)
                return null;

            //2. Local reference to the array to handle expansion mid-read
            var registry = _connections;
            if (id >= registry.Length)
                return null;

            var conn = registry[id];
            //Only return if the connection exists and is currently in an active state
            return (conn != null && conn.IsActive) ? conn : null;
        }

        ///<summary>
        ///Returns a connection to the pool.
        ///Only <see cref="ExternalConnection.FinishDispose"/> may call this: the connection has been through
        ///CLEANING and every operation the kernel was given has reported, so nothing can still be looking at
        ///its buffers or SAEAs.
        ///</summary>
        protected internal virtual void ReturnToFreePool(ExternalConnection conn)
        {
            if (internals != null)
            { //a multiplexed port: the slot rests as its own Internal until the next caller names its connection
                if (conn.Internal != conn)
                {
                    conn.incumbent = conn.Internal; //kept at hand: a caller of the same connection takes it back for nothing
                    conn.Internal = conn;
                }
                conn.held_ws_connect = false;
            }
            conn.conn_state = ExternalConnection.FREE; //Mark as eligible for reuse

            //Standard Lock-Free Stack Push
            ExternalConnection? head;
            do
            {
                head = Volatile.Read(ref _freeConnections);
                conn.next = head;
            } while (Interlocked.CompareExchange(ref _freeConnections, conn, head) != head);
        }

        ///<summary>
        ///Allocates a connection. It first attempts to pop a recycled connection from the free stack.
        ///If the stack is empty, it expands the registry and creates a new instance.
        ///</summary>
        protected ExternalConnection allocate()
        {
            ExternalConnection? conn;

            //1. Fast Path: Try to pop from the lock-free recycling stack
            while ((conn = Volatile.Read(ref _freeConnections)) != null)
                if (Interlocked.CompareExchange(ref _freeConnections, conn.next, conn) == conn)
                    //Attempt to transition the connection from FREE to ACTIVE
                    if (conn.IsActivateDeactivated())
                    {
                        conn.next = null; //Clean up the stack pointer
                        return conn;
                    }

            //2. Slow Path: Create new instance and potentially expand the registry
            lock (this)
            {
                //Double-check the free stack under lock
                conn = Volatile.Read(ref _freeConnections);
                if (conn != null && Interlocked.CompareExchange(ref _freeConnections, conn.next, conn) == conn)
                {
                    if (conn.IsActivateDeactivated())
                    {
                        conn.next = null;
                        return conn;
                    }
                }

                //Expansion logic
                var index = _connectionsSize;
                //Check if we need to expand the registry array
                if (_connections.Length <= index)
                {
                    var newRegistry = new ExternalConnection[_connections.Length * 2];
                    Array.Copy(_connections, 0, newRegistry, 0, _connections.Length);
                    _connections = newRegistry; //Volatile publication of the new array
                }

                //Create and initialize the new connection
                conn = NewConnection(this);
                if (internals != null)
                    conn.Internal = conn; //a multiplexed port: the slot starts as its own Internal
                conn.index_ = index;

                _connections[index] = conn; //Place in array BEFORE incrementing size

                //Force activation state
                if (!conn.IsActivateDeactivated())
                    throw new InvalidOperationException(
                        $"Failed to activate newly constructed connection at index {index}. " +
                        $"Factory implementations must not touch the connection's lifecycle state.");

                //Increment size last (Acts as a publication for GetConnection and Maintenance loops)
                Interlocked.Increment(ref _connectionsSize);
            }

            return conn;
        }

