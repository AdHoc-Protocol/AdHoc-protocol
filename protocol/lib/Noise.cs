//The handshake of an encrypted connection: Noise_NK_25519_ChaChaPoly_SHA256, as the Noise Protocol Framework (revision 34,
//https://noiseprotocol.org/noise.html) defines it. The client knows the server's static public key beforehand - pinned,
//as an SSH host key or a WireGuard peer key - and the server proves it holds the secret; both sides get keys of their own
//per connection, with forward secrecy. The client is authenticated later, by the application's own login inside.
//
//  <- s              the server's static key, known to the client
//  ...
//  -> e, es          message 1, client to server: 32 bytes of ephemeral key, the payload, a 16-byte tag
//  <- e, ee          message 2, server to client: the same
//
//Then Split gives one ChaCha20-Poly1305 key per direction. Transport-agnostic: the UDP transport carries the two
//messages in its INITIAL and ACCEPT, a stream transport as its first exchange; each numbers its messages itself.
//The same wire as the Java runtime's Noise.java. The cryptography lies in the native library: see Chain.cs.
using System;
using System.Buffers;
using System.Runtime.InteropServices;
using System.Threading;

namespace org.unirail;

///<summary>
///The handshake, in the native library: one call a message, which makes every hash, agreement and key of it; when the last message is
///through, the transport keys and the key of the packs lie made in its memory, and only what the session needs of them ever reaches managed memory.
///</summary>
public sealed unsafe class NoiseNK
{
    public const int KEY = 32, TAG = ChaCha20.Aead.TAG;

    ///<summary>The overhead of a handshake message of NK: the ephemeral key and the tag of the payload.</summary>
    public const int OVERHEAD = KEY + TAG;

    ///<summary>The patterns of the Noise Protocol Framework. NK: the client knows the server. IK: and proves itself in its first message. XX: neither knows the other beforehand. KK: both know.</summary>
    public const int PATTERN_NK = 0, PATTERN_IK = 1, PATTERN_XX = 2, PATTERN_KK = 3;

    const int H = 0, PACK_KEY = 32, PACK_IV = 64, DONE = 76, PEER = 80;
    static readonly int size = Crypto.adhoc_noise_size(), tx = Crypto.adhoc_noise_tx(), rx = Crypto.adhoc_noise_rx();

    readonly byte *state;

    NoiseNK(int pattern, bool initiator, ReadOnlySpan<byte> prologue, ReadOnlySpan<byte> staticSecret, ReadOnlySpan<byte> staticPublic, ReadOnlySpan<byte> peer, ReadOnlySpan<byte> ephemeral)
    {
        state = (byte *)NativeMemory.AlignedAlloc((nuint)size, 16);
        fixed(byte *pr = prologue, ss = staticSecret, sp = staticPublic, pe = peer, ep = ephemeral)
            Crypto.adhoc_noise_init((long)state, pattern, initiator ? 1 : 0, pr, prologue.Length, staticSecret.IsEmpty ? null : ss, staticPublic.IsEmpty ? null : sp, peer.IsEmpty ? null : pe, ephemeral.IsEmpty ? null : ep);
    }

    ~NoiseNK()
    {
        NativeMemory.Clear(state, (nuint)size);
        NativeMemory.AlignedFree(state);
    }

    ///<summary>Any of the patterns. <paramref name="staticSecret"/>: this side's, empty - the pattern gives it none. <paramref name="peer"/>: the other side's static
    ///key where the pattern has it known beforehand, empty otherwise. <paramref name="ephemeral"/> for tests only.</summary>
    public static NoiseNK Of(int pattern, bool initiator, ReadOnlySpan<byte> prologue, ReadOnlySpan<byte> staticSecret, ReadOnlySpan<byte> peer, ReadOnlySpan<byte> ephemeral = default) => new(pattern, initiator, prologue, staticSecret, default, peer, ephemeral);

    ///<summary>The client's side: it knows the server's static public key.</summary>
    ///<param name="ephemeral">For tests only: the ephemeral secret to use instead of a random one.</param>
    public static NoiseNK Initiator(ReadOnlySpan<byte> serverPublic, ReadOnlySpan<byte> prologue, ReadOnlySpan<byte> ephemeral = default) => new(PATTERN_NK, true, prologue, default, default, serverPublic.Slice(0, KEY), ephemeral);

    ///<summary>The server's side: its static key pair.</summary>
    public static NoiseNK Responder(ReadOnlySpan<byte> staticSecret, ReadOnlySpan<byte> prologue, ReadOnlySpan<byte> ephemeral = default) => new(PATTERN_NK, false, prologue, staticSecret.Slice(0, KEY), default, default, ephemeral);

    ///<summary>The server's side, with the public key of its static secret computed once: not a curve multiplication a handshake.</summary>
    public static NoiseNK Responder(ReadOnlySpan<byte> staticSecret, ReadOnlySpan<byte> staticPublic, ReadOnlySpan<byte> prologue, ReadOnlySpan<byte> ephemeral) => new(PATTERN_NK, false, prologue, staticSecret.Slice(0, KEY), staticPublic.Slice(0, KEY), default, ephemeral);

    ///<summary>
    ///Writes this side's next handshake message, with <paramref name="payload"/>, encrypted.
    ///</summary>
    ///<returns>The length written; -1 - not this side's turn, or the peer's key is of low order.</returns>
    public int WriteMessage(Span<byte> dst, ReadOnlySpan<byte> payload)
    {
        fixed(byte *d = dst, p = payload) return Crypto.adhoc_noise_write((long)state, d, dst.Length, p, payload.Length);
    }

    ///<summary>Reads the peer's handshake message; its payload is decrypted into <paramref name="payload"/>. A message that fails leaves the state
    ///as it was: a forged one ahead of the real one does not spoil the handshake.</summary>
    ///<returns>The payload length; -1 - out of turn, too short, a low-order key, or forged.</returns>
    public int ReadMessage(ReadOnlySpan<byte> msg, Span<byte> payload)
    {
        fixed(byte *m = msg, p = payload) return Crypto.adhoc_noise_read((long)state, m, msg.Length, p, payload.Length);
    }

    public bool Done => *(int *)(state + DONE) != 0;

    ///<summary>The handshake hash: the same on both sides, unique to this handshake - a channel binding.</summary>
    public ReadOnlySpan<byte> HandshakeHash => new(state + H, 32);

    ///<summary>The static key of the other side, proved by the handshake, once it is done: what a pattern with a client key brings ( E5 ).</summary>
    public byte[] PeerKey() => new ReadOnlySpan<byte>(state + PEER, KEY).ToArray();

    ///<summary>
    ///The transport keys once the handshake is done: one ChaCha20-Poly1305 key per direction, each message numbered by
    ///its sender from 0 (the nonce). They lie in this handshake's memory.
    ///</summary>
    public void Split(out ChaCha20.Aead send, out ChaCha20.Aead receive)
    {
        if (!Done)
            throw new InvalidOperationException("The handshake is not done.");
        send = new ChaCha20.Aead((long)state + tx, this);
        receive = new ChaCha20.Aead((long)state + rx, this);
    }

    ///<summary>
    ///The key this handshake gives the pack stages of the session (<see cref="AdHoc.Connection.Keyring"/>): 32 bytes of key and 12 of
    ///base nonce, the id from the handshake hash - the same on both sides, never 0. Call before <see cref="Wipe"/>.
    ///</summary>
    public AdHoc.Connection.Keyring.Key PackKey()
    {
        if (!Done)
            throw new InvalidOperationException("The handshake is not done.");
        var id = *(uint *)(state + H);
        return new AdHoc.Connection.Keyring.Key(id == 0 ? 1 : id, new ReadOnlySpan<byte>(state + PACK_KEY, 32).ToArray(), new ReadOnlySpan<byte>(state + PACK_IV, 12).ToArray());
    }

    ///<summary>What is secret and not needed any more goes. When the handshake is done that is the key of the packs; its transport keys stay until their <see cref="ChaCha20.Aead.Wipe"/>.</summary>
    public void Wipe()
    {
        if (Done)
            NativeMemory.Clear(state + PACK_KEY, (nuint)(DONE - PACK_KEY));
        else
            NativeMemory.Clear(state, (nuint)size);
    }
}

///<summary>
///An encrypted byte stream between a connection's Internal and its transport - TCP, a WebSocket (inside its frames), any
///ordered, reliable byte stream. The transport reads the outgoing bytes from it and writes the incoming ones to it, in
///place of the Internal's <c>BytesSrc</c> and <c>BytesDst</c>; it talks to the Internal through the two getters it is given,
///so an Internal that changes under the connection is followed.
///<para>
///First the <see cref="NoiseNK"/> handshake, each message as <c>[length 1][message]</c>: the client writes message 1 at once,
///the server answers with message 2. Then records, as TLS and Noise frame a stream: <c>[length 2, little-endian]
///[ciphertext][tag 16]</c>, at most 16 KB of plaintext each, ChaCha20-Poly1305 with the length as the associated data and
///the record count of the direction as the nonce - nothing of it on the wire, the stream keeps the order. A record that does
///not open - forged, damaged, replayed, dropped, reordered - ends the stream: a byte stream has no record to skip.
///</para>
///<para>
///The records are sealed in place in the transport's own send buffer. Received records that lie whole in the transport's
///receive buffer are opened there, all in one call, and handed on from there; only a record cut by the end of what was offered
///comes to a buffer taken from the pool, for as long as it takes. A connection keeps no buffer of data here.
///</para>
///</summary>
public sealed class NoiseStream : AdHoc.BytesSrc, AdHoc.BytesDst
{
    public const int RECORD = 16 * 1024, HEADER = 2, TAG = NoiseNK.TAG;

    ///<summary>What the handshake of a stream is bound to: the protocol and its version.</summary>
    internal static readonly byte[] PROLOGUE = System.Text.Encoding.ASCII.GetBytes("AdHoc stream 1");

    readonly Func<AdHoc.BytesSrc?> src;
    readonly Func<AdHoc.BytesDst?> dst;
    readonly Action wake;
    readonly Action<AdHoc.Connection.Keyring.Key>? keys;

    ///<summary>The key this connection's handshake gives the pack stages of its session (<see cref="AdHoc.Connection.Keyring"/>); null before the handshake is done.</summary>
    public AdHoc.Connection.Keyring.Key? PackKey { get; private set; }

    NoiseNK? hs;
    ChaCha20.Aead? tx, rx;
    long txN, rxN;

    //The handshake messages: [length][message]. The longest message of the patterns, with no payload: 96 bytes, and its length. Gone when the handshake is over.
    const int HS_BUFFER = 128;
    byte[]? hsOut = new byte[HS_BUFFER], hsIn = new byte[HS_BUFFER];
    int hsOutLen, hsOutPos;

    //A record cut by the end of what was offered, and the plaintext of one the destination has not taken all of: from the pool, only while one comes this way.
    byte[]? recBuf;
    int got, need = 1, plainPos, plainEnd;

    //Bytes ahead in the offer that are whole records opened already; of the current one, the plaintext not yet taken.
    int opened, body, tagLeft, skip;
    bool ahead; //the chain has been through this offer: no call for what it could not open

    volatile bool failed;

    ///<summary>Records that did not open: the stream ended at the first.</summary>
    public long forged;

    ///<summary>Calls into the native library past those of the chain: a record cut by the end of what was offered.</summary>
    public long extraCalls;

    ///<summary>The chain this stream is a layer of: it seals and opens with the others, in their one call.</summary>
    internal Chain.Link? link;

    ///<summary>What decides who may come in, when the pattern brings the key of the other side. null - anyone.</summary>
    Predicate<byte[]>? onPeer;

    ///<summary>The key of the other side, proved by the handshake: for a pattern that brings it.</summary>
    public byte[]? peerKey;

    NoiseStream(Func<AdHoc.BytesSrc?> src, Func<AdHoc.BytesDst?> dst, Action wake, Action<AdHoc.Connection.Keyring.Key>? keys)
    {
        this.src = src;
        this.dst = dst;
        this.wake = wake;
        this.keys = keys;
    }

    void first()
    {
        hsOutLen = 1 + hs!.WriteMessage(hsOut.AsSpan(1), ReadOnlySpan<byte>.Empty);
        hsOut![0] = (byte)(hsOutLen - 1);
    }

    ///<summary>The client's end: it pinned the server's static public key, and sends the first message at once.</summary>
    ///<param name="wake">Asks the transport to read from this again: the handshake got on, and there is something to send.</param>
    ///<param name="keys">Takes the pack key of the handshake, for the session the connection carries - before anything is sent under the new keys.</param>
    public static NoiseStream Client(ReadOnlySpan<byte> serverPublic, Func<AdHoc.BytesSrc?> src, Func<AdHoc.BytesDst?> dst, Action wake, Action<AdHoc.Connection.Keyring.Key>? keys = null)
    {
        var s = new NoiseStream(src, dst, wake, keys) { hs = NoiseNK.Initiator(serverPublic, PROLOGUE) };
        s.first();
        return s;
    }

    ///<summary>The server's end, with its static secret key: it waits for the client's first message.</summary>
    public static NoiseStream Server(ReadOnlySpan<byte> staticSecret, Func<AdHoc.BytesSrc?> src, Func<AdHoc.BytesDst?> dst, Action wake, Action<AdHoc.Connection.Keyring.Key>? keys = null) =>
        new(src, dst, wake, keys) { hs = NoiseNK.Responder(staticSecret, PROLOGUE) };

    ///<summary>The server's end, with the public key of its static secret computed once.</summary>
    public static NoiseStream Server(ReadOnlySpan<byte> staticSecret, ReadOnlySpan<byte> staticPublic, Func<AdHoc.BytesSrc?> src, Func<AdHoc.BytesDst?> dst, Action wake, Action<AdHoc.Connection.Keyring.Key>? keys = null) =>
        new(src, dst, wake, keys) { hs = NoiseNK.Responder(staticSecret, staticPublic, PROLOGUE, default) };

    ///<summary>Any pattern. <paramref name="client"/>: this side writes the first message.</summary>
    public static NoiseStream Of(int pattern, bool client, ReadOnlySpan<byte> staticSecret, ReadOnlySpan<byte> peer, Func<AdHoc.BytesSrc?> src, Func<AdHoc.BytesDst?> dst, Action wake, Action<AdHoc.Connection.Keyring.Key>? keys, Predicate<byte[]>? onPeer)
    {
        var s = new NoiseStream(src, dst, wake, keys) { hs = NoiseNK.Of(pattern, client, PROLOGUE, staticSecret, peer), onPeer = onPeer };
        if (client)
            s.first();
        return s;
    }

    ///<summary>Both directions have their keys.</summary>
    public bool Ready => Volatile.Read(ref tx) != null;

    ///<summary>The chain may open the records of the next offer: nothing of a record is held here.</summary>
    internal bool Aligned => rx != null && opened == 0 && got == 0 && need == HEADER && body == 0 && tagLeft == 0 && plainPos == plainEnd;

    internal long RxContext => rx!.ctx;

    internal long RxNumber => rxN;

    ///<summary>The chain has opened this many bytes of the next offer, in so many records.</summary>
    internal void OpenedAhead(int bytes, int records)
    {
        opened = bytes;
        rxN += records;
        ahead = true;
    }

    ///<summary>What is held of a record moves to the start of <paramref name="dst"/>, when it leaves room to read: how much.</summary>
    internal int GiveBack(byte[] dst)
    {
        if (got == 0 || rx == null || recBuf == null || opened != 0 || body != 0 || tagLeft != 0 || plainPos != plainEnd || dst.Length <= got << 1)
            return 0;
        var len = got;
        System.Buffer.BlockCopy(recBuf, 0, dst, 0, len);
        got = 0;
        need = HEADER;
        Release();
        return len;
    }

    ///<summary>The whole-record buffer, back where it came from: the record is taken up, or the connection is gone.</summary>
    internal void Release()
    {
        var b = recBuf;
        recBuf = null;
        if (b != null)
            ArrayPool<byte>.Shared.Return(b);
    }
#region out
    ///<summary>The bytes to send: the handshake message, then records of what the Internal's source gives.</summary>
    public int Read(byte[] dst_, int at, int room)
    {
        if (failed)
            return -1;
        var tx = Volatile.Read(ref this.tx); //first: the handshake answer is written before the keys are published
        if (hsOutPos < Volatile.Read(ref hsOutLen))
        {
            var n = Math.Min(room, hsOutLen - hsOutPos);
            Array.Copy(hsOut!, hsOutPos, dst_, at, n);
            hsOutPos += n;
            return n;
        }
        if (tx == null)
            return 0; //the keys come with the server's answer
        hsOut = null;
        var inner = src();
        if (inner == null)
            return 0;
        var pos = at;
        var end = at + room;
        var records = 0;
        while (HEADER + 1 + TAG <= end - pos)
        {
            var n = inner.Read(dst_, pos + HEADER, Math.Min(RECORD, end - pos - HEADER - TAG));
            if (n < 1)
            {
                if (pos == at)
                    return n; //nothing now, or the source is dry
                break;
            }
            dst_[pos] = (byte)n;
            dst_[pos + 1] = (byte)(n >> 8);
            pos += HEADER + n + TAG;
            records++;
        }
        if (link != null)
        { //goes with the rest of this buffer's chain
            link.Noise(tx.ctx, txN, at, pos - at);
            txN += records;
        }
        else if ((txN = tx.SealRecords(txN, dst_, at, pos - at)) < 0) //all of them, in one call
            throw new InvalidOperationException("seal");
        return pos - at;
    }

    public bool isOpen() => !failed && (src()?.isOpen() ?? false);

    void AdHoc.BytesSrc.Close() => src()?.Close();
#endregion
#region in
    ///<summary>The bytes received: the handshake message, then records, opened and handed on to the Internal's destination.</summary>
    ///<returns>How many were taken; 0 - the destination refuses now, offer them again later; -1 - the stream is broken.</returns>
    public int Write(byte[] src_, int at, int length)
    {
        if (failed)
            return -1;
        var taken = 0;
        var pos = at;
        var end = at + length;
        if (skip != 0 && pos < end)
        { //a byte taken already, kept in the transport's hands: see below
            pos++;
            skip = 0;
            taken = 1;
        }
        for (;;)
        {
            if (plainPos < plainEnd)
            { //an opened record the destination has not taken all of
                var d = dst();
                if (d == null)
                    return keepTail(pos, end, taken);
                var n = d.Write(recBuf!, plainPos, plainEnd - plainPos);
                if (n < 0)
                    return n;
                if (n == 0)
                    return keepTail(pos, end, taken);
                plainPos += n;
                if (plainPos == plainEnd)
                    Release();
                continue;
            }

            if (!ahead && opened == 0 && got == 0 && need == HEADER && rx != null && HEADER < end - pos)
            { //all the whole records in the transport's buffer, opened where they lie, in one call
                extraCalls++;
                var r = rx.OpenRecords(rxN, src_, pos, end - pos, RECORD);
                if (r < 0)
                    return fail();
                rxN += (int)r;
                opened = (int)(r >> 32);
            }
            while (0 < opened)
            { //handed on from there; what the destination refuses stays there, for the transport to offer again
                //Every step only as far as this offer goes: an offer may stop short of what was opened from a longer one.
                if (0 < tagLeft)
                {
                    var k = Math.Min(tagLeft, end - pos);
                    if (k == 0)
                        return taken;
                    pos += k;
                    tagLeft -= k;
                    opened -= k;
                    taken += k;
                    continue;
                }
                if (body == 0)
                {
                    if (end - pos < HEADER)
                        return taken;
                    body = src_[pos] | src_[pos + 1] << 8;
                    pos += HEADER;
                    opened -= HEADER;
                    taken += HEADER;
                }
                var d = dst();
                if (d == null)
                    return taken;
                var offered = Math.Min(body, end - pos);
                if (offered == 0)
                    return taken;
                var n = d.Write(src_, pos, offered);
                if (n < 0)
                    return n;
                pos += n;
                body -= n;
                opened -= n;
                taken += n;
                if (n < offered)
                    return taken;
                if (body == 0)
                    tagLeft = TAG;
            }
            if (pos == end)
                return taken;
            ahead = false; //what the chain could not open goes the slow way: a part of a record, or one that fails there

            var more = Math.Min(need - got, end - pos);
            if (rx == null)
                System.Buffer.BlockCopy(src_, pos, hsIn!, got, more);
            else
            {
                recBuf ??= ArrayPool<byte>.Shared.Rent(HEADER + RECORD + TAG);
                System.Buffer.BlockCopy(src_, pos, recBuf, got, more);
            }
            pos += more;
            got += more;
            taken += more;
            if (got < need)
                continue;

            if (rx == null)
            { //the handshake: [length][message]
                if (need == 1)
                {
                    need = 1 + hsIn![0];
                    if (need - 1 < NoiseNK.KEY || HS_BUFFER < need)
                        return fail();
                    continue;
                }
                if (!handshake())
                    return fail();
                got = 0;
                need = rx != null ? HEADER : 1; //a pattern of three messages goes on
                continue;
            }
            if (need == HEADER)
            {
                var len = recBuf![0] | recBuf[1] << 8;
                if (len == 0 || RECORD < len)
                    return fail();
                need = HEADER + len + TAG;
                continue;
            }
            var plain = need - HEADER - TAG;
            extraCalls++;
            if (!rx.Open((ulong)rxN++, recBuf.AsSpan(0, HEADER), recBuf.AsSpan(HEADER, plain), recBuf.AsSpan(HEADER + plain, TAG)))
                return fail();
            plainPos = HEADER;
            plainEnd = HEADER + plain;
            got = 0;
            need = HEADER;
        }
    }

    //The plaintext of a record put together here is refused, and the transport's buffer has no more: the transport wakes a
    //parked receive only for a tail it holds, so the last byte stays with it, counted as taken when it comes again.
    int keepTail(int pos, int end, int taken)
    {
        if (pos == end && 0 < taken && skip == 0)
        {
            skip = 1;
            return taken - 1;
        }
        return taken;
    }

    //A handshake message in hsIn[1..need): the server reads the first and answers, the client reads the answer.
    bool handshake()
    {
        var h = hs!;
        if (h.ReadMessage(hsIn.AsSpan(1, need - 1), Span<byte>.Empty) < 0)
            return false;
        if (!h.Done)
        {
            //The transmit runs on a thread of its own and is done with the last message: it sees this one when it is whole.
            var len = 1 + h.WriteMessage(hsOut.AsSpan(1), ReadOnlySpan<byte>.Empty);
            hsOut![0] = (byte)(len - 1);
            hsOutLen = 0;
            hsOutPos = 0;
            Volatile.Write(ref hsOutLen, len);
            if (!h.Done)
            { //a pattern of three messages: its answer goes, the keys come with the next
                wake();
                return true;
            }
        }
        var peer = h.PeerKey();
        if (peer.AsSpan().ContainsAnyExcept((byte)0)) //a side that does not learn the key of the other ( the server of NK ) has nothing to ask about
        {
            peerKey = peer;
            if (onPeer != null && !onPeer(peer))
                return false;
        }
        PackKey = h.PackKey();
        keys?.Invoke(PackKey); //before the keys are published: no pack goes out ahead of its key
        h.Split(out var send, out var receive);
        h.Wipe();
        hs = null;
        hsIn = null;
        rx = receive;
        Volatile.Write(ref tx, send); //last: a transmit on another thread that sees the keys sees the answer too
        wake();                       //the server's answer, or what the client queued meanwhile
        return true;
    }

    int fail()
    {
        forged++;
        failed = true;
        return -1;
    }

    void AdHoc.BytesDst.Close() => dst()?.Close();
#endregion
}
