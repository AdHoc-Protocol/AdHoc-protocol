///<summary>
///The built-in stages of a chain - <c>[Zstd]</c>, <c>[ChaCha20]</c>, <c>[Envelope]</c> - as one: the native library runs all of them in
///one call a buffer each way, C# only says which and hands it the buffers. What is chosen and what came of a call lies in the memory of
///the library, read and written here where it lies: the offsets are those of <c>Stages</c> in adhoc_crypto.c.
///<para>A lone <c>ChaCha20</c> copies nothing: the plaintext is ciphered where it lies, in the buffer of the socket. With <c>Zstd</c> or an
///<c>Envelope</c> it goes through the staging - an array of C#, pinned, the library reads and writes it where it is: the serializer
///writes into it as into any buffer, the call takes it from there into the buffer of the socket. The staging grows here, never there:
///a call that wants more room gives -3 and says how much.</para>
///<list type="bullet">
///<item><c>[ChaCha20]</c> on a pack: 12 bytes in clear ahead of it - the id of the session's key it is ciphered with and the sequence of
///its nonce -, each pack deciphered alone with the key it names (<see cref="AdHoc.Connection.Transmitter.keys"/>).</item>
///<item><c>[Envelope]</c>: the pack sealed for one reader and signed by its author, as <see cref="Chain.Pack"/> makes it: [id 4][number 8],
///the text, the signature, the tag. Its keys are the <see cref="Chain.Pack"/> of the transmitter and of the receiver (<c>envelope</c>),
///set before the pack goes or comes. Gathered whole: it is opened only so, and nothing of it reaches the pack before it is.</item>
///</list>
///</summary>
public sealed unsafe class Stages
{
    ///<summary>The kinds of the stages, as the native library knows them.</summary>
    public const int ZSTD = 1, CHACHA20 = 2, CHACHA20_PACK = 3, ENVELOPE = 4;

    const int COUNT = 0, TX = 4, KIND = 8, LEVEL = 24, ENV_CTX = 40, ENV_KEY = 48, ENV_N = 56, ENV_ID = 64, KEYS = 68, RING = 72, SEQ = 264,
              BUF = 272, CAP = 280, LEN = 288, AT = 292, DONE = 296, TAKEN = 300, OPEN = 304, PHASE = 308, EXT = 312, NEED = 316, HEADER = 12,
              MAX_KEYS = 4, MIN_ROOM = 256, NO_ROOM = -3;

    static readonly int size = Crypto.adhoc_stages_size();

    ///<summary>The memory of the library: what is chosen, what a call did, its codecs behind them.</summary>
    readonly byte *mem;

    ///<summary>The staging: pinned, the library reads and writes it where it lies.</summary>
    byte[] staging = Array.Empty<byte>();

    bool inPlace; //a lone ChaCha20: in place, no staging
    int kinds;    //bits of the kinds chosen
    int envelope; //of an Envelope: 1 - sealed, 2 - signed

    Stages(bool tx)
    {
        mem = (byte *)NativeMemory.AllocZeroed((nuint)size);
        I(TX, tx ? 1 : 0);
        I(EXT, 1);
    }

    ~Stages()
    {
        Crypto.adhoc_stages_free((long)mem);
        NativeMemory.Free(mem);
    }

    int I(int at) => *(int *)(mem + at);
    void I(int at, int v) => *(int *)(mem + at) = v;
    void L(int at, long v) => *(long *)(mem + at) = v;
    long L(int at) => *(long *)(mem + at);

    bool Has(int kind) => (kinds & 1 << kind) != 0;

    ///<summary>The stages, leaf first: one or two - a compressor, then a cipher.</summary>
    void Choose(int kind1, int level1, int kind2, int level2)
    {
        var n = kind2 == 0 ? 1 : 2;
        I(COUNT, n);
        I(KIND, kind1);
        I(LEVEL, level1);
        I(KIND + 4, kind2);
        I(LEVEL + 4, level2);
        kinds = 1 << kind1 | (kind2 == 0 ? 0 : 1 << kind2);
        envelope = kind1 == ENVELOPE ? level1 : kind2 == ENVELOPE ? level2
                                                                  : 0;
        inPlace = n == 1 && (kind1 == CHACHA20 || kind1 == CHACHA20_PACK);
        if (Has(ZSTD))
            Room(128 * 1024 + 64); //what Zstd decompresses into at once
        Rearm();
    }

    ///<summary>A new stream: nothing of the last one is left.</summary>
    void Rearm()
    {
        var b = I(TX) == 1 && Has(ENVELOPE) && !Has(ZSTD) ? HEADER : 0;
        I(LEN, b);
        I(AT, b);
        I(DONE, 0);
        I(TAKEN, 0);
        I(OPEN, 0);
        I(PHASE, 0);
    }

    ///<summary>Room for <paramref name="need"/> bytes in the staging: a bigger array, pinned, what was there kept.</summary>
    void Room(int need)
    {
        if (need <= staging.Length)
            return;
        var b = GC.AllocateUninitializedArray<byte>(Math.Max(need, Math.Max(4096, staging.Length * 2)), pinned: true);
        Buffer.BlockCopy(staging, 0, b, 0, staging.Length);
        staging = b;
        *(long *)(mem + BUF) = (long)Unsafe.AsPointer(ref MemoryMarshal.GetArrayDataReference(b));
        I(CAP, b.Length);
    }

    void Key(int i, AdHoc.Connection.Keyring.Key k)
    {
        I(RING + 48 * i, (int)k.id);
        new ReadOnlySpan<byte>(k.key).CopyTo(new Span<byte>(mem + RING + 48 * i + 4, 32));
        new ReadOnlySpan<byte>(k.iv).CopyTo(new Span<byte>(mem + RING + 48 * i + 36, 12));
    }

    ///<summary>The key and nonce of a stream's own ChaCha20.</summary>
    void StreamKey(byte[]? key, byte[]? nonce)
    {
        if (key == null || nonce == null)
            return;
        if (key.Length != 32 || nonce.Length != 12)
            throw new ArgumentException("ChaCha20: a key of 32 bytes and a nonce of 12");
        I(RING, 0);
        key.AsSpan().CopyTo(new Span<byte>(mem + RING + 4, 32));
        nonce.AsSpan().CopyTo(new Span<byte>(mem + RING + 36, 12));
        I(KEYS, 1);
        L(SEQ, 0);
    }

    ///<summary>A pack's keys, at its first bytes: the newest key of the session and a fresh sequence; the Envelope of the transmitter.</summary>
    void KeyedTx(AdHoc.Connection.Transmitter dst)
    {
        if (Has(CHACHA20_PACK))
        {
            var k = dst.keys.Current ?? throw new InvalidOperationException("A pack chain with ChaCha20 on a connection without keys: encrypt the connection (a host key, a pinned server key), or add a key to its Transmitter's and Receiver's keys.");
            Key(0, k);
            I(KEYS, 1);
            L(SEQ, (long)ChaCha20.Core.NextSeq());
        }
        if (Has(ENVELOPE))
        {
            var e = dst.envelope ?? throw new InvalidOperationException("A pack chain with Envelope and no keys of it: set the Transmitter's envelope ( Chain.Pack: Pair, SignedBy ) before the pack goes.");
            if ((envelope & 1) != 0 && e.ctx == 0 || (envelope & 2) != 0 && e.secret == 0)
                throw new InvalidOperationException("The Envelope of the pack is to be " + ((envelope & 1) != 0 ? "sealed - its pair is not set ( Chain.Pack.Pair )" : "") + ((envelope & 3) == 3 ? " and " : "") + ((envelope & 2) != 0 ? "signed - the key to sign with is not set ( Chain.Pack.SignedBy )" : ""));
            L(ENV_CTX, (envelope & 1) != 0 ? e.ctx : 0);
            L(ENV_KEY, (envelope & 2) != 0 ? e.secret : 0);
            L(ENV_N, e.number++);
            I(ENV_ID, e.id);
        }
    }

    ///<summary>A pack's keys on the receiving side: the session's newest ones - the pack names its own -; the Envelope of the receiver.</summary>
    void KeyedRx(AdHoc.Connection.Receiver src)
    {
        if (Has(CHACHA20_PACK))
        {
            var n = 0;
            for (AdHoc.Connection.Keyring.Key? k; n < MAX_KEYS && (k = src.keys.Newest(n)) != null; n++)
                Key(n, k);
            I(KEYS, n);
        }
        if (Has(ENVELOPE))
        {
            var e = src.envelope ?? throw new InvalidOperationException("A pack chain with Envelope and no keys of it: set the Receiver's envelope ( Chain.Pack: Pair, SignerOf ) before the pack comes.");
            if ((envelope & 1) != 0 && e.ctx == 0 || (envelope & 2) != 0 && e.pub == 0)
                throw new InvalidOperationException("The Envelope of the pack is " + ((envelope & 1) != 0 ? "sealed - its pair is not set ( Chain.Pack.Pair )" : "") + ((envelope & 3) == 3 ? " and " : "") + ((envelope & 2) != 0 ? "signed - whose key it is signed by is not set ( Chain.Pack.SignerOf )" : ""));
            L(ENV_CTX, (envelope & 1) != 0 ? e.ctx : 0);
            L(ENV_KEY, (envelope & 2) != 0 ? e.pub : 0);
            I(ENV_ID, e.id);
        }
    }

    ///<summary>Transmitting stages.</summary>
    public interface Transmitter
    {
        ///<summary>
        ///The built-in stages of a chain on the transmitting side. Inner role (<see cref="Init(AdHoc.Connection.Transmitter.BytesSrc,int,int)"/>):
        ///an upstream serializer writes its plaintext - into the buffer of the socket, a lone ChaCha20 enciphers it there; else into the
        ///staging, and one call takes it through every stage into the buffer of the socket. Transport role (<c>Init_</c>): the whole stream
        ///of a connection.
        ///</summary>
        public sealed class Stage : AdHoc.Connection.Transmitter.BytesSrc, AdHoc.BytesSrc
        {
            readonly Stages s = new(true);
            AdHoc.Connection.Transmitter.BytesSrc? src;
            bool eof;
            readonly byte[] hdr = new byte[HEADER];
            int hdrPut = HEADER;

            public int __id { get; set; }

            ///<summary>One stage: its kind, and Zstd's level ( an Envelope's flags, 0 for ChaCha20 ).</summary>
            public Stage Init(AdHoc.Connection.Transmitter.BytesSrc src, int kind, int level) => Init(src, kind, level, 0, 0);

            ///<summary>Two stages, leaf first: a compressor, then a cipher.</summary>
            public Stage Init(AdHoc.Connection.Transmitter.BytesSrc src, int kind1, int level1, int kind2, int level2)
            {
                this.src = src;
                src_ = null;
                s.Choose(kind1, level1, kind2, level2);
                eof = false;
                hdrPut = s.Has(CHACHA20_PACK) && s.inPlace ? -1 : HEADER;
                return this;
            }

            ///<summary>With a stream's own ChaCha20 key and nonce ( 32 and 12 bytes ), set at runtime.</summary>
            public Stage Init(AdHoc.Connection.Transmitter.BytesSrc src, int kind1, int level1, int kind2, int level2, byte[]? key, byte[]? nonce)
            {
                Init(src, kind1, level1, kind2, level2);
                s.StreamKey(key, nonce);
                return this;
            }

            public bool __get_bytes(AdHoc.Connection.Transmitter dst)
            {
                if (s.inPlace)
                { //a lone ChaCha20: the key id and the sequence in clear, then the plaintext ciphered where it lies
                    if (hdrPut < 0)
                    {
                        s.KeyedTx(dst);
                        var seq = s.L(SEQ);
                        var id = s.I(RING);
                        for (var i = 0; i < 4; i++)
                            hdr[i] = (byte)(id >>> 8 * i);
                        for (var i = 0; i < 8; i++)
                            hdr[4 + i] = (byte)(seq >>> 8 * i);
                        hdrPut = 0;
                    }
                    for (; hdrPut < HEADER; hdrPut++)
                    {
                        if (dst.byte_max <= dst.byte_)
                            return false;
                        dst.buffer![dst.byte_++] = hdr[hdrPut];
                    }
                    var from = dst.byte_;
                    var done = src!.__get_bytes(dst);
                    if (from < dst.byte_)
                        fixed(byte *p = dst.buffer)
                            Crypto.adhoc_stages_xor((long)s.mem, p + from, dst.byte_ - from);
                    if (done)
                    {
                        s.I(PHASE, 0);
                        hdrPut = s.Has(CHACHA20_PACK) ? -1 : HEADER;
                    }
                    return done;
                }
                if (s.I(PHASE) == 0 && s.I(LEN) == s.I(AT) && !eof)
                    s.KeyedTx(dst);
                for (;;)
                {
                    var wrote = false;
                    var len = s.I(LEN);
                    if (len == s.I(AT) && !eof)
                    { //the stages took all: the serializer writes more
                        if (!s.Has(ENVELOPE) || s.Has(ZSTD))
                        {
                            s.I(LEN, len = 0);
                            s.I(AT, 0);
                        }
                        s.Room(len + MIN_ROOM);
                        var outBuf = dst.buffer;
                        var outPos = dst.byte_;
                        var outMax = dst.byte_max;
                        dst.buffer = s.staging;
                        dst.byte_ = len;
                        dst.byte_max = s.staging.Length;
                        int to;
                        try
                        {
                            eof = src!.__get_bytes(dst);
                        }
                        finally
                        {
                            to = dst.byte_;
                            dst.buffer = outBuf;
                            dst.byte_ = outPos;
                            dst.byte_max = outMax;
                        }
                        wrote = len < to;
                        s.I(LEN, to);
                    }
                    int r;
                    fixed(byte *o = dst.buffer)
                        r = Crypto.adhoc_stages_tx((long)s.mem, o + dst.byte_, dst.byte_max - dst.byte_, eof ? 1 : 0);
                    if (r == NO_ROOM)
                    {
                        s.Room(s.I(NEED));
                        continue;
                    }
                    var done = s.I(DONE);
                    dst.byte_ += done;
                    if (r < 0)
                        throw new InvalidOperationException("The stages of a chain failed: out of memory, or no key.");
                    if (r == 1)
                    {
                        eof = false;
                        return true;
                    }
                    if (dst.byte_max <= dst.byte_ || !wrote && done == 0 && !eof && s.I(LEN) == s.I(AT))
                        return false; //the socket's buffer is full, or the serializer has nothing now
                }
            }
#region TRANSPORT role : the whole stream of a connection.No end : where the upper layer has nothing now, the stages flush.
            AdHoc.BytesSrc? src_;
            bool closed, dirty;
            ///<summary>Bytes the stages put on the wire so far.</summary>
            public long wire_bytes;

            ///<summary>Arm as the transport stage of a connection. A stream's own ChaCha20 key and nonce, if it has one.</summary>
            public Stage Init_(AdHoc.BytesSrc src_, int kind1, int level1, int kind2, int level2, byte[]? key, byte[]? nonce)
            {
                this.src_ = src_;
                src = null;
                s.Choose(kind1, level1, kind2, level2);
                s.StreamKey(key, nonce);
                if (s.Has(ENVELOPE) || s.Has(CHACHA20_PACK))
                    throw new ArgumentException("An Envelope, and a ChaCha20 of the session's keys, take packs: not the stream of a connection.");
                closed = dirty = false;
                return this;
            }

            public Stage Init_(AdHoc.BytesSrc src_, int kind1, int level1, int kind2, int level2) => Init_(src_, kind1, level1, kind2, level2, null, null);

            public Stage Init_(AdHoc.BytesSrc src_, int kind, int level) => Init_(src_, kind, level, 0, 0, null, null);

            public bool isOpen() => !closed && (src_?.isOpen() ?? true);

            public void Close()
            {
                if (closed)
                    return;
                closed = true;
                src_?.Close();
            }

            ///<summary>Let the upper layer write, then take it through the stages into <paramref name="dst"/>. -1 / 0 of the upper layer are relayed.</summary>
            public int Read(byte[] dst, int dst_byte, int dst_bytes)
            {
                if (closed || src_ == null)
                    return -1;
                if (s.inPlace)
                {
                    var n = src_.Read(dst, dst_byte, dst_bytes);
                    if (0 < n)
                    {
                        fixed(byte *p = dst)
                            Crypto.adhoc_stages_xor((long)s.mem, p + dst_byte, n);
                        wire_bytes += n;
                    }
                    return n;
                }
                int last = 0, put = 0;
                while (put < dst_bytes)
                {
                    if (s.I(LEN) == s.I(AT))
                    { //all taken: the upper layer writes more
                        s.I(LEN, 0);
                        s.I(AT, 0);
                        s.Room(MIN_ROOM);
                        last = src_.Read(s.staging, 0, s.staging.Length);
                        if (0 < last)
                        {
                            s.I(LEN, last);
                            dirty = true;
                        }
                    }
                    var drain = last < 1 && dirty; //the upper layer has nothing now: what the codec holds goes out ( a frame's end )
                    int r;
                    fixed(byte *o = dst)
                        r = Crypto.adhoc_stages_tx((long)s.mem, o + dst_byte + put, dst_bytes - put, drain ? 1 : 0);
                    if (r < 0)
                        throw new IOException("The stages of a connection failed.");
                    put += s.I(DONE);
                    if (r == 1)
                        dirty = false;
                    if (last < 1 && !dirty)
                        break;
                }
                wire_bytes += put;
                return 0 < put ? put : last;
            }
#endregion
        }
    }

    ///<summary>Receiving stages.</summary>
    public interface Receiver
    {
        ///<summary>
        ///The built-in stages of a chain on the receiving side. Inner role: each de-framed chunk goes through every stage - a lone
        ///ChaCha20 deciphers it where it lies -, the plaintext to the downstream deserializer. The end of the stream is the call with an
        ///empty window ( the terminator ): an Envelope opens then, and only then gives what it holds. Transport role (<c>Init_</c>): the
        ///whole stream of a connection.
        ///</summary>
        public sealed class Stage : AdHoc.Connection.Receiver.BytesDst, AdHoc.BytesDst
        {
            readonly Stages s = new(false);
            AdHoc.Connection.Receiver.BytesDst? dst;
            int left, leftTo; //the plaintext the downstream did not take yet, in the staging
            bool inFlight, discard;
            readonly byte[] hdr = new byte[HEADER];
            int hdrGot = HEADER, open;

            public int __id { get; set; }

            public Stage Init(AdHoc.Connection.Receiver.BytesDst dst, int kind, int level) => Init(dst, kind, level, 0, 0);

            public Stage Init(AdHoc.Connection.Receiver.BytesDst dst, int kind1, int level1, int kind2, int level2)
            {
                this.dst = dst;
                dst_ = null;
                s.Choose(kind1, level1, kind2, level2);
                left = leftTo = 0;
                discard = false;
                hdrGot = s.inPlace && s.Has(CHACHA20_PACK) ? 0 : HEADER;
                return this;
            }

            public Stage Init(AdHoc.Connection.Receiver.BytesDst dst, int kind1, int level1, int kind2, int level2, byte[]? key, byte[]? nonce)
            {
                Init(dst, kind1, level1, kind2, level2);
                s.StreamKey(key, nonce);
                return this;
            }

            ///<summary>Hands the downstream what the staging holds: false - it did not take all of it.</summary>
            bool Give(AdHoc.Connection.Receiver src)
            {
                if (left == leftTo)
                    return true;
                var inBuf = src.buffer;
                var inPos = src.byte_;
                var inMax = src.byte_max;
                src.buffer = s.staging;
                src.byte_ = left;
                src.byte_max = leftTo;
                inFlight = true;
                try
                {
                    dst!.__put_bytes(src);
                }
                finally
                {
                    inFlight = false;
                    left = src.byte_;
                    src.buffer = inBuf;
                    src.byte_ = inPos;
                    src.byte_max = inMax;
                }
                return left == leftTo;
            }

            public bool __put_bytes(AdHoc.Connection.Receiver src)
            {
                if (inFlight)
                    return false; //a re-entrant refill: the outer drive refills
                if (s.inPlace)
                    return Lone(src);
                if (discard)
                {
                    src.byte_ = src.byte_max;
                    return false;
                }
                if (!Give(src))
                    return false; //the downstream takes the rest first
                var end = src.byte_max <= src.byte_;
                if (s.I(PHASE) == 0 && s.I(TAKEN) == 0)
                    s.KeyedRx(src);
                for (;;)
                {
                    int r;
                    fixed(byte *p = src.buffer)
                        r = Crypto.adhoc_stages_rx((long)s.mem, p + src.byte_, src.byte_max - src.byte_, end ? 1 : 0);
                    if (r == NO_ROOM)
                    {
                        s.Room(s.I(NEED));
                        continue;
                    }
                    src.byte_ += s.I(TAKEN);
                    if (r < 0)
                    { //forged, not of its signer, or of a key this session has not: taken, and dropped whole
                        discard = true;
                        src.drop_received = true;
                        src.byte_ = src.byte_max;
                        return false;
                    }
                    left = s.I(AT);
                    leftTo = s.I(LEN);
                    if (!Give(src) || r == 1)
                        return false;
                    if (!end && src.byte_max <= src.byte_ || end && leftTo == 0)
                        return false;
                }
            }

            //A lone ChaCha20: the header in clear, then deciphered where it lies; what the downstream does not take is offered again.
            bool Lone(AdHoc.Connection.Receiver src)
            {
                var buf = src.buffer!;
                if (hdrGot < HEADER)
                {
                    for (; hdrGot < HEADER; hdrGot++)
                    {
                        if (src.byte_max <= src.byte_)
                            return false;
                        hdr[hdrGot] = buf[src.byte_++];
                    }
                    var id = (uint)(hdr[0] | hdr[1] << 8 | hdr[2] << 16 | hdr[3] << 24);
                    var seq = BitConverter.ToInt64(hdr, 4);
                    var k = src.keys.Find(id);
                    if (k == null)
                    {
                        discard = true;
                        src.drop_received = true;
                    }
                    else
                    {
                        s.Key(0, k);
                        s.I(KEYS, 1);
                        s.L(SEQ, seq);
                        s.I(PHASE, 0);
                    }
                    open = 0;
                }
                if (discard)
                {
                    src.byte_ = src.byte_max;
                    return false;
                }
                int from = src.byte_, to = src.byte_max;
                if (from + open < to)
                {
                    fixed(byte *p = buf)
                        Crypto.adhoc_stages_xor((long)s.mem, p + from + open, to - from - open);
                    open = to - from;
                }
                inFlight = true;
                try
                {
                    dst!.__put_bytes(src);
                }
                finally
                {
                    inFlight = false;
                }
                open = to - src.byte_;
                if (from == to)
                { //the end of the stream: the next pack names its key again
                    hdrGot = s.Has(CHACHA20_PACK) ? 0 : HEADER;
                    discard = false;
                }
                return false;
            }
#region TRANSPORT role : the whole stream of a connection.
            AdHoc.BytesDst? dst_;
            bool closed;
            ///<summary>Bytes taken off the wire so far.</summary>
            public long wire_bytes;

            public Stage Init_(AdHoc.BytesDst dst_, int kind1, int level1, int kind2, int level2, byte[]? key, byte[]? nonce)
            {
                this.dst_ = dst_;
                dst = null;
                s.Choose(kind1, level1, kind2, level2);
                s.StreamKey(key, nonce);
                if (s.Has(ENVELOPE) || s.Has(CHACHA20_PACK))
                    throw new ArgumentException("An Envelope, and a ChaCha20 of the session's keys, take packs: not the stream of a connection.");
                closed = false;
                open = left = leftTo = 0;
                return this;
            }

            public Stage Init_(AdHoc.BytesDst dst_, int kind1, int level1, int kind2, int level2) => Init_(dst_, kind1, level1, kind2, level2, null, null);

            public Stage Init_(AdHoc.BytesDst dst_, int kind, int level) => Init_(dst_, kind, level, 0, 0, null, null);

            public bool isOpen() => !closed && (dst_?.isOpen() ?? true);

            public void Close()
            {
                if (closed)
                    return;
                closed = true;
                dst_?.Close();
            }

            ///<summary>The bytes of <paramref name="src"/> through the stages, the plaintext to the upper layer. What it does not take stays for the next offer.</summary>
            public int Write(byte[] src, int src_byte, int src_bytes)
            {
                if (closed || dst_ == null || src_bytes < 0)
                    return 0;
                if (s.inPlace)
                {
                    if (open < src_bytes)
                    {
                        fixed(byte *p = src)
                            Crypto.adhoc_stages_xor((long)s.mem, p + src_byte + open, src_bytes - open);
                        open = src_bytes;
                    }
                    var n = dst_.Write(src, src_byte, src_bytes);
                    if (n < 0)
                        return n;
                    open = src_bytes - n;
                    wire_bytes += n;
                    return n;
                }
                var took = 0;
                for (;;)
                {
                    if (left < leftTo)
                    { //the plaintext not taken yet
                        var n = dst_.Write(s.staging, left, leftTo - left);
                        if (n < 0)
                            return n;
                        left += n;
                        if (left < leftTo)
                            break;
                    }
                    if (src_bytes <= took)
                        break;
                    int r;
                    fixed(byte *p = src)
                        r = Crypto.adhoc_stages_rx((long)s.mem, p + src_byte + took, src_bytes - took, 0);
                    if (r == NO_ROOM)
                    {
                        s.Room(s.I(NEED));
                        continue;
                    }
                    if (r < 0)
                        throw new IOException("The stages of a connection failed: the stream is broken.");
                    took += s.I(TAKEN);
                    left = s.I(AT);
                    leftTo = s.I(LEN);
                    if (left == leftTo && s.I(TAKEN) == 0)
                        break;
                }
                wire_bytes += took;
                return took;
            }
#endregion
        }
    }
