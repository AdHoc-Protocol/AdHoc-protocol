    public const int KEY = 32;

    ///<summary>A fresh key pair: 32 random bytes of secret, and the public key they give.</summary>
    public static void KeyPair(Span<byte> secret, Span<byte> pub)
    {
        RandomNumberGenerator.Fill(secret.Slice(0, KEY));
        PublicKey(pub, secret);
    }

    ///<summary>The public key of <paramref name="secret"/>: its product with the base point 9.</summary>
    public static void PublicKey(Span<byte> pub, ReadOnlySpan<byte> secret)
    {
        Span<byte> nine = stackalloc byte[KEY];
        nine.Clear();
        nine[0] = 9;
        Agree(pub, secret, nine);
    }

    ///<summary>
    ///The raw shared secret of <paramref name="secret"/> and the peer's <paramref name="peer"/> public key.
    ///</summary>
    ///<returns><c>false</c> when the result is all zero: the peer's key is of low order, and the secret is no secret
    ///(RFC 7748, 6.1 - a protocol must check it).</returns>
    public static bool Agree(Span<byte> shared, ReadOnlySpan<byte> secret, ReadOnlySpan<byte> peer)
    {
        if (secret.Length < KEY || peer.Length < KEY || shared.Length < KEY)
            throw new ArgumentException("X25519 keys are 32 bytes");
        Span<byte> e = stackalloc byte[KEY];
        secret.Slice(0, KEY).CopyTo(e);
        e[0] &= 248; //the scalar is trimmed: a multiple of 8, bit 254 set
        e[31] &= 127;
        e[31] |= 64;
        ScalarMult(shared, e, peer);
        CryptographicOperations.ZeroMemory(e);
        var zero = 0;
        for (var i = 0; i < KEY; i++)
            zero |= shared[i];
        return zero != 0;
    }

    //The Montgomery ladder over the x coordinate, in projective coordinates: x = X / Z.
    static void ScalarMult(Span<byte> q, ReadOnlySpan<byte> scalar, ReadOnlySpan<byte> p)
    {
        Span<int> all = stackalloc int[70];
        Span<int> x1 = all.Slice(0, 10), x2 = all.Slice(10, 10), z2 = all.Slice(20, 10), x3 = all.Slice(30, 10),
                  z3 = all.Slice(40, 10), t0 = all.Slice(50, 10), t1 = all.Slice(60, 10);
        FromBytes(x1, p);
        One(x2);
        z2.Clear();
        x1.CopyTo(x3);
        One(z3);
        var swap = 0;
        for (var pos = 254; pos >= 0; --pos)
        {
            var b = (scalar[pos >> 3] >> (pos & 7)) & 1;
            swap ^= b; //the xor trick: no swap back at the end of each step
            CSwap(x2, x3, swap);
            CSwap(z2, z3, swap);
            swap = b;

            //(P2, P3) -> (2 P2, P2 + P3), a differential addition
            Sub(t0, x3, z3);
            Sub(t1, x2, z2);
            Add(x2, x2, z2);
            Add(z2, x3, z3);
            Mul(z3, t0, x2);
            Mul(z2, z2, t1);
            Sq(t0, t1);
            Sq(t1, x2);
            Add(x3, z3, z2);
            Sub(z2, z3, z2);
            Mul(x2, t1, t0);
            Sub(t1, t1, t0);
            Sq(z2, z2);
            MulSmall(z3, t1, 121666);
            Sq(x3, x3);
            Add(t0, t0, z3);
            Mul(z3, x1, z2);
            Mul(z2, t1, t0);
        }
        CSwap(x2, x3, swap);
        CSwap(z2, z3, swap);

        Invert(z2, z2);
        Mul(x2, x2, z2);
        ToBytes(q, x2);
        all.Clear();
    }
#region field arithmetic modulo 2 ^ 255 - 19
    static void One(Span<int> h)
    {
        h.Clear();
        h[0] = 1;
    }

    static void Add(Span<int> h, ReadOnlySpan<int> f, ReadOnlySpan<int> g)
    {
        for (var i = 0; i < 10; i++)
            h[i] = f[i] + g[i];
    }

    static void Sub(Span<int> h, ReadOnlySpan<int> f, ReadOnlySpan<int> g)
    {
        for (var i = 0; i < 10; i++)
            h[i] = f[i] - g[i];
    }

    ///<summary>Swaps <paramref name="f"/> and <paramref name="g"/> when <paramref name="b"/> is 1, in constant time.</summary>
    [MethodImpl(MethodImplOptions.NoInlining)] //as Monocypher's volatile mask: the JIT is not to turn it into a branch
    static void CSwap(Span<int> f, Span<int> g, int b)
    {
        var mask = -b;
        for (var i = 0; i < 10; i++)
        {
            var x = (f[i] ^ g[i]) & mask;
            f[i] ^= x;
            g[i] ^= x;
        }
    }

    //Signed carry propagation: limbs back to |t even| < 1.1 * 2^25, |t odd| < 1.1 * 2^24 (Monocypher's FE_CARRY).
    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    static void Carry(Span<int> h, long t0, long t1, long t2, long t3, long t4, long t5, long t6, long t7, long t8, long t9)
    {
        long c;
        c = (t0 + (1L << 25)) >> 26;
        t0 -= c << 26;
        t1 += c;
        c = (t4 + (1L << 25)) >> 26;
        t4 -= c << 26;
        t5 += c;
        c = (t1 + (1L << 24)) >> 25;
        t1 -= c << 25;
        t2 += c;
        c = (t5 + (1L << 24)) >> 25;
        t5 -= c << 25;
        t6 += c;
        c = (t2 + (1L << 25)) >> 26;
        t2 -= c << 26;
        t3 += c;
        c = (t6 + (1L << 25)) >> 26;
        t6 -= c << 26;
        t7 += c;
        c = (t3 + (1L << 24)) >> 25;
        t3 -= c << 25;
        t4 += c;
        c = (t7 + (1L << 24)) >> 25;
        t7 -= c << 25;
        t8 += c;
        c = (t4 + (1L << 25)) >> 26;
        t4 -= c << 26;
        t5 += c;
        c = (t8 + (1L << 25)) >> 26;
        t8 -= c << 26;
        t9 += c;
        c = (t9 + (1L << 24)) >> 25;
        t9 -= c << 25;
        t0 += c * 19;
        c = (t0 + (1L << 25)) >> 26;
        t0 -= c << 26;
        t1 += c;
        h[0] = (int)t0;
        h[1] = (int)t1;
        h[2] = (int)t2;
        h[3] = (int)t3;
        h[4] = (int)t4;
        h[5] = (int)t5;
        h[6] = (int)t6;
        h[7] = (int)t7;
        h[8] = (int)t8;
        h[9] = (int)t9;
    }

    static uint Load32(ReadOnlySpan<byte> s, int at) => BinaryPrimitives.ReadUInt32LittleEndian(s.Slice(at));

    static uint Load24(ReadOnlySpan<byte> s, int at) => s[at] | (uint)s[at + 1] << 8 | (uint)s[at + 2] << 16;

    //The top bit is ignored, as RFC 7748 asks of a u coordinate.
    static void FromBytes(Span<int> h, ReadOnlySpan<byte> s)
    {
        Carry(h,
              Load32(s, 0),
              (long)Load24(s, 4) << 6,
              (long)Load24(s, 7) << 5,
              (long)Load24(s, 10) << 3,
              (long)Load24(s, 13) << 2,
              Load32(s, 16),
              (long)Load24(s, 20) << 7,
              (long)Load24(s, 23) << 5,
              (long)Load24(s, 26) << 4,
              (long)(Load24(s, 29) & 0x7fffff) << 2);
    }

    //Fully reduced, little-endian.
    static void ToBytes(Span<byte> s, ReadOnlySpan<int> h)
    {
        Span<int> t = stackalloc int[10];
        h.CopyTo(t);
        var q = (19 * t[9] + (1 << 24)) >> 25;
        for (var i = 0; i < 5; i++)
        {
            q += t[2 * i];
            q >>= 26;
            q += t[2 * i + 1];
            q >>= 25;
        }
        q *= 19; //q is 0 when h >= 0, -1 when negative: adding 19 q reduces h to its range
        for (var i = 0; i < 5; i++)
        {
            t[i * 2] += q;
            q = t[i * 2] >> 26;
            t[i * 2] -= q * (1 << 26);
            t[i * 2 + 1] += q;
            q = t[i * 2 + 1] >> 25;
            t[i * 2 + 1] -= q * (1 << 25);
        }
        BinaryPrimitives.WriteUInt32LittleEndian(s, (uint)t[0] >> 0 | (uint)t[1] << 26);
        BinaryPrimitives.WriteUInt32LittleEndian(s.Slice(4), (uint)t[1] >> 6 | (uint)t[2] << 19);
        BinaryPrimitives.WriteUInt32LittleEndian(s.Slice(8), (uint)t[2] >> 13 | (uint)t[3] << 13);
        BinaryPrimitives.WriteUInt32LittleEndian(s.Slice(12), (uint)t[3] >> 19 | (uint)t[4] << 6);
        BinaryPrimitives.WriteUInt32LittleEndian(s.Slice(16), (uint)t[5] >> 0 | (uint)t[6] << 25);
        BinaryPrimitives.WriteUInt32LittleEndian(s.Slice(20), (uint)t[6] >> 7 | (uint)t[7] << 19);
        BinaryPrimitives.WriteUInt32LittleEndian(s.Slice(24), (uint)t[7] >> 13 | (uint)t[8] << 12);
        BinaryPrimitives.WriteUInt32LittleEndian(s.Slice(28), (uint)t[8] >> 20 | (uint)t[9] << 6);
        t.Clear();
    }

    static void MulSmall(Span<int> h, ReadOnlySpan<int> f, int g) =>
