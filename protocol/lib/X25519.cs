//X25519 key agreement (RFC 7748), pure managed: the same code on .NET, Unity and the browser, where the platform has
//none (.NET gains X25519DiffieHellman only in 11, and not for the browser).
//
//Ported from Monocypher 4 (https://monocypher.org, CC0 / public domain; audited by Cure53 in 2020), which takes it from
//SUPERCOP's ref10: field elements of ten signed limbs of 26 and 25 bits, 64-bit products, a Montgomery ladder with a
//constant-time swap. The inversion is ref10's exponentiation by p - 2 (Monocypher inverts through its EdDSA inverse
//square root, which X25519 alone does not need). No secret-dependent branch or index anywhere.
using System;
using System.Buffers.Binary;
using System.Runtime.CompilerServices;
using System.Security.Cryptography;

namespace org.unirail;

