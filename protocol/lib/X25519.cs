//X25519 key agreement (RFC 7748), in the native library: see Chain.cs.
using System;

namespace org.unirail;

public static unsafe class X25519
{
    public const int KEY = 32;

    ///<summary>A fresh key pair: 32 random bytes of secret, and the public key they give.</summary>
    public static void KeyPair(Span<byte> secret, Span<byte> pub)
    {
        if (secret.Length < KEY || pub.Length < KEY)
            throw new ArgumentException("X25519 keys are 32 bytes");
        fixed(byte *s = secret, p = pub)
            Crypto.adhoc_x25519_keypair(s, p);
    }

    ///<summary>The public key of <paramref name="secret"/>: its product with the base point 9.</summary>
    public static void PublicKey(Span<byte> pub, ReadOnlySpan<byte> secret)
    {
        if (secret.Length < KEY || pub.Length < KEY)
            throw new ArgumentException("X25519 keys are 32 bytes");
        fixed(byte *s = secret, p = pub)
            Crypto.adhoc_x25519_public(p, s);
    }

    ///<summary>
    ///The raw shared secret of <paramref name="secret"/> and the peer's <paramref name="peer"/> public key.
    ///</summary>
    ///<returns><c>false</c> when the result is all zero: the peer's key is of low order, and the secret is no secret
    ///(RFC 7748, 6.1 - a protocol must check it).</returns>
    public static bool Agree(Span<byte> shared, ReadOnlySpan<byte> secret, ReadOnlySpan<byte> peer)
    {
        if (secret.Length < KEY || peer.Length < KEY || shared.Length < KEY)
            throw new ArgumentException("X25519 keys are 32 bytes");
        fixed(byte *o = shared, s = secret, p = peer) return Crypto.adhoc_x25519(o, s, p) != 0;
    }
}
