    }

    static void SqN(Span<int> h, ReadOnlySpan<int> f, int n)
    {
        Sq(h, f);
        for (var i = 1; i < n; i++)
            Sq(h, h);
    }

    //out = z^(p - 2) = 1/z: ref10's chain of 254 squarings and 11 multiplications.
    static void Invert(Span<int> o, ReadOnlySpan<int> z)
    {
        Span<int> all = stackalloc int[40];
        Span<int> t0 = all.Slice(0, 10), t1 = all.Slice(10, 10), t2 = all.Slice(20, 10), t3 = all.Slice(30, 10);
        Sq(t0, z);       //2
        SqN(t1, t0, 2);  //8
        Mul(t1, z, t1);  //9
        Mul(t0, t0, t1); //11
        Sq(t2, t0);      //22
        Mul(t1, t1, t2); //2^5 - 1
        SqN(t2, t1, 5);
        Mul(t1, t2, t1); //2^10 - 1
        SqN(t2, t1, 10);
        Mul(t2, t2, t1); //2^20 - 1
        SqN(t3, t2, 20);
        Mul(t2, t3, t2); //2^40 - 1
        SqN(t2, t2, 10);
        Mul(t1, t2, t1); //2^50 - 1
        SqN(t2, t1, 50);
        Mul(t2, t2, t1); //2^100 - 1
        SqN(t3, t2, 100);
        Mul(t2, t3, t2); //2^200 - 1
        SqN(t2, t2, 50);
        Mul(t1, t2, t1); //2^250 - 1
        SqN(t1, t1, 5);  //2^255 - 2^5
        Mul(o, t1, t0);  //2^255 - 21 = p - 2
        all.Clear();
    }
