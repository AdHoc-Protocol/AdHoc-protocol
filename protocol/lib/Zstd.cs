//Optional Zstandard compression stages for org.unirail.AdHoc streams.
//
//REQUIRES the ZstdSharp.Port NuGet package (pure-managed zstd port) and <AllowUnsafeBlocks>true</AllowUnsafeBlocks>:
//
//  dotnet add package ZstdSharp.Port
//  <PackageReference Include="ZstdSharp.Port" Version="0.8.8" />
//
//Entirely OPTIONAL: if you do not compress streamed payloads, delete this file and drop the ZstdSharp.Port
//dependency — the AdHoc core (AdHoc.cs) never references it.
//
//Two pure-byte inner stages — a transparent zstd codec between the outer framer (Receiver/Transmitter.Chunked)
//and what it wraps. Zstd.Receiver.Stage decompresses each de-framed chunk into a scratch buffer and drains the
//plaintext to its inner stage; Zstd.Transmitter.Stage compresses plaintext pulled from its inner stage straight
//into the transmit buffer. Compose it like any other stage: WIRE the chain once (Init(stage)), then ARM the
//framing per stream (Init(id, …)).
//
//Pairing is mandatory and symmetric: Zstd.Transmitter.Stage MUST be matched by Zstd.Receiver.Stage. Valid only
//under the terminator-framed `Chunked`, never `File`: compressed length is not known up front and a `File`
//packet must declare its size in its header.
//
//Lifecycle: construct directly (new Stage()); Init() resets the zstd context for a fresh frame and a statically
//wired stage self-rearms per stream. A finalizer frees the native context if an instance is ever dropped.
//

using System;
using System.IO;
using ZstdSharp.Unsafe;
using static ZstdSharp.Unsafe.Methods;

namespace org.unirail;

public interface Zstd
{
    ///<summary>Decompressing receive-side stage.</summary>
    interface Receiver
    {
        ///<summary>
        ///Decompressing inner stage for <see cref="AdHoc.Connection.Receiver.Chunked"/>: decompresses each de-framed
        ///chunk straight out of the receive buffer into a scratch buffer, then drains the recovered plaintext into a
        ///downstream <see cref="AdHoc.Connection.Receiver.BytesDst"/> (a <c>Terminal</c> sink, or another stage).
        ///Pair with <see cref="Transmitter.Stage"/>.
        ///<para>
        ///The native <c>ZSTD_DCtx</c> retains frame state across <see cref="__put_bytes"/> calls, so a single zstd
        ///frame may span any number of Chunked chunks and socket fills. As a pure-byte inner stage it never touches the
        ///slot and never self-completes — the outer framer's <c>0x0000</c> terminator is the sole end-authority, so
        ///<see cref="__put_bytes"/> always returns <c>false</c>.
        ///</para>
        ///</summary>
        unsafe class Stage : AdHoc.Connection.Receiver.BytesDst, AdHoc.BytesDst, IDisposable
        {
            public static int buffer_size = 1 << 16; //staging buffer for decompressed plaintext

            ZSTD_DCtx_s *_dctx;
            readonly byte[] _zout = new byte[buffer_size]; //staging buffer for decompressed plaintext
            int _zoutPos;                                  //read cursor into _zout (plaintext already delivered downstream)
            int _zoutLen;                                  //valid plaintext length currently staged in _zout
            bool _inFlight;                                //re-entrancy guard: a nested downstream consumer must not re-drive this stage mid-read (ports Java's inFlight)

            AdHoc.Connection.Receiver.BytesDst dst = null!; //inner stage — another IStream (Chunked/File) or a Terminal leaf

            ///<summary>Chain builder: swap the inner next-stage <see cref="dst"/> — set it (null to detach), return the previous.</summary>

            public int __id { get; set; } //unused for an inner stage (the outer framer carries the dispatch id)

            public Stage() => _dctx = ZSTD_createDCtx();

            ~Stage() => FreeContext();

            ///<summary>Releases the native context exactly once — idempotent, so whichever of <see cref="Close"/>,
            ///<see cref="Dispose"/> or the finalizer runs first wins and the rest are no-ops.</summary>
            void FreeContext()
            {
                if (_dctx == null)
                    return;
                ZSTD_freeDCtx(_dctx);
                _dctx = null;
            }

            ///<summary>Deterministic native cleanup — <c>using( … )</c> support: <see cref="Close"/> plus the release of the
            ///context. <see cref="Close"/> alone keeps the context for the next <c>Init</c>: Network closes the codecs on every
            ///teardown and a client keeps ONE Internal across reconnects. A disposed stage must NOT be re-<c>Init</c>ed.</summary>
            public void Dispose()
            {
                Close();
                FreeContext();
                GC.SuppressFinalize(this);
            }

            ///<summary>Fresh zstd frame + empty staging.</summary>
            void Rearm()
            {
                ZSTD_DCtx_reset(_dctx, ZSTD_ResetDirective.ZSTD_reset_session_and_parameters);
                _zoutPos = _zoutLen = 0;
            }

            ///<summary>(Re)configure: inner dst + a fresh zstd frame (context reset, staging emptied). Returns <c>this</c> for chaining.
            ///The <paramref name="level"/> argument is accepted for signature symmetry with <see cref="Transmitter.Stage.Init_"/> and
            ///ignored (decompression takes no level).</summary>
            public Stage Init(AdHoc.Connection.Receiver.BytesDst dst, int level)
            {
                this.dst = dst;
                dst_ = null; //INNER role — the two roles are mutually exclusive per instance
                Rearm();
                return this;
            }
#region TRANSPORT role
            //Two rules the inner role does not need:
            //  1. the peer closes a frame when ITS upper layer runs dry, so the input is a sequence of standalone
            //     frames — reset the context after each;
            //  2. never consume input we cannot pay out: on a refusal report a SHORT count (_skip), else the
            //     transport keeps no tail and its WakeReceive is a no-op on an empty tail.

            AdHoc.BytesDst? dst_; //TRANSPORT role: the connection's own Receiver (null ⇒ inner role)
            int _skip;            //compressed bytes already inside the codec that the transport will re-offer
            bool _closed;

            ///<summary>Compressed bytes consumed off the transport so far.</summary>
            public long wire_bytes;

            ///<summary>Plaintext bytes delivered to <see cref="dst_"/> so far.</summary>
            public long plain_bytes;

            ///<summary>Arm as the connection's transport-level decompressor: takes zstd bytes off the socket and feeds
            ///the recovered protocol bytes to <paramref name="dst_"/> (normally <c>Connection.receiver</c>).
            ///Pair with <see cref="Transmitter.Stage.Init"/>.</summary>
            public Stage Init_(AdHoc.BytesDst dst_, int level)
            {
                this.dst_ = dst_;
                dst = null!; //TRANSPORT role
                _closed = false;
                _skip = 0;
                Rearm();
                return this;
            }

            public bool isOpen() => !_closed && (dst_?.isOpen() ?? true);

            public void Close()
            {
                if (_closed)
                    return;
                _closed = true;
                _zoutPos = _zoutLen = 0;
                _skip = 0;
                dst_?.Close();
            }

            ///<summary>
            ///Transport entry: decompress <paramref name="src"/> and drain the recovered protocol bytes into
            ///<see cref="dst_"/>. Reports a SHORT count when the sink refuses — that is how the transport learns
            ///to stash the rest and re-drive on <c>WakeReceive</c>.
            ///<para>ATTENTION! <paramref name="src"/> is borrowed and must not be referenced after this returns.</para>
            ///</summary>
            ///<returns>The number of COMPRESSED bytes consumed from <paramref name="src"/>.</returns>
            public int Write(byte[] src, int src_byte, int src_bytes)
            {
                if (_dctx == null || dst_ == null || src_bytes < 0)
                    return 0;
                var inPos = src_byte;
                var inMax = src_byte + src_bytes;

                if (0 < _skip) //these bytes are already inside the codec — count them, do not feed them again
                {
                    var s = Math.Min(_skip, src_bytes);
                    inPos += s;
                    _skip -= s;
                }

                while (true)
                {
                    if (_zoutPos < _zoutLen) //deliver staged plaintext BEFORE producing more
                    {
                        var n = dst_.Write(_zout, _zoutPos, _zoutLen - _zoutPos);
                        if (n < 1)
                            break; //sink refuses → keep the staging, report what we consumed
                        _zoutPos += n;
                        plain_bytes += n;
                        if (_zoutPos < _zoutLen)
                            break; //partial take → same
                    }

                    _zoutPos = _zoutLen = 0;

                    //Refill from the remaining compressed input AND/OR from plaintext the context still holds: a tiny
                    //input can expand past the staging array, so the window can be consumed while the context still owes
                    //plaintext. The stall guard below is the only input-exhaustion exit.
                    var inBefore = inPos;
                    fixed(byte *ip = src)
                        fixed(byte *op = _zout)
                    {
                        var input = new ZSTD_inBuffer_s { src = ip + inPos, size = (nuint)(inMax - inPos), pos = 0 };
                        var output = new ZSTD_outBuffer_s { dst = op, size = (nuint)_zout.Length, pos = 0 };
                        var code = ZSTD_decompressStream(_dctx, &output, &input);
                        if (ZSTD_isError(code))
                            throw new IOException("zstd decompress failed: " + ZSTD_getErrorName(code));
                        inPos += (int)input.pos;
                        wire_bytes += (int)input.pos; //counted where bytes actually enter the codec — a deferred byte must not count twice
                        _zoutLen = (int)output.pos;
                        _zoutPos = 0;
                        if (code == 0) //frame fully decoded → ready for the next standalone frame
                            ZSTD_DCtx_reset(_dctx, ZSTD_ResetDirective.ZSTD_reset_session_and_parameters);
                    }

                    if (inPos == inBefore && _zoutLen == 0)
                        break; //no progress → needs more compressed input
                }

                var consumed = inPos - src_byte;
                if (_zoutPos < _zoutLen && consumed == src_bytes && 0 < consumed) //keep the transport's tail non-empty
                {
                    consumed--;
                    _skip = 1;
                }

                return consumed;
            }
#endregion

            ///<summary>
            ///Framework entry. Decompresses the available (chunk-clamped) compressed bytes from the receive window,
            ///draining the recovered plaintext into <see cref="dst"/> via a buffer swap. Always returns <c>false</c>:
            ///a codec stage never self-completes — the outer Chunked framer's <c>0x0000</c> terminator ends the stream.
            ///</summary>
            public bool __put_bytes(AdHoc.Connection.Receiver src)
            {
                //A deeply-nested downstream consumer (reached through _zout) could, on its own park/resume, re-enter and
                //re-drive THIS stage mid-read — which would decompress over the swapped _zout window and corrupt state.
                //Refuse the re-entrant refill: park; the outer (non-re-entrant) drive refills after the framer's clamped
                //feed. (Ports Java's inFlight guard; in C#'s streaming model no such re-entry path is known, so this is a
                //safe no-op guard for parity — never fires unless a re-entry exists.)
                if (_inFlight)
                    return false;
                _inFlight = true;
                var inBuf = src.buffer!; //compressed input window (already clamped to the current chunk by the framer)
                var inPos = src.byte_;
                var inMax = src.byte_max;
                try
                {
                    while (true)
                    {
                        //1. Flush any plaintext still staged in _zout to the inner stage before producing more.
                        if (_zoutPos < _zoutLen)
                        {
                            src.buffer = _zout;
                            src.byte_ = _zoutPos;
                            src.byte_max = _zoutLen;
                            dst.__put_bytes(src); //inner stage consumes pure bytes; its return is ignored (terminator is end-authority)
                            _zoutPos = src.byte_; //the inner stage is the source of truth for what it consumed
                            if (_zoutPos < _zoutLen)
                                break; //inner parked (backpressure) → yield, leaving the unconsumed _zout intact
                        }

                        //2. _zout is empty — refill it from remaining compressed input AND/OR from plaintext zstd still
                        //   holds buffered internally. A tiny compressed chunk can expand to far more than _zout, so 'inPos'
                        //   can already be == inMax while the context still owes us plaintext; do NOT break merely because
                        //   the compressed input is consumed — keep querying the context.
                        var inBefore = inPos;
                        fixed(byte *ip = inBuf)
                            fixed(byte *op = _zout)
                        {
                            var input = new ZSTD_inBuffer_s { src = ip + inPos, size = (nuint)(inMax - inPos), pos = 0 };
                            var output = new ZSTD_outBuffer_s { dst = op, size = (nuint)_zout.Length, pos = 0 };
                            var code = ZSTD_decompressStream(_dctx, &output, &input); //consume from 'input', produce plaintext into 'output'
                            if (ZSTD_isError(code))
                                throw new IOException("zstd decompress failed: " + ZSTD_getErrorName(code));
                            if (code == 0) //frame fully decoded → re-arm the context so the statically wired stage is
                                //ready for the NEXT stream without re-Init (one zstd frame per stream; the framer's
                                //0x0000 terminator ends the stream itself)
                                ZSTD_DCtx_reset(_dctx, ZSTD_ResetDirective.ZSTD_reset_session_and_parameters);
                            inPos += (int)input.pos;
                            _zoutLen = (int)output.pos;
                            _zoutPos = 0;
                        }

                        //3. Stall guard: zstd neither consumed input nor produced output → the context is drained and
                        //   needs the next chunk to make progress → yield (this is the ONLY input-exhaustion exit).
                        if (inPos == inBefore && _zoutLen == 0)
                            break;
                    }
                }
                finally
                {
                    //Restore the compressed wire window; src.byte_ reflects exactly how much compressed input we consumed
                    //(the framer reads it back as the chunk's consumption count). Runs even if a nested call threw.
                    src.buffer = inBuf;
                    src.byte_ = inPos;
                    src.byte_max = inMax;
                    _inFlight = false;
                }

                return false; //a codec never self-completes; the framer's 0x0000 terminator is the end-authority
            }
        }
    }

    ///<summary>Compressing transmit-side stage.</summary>
    interface Transmitter
    {
        ///<summary>
        ///Compressing inner stage for <see cref="AdHoc.Connection.Transmitter.Chunked"/>: lets an upstream
        ///<see cref="AdHoc.Connection.Transmitter.BytesSrc"/> (a <c>Terminal</c> source, or another stage) write
        ///plaintext into a scratch buffer, compresses that straight into the transmit buffer, and hands the compressed
        ///bytes back to the framer for chunk framing. Pair with <see cref="Receiver.Stage"/>.
        ///<para>
        ///The native <c>ZSTD_CCtx</c> retains frame state across <see cref="__get_bytes"/> calls, so a single zstd
        ///frame may span any number of Chunked chunks and transmit-buffer fills. <see cref="__get_bytes"/> returns
        ///<c>true</c> only once the whole frame — including the <c>ZSTD_e_end</c> epilogue — is flushed, which is the
        ///framer's cue to write the <c>0x0000</c> terminator.
        ///</para>
        ///<para>
        ///Compressed output length is unknown up front —
        ///this stage is valid only under the chunked <c>Chunked</c> framer, never <c>File</c> (which must declare its size at Init).
        ///</para>
        ///</summary>
        unsafe class Stage : AdHoc.Connection.Transmitter.BytesSrc, AdHoc.BytesSrc, IDisposable
        {
            public static int buffer_size = 1 << 16; //staging buffer for serialized plaintext

            public static int level = 3; //default zstd compression level when none is supplied

            ZSTD_CCtx_s *_cctx;
            readonly byte[] _zin = new byte[buffer_size]; //staging buffer for serialized plaintext
            int _zinPos;                                  //read cursor into _zin (plaintext already compressed)
            int _zinLen;                                  //valid plaintext length currently staged in _zin
            bool _sourceEof;                              //inner source finished; stays true across calls while the zstd END epilogue drains

            AdHoc.Connection.Transmitter.BytesSrc src = null!; //inner stage — another IStream (Chunked/File) or a Terminal leaf

            ///<summary>Chain builder: swap the inner next-stage <see cref="src"/> — set it (null to detach), return the previous.</summary>

            public int __id { get; set; } //unused for an inner stage (the outer framer carries the dispatch id)

            public Stage() => _cctx = ZSTD_createCCtx();

            ~Stage() => FreeContext();

            ///<summary>Releases the native context exactly once — idempotent, so whichever of <see cref="Close"/>,
            ///<see cref="Dispose"/> or the finalizer runs first wins and the rest are no-ops.</summary>
            void FreeContext()
            {
                if (_cctx == null)
                    return;
                ZSTD_freeCCtx(_cctx);
                _cctx = null;
            }

            ///<summary>Deterministic native cleanup — <c>using( … )</c> support; identical to <see cref="Close"/>,
            ///including its caveat: bytes still inside the codec are DROPPED, so a graceful shutdown must let the
            ///transmitter drain first. In the inner role (no <see cref="src_"/>) it only releases the context — the
            ///statically wired <see cref="src"/> chain has no Close contract and is left untouched.
            ///A disposed stage must NOT be re-<c>Init</c>ed: the context is gone for good.</summary>
            public void Dispose()
            {
                Close();
                FreeContext();
                GC.SuppressFinalize(this);
            }

            int _level; //remembered for the per-stream self-rearm

            ///<summary>(Re)configure: inner src + a fresh zstd frame at <paramref name="level"/> (context reset, staging emptied). Returns <c>this</c> for chaining.</summary>
            ///<param name="level">zstd compression level, native range -131072..22: negative = fast, 1..19 = normal,
            ///20..22 = ultra (heavier memory/CPU), 0 = default (3).</param>
            public Stage Init(AdHoc.Connection.Transmitter.BytesSrc src, int level)
            {
                this.src = src;
                src_ = null; //INNER role — the two roles are mutually exclusive per instance
                _level = level;
                Rearm();
                return this;
            }
#region TRANSPORT role
            //A connection has no EOF, and zstd buffers until it has a block: the drain boundary is "the upper layer
            //returned < 1" → ZSTD_e_end there, or the peer waits forever. keep_frame_open trades that for ZSTD_e_flush.

            ///<summary>Below this much free room we stop pulling new plaintext and hand back what is already compressed —
            ///the transport ships it and calls again with a fresh window, so the codec is never asked to emit a frame
            ///epilogue into a couple of bytes.</summary>
            const int MIN_ROOM = 64;

            AdHoc.BytesSrc? src_; //TRANSPORT role: the connection's own Transmitter (null ⇒ inner role)
            bool _dirty;          //plaintext entered the codec since the last completed drain
            bool _draining;       //mid ZSTD_e_end/flush epilogue: keep flushing, do NOT pull new plaintext
            bool _closed;

            ///<summary>Drain with <c>ZSTD_e_flush</c> and keep ONE frame open for the whole connection (best ratio, not
            ///replayable) instead of the default <c>ZSTD_e_end</c> frame-per-burst.</summary>
            public bool keep_frame_open;

            ///<summary>Plaintext bytes pulled from <see cref="src_"/> so far.</summary>
            public long plain_bytes;

            ///<summary>Compressed bytes handed to the transport so far.</summary>
            public long wire_bytes;

            ///<summary>Arm as the connection's transport-level compressor: pulls protocol bytes from
            ///<paramref name="src_"/> (normally <c>Connection.transmitter</c>) and hands the socket zstd bytes
            ///instead. Pair with <see cref="Receiver.Stage.Init_"/>.</summary>
            public Stage Init_(AdHoc.BytesSrc src_, int level)
            {
                this.src_ = src_;
                src = null!; //TRANSPORT role
                _level = level;
                _closed = false;
                Rearm();
                return this;
            }

            public bool isOpen() => !_closed && (src_?.isOpen() ?? true);

            ///<summary>Frees the native context and closes the upper layer. Bytes still inside the codec are dropped —
            ///the transport is done reading by then; a graceful close must let the transmitter drain FIRST (that drain
            ///ends the frame by itself, because a dry upper layer is exactly the drain trigger).</summary>
            public void Close()
            {
                if (_closed)
                    return;
                _closed = true;
                _zinPos = _zinLen = 0;
                _dirty = _draining = false;
                src_?.Close();
            }

            ///<summary>
            ///Transport entry: pull protocol bytes from <see cref="src_"/> into staging, compress them straight
            ///into <paramref name="dst"/>, and close the frame as soon as the upper layer runs dry. Resumes across
            ///calls: a frame and its epilogue may span any number of transport buffers.
            ///</summary>
            ///<returns>Compressed bytes written; <c>0</c> when nothing could be produced but payload is still held;
            ///<c>-1</c> when the whole chain is dry (the transport parks until <c>WakeTransmit</c>).</returns>
            public int Read(byte[] dst, int dst_byte, int dst_bytes)
            {
                if (_cctx == null || src_ == null)
                    return -1;
                var outPos = dst_byte;
                var outMax = dst_byte + dst_bytes;

                while (outPos < outMax)
                {
                    if (_zinPos >= _zinLen && !_draining) //staging drained and not mid-epilogue → pull the next batch
                    {
                        if (outMax - outPos < MIN_ROOM && dst_byte < outPos)
                            break; //too little room left → ship what we have

                        var n = src_.Read(_zin, 0, _zin.Length);
                        if (n < 1) //upper layer has nothing more RIGHT NOW — the drain boundary
                        {
                            if (!_dirty)
                                break; //…and the codec holds nothing → genuinely nothing to send
                            _draining = true;
                        }
                        else
                        {
                            _zinPos = 0;
                            _zinLen = n;
                            _dirty = true;
                            plain_bytes += n;
                        }
                    }

                    var outBefore = outPos;
                    var zinBefore = _zinPos;
                    fixed(byte *zp = _zin)
                        fixed(byte *op = dst)
                    {
                        var input = new ZSTD_inBuffer_s { src = zp + _zinPos, size = (nuint)(_zinLen - _zinPos), pos = 0 };
                        var output = new ZSTD_outBuffer_s { dst = op + outPos, size = (nuint)(outMax - outPos), pos = 0 };
                        var code = ZSTD_compressStream2(_cctx, &output, &input,
                                                        _draining ? keep_frame_open ? ZSTD_EndDirective.ZSTD_e_flush : ZSTD_EndDirective.ZSTD_e_end : ZSTD_EndDirective.ZSTD_e_continue);
                        if (ZSTD_isError(code))
                            throw new IOException("zstd compress failed: " + ZSTD_getErrorName(code));
                        _zinPos += (int)input.pos;
                        outPos += (int)output.pos;
                        wire_bytes += (int)output.pos;

                        if (_draining && code == 0) //everything the codec held is on the wire
                        {
                            _draining = false;
                            _dirty = false;
                            if (!keep_frame_open)
                                Rearm(); //frame closed → next burst is a standalone frame
                            break;       //the upper layer was dry when this drain started
                        }
                    }

                    if (outPos == outBefore && _zinPos == zinBefore)
                        break; //no progress (window full) → park
                }

                if (dst_byte < outPos)
                    return outPos - dst_byte;

                return _dirty || _zinPos < _zinLen ? 0 : //payload still held, but this window was too small for any of it
                           -1;                           //nothing anywhere
            }
#endregion

            ///<summary>Fresh zstd frame + clean staging. Called by <see cref="Init"/> and again after each finished
            ///stream, so a statically wired stage serves any number of consecutive streams without re-Init.</summary>
            void Rearm()
            {
                ZSTD_CCtx_reset(_cctx, ZSTD_ResetDirective.ZSTD_reset_session_and_parameters);
                ZSTD_CCtx_setParameter(_cctx, ZSTD_cParameter.ZSTD_c_compressionLevel, _level);
                _sourceEof = false;
                _dirty = _draining = false; //TRANSPORT role state — harmless for the inner role
                _zinPos = _zinLen = 0;
            }

            ///<summary>
            ///Framework entry. Pulls plaintext from <see cref="src"/> into a scratch buffer (via a buffer swap),
            ///compresses it into the transmit window, and resumes across fills. Returns <c>true</c> once the whole
            ///zstd frame (incl. the <c>ZSTD_e_end</c> epilogue) is flushed — the framer then writes the <c>0x0000</c>
            ///terminator; <c>false</c> to park when the transmit buffer fills or the inner source parks.
            ///</summary>
            public bool __get_bytes(AdHoc.Connection.Transmitter dst)
            {
                var outBuf = dst.buffer!; //real transmit window — compressed bytes are written here
                var outPos = dst.byte_;
                var outMax = dst.byte_max;
                var done = false; //true only when the whole frame (incl. END epilogue) is flushed
                try
                {
                    while (outPos < outMax)
                    {
                        if (_zinPos >= _zinLen && !_sourceEof) //_zin drained and source not finished → pull the next batch of plaintext
                        {
                            dst.buffer = _zin; //redirect the inner stage to write plaintext into _zin
                            dst.byte_ = 0;
                            dst.byte_max = _zin.Length;
                            _sourceEof = src.__get_bytes(dst); //true = inner source exhausted; false = _zin filled / more to come
                            _zinLen = dst.byte_;               //however many plaintext bytes the inner stage actually wrote
                            _zinPos = 0;
                        }

                        var outBefore = outPos;
                        var zinBefore = _zinPos;
                        fixed(byte *zp = _zin)
                            fixed(byte *op = outBuf)
                        {
                            var input = new ZSTD_inBuffer_s { src = zp + _zinPos, size = (nuint)(_zinLen - _zinPos), pos = 0 };
                            var output = new ZSTD_outBuffer_s { dst = op + outPos, size = (nuint)(outMax - outPos), pos = 0 };
                            //Compress staged plaintext from _zin into the wire window. Once the source is finished, ZSTD_e_end
                            //flushes the frame epilogue; a partially-consumed _zin simply keeps its cursor and resumes next call.
                            var code = ZSTD_compressStream2(_cctx, &output, &input,
                                                            _sourceEof ? ZSTD_EndDirective.ZSTD_e_end : ZSTD_EndDirective.ZSTD_e_continue);
                            if (ZSTD_isError(code))
                                throw new IOException("zstd compress failed: " + ZSTD_getErrorName(code));
                            _zinPos += (int)input.pos;
                            outPos += (int)output.pos;
                            if (_sourceEof && code == 0) //whole frame (incl. END epilogue) flushed → signal complete so the framer writes the [0] terminator
                            {
                                done = true;
                                Rearm(); //stream finished → fresh frame, ready for the next stream without re-Init
                                break;
                            }
                        }

                        if (outPos == outBefore && _zinPos == zinBefore)
                            break; //no progress (source parked or out is full) → park
                    }
                }
                finally
                {
                    //Restore the real transmit window; dst.byte_ reflects exactly how many compressed bytes we wrote
                    //(the framer reads it back as the chunk length). Runs even if a nested call threw.
                    dst.buffer = outBuf;
                    dst.byte_ = outPos;
                    dst.byte_max = outMax;
                }

                return done; //true = whole frame flushed → framer writes the 0x0000 terminator; false = park
            }
        }
    }
}
