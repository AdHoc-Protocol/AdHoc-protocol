            private bool _hasCurrent;

            [MethodImpl(MethodImplOptions.AggressiveInlining)]
            internal KeyEnumerator(ByteMap<K, V> map)
            {
                _map = map;
                _inner = map.keys.GetEnumerator();
                _version = map.keys._version;
                _current = default;
                _hasCurrent = false;
            }

            public K Current
            {
                [MethodImpl(MethodImplOptions.AggressiveInlining)]
                get => _current;
            }

            object IEnumerator.Current
            {
                [MethodImpl(MethodImplOptions.AggressiveInlining)]
                get => Current;
            }

            [MethodImpl(MethodImplOptions.AggressiveInlining)]
            public bool MoveNext()
            {
                if (_version != _map.keys._version)
                    throw new InvalidOperationException("Collection was modified");
                if (!_inner.MoveNext())
                {
                    _hasCurrent = false;
                    return false;
                }
                _current = _inner.Current;
                _hasCurrent = true;
                return true;
            }

            [MethodImpl(MethodImplOptions.AggressiveInlining)]
            public void Reset()
            {
                _inner.Reset();
                _version = _map.keys._version;
                _current = default;
                _hasCurrent = false;
            }

            [MethodImpl(MethodImplOptions.AggressiveInlining)]
            public void Dispose() {}
        }
    }

    ///<summary>
    ///A read-only collection of values in the ByteMap.
    ///</summary>
    private class ValueCollection : ICollection<V>
    {
        private readonly ByteMap<K, V> _map;

        [MethodImpl(MethodImplOptions.AggressiveInlining)]
        public ValueCollection(ByteMap<K, V> map) => _map = map;

        public int Count
        {
            [MethodImpl(MethodImplOptions.AggressiveInlining)]
            get => _map.Count;
        }

        public bool IsReadOnly
        {
            [MethodImpl(MethodImplOptions.AggressiveInlining)]
            get => true;
        }

        [MethodImpl(MethodImplOptions.AggressiveInlining)]
        public void Add(V item) => throw new NotSupportedException();

        [MethodImpl(MethodImplOptions.AggressiveInlining)]
        public void Clear() => throw new NotSupportedException();

        [MethodImpl(MethodImplOptions.AggressiveInlining)]
        public bool Contains(V item) => _map.Any(kvp => equal_hash_V.Equals(kvp.Value, item));

        [MethodImpl(MethodImplOptions.AggressiveInlining)]
        public bool Remove(V item) => throw new NotSupportedException();

        public void CopyTo(V[] dst, int dstIndex)
        {
            ArgumentNullException.ThrowIfNull(dst);
            ArgumentOutOfRangeException.ThrowIfGreaterThanOrEqual((uint)dstIndex, (uint)dst.Length);
            if (dst.Length - dstIndex < Count)
                throw new ArgumentException("Destination array is not long enough.");

            foreach (var kvp in _map)
                dst[dstIndex++] = kvp.Value;
        }

        [MethodImpl(MethodImplOptions.AggressiveInlining)]
        public IEnumerator<V> GetEnumerator() => new ValueEnumerator(_map);

        [MethodImpl(MethodImplOptions.AggressiveInlining)]
        IEnumerator IEnumerable.GetEnumerator() => GetEnumerator();

        ///<summary>
        ///Enumerator for iterating over values in the ByteMap. Uses the same lockstep
        ///segment walk as <see cref="ByteMap{K,V}.Enumerator"/> — segments of <c>keys</c>
        ///and <c>nullsVal</c> are loaded together at segment boundaries, value resolution
        ///per element is a single bit test.
        ///</summary>
        private struct ValueEnumerator : IEnumerator<V>
        {
            private readonly ByteMap<K, V> _map;
            private readonly V[] _values;
            private readonly bool _isFlat;

            private ulong _keysSeg;
            private ulong _nullsSeg;
            private int _segmentBase;
            private uint _version;
            private int _valIndex;
            private V _current;
            private bool _hasCurrent;

            [MethodImpl(MethodImplOptions.AggressiveInlining)]
            internal ValueEnumerator(ByteMap<K, V> map)
            {
                _map = map;
                _values = map.values;
                _isFlat = map.IsFlat;
                _keysSeg = 0;
                _nullsSeg = 0;
                _segmentBase = -64;
                _version = map.keys._version;
                _valIndex = -1;
                _current = default!;
                _hasCurrent = false;
            }

            public V Current
            {
                [MethodImpl(MethodImplOptions.AggressiveInlining)]
                get => _current;
            }

            object IEnumerator.Current
            {
                [MethodImpl(MethodImplOptions.AggressiveInlining)]
                get => Current;
            }

            [MethodImpl(MethodImplOptions.AggressiveInlining)]
            public bool MoveNext()
            {
                if (_version != _map.keys._version)
                    throw new InvalidOperationException("Collection was modified");

                var keysSeg = _keysSeg;
                if (keysSeg != 0)
                {
                    int bit = BitOperations.TrailingZeroCount(keysSeg);
                    ulong bitMask = 1UL << bit;
                    byte keyByte = (byte)(_segmentBase + bit);
                    _keysSeg = keysSeg & (keysSeg - 1);

                    _current = (_nullsSeg & bitMask) != 0
                                   ? _values[_isFlat ? keyByte : ++_valIndex]
                                   : default!;
                    _hasCurrent = true;
                    return true;
                }
                return AdvanceSegment();
            }

            [MethodImpl(MethodImplOptions.NoInlining)]
            private bool AdvanceSegment()
            {
                while (true)
                {
                    _segmentBase += 64;
                    if ((uint)_segmentBase >= 256u)
                    {
                        _segmentBase = 256;
                        _hasCurrent = false;
                        _current = default!;
                        return false;
                    }
                    int idx = _segmentBase >> 6;
                    ulong keysSeg = _map.keys.Segment(idx);
                    if (keysSeg == 0)
                        continue;

                    _nullsSeg = _map.nullsVal.Segment(idx);

                    int bit = BitOperations.TrailingZeroCount(keysSeg);
                    ulong bitMask = 1UL << bit;
                    byte keyByte = (byte)(_segmentBase + bit);
                    _keysSeg = keysSeg & (keysSeg - 1);

                    _current = (_nullsSeg & bitMask) != 0
                                   ? _values[_isFlat ? keyByte : ++_valIndex]
                                   : default!;
                    _hasCurrent = true;
                    return true;
                }
            }

            [MethodImpl(MethodImplOptions.AggressiveInlining)]
            public void Reset()
            {
                _keysSeg = 0;
                _nullsSeg = 0;
                _segmentBase = -64;
                _valIndex = -1;
                _current = default!;
                _hasCurrent = false;
                _version = _map.keys._version;
            }

            [MethodImpl(MethodImplOptions.AggressiveInlining)]
            public void Dispose() { _current = default!; }
        }
    }
