    ///<summary>
    ///Adds or updates a key-value pair in the map.
    ///Handles the transition to the Flat strategy when the 128th non-null value is added.
    ///</summary>
    ///<param name="key">The key to add or update.</param>
    ///<param name="value">The value to associate with the key (can be null).</param>
    ///<returns>True if the key was added, false if it was updated.</returns>
    public bool Add_(K key, V value)
    {
        var _key = Unsafe.As<K, byte>(ref key);

        if (equal_hash_V.Equals(value, default))
        {
            if (nullsVal.Set0(_key) && !IsFlat)
                BitList.Resize(values, values, nullsVal.Rank(_key), nullsVal.Count + 1, -1);
            return keys.Set1(_key);
        }

        if (nullsVal.Get(_key))
        {
            values[IsFlat ? _key : nullsVal.Rank(_key) - 1] = value;
            return false;
        }

        //We've already established nullsVal does NOT contain _key, so the
        //original `&& !nullsVal[_key]` guard on the transition branch was redundant.
        if (IsFlat)
            values[_key] = value;
        else if (nullsVal.Count == 128)
        {
            //Transition Compressed → Flat: walk the 128 nullsVal entries directly
            //(no need to scan all `keys` and re-test nullsVal for each).
            var values_ = new V[256];
            int ii = 0;
            foreach (var k in nullsVal)
            {
                var kk = k;
                values_[Unsafe.As<K, byte>(ref kk)] = values[ii++];
            }
            (values = values_)[_key] = value;
        }
        else
        {
            //Compressed insert: inline the array-resize+shift logic instead of going
            //through BitList.Resize (4 validation branches + a switch on resize sign,
            //most of which are dead for this call shape). The common sequential-append
            //case (r == oldCount, capacity available) collapses to a single array store.
            var oldCount = nullsVal.Count;
            var r = nullsVal.Rank(_key);
            var capacity = values.Length;

            if (oldCount >= capacity)
            {
                //Grow: allocate doubled array, copy prefix [0,r) and shift suffix [r,oldCount).
                var newValues = new V[capacity << 1];
                if (r > 0)
                    Array.Copy(values, 0, newValues, 0, r);
                if (r < oldCount)
                    Array.Copy(values, r, newValues, r + 1, oldCount - r);
                values = newValues;
            }
            else if (r < oldCount)
            {
                //No grow but mid-insert: in-place right shift to open slot at r.
                Array.Copy(values, r, values, r + 1, oldCount - r);
            }
            //r == oldCount && oldCount < capacity: pure append, no copy or alloc needed.
            values[r] = value;
        }

        nullsVal.Set1(_key);
        return keys.Set1(_key);
    }

