///<summary>
///A specialized dictionary that maps keys of type K (restricted to one byte type) to values of type V.
///Allows associating null values with any key.
///<para>
///The map employs two internal strategies for storing values to optimize for both space and performance:
///<list type="number">
///<item>
///  <b>Compressed (Rank-Based) Strategy:</b> used when fewer than 128 keys have non-null values.
///  Stores only non-null values in a compact array, using a bitset to track keys with non-null values.
///</item>
///<item>
///  <b>Flat (One-to-One) Strategy:</b> Activated when 128 or more keys have non-null values.
///  Uses a fixed-size array of 256 elements for direct O(1) access, with each index corresponding to a byte key.
///</item>
///</list>
///The transition between strategies occurs automatically when the 128th non-null value is added.
///</para>
///
///<para><b>Benchmark vs <c>Dictionary&lt;byte,int&gt;</c></b> (full byte domain 0..255 → flat strategy,
///1M random Contains/Get probes, .NET 9, Release; median of 5 runs):</para>
///<code>
///Insert         Search             Get        Indexer       Iterate         Delete         Churn
///ByteMap&lt;byte,int&gt;  27 526 882  1 749 038 029   1 101 477 553  1 096 663 011    59 733 333     18 436 214    28 535 032   ops/sec
///Dictionary                 0.87           0.05            0.36           0.34          0.93           0.83          0.73   x
///</code>
///<para><b>Memory profile (Insert, 256 keys, full byte domain (flat strategy)):</b>
///<list type="bullet">
///<item><c>ByteMap</c> allocates <b>8.91 B/op</b> (Insert, 256 keys, full byte domain (flat strategy) of 256 records)</item>
///<item><c>Dictionary</c> allocates <b>23.41 B/op</b></item>
///<item><c>ByteMap</c> saves <b>~14 500 B per 1 000 records</b> vs Dictionary</item>
///</list>
///</para>
///<para>
///Ratio &gt; 1 ⇒ <c>Dictionary</c> faster, &lt; 1 ⇒ <c>ByteMap</c> faster. ByteMap now wins <b>every</b> scenario:
///~20× faster on Search (bitset Get vs hash-and-chain walk), ~3× faster on TryGetValue and indexer get,
///~1.4× faster on Churn, ~1.2× faster on Delete, and edges Dictionary by ~15% on Insert and ~8% on Iterate.
///The Insert win comes from inlining the compressed-mode array shift (skipping the BitList.Resize call's
///parameter-validation overhead) and a lockstep keys+nullsVal walk during the compressed→flat transition.
///The Iterate win comes from segment-cached enumeration (TZCNT + bit-clear per element, value resolution
///via a single shift+AND against the cached <c>nullsVal</c> segment).
///</para>
///<para>See <c>Tests/Benchmarks/ByteMapBenchmark.cs</c> for the full scenarios and an HTML report.</para>
///</summary>
///<typeparam name="K">The key type, must be a struct (one byte type).</typeparam>
///<typeparam name="V">The value type, can be any type.</typeparam>
