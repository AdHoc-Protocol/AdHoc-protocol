    ///Gets a reference to the value associated with the specified key, adding a provided default value if the key does not exist.
    ///</summary>
    ///<param name="key">The key to search for.</param>
    ///<param name="defaultValue">The value to add if the key does not exist.</param>
    ///<param name="exists">When this method returns, contains <c>true</c> if the key already existed; otherwise, <c>false</c>.</param>
    ///<returns>A reference to the value associated with the specified key.</returns>
    ///<remarks>
    ///Note: Do not add or remove items from the map while holding this reference, as triggering a resize of the internal arrays will invalidate it.
    ///</remarks>
    public ref V GetValueRefOrAddDefault(K key, V defaultValue, out bool exists)
    {
        var _key = Unsafe.As<K, byte>(ref key);

        exists = keys.Get(_key);
        bool hasSlot = nullsVal.Get(_key);

        if (exists && hasSlot)
        {
            return ref values[IsFlat ? _key : nullsVal.Rank(_key) - 1];
        }

        //If the key existed but had no physical slot (stored logically as default),
        //we must instantiate its slot with default(V) to preserve its current logical value.
        V insertValue = exists ? default! : defaultValue;

        //1. Flat Strategy Logic
        if (IsFlat)
        {
            if (!exists)
                keys.Set1(_key);
            nullsVal.Set1(_key);
            values[_key] = insertValue;
            return ref values[_key];
        }

        //2. Switch to Flat Strategy if threshold is met
        if (nullsVal.Count == 128 && !hasSlot)
        {
            var values_ = new V[256];
            ref var oldRef = ref MemoryMarshal.GetArrayDataReference(values);
            ref var newRef = ref MemoryMarshal.GetArrayDataReference(values_);
            for (int key_ = -1, ii = 0; (key_ = keys.Next1(key_)) != -1;)
            {
                if (nullsVal[key_])
                    Unsafe.Add(ref newRef, key_) = Unsafe.Add(ref oldRef, ii++);
            }

            values = values_;
            if (!exists)
                keys.Set1(_key);
            nullsVal.Set1(_key);
            values[_key] = insertValue;
            return ref values[_key];
        }

        //3. Compressed Strategy Logic
        var r = nullsVal.Rank(_key);
        BitList.Resize(values, nullsVal.Count < values.Length ? values : values = new V[values.Length * 2], r, nullsVal.Count, 1);
        values[r] = insertValue;

        if (!exists)
            keys.Set1(_key);
        nullsVal.Set1(_key);

        return ref values[r];
    }

