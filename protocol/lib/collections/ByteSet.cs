    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    public void CopyTo(K[] dst, int dstIndex)
    {
        ArgumentNullException.ThrowIfNull(dst);
        ArgumentOutOfRangeException.ThrowIfGreaterThanOrEqual((uint)dstIndex, (uint)dst.Length);
        //Materialize Count once — also resolves any -2 cache state before EmitSegment runs.
        var count = Count;
        if (dst.Length - dstIndex < count)
            throw new ArgumentException("Destination array is not long enough.");

        if (count == 0)
            return;

        //Outer loop unrolled with constant-index GetElement so `_bits` stays
        //in a vector register; the inner per-segment scan uses TZCNT.
        EmitSegment(_bits.GetElement(0), 0, dst, ref dstIndex);
        EmitSegment(_bits.GetElement(1), 64, dst, ref dstIndex);
        EmitSegment(_bits.GetElement(2), 128, dst, ref dstIndex);
        EmitSegment(_bits.GetElement(3), 192, dst, ref dstIndex);
    }

    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    private static void EmitSegment(ulong segment, int baseKey, K[] dst, ref int dstIndex)
    {
        while (segment != 0)
        {
            var byteKey = (byte)(baseKey + BitOperations.TrailingZeroCount(segment));
            dst[dstIndex++] = Unsafe.As<byte, K>(ref byteKey);
            segment &= segment - 1; //clear the least significant set bit
        }
    }

