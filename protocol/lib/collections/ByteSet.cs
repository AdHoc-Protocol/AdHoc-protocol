    ///<summary>
    ///Forward enumerator. Caches the current 64-bit segment with consumed bits cleared,
    ///so the per-element fast path is just TZCNT + bit-clear + base-add. Segment
    ///boundaries are crossed only four times across a full enumeration.
    ///<para>
    ///Due to ByteSet being a struct, the snapshot taken at construction is a value copy.
    ///External modifications to the original ByteSet instance after enumerator creation
    ///will NOT be detected, unless the ByteSet is a field within a class (like in NullableByteMap).
    ///</para>
    ///</summary>
    public struct Enumerator : IEnumerator<K>
    {
        private readonly ByteSet<K> _set;
        private ulong _segment;   //remaining bits in the current segment (consumed bits cleared)
        private int _segmentBase; //0/64/128/192 once enumerating; -64 = not started; 256 = finished
        private K _current;

        [MethodImpl(MethodImplOptions.AggressiveInlining)]
        internal Enumerator(in ByteSet<K> set)
        {
            _set = set;
            _segmentBase = -64;
            _segment = 0;
            _current = default;
        }

        public K Current
        {
            [MethodImpl(MethodImplOptions.AggressiveInlining)]
            get
            {
                //(uint) cast catches both -64 (not-started) and >=256 (finished)
                //with a single comparison.
                if ((uint)_segmentBase >= 256u)
                    throw new InvalidOperationException("Enumeration has either not started or has already finished.");
                return _current;
            }
        }

        object IEnumerator.Current
        {
            [MethodImpl(MethodImplOptions.AggressiveInlining)]
            get => Current;
        }

        //AggressiveInlining is deliberate: fast path is the small body below; the cold
        //segment-transition logic lives in [NoInlining] AdvanceSegment so callers'
        //foreach bodies can inline this hot path without bloating their inline budget.
        [MethodImpl(MethodImplOptions.AggressiveInlining)]
        public bool MoveNext()
        {
            //Fast path: more set bits remain in the current segment.
            var seg = _segment;
            if (seg != 0)
            {
                var bit = BitOperations.TrailingZeroCount(seg);
                var k = (byte)(_segmentBase + bit);
                _current = Unsafe.As<byte, K>(ref k);
                _segment = seg & (seg - 1); //clear least significant set bit
                return true;
            }
            return AdvanceSegment();
        }

        [MethodImpl(MethodImplOptions.NoInlining)]
        private bool AdvanceSegment()
        {
            //Step through segments until we find one with any set bit, or run out.
            //Constant-index GetElement keeps the source `_bits` in a vector register.
            while (true)
            {
                _segmentBase += 64;
                ulong seg;
                switch (_segmentBase)
                {
                    case 0:
                        seg = _set._bits.GetElement(0);
                        break;
                    case 64:
                        seg = _set._bits.GetElement(1);
                        break;
                    case 128:
                        seg = _set._bits.GetElement(2);
                        break;
                    case 192:
                        seg = _set._bits.GetElement(3);
                        break;
                    default:
                        _segmentBase = 256;
                        return false;
                }
                if (seg != 0)
                {
                    var bit = BitOperations.TrailingZeroCount(seg);
                    var k = (byte)(_segmentBase + bit);
                    _current = Unsafe.As<byte, K>(ref k);
                    _segment = seg & (seg - 1);
                    return true;
                }
            }
        }

        [MethodImpl(MethodImplOptions.AggressiveInlining)]
        public void Reset()
        {
            _segmentBase = -64;
            _segment = 0;
            _current = default;
        }

        [MethodImpl(MethodImplOptions.AggressiveInlining)]
        public void Dispose() {}
    }

