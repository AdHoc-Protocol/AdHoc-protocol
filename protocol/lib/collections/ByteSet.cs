    ///<summary>
    ///Finds the smallest key greater than the specified key.
    ///</summary>
    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    internal int Next1(int key)
    {
        if (_count == 0 || ++key >= 256)
            return INVALID;

        //Unrolled switch over the starting segment using constant-index
        //GetElement so `_bits` stays in a vector register. Original used a
        //for-loop with runtime-index GetElement which forced spills.
        var rel = key & 63;
        ulong w;
        switch (key >> 6)
        {
            case 0:
                if ((w = _bits.GetElement(0) >> rel) != 0)
                    return key + BitOperations.TrailingZeroCount(w);
                if ((w = _bits.GetElement(1)) != 0)
                    return 64 + BitOperations.TrailingZeroCount(w);
                if ((w = _bits.GetElement(2)) != 0)
                    return 128 + BitOperations.TrailingZeroCount(w);
                if ((w = _bits.GetElement(3)) != 0)
                    return 192 + BitOperations.TrailingZeroCount(w);
                return INVALID;
            case 1:
                if ((w = _bits.GetElement(1) >> rel) != 0)
                    return key + BitOperations.TrailingZeroCount(w);
                if ((w = _bits.GetElement(2)) != 0)
                    return 128 + BitOperations.TrailingZeroCount(w);
                if ((w = _bits.GetElement(3)) != 0)
                    return 192 + BitOperations.TrailingZeroCount(w);
                return INVALID;
            case 2:
                if ((w = _bits.GetElement(2) >> rel) != 0)
                    return key + BitOperations.TrailingZeroCount(w);
                if ((w = _bits.GetElement(3)) != 0)
                    return 192 + BitOperations.TrailingZeroCount(w);
                return INVALID;
            default:
                if ((w = _bits.GetElement(3) >> rel) != 0)
                    return key + BitOperations.TrailingZeroCount(w);
                return INVALID;
        }
    }

