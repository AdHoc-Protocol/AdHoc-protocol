            //bloat callers' inline budgets and so the throw site doesn't pessimize
            //the JIT's view of the fast path.
            var c = _count;
            return c >= 0 ? c : CountSlow();
        }
    }

    [MethodImpl(MethodImplOptions.NoInlining)]
    private int CountSlow()
    {
        if (_count == -1)
            throw new InvalidOperationException("Set is not valid.");
        //Constant-index GetElement keeps `_bits` in a vector register — taking
        //ref _bits via Unsafe.As would force a stack spill.
        return _count = BitOperations.PopCount(_bits.GetElement(0)) + BitOperations.PopCount(_bits.GetElement(1)) + BitOperations.PopCount(_bits.GetElement(2)) + BitOperations.PopCount(_bits.GetElement(3));
    }

