    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    private ref uint GetBucket(uint hashCode) => ref Unsafe.Add(ref MemoryMarshal.GetArrayDataReference(_buckets!), (nint)(MixHash(hashCode) & _mask));

    //speed_up selects two buckets per entry slot; otherwise one. Links grow on demand.
    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    private int BucketsFor(int size) => _speedUp && size < 1 << 30 ? size << 1 : size;

    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    private static int LinksFor(int size) => Math.Max(Math.Min(size, 16), size >> 2);

    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    private static uint MixHash(uint h) => h ^ (h >> 8) ^ (h >> 13) ^ (h >> 24);

    [DoesNotReturn]
    [MethodImpl(MethodImplOptions.NoInlining)]
    private static void ThrowChainTooLong() => throw new InvalidOperationException("Hash collision chain is unexpectedly long. Possible data corruption.");

    private int Initialize(int capacity)
    {
        var size = GetPowerOfTwo(capacity);
        var bucketCount = BucketsFor(size);
        _buckets = new uint[bucketCount];
        _entries = new Entry[size];
        _vals = new V[size];
        _links = new uint[LinksFor(size)];
        _loSize = _hiSize = 0;
        _mask = (uint)(bucketCount - 1);
        return size;
    }

    ///<summary>
    ///Gets a reference to the value associated with the specified key, adding a provided default value if the key does not exist.
    ///</summary>
    ///<remarks>Do not add or remove items while holding this reference; a resize will invalidate it.</remarks>
    public ref V GetValueRefOrAddDefault(K key, V defaultValue, out bool exists)
    {
        ArgumentNullException.ThrowIfNull(key);
        if (_buckets == null)
            Initialize(DefaultCapacity);
        var hashCode = KeyHash(key);
        ref var bucket = ref GetBucket((uint)hashCode);
        if (bucket != 0)
        {
            var i = (int)bucket - 1;
            ref var entry = ref _entries![i];
            if (entry.hash != hashCode || !KeyEquals(entry.key, key))
                i = _loSize <= i ? -1 : FindInChain(i, key, hashCode);
            if (0 <= i)
            {
                exists = true;
                return ref _vals![i];
            }
        }
        exists = false;
        if (_entries!.Length <= _loSize + _hiSize)
            return ref GrowAndAdd(key, defaultValue, hashCode);
        return ref AddNew(ref bucket, key, defaultValue, hashCode);
    }

    ///<summary>Rebuilds into local arrays, growing links on demand, then publishes the completed table.</summary>
    private int Resize(int newSize)
    {
        var oldData = _entries!;
        var oldVals = _vals!;
        var oldLoSize = _loSize;
        var oldEnd = oldData.Length;
        var oldHiStart = oldEnd - _hiSize;
        var size = GetPowerOfTwo(newSize);
        var bucketCount = BucketsFor(size);
        var buckets = new uint[bucketCount];
        var data = new Entry[size];
        var vals = new V[size];
        var links = new uint[LinksFor(size)];
        var mask = (uint)(bucketCount - 1);
        ref var oldData0 = ref MemoryMarshal.GetArrayDataReference(oldData);
        ref var oldVals0 = ref MemoryMarshal.GetArrayDataReference(oldVals);
        ref var data0 = ref MemoryMarshal.GetArrayDataReference(data);
        ref var vals0 = ref MemoryMarshal.GetArrayDataReference(vals);
        ref var links0 = ref MemoryMarshal.GetArrayDataReference(links);
        ref var buckets0 = ref MemoryMarshal.GetArrayDataReference(buckets);
        var loSize = 0;
        var hi = size;

        //the lo region, then the hi one
        for (int i = 0, end = oldLoSize;; i = oldHiStart, end = oldEnd)
        {
            for (; i < end; i++)
            {
                ref var entry = ref Unsafe.Add(ref oldData0, i);
                ref var bucket = ref Unsafe.Add(ref buckets0, (nint)(MixHash((uint)entry.hash) & mask));
                var head = bucket;
                int dstIndex;
                if (head == 0)
                    dstIndex = --hi;
                else
                {
                    if (loSize == links.Length)
                    {
                        Array.Resize(ref links, Math.Min(size, links.Length * 2));
                        links0 = ref MemoryMarshal.GetArrayDataReference(links);
                    }
                    Unsafe.Add(ref links0, dstIndex = loSize++) = (uint)(head - 1);
                }
                Unsafe.Add(ref data0, dstIndex) = entry;
                Unsafe.Add(ref vals0, dstIndex) = Unsafe.Add(ref oldVals0, i);
                bucket = (uint)(dstIndex + 1);
            }
            if (end == oldEnd)
                break;
        }

        _buckets = buckets;
        _entries = data;
        _vals = vals;
        _links = links;
        _mask = mask;
        _loSize = loSize;
        _hiSize = size - hi;
        return size;
    }

    //Moves the entry at src to dst and updates the one pointer to src ( the bucket or a link ).
    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    private void Move(int src, int dst)
    {
        if (src == dst)
            return;

        //Skip the array-bounds checks: src < _entries.Length and the chain-walked
        //indices are bounded by the same. Same trick the BCL uses internally.
        ref var entries0 = ref MemoryMarshal.GetArrayDataReference(_entries!);
        ref var vals0 = ref MemoryMarshal.GetArrayDataReference(_vals!);
        ref var links0 = ref MemoryMarshal.GetArrayDataReference(_links!);
        ref var srcEntry = ref Unsafe.Add(ref entries0, src);
        ref var srcBucket = ref GetBucket((uint)srcEntry.hash);
        var index = (int)srcBucket - 1;

        if (index == src)
            srcBucket = (uint)(dst + 1);
        else
        {
            //Walk the source's chain until we find the link that points at `src`,
            //then rewire it to `dst` in O(1) at that link. Chain length is the
            //structural cost vs Dictionary's freelist O(1) — unavoidable without
            //adding a back-pointer per Entry (4 bytes/entry memory cost).
            ref var link = ref Unsafe.Add(ref links0, index);
            while (link != src)
            {
                index = (int)link;
                link = ref Unsafe.Add(ref links0, index);
            }

            link = (uint)dst;
        }

        if (src < _loSize)
            Unsafe.Add(ref links0, dst) = Unsafe.Add(ref links0, src);

        Unsafe.Add(ref entries0, dst) = srcEntry;
        Unsafe.Add(ref vals0, dst) = Unsafe.Add(ref vals0, src);
    }

    ///<summary>
    ///Removes <paramref name="key"/> if present. The common case inline - a key not there, or alone in its bucket ( an
    ///entry of hi ) - the chains in <see cref="RemoveChain"/> ( see PrimitiveKeyMap ).
    ///</summary>
    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    public bool Remove(K key)
    {
        ArgumentNullException.ThrowIfNull(key);
        if (_loSize + _hiSize == 0)
            return false;

        var hashCode = KeyHash(key);
        ref var bucket = ref GetBucket((uint)hashCode);
        var idx = (int)bucket - 1;
        if (idx < 0)
            return false;

        //Chain length 1: the only entry sits in hi-region (the original empty-bucket placement).
        //Bucket goes empty; compact hi-region by moving the newest hi entry into the hole.
        if (_loSize <= idx)
        {
            ref var e = ref Unsafe.Add(ref MemoryMarshal.GetArrayDataReference(_entries!), idx);
            if (e.hash != hashCode || !KeyEquals(e.key, key))
                return false;
            Move(_entries!.Length - _hiSize, idx);
            _hiSize--;
            bucket = 0;
            return true;
        }
        return RemoveChain(ref bucket, idx, key, hashCode);
    }

    ///<summary>
    ///<see cref="Remove"/> of a chain that begins in lo.
    ///<para>Index-based chain walk (no <c>ref</c> aliasing across iterations) so the JIT can keep
    ///the loop in registers. The walker tracks the immediate predecessor (<c>prev</c>) and the
    ///pre-predecessor (<c>prevPrev</c>) so the hi-terminator migration case can rewire the back-pointer
    ///in O(1) instead of re-walking.</para>
    ///</summary>
    [MethodImpl(MethodImplOptions.NoInlining)]
    private bool RemoveChain(ref uint bucket, int idx, K key, int hashCode)
    {
        var loSize = _loSize;
        ref var entries0 = ref MemoryMarshal.GetArrayDataReference(_entries!);
        ref var links0 = ref MemoryMarshal.GetArrayDataReference(_links!);
        var prev = -1;     //immediate predecessor (-1 means current is at chain head; bucket points to it)
        var prevPrev = -1; //predecessor's predecessor (-1 means prev is at chain head)

        for (var collisions = 0;
             Unsafe.Add(ref entries0, idx).hash != hashCode || !KeyEquals(Unsafe.Add(ref entries0, idx).key, key);
             prevPrev = prev, idx = (int)Unsafe.Add(ref links0, prev = idx))
        {
            if (idx >= loSize)
                return false; //chain terminator without match
            if (++collisions > loSize)
                ThrowChainTooLong();
        }

        var lastLo = loSize - 1;
        if (idx < loSize)
        {
            //Standard removal: rewire (prev or bucket) → next; compact lo by swap-with-last.
            //Single read of the matched entry's link; both branches consume `next`.
            var next = Unsafe.Add(ref links0, idx);
            if (prev < 0)
                bucket = next + 1;
            else
                Unsafe.Add(ref links0, prev) = next;
            Move(lastLo, idx);
        }
        else
        {
            //Found at hi-terminator with chain length ≥ 2. Migrate prev (lo) into the hi slot
            //so the chain still terminates in hi; prev's lo slot becomes the hole.
            ref var vals0 = ref MemoryMarshal.GetArrayDataReference(_vals!);
            Unsafe.Add(ref entries0, idx) = Unsafe.Add(ref entries0, prev);
            Unsafe.Add(ref vals0, idx) = Unsafe.Add(ref vals0, prev);
            if (prevPrev < 0)
                bucket = (uint)(idx + 1);
            else
                Unsafe.Add(ref links0, prevPrev) = (uint)idx;
            Move(lastLo, prev);
        }

        _loSize = lastLo;
        return true;
    }

    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    public bool Remove(KeyValuePair<K, V> item) => TryGetValue(item.Key, out var value) && EqualityComparer<V>.Default.Equals(value, item.Value) && Remove(item.Key);

    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    public bool Contains(KeyValuePair<K, V> item) => TryGetValue(item.Key, out var value) && EqualityComparer<V>.Default.Equals(value, item.Value);

    public void CopyTo(KeyValuePair<K, V>[] dst, int dstIndex)
    {
        ArgumentNullException.ThrowIfNull(dst);
        ArgumentOutOfRangeException.ThrowIfGreaterThanOrEqual((uint)dstIndex, (uint)dst.Length);
        if (dst.Length - dstIndex < Count)
            throw new ArgumentException("Destination array is not long enough.");

        if (_entries == null)
            return;

        for (var i = 0; i < _loSize; i++)
            dst[dstIndex++] = new KeyValuePair<K, V>(_entries[i].key, _vals![i]);

        if (_hiSize == 0)
            return;
        for (var i = _entries.Length - _hiSize; i < _entries.Length; i++)
            dst[dstIndex++] = new KeyValuePair<K, V>(_entries[i].key, _vals![i]);
    }

    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    private static int GetPowerOfTwo(int capacity) => capacity <= DefaultCapacity ? DefaultCapacity : (int)BitOperations.RoundUpToPowerOf2((uint)capacity);

