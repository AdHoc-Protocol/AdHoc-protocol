    public struct Enumerator : IEnumerator<KeyValuePair<K, V>>
    {
        //Snapshot the layout at construction so MoveNext only reads instance fields when
        //version-checking. Field reads on a heap object cost a load + a possible cache miss
        //per call; locals stay in registers across the iteration. Same approach the BCL
        //Dictionary enumerator uses.
        private readonly Map<K, V> _map;
        private readonly Entry[]? _entries;
        private readonly int _loEnd;   //_loSize at construction
        private readonly int _hiStart; //_entries.Length - _hiSize at construction
        private readonly int _hiEnd;   //_entries.Length at construction

        private readonly int _version;

        //_index uses a single sentinel — _hiEnd — for "finished" so MoveNext doesn't need
        //a separate -2 check on the hot path. Initial -1 is the "not started" state; any
        //value in [0, _loEnd) ∪ [_hiStart, _hiEnd) is the current entry index.
        private int _index;
        private KeyValuePair<K, V> _current;

        [MethodImpl(MethodImplOptions.AggressiveInlining)]
        internal Enumerator(Map<K, V> map)
        {
            _map = map;
            _version = map._version;
            _entries = map._entries;
            _loEnd = map._loSize;
            _hiEnd = _entries?.Length ?? 0;
            _hiStart = _hiEnd - map._hiSize;
            _index = -1;
            _current = default;
        }

        [MethodImpl(MethodImplOptions.AggressiveInlining)]
        public bool MoveNext()
        {
            if (_version != _map._version)
                throw new InvalidOperationException("Collection was modified during enumeration.");

            //Single linear walk: 0 .. _loEnd, then _hiStart .. _hiEnd. Fold the
            //"already finished" detection into the same `i >= _hiEnd` test that
            //signals end-of-iteration, eliminating the separate -2 check.
            int i = _index + 1;
            if (i == _loEnd)
                i = _hiStart; //bridge fires at most once per enumeration
            if (i >= _hiEnd)
            {
                _index = _hiEnd;
                return false;
            }

            //Skip the array-bounds check: we just verified `i < _hiEnd ≤ _entries.Length`,
            //so the JIT-generated `_entries![i]` bounds check is provably redundant.
            //MemoryMarshal.GetArrayDataReference + Unsafe.Add lets us skip it.
            ref var entry = ref Unsafe.Add(ref MemoryMarshal.GetArrayDataReference(_entries!), i);
            _current = new KeyValuePair<K, V>(entry.key, entry.value);
            _index = i;
            return true;
        }

        //Matches BCL Dictionary: Current is a bare field read with no checks.
        //Concurrent-modification detection lives entirely in MoveNext, which is what
        //foreach calls before each Current access — sufficient to catch real-world misuse,
        //and removing the per-iteration heap deref of `_map._version` here halves the
        //version-check cost of foreach iteration.
        public KeyValuePair<K, V> Current
        {
            [MethodImpl(MethodImplOptions.AggressiveInlining)]
            get => _current;
        }

        object? IEnumerator.Current
        {
            [MethodImpl(MethodImplOptions.AggressiveInlining)]
            get => Current;
        }

        [MethodImpl(MethodImplOptions.AggressiveInlining)]
        public void Reset()
        {
            if (_version != _map._version)
                throw new InvalidOperationException("Collection was modified during enumeration.");
            _index = -1;
            _current = default;
        }

        [MethodImpl(MethodImplOptions.AggressiveInlining)]
        public void Dispose() {}
    }

    public int EnsureCapacity(int capacity)
    {
        ArgumentOutOfRangeException.ThrowIfNegative(capacity);
        var currentCapacity = _entries?.Length ?? 0;
        if (currentCapacity >= capacity)
            return currentCapacity;
        _version++;
        return _buckets == null ? Initialize(capacity) : Resize(GetPowerOfTwo(capacity));
    }

    public void TrimExcess()
    {
        var count = Count;
        if (count == 0)
        {
            Initialize(0);
            _version++;
            return;
        }

        if (_entries != null && GetPowerOfTwo(count) < _entries.Length)
            Resize(GetPowerOfTwo(count));
    }
#region Equality
    public bool Equals(Map<K, V>? other)
    {
        if (other == null || Count != other.Count || !Comparer.Equals(other.Comparer))
            return false;
        foreach (var pair in this)
            if (!other.TryGetValue(pair.Key, out var otherValue) || !EqualityComparer<V>.Default.Equals(pair.Value, otherValue))
                return false;
        return true;
    }

    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    public override bool Equals(object? obj) => Equals(obj as Map<K, V>);

    public override int GetHashCode()
    {
        var hashCode = Comparer.GetHashCode();
        for (var i = 0; i < _loSize; i++)
        {
            var entry = _entries![i];
            hashCode ^= entry.hash ^ (entry.value?.GetHashCode() ?? 0);
        }

        if (_hiSize == 0)
            return hashCode;
        for (var i = _entries!.Length - _hiSize; i < _entries.Length; i++)
        {
            var entry = _entries[i];
            hashCode ^= entry.hash ^ (entry.value?.GetHashCode() ?? 0);
        }

        return hashCode;
    }
