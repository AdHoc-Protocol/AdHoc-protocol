    public int Count
    {
        [MethodImpl(MethodImplOptions.AggressiveInlining)]
        get => _loSize + _hiSize;
    }

    public bool IsReadOnly
    {
        [MethodImpl(MethodImplOptions.AggressiveInlining)]
        get => false;
    }

    public V this[K key]
    {
        [MethodImpl(MethodImplOptions.AggressiveInlining)]
        get
        {
            ArgumentNullException.ThrowIfNull(key);
            var i = FindIndex(key);
            if (i < 0)
                throw new KeyNotFoundException("The given key was not present in the dictionary.");
            return _vals![i];
        }
        [MethodImpl(MethodImplOptions.AggressiveInlining)]
        //TryInsert performs the null check; calling it again here would be a redundant branch.
        set => TryInsert(key, value, true);
    }

    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    public void Add(K key, V value)
    {
        if (!TryInsert(key, value, false))
            throw new ArgumentException("An item with the same key has already been added.");
    }

    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    public void Add(KeyValuePair<K, V> item) => Add(item.Key, item.Value);

    ///<summary>Attempts to add the specified key and value. Returns false if the key already exists.</summary>
    ///<remarks>Native implementation. Avoids the BCL <c>IDictionary&lt;K,V&gt;</c> extension method's
    ///double dispatch (ContainsKey + Add).</remarks>
    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    public bool TryAdd(K key, V value) => TryInsert(key, value, false);

    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    private bool TryInsert(K key, V value, bool overwrite)
    {
        ArgumentNullException.ThrowIfNull(key);

        if (_buckets == null)
            Initialize(DefaultCapacity);
        var hashCode = KeyHash(key);
        ref var bucket = ref GetBucket((uint)hashCode);
        if (bucket != 0)
        {
            var i = (int)bucket - 1;
            ref var entry = ref _entries![i];
            if (entry.hash != hashCode || !KeyEquals(entry.key, key))
                i = _loSize <= i ? -1 : FindInChain(i, key, hashCode);
            if (0 <= i)
            {
                if (overwrite)
                    _vals![i] = value;
                return false;
            }
        }

        if (_entries!.Length <= _loSize + _hiSize)
            GrowAndAdd(key, value, hashCode);
        else
            AddNew(ref bucket, key, value, hashCode);
        return true;
    }
    //The key is known to be absent and the table has a free entry slot.
    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    private ref V AddNew(ref uint bucket, K key, V value, int hashCode)
    {
        var entries = _entries!;
        var head = bucket;
        int dstIndex;
        if (head == 0)
            dstIndex = entries.Length - 1 - _hiSize++;
        else
        {
            if (_links!.Length == (dstIndex = _loSize++))
                Array.Resize(ref _links, Math.Max(16, Math.Min(entries.Length, _links.Length * 2)));
            _links[dstIndex] = (uint)(head - 1);
        }
        ref var entry = ref entries[dstIndex];
        entry.key = key;
        entry.hash = hashCode;
        ref var v = ref _vals![dstIndex];
        v = value;
        bucket = (uint)(dstIndex + 1);
        return ref v;
    }

    [MethodImpl(MethodImplOptions.NoInlining)]
    private ref V GrowAndAdd(K key, V value, int hashCode)
    {
        Resize(_entries!.Length * 2);
        return ref AddNew(ref GetBucket((uint)hashCode), key, value, hashCode);
    }

    public void Clear()
    {
        if (Count == 0)
            return;
        if (_buckets != null)
            if ((_loSize + _hiSize) * 8 <= _buckets.Length) //a few entries in a large table: only their buckets ( a map received pack after pack, once large: 1.9 µs -> 20 ns )
            {
                var e = _entries!;
                for (var i = 0; i < _loSize; i++)
                    GetBucket((uint)e[i].hash) = 0;
                for (var i = e.Length - _hiSize; i < e.Length; i++)
                    GetBucket((uint)e[i].hash) = 0;
            }
            else
                Array.Clear(_buckets, 0, _buckets.Length);
        _loSize = _hiSize = 0;
    }

    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    public bool ContainsKey(K key)
    {
        ArgumentNullException.ThrowIfNull(key);
        return FindIndex(key) >= 0;
    }

    public bool ContainsValue(V value)
    {
        var cmp = EqualityComparer<V>.Default;
        for (var i = 0; i < _loSize; i++)
            if (cmp.Equals(_vals![i], value))
                return true;
        if (_hiSize == 0)
            return false;
        for (var i = _vals!.Length - _hiSize; i < _vals.Length; i++)
            if (cmp.Equals(_vals[i], value))
                return true;
        return false;
    }

    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    public bool TryGetValue(K key, [MaybeNullWhen(false)] out V value)
    {
        ArgumentNullException.ThrowIfNull(key);
        var i = FindIndex(key);
        if (i < 0)
        {
            value = default;
            return false;
        }

        value = _vals![i];
        return true;
    }

    ///<summary>
    ///Internal finder: the index of the key, or -1. Marked AggressiveInlining so callers (TryGetValue,
    ///ContainsKey, indexer) inline the body — empirically the best variant tested. The chain past its head is
    ///<see cref="FindInChain"/> ( see PrimitiveKeyMap: a thrower called in the loop made the JIT save 7 registers ).
    ///</summary>
    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    private int FindIndex(K key)
    {
        var buckets = _buckets;
        if (buckets == null)
            return -1;
        var hashCode = KeyHash(key);
        var i = (int)Unsafe.Add(ref MemoryMarshal.GetArrayDataReference(buckets), (nint)(MixHash((uint)hashCode) & (uint)(buckets.Length - 1))) - 1;
        if (i < 0)
            return -1;
        ref var entry = ref _entries![i];
        if (entry.hash == hashCode && KeyEquals(entry.key, key))
            return i;
        return _loSize <= i ? -1 : FindInChain(i, key, hashCode);
    }

    ///<summary>The index of <paramref name="key"/> in the chain past its lo entry <paramref name="i"/>, or -1.</summary>
    [MethodImpl(MethodImplOptions.NoInlining)]
    private int FindInChain(int i, K key, int hashCode)
    {
        var entries = _entries!;
        var links = _links!;
        var loSize = _loSize;
        for (var budget = loSize;;)
        {
            ref var entry = ref entries[i = (int)links[i]];
            if (entry.hash == hashCode && KeyEquals(entry.key, key))
                return i;
            if (loSize <= i)
                return -1;
            if (--budget < 0)
                ThrowChainTooLong();
        }
    }

