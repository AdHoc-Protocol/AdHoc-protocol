///<summary>
///A generic dictionary with reference-type keys, optimized for top throughput and minimal GC pressure.
///<para><b>Storage layout (selected design — single Entry array + side _links):</b></para>
///<para>
///A single <see cref="Entry"/> array is split into two regions:
///<list type="bullet">
///<item><b>Hi-region</b> [<c>_entries.Length - _hiSize .. _entries.Length</c>) — chain terminators
///(entries placed when their bucket was empty).</item>
///<item><b>Lo-region</b> [<c>0 .. _loSize</c>) — collision-chain entries. Their successor index lives
///in a separate <c>_links</c> array sized only to <c>_loSize</c>, so memory is paid only for actual
///collisions.</item>
///</list>
///Chain termination is detected implicitly via <c>_loSize &lt;= i</c> while walking — no sentinel
///and no per-hop region flag needed.
///</para>
///
///<para><b>Alternative considered: Option D — split <c>LoEntry</c>/<c>HiEntry</c> types</b></para>
///<para>
///Inlining <c>next</c> into a typed <c>LoEntry</c> struct would save one cache-line load per chain
///hop on collision walks. Prototyped and benchmarked against this layout for <c>Map&lt;string,int&gt;</c>:
///every method regressed — including the forced-collision case Option D was meant to win, where the
///measured throughput dropped 20%. The locality of a single shared <c>_entries</c> array beats the
///theoretical inlined-next saving, because typical workloads have short chains (Poisson-weighted
///average ~1.76 at 75% load) that don't amortize the dispatch overhead between two typed regions.
///The same outcome was observed earlier on <c>PrimitiveKeyMap</c>, so Option D is rejected for both
///class and unmanaged key maps.
///</para>
///
///<para><b>Benchmark vs <c>Dictionary&lt;string,int&gt;</c></b> (N = 100 000, 15-char string keys, .NET 9, Release;
///median of 7–10 runs):</para>
///<code>
///Insert       Search          Get          Iterate       Delete       Churn
///Map&lt;string,int&gt;       26 335 591   48 785 927   35 753 505    1 305 000 000   20 000 000   16 100 000   ops/sec
///Dictionary                  0.97         0.83         0.98             0.91         1.11         1.46   x
///</code>
///<para><b>Memory profile (grow-from-empty Insert, 100 000 string keys):</b>
///<list type="bullet">
///<item><c>Map</c> allocates <b>57.68 B/op</b> (grow-from-empty Insert of 100 000 records)</item>
///<item><c>Dictionary</c> allocates <b>84.52 B/op</b></item>
///<item><c>Map</c> saves <b>~26 840 B per 1 000 records</b> vs Dictionary</item>
///</list>
///</para>
///<para>
///Ratio &gt; 1 ⇒ <c>Dictionary</c> faster, &lt; 1 ⇒ <c>Map</c> faster. Map matches or beats Dictionary
///on read-heavy paths (Search/Get/Insert) and <b>beats Dictionary on Iterate by ~10%</b> (structural
///advantage of the packed dual-region layout — entries occupy
///<c>[0..loSize) ∪ [Length-hiSize..Length)</c>, no holes within either region). Remove/churn gap to
///Dictionary's freelist-O(1) closed dramatically: Remove went from 1.64× to 1.10× behind, Churn
///from 1.89× to 1.48× behind. The win came from skipping the JIT-emitted array-bounds checks
///during the chain walks — <c>Unsafe.Add</c> + <c>MemoryMarshal.GetArrayDataReference</c> on
///<c>_entries</c>/<c>_links</c>: every chain hop was paying for a bounds check we'd already proven
///safe. The remaining churn gap is structural: Map's <c>Move</c> still walks the moved entry's
///chain to rewire its predecessor's link (vs Dictionary's O(1) freelist add).
///</para>
///<para>See <c>Tests/Benchmarks/MapBenchmark.cs</c> for the full scenarios and an HTML report.</para>
///</summary>
///<typeparam name="K">The reference-type key.</typeparam>
///<typeparam name="V">The value type.</typeparam>
