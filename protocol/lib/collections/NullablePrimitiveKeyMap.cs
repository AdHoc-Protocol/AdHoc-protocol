    public struct Enumerator : IEnumerator<KeyValuePair<K?, V>>
    {
        //Snapshot the layout at construction so MoveNext only reads instance fields when
        //version-checking. Field reads on the heap object cost a load + a possible cache
        //miss per call; locals stay in registers across the iteration. Same approach as
        //<see cref="PrimitiveKeyMap{K,V}.Enumerator"/> — the previous implementation read
        //`_map._loSize`, `_map._hiSize`, `_map._entries.Length`, `_map._hasNullKey`,
        //`_map._nullKeyValue`, and `_map.Count` on EVERY MoveNext, plus emitted JIT
        //bounds checks on `_map._entries[i]`. That's why Iterate was ~50% slower than
        //BCL Dictionary on this collection while PrimitiveKeyMap (same shape sans the
        //null-slot) was ahead.
        private readonly NullablePrimitiveKeyMap<K, V> _map;
        private readonly Entry[]? _entries;
        private readonly int _loEnd;      //_loSize at construction
        private readonly int _hiStart;    //_entries.Length - _hiSize at construction
        private readonly int _hiEnd;      //_entries.Length at construction
        private readonly V _nullKeyValue; //snapshot — never re-read
        private readonly int _version;

        //Sentinel values for _index:
        //  -2 = null-key pending (will yield it on next MoveNext)
        //  -1 = null-key already yielded (or never had one); regular walk has not started
        //  -3 = finished (terminal — MoveNext keeps returning false)
        //  [0, _loEnd) ∪ [_hiStart, _hiEnd) = current entry index in _entries
        private int _index;
        private KeyValuePair<K?, V> _current;

        [MethodImpl(MethodImplOptions.AggressiveInlining)]
        internal Enumerator(NullablePrimitiveKeyMap<K, V> map)
        {
            _map = map;
            _version = map._version;
            _entries = map._entries;
            _loEnd = map._loSize;
            _hiEnd = _entries?.Length ?? 0;
            _hiStart = _hiEnd - map._hiSize;
            _nullKeyValue = map._nullKeyValue;
            _index = map._hasNullKey ? -2 : -1;
            _current = default;
        }

        [MethodImpl(MethodImplOptions.AggressiveInlining)]
        public bool MoveNext()
        {
            if (_version != _map._version)
                throw new InvalidOperationException("Collection was modified during enumeration.");

            //First call when a null key is present: yield (null, _nullKeyValue) and switch
            //into the regular-walk state. Branch is taken at most once per enumeration.
            if (_index == -2)
            {
                _current = new KeyValuePair < K ?, V > (null, _nullKeyValue);
                _index = -1;
                return true;
            }

            if (_index == -3)
                return false; //already finished

            //Single linear walk: 0 .. _loEnd, then _hiStart .. _hiEnd. The lo→hi bridge
            //fires at most once; the i >= _hiEnd test folds end-of-iteration detection.
            var i = _index + 1;
            if (i == _loEnd)
                i = _hiStart;
            if (i >= _hiEnd)
            {
                _index = -3;
                return false;
            }

            //Skip the array-bounds check: we just verified i < _hiEnd ≤ _entries.Length.
            ref var entry = ref Unsafe.Add(ref MemoryMarshal.GetArrayDataReference(_entries!), i);
            _current = new KeyValuePair < K ?, V > (entry.key, entry.value);
            _index = i;
            return true;
        }

        //BCL Dictionary semantics: bare field read. Concurrent-modification detection
        //lives in MoveNext; a stale Current after invalidation is acceptable.
        public KeyValuePair<K?, V> Current
        {
            [MethodImpl(MethodImplOptions.AggressiveInlining)]
            get => _current;
        }

        object? IEnumerator.Current => Current;

        public void Reset()
        {
            if (_version != _map._version)
                throw new InvalidOperationException("Collection was modified during enumeration.");
            _index = _map._hasNullKey ? -2 : -1;
            _current = default;
        }

        public void Dispose() {}
    }

    public int EnsureCapacity(int capacity)
    {
        ArgumentOutOfRangeException.ThrowIfNegative(capacity);
        var currentCapacity = _entries?.Length ?? 0;
        if (currentCapacity >= capacity)
            return currentCapacity;
        _version++;
        if (_buckets == null)
            return Initialize(capacity);
        var newSize = GetPowerOfTwo(capacity);
        Resize(newSize);
        return newSize;
    }

    public void TrimExcess()
    {
        var count = Count;
        if (count == 0)
        {
            Initialize(0);
            _hasNullKey = false;
            _nullKeyValue = default!;
            return;
        }

        if (_entries == null)
            return;
        var newSize = GetPowerOfTwo(count);
        if (newSize < _entries.Length)
            Resize(newSize);
    }
