///<summary>
///Represents a collection of keys and values, where keys are unique nullable primitive values of type <typeparamref name="K"/>.
///This map implementation uses a hash table and is optimized for nullable primitive keys.
///It supports a single null key.
///
///<para><b>Benchmark vs <c>Dictionary&lt;int?,int&gt;</c></b> (N = 100 000 random int keys, .NET 9, Release):</para>
///<code>
///Insert       Search          Get        Get miss       Iterate         Delete
///NullablePrimitiveKeyMap&lt;int?,int&gt;  35 768 303  168 813 003  166 168 162     155 176 236   680 404 355     17 498 250   ops/sec
///Dictionary                              0.53         0.17         0.17            0.22          1.51           1.09   x
///</code>
///<para><b>Memory profile (Insert, 100 000 random int keys):</b>
///<list type="bullet">
///<item><c>NullablePrimitiveKeyMap</c> allocates <b>36.71 B/op</b> (Insert of 100 000 records)</item>
///<item><c>Dictionary</c> allocates <b>72.45 B/op</b></item>
///<item><c>NullablePrimitiveKeyMap</c> saves <b>~35 739 B per 1 000 records</b> vs Dictionary</item>
///</list>
///</para>
///<para>
///Ratio &gt; 1 ⇒ <c>Dictionary</c> faster, &lt; 1 ⇒ NullablePrimitiveKeyMap faster. NullablePrimitiveKeyMap
///is <b>~6× faster on reads</b> (Search/Get) - the BCL <c>Dictionary&lt;int?,int&gt;</c> pays heavy
///nullable-wrapping overhead per lookup, while this class stores a separate <c>_hasNullKey</c> flag
///and raw <c>int</c> entries. Insert is also ~2× faster; Delete is parity. Dictionary wins Iterate
///(its contiguous entry layout beats the dual-region split).
///</para>
///<para>See <c>Tests/Benchmarks/NullablePrimitiveKeyMapBenchmark.cs</c> for the full scenarios and an HTML report.</para>
///<para><b>Layout notes.</b> Keys are spread with a three-shift xor mix (<see cref="Hash"/>) before masking, and the
///bucket array holds two buckets per entry slot by default (load factor at most 0.5). The figures above were measured before
///these two changes; re-run the benchmark to refresh them. The bucket count is a single tuning point,
///<see cref="BucketsFor"/>: see its remarks to trade lookup speed for 4 bytes per slot.</para>
///</summary>
///<typeparam name="K">The type of the primitive keys in the map. Must be an unmanaged type.</typeparam>
///<typeparam name="V">The type of the values in the map.</typeparam>
[DebuggerDisplay("Count = {Count}")]
public class NullablePrimitiveKeyMap<K, V> : IDictionary<K?, V>, IReadOnlyDictionary<K?, V>
    where K : unmanaged
{
    //Never null: a map without a table holds NoBuckets ( one empty bucket, mask 0 ) and empty arrays, so a lookup misses
    //and the first insert finds no free slot and grows, with no null check on either path.
    private static readonly uint[] NoBuckets = new uint[1];

    private uint[] _buckets = NoBuckets;
    private K[] _entries = [];  //the keys of the entries: a lookup walks them alone ( see PrimitiveKeyMap )
    private V[] _vals = [];     //the value of _entries[i] at i
    private uint[] _links = []; //0-based indices into _entries for collision chains.

    //The _entries array is split into two regions to optimize for non-colliding entries:
    //1. Lo-Region (indices 0 to _loSize-1): Stores entries that have caused a hash collision.
    //2. Hi-Region (indices _entries.Length - _hiSize to _entries.Length-1): Stores entries that have not caused a collision.
    private int _hiSize; //Number of active entries in the high region.
    private int _loSize; //Number of active entries in the low region.

    private V _nullKeyValue;
    private bool _hasNullKey;

    private uint _mask;

    private KeysCollection? _keys;
    private ValuesCollection? _values;

    private readonly bool _speedUp;

    private const int DefaultCapacity = 4;

