    public int Count
    {
        [MethodImpl(MethodImplOptions.AggressiveInlining)]
        get => _loSize + _hiSize + (_hasNullKey ? 1 : 0);
    }

    public bool IsReadOnly => false;

    public V this[K? key]
    {
        [MethodImpl(MethodImplOptions.AggressiveInlining)]
        get
        {
            if (!key.HasValue)
            {
                if (_hasNullKey)
                    return _nullKeyValue;
                throw new KeyNotFoundException("The given key was not present in the dictionary.");
            }
            var i = FindIndex(key.Value);
            if (i < 0)
                throw new KeyNotFoundException("The given key was not present in the dictionary.");
            return _vals![i];
        }
        [MethodImpl(MethodImplOptions.AggressiveInlining)]
        set => TryInsert(key, value, true);
    }

    ///<summary>Native TryAdd — avoids the BCL IDictionary extension's double dispatch.</summary>
    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    public bool TryAdd(K? key, V value) => TryInsert(key, value, false);

    ///<summary>
    ///Internal finder for non-null keys: the index of the key, or -1. Marked AggressiveInlining so callers
    ///(TryGetValue, ContainsKey, indexer) inline the body. Null-key handling is short-circuited at
    ///each public method's entry — this helper handles only the value-key path.
    ///<para>
    ///The bucket mask is derived from the bucket array that was actually loaded (not from <c>_mask</c>),
    ///so the unchecked bucket read stays in bounds even if a reader races a resize; key and link reads
    ///keep their bounds checks for the same reason. The chain past its head is <see cref="FindInChain"/>:
    ///its length check calls a thrower, and a call in the loop made the JIT save 7 registers at every lookup.
    ///</para>
    ///</summary>
    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    private int FindIndex(K key)
    {
        var buckets = _buckets;
        if (buckets == null)
            return -1;

        var i = (int)Unsafe.Add(ref MemoryMarshal.GetArrayDataReference(buckets), (nint)(Hash(key) & (uint)(buckets.Length - 1))) - 1;
        if (i < 0)
            return -1;
        if (EqualityComparer<K>.Default.Equals(_entries![i], key))
            return i;
        return _loSize <= i ? -1 : //terminal node
                   FindInChain(i, key);
    }

    ///<summary>The index of <paramref name="key"/> in the chain past its lo entry <paramref name="i"/>, or -1.</summary>
    [MethodImpl(MethodImplOptions.NoInlining)]
    private int FindInChain(int i, K key)
    {
        var keys = _entries!;
        var links = _links!;
        var loSize = _loSize;
        for (var budget = loSize;;)
        {
            i = (int)links[i];
            if (EqualityComparer<K>.Default.Equals(keys[i], key))
                return i;
            if (loSize <= i)
                return -1; //terminal node
            if (--budget < 0)
                ThrowChainTooLong();
        }
    }

    [DoesNotReturn]
    [MethodImpl(MethodImplOptions.NoInlining)]
    private static void ThrowChainTooLong() => throw new InvalidOperationException("Hash collision chain is unexpectedly long. Possible data corruption.");

    public ICollection<K?> Keys => _keys ??= new KeysCollection(this);
    public ICollection<V> Values => _values ??= new ValuesCollection(this);

    IEnumerable<K?> IReadOnlyDictionary<K?, V>.Keys => Keys;
    IEnumerable<V> IReadOnlyDictionary<K?, V>.Values => Values;

    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    private ref uint GetBucket(uint hash) => ref Unsafe.Add(ref MemoryMarshal.GetArrayDataReference(_buckets!), (nint)(hash & _mask));

    ///<summary>
    ///Hash used for bucket selection: <c>GetHashCode()</c> folded by a three-shift xor.
    ///<para>
    ///Buckets are selected by masking low bits, and <c>int.GetHashCode()</c> is the identity, so without a mix
    ///keys that differ only in high bits (multiples of 256, 1024, 65536, ids with a type tag in the top bits…)
    ///all land in a few buckets and every operation degrades to a chain walk. A sum of right shifts is a bijection
    ///on every <c>0..2^k-1</c> prefix, so dense counter keys still never collide at any table size.
    ///</para>
    ///</summary>
    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    private static uint Hash(K key)
    {
        var h = (uint)key.GetHashCode();
        return h ^ (h >> 8) ^ (h >> 13) ^ (h >> 24);
    }

    ///<summary>
    ///Bucket count for an entry capacity: two buckets per slot when speed_up is true, otherwise one. At load factor 1 about 37%
    ///of random keys collide and need a chain walk; at 0.5 about 21% do. Costs 4 bytes per slot.
    ///</summary>
    ///<remarks>
    ///<para>
    ///With speed_up enabled the extra buckets hold no keys or values: each is a <c>uint</c> chain head, and most of them stay 0. They only
    ///make it likelier that a key's bucket is empty or holds a single entry. With random keys at full capacity:
    ///</para>
    ///<code>
    ///1 bucket/slot   2 buckets/slot
    ///entries alone in their bucket (Hi-Region)     ~63%            ~79%
    ///entries in collision chains (Lo-Region)       ~37%            ~21%
    ///misses rejected by an empty bucket            ~37%            ~61%
    ///</code>
    ///<para>
    ///<b>Tuning.</b> Pass <c>speed_up: false</c> to a constructor for one bucket per slot; everything else reads
    ///<c>_buckets.Length</c> or <c>_mask</c>. This restores the original bucket ratio (saves ~3–3.5 bytes per
    ///slot; the hash mix and every other change still apply). Expect slower hits, misses and inserts on random keys
    ///(the Java port of this layout measured 14–36%, 23–50% and up to 45%); dense sequential keys are unaffected.
    ///<see cref="LinksFor"/> needs no change: <c>_links</c> grows on demand in both insertion and <see cref="Resize"/>.
    ///</para>
    ///</remarks>
    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    private int BucketsFor(int size) => _speedUp && size < 1 << 30 ? size << 1 : size;

    private int Initialize(int capacity)
    {
        var size = GetPowerOfTwo(capacity);
        var bucketCount = BucketsFor(size);
        _buckets = new uint[bucketCount];
        _entries = new K[size];
        _vals = new V[size];
        _links = new uint[LinksFor(size)];
        _loSize = _hiSize = 0;
        _mask = (uint)(bucketCount - 1);
        return size;
    }

    ///<summary>
    ///Initial <c>_links</c> length: at load factor at most 0.5 the Lo-Region stays near 21% of capacity, so a quarter
    ///almost never has to grow. With one bucket per slot (see <see cref="BucketsFor"/>) the Lo-Region reaches ~37% and
    ///<c>_links</c> simply grows once or twice per fill; <c>size * 3 / 8</c> would avoid that.
    ///</summary>
    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    private static int LinksFor(int size) => Math.Max(Math.Min(size, 16), size >> 2);

    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    private bool TryInsert(K? key, V value, bool overwrite)
    {
        if (key.HasValue)
            return TryInsertKey(key.GetValueOrDefault(), value, overwrite);
        if (_hasNullKey && !overwrite)
            return false;
        PutNullKey(value);
        return true;
    }

    ///<summary>Inserts or overwrites the value of a non-null key. Returns <c>true</c> if the key was new.</summary>
    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    public bool PutKey(K key, V value) => TryInsertKey(key, value, true);

    ///<summary>Inserts or overwrites the value of the null key. Returns <c>true</c> if the null key was new.</summary>
    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    public bool PutNullKey(V value)
    {
        _nullKeyValue = value;
        if (_hasNullKey)
            return false;
        _hasNullKey = true;
        return true;
    }

    ///<summary>Whether the map holds the null key.</summary>
    public bool HasNullKey
    {
        [MethodImpl(MethodImplOptions.AggressiveInlining)]
        get => _hasNullKey;
    }

    ///<summary>The value of the null key; default when the null key is absent.</summary>
    public V NullKeyValue
    {
        [MethodImpl(MethodImplOptions.AggressiveInlining)]
        get => _nullKeyValue;
    }

    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    private bool TryInsertKey(K kv, V value, bool overwrite)
    {
        if (_buckets == null)
            Initialize(DefaultCapacity);

        ref var bucket = ref GetBucket(Hash(kv));

        if (bucket != 0)
        {
            //Search first: updating an existing key never resizes.
            var i = (int)bucket - 1;
            if (!EqualityComparer<K>.Default.Equals(_entries![i], kv))
                i = _loSize <= i ? -1 : FindInChain(i, kv);
            if (0 <= i)
            {
                //Key found: Overwrite if allowed, otherwise return false (add failed).
                if (overwrite)
                    _vals![i] = value;
                return false; //Return false as no *new* entry was added (it was an update).
            }
        }

        if (_entries!.Length <= _loSize + _hiSize)
            GrowAndAdd(kv, value); //Rare: kept out of line so the hot insertion path stays small.
        else
            AddNew(ref bucket, kv, value);
        return true; //Item successfully added.
    }

    ///<summary>
    ///Places a key known to be absent into the bucket's chain: an empty bucket sends it to the Hi-Region,
    ///an occupied one to the Lo-Region as the new chain head. The table must have a free slot.
    ///</summary>
    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    private ref V AddNew(ref uint bucket, K key, V value)
    {
        var keys = _entries!;
        var head = bucket;
        int dstIndex;
        if (head == 0)
            dstIndex = keys.Length - 1 - _hiSize++; //Bucket is empty: Place new entry in the Hi-Region (non-colliding entries).
        else
        {
            //Collision: add new entry to the Lo-Region (colliding entries).
            if (_links!.Length == (dstIndex = _loSize++))
                Array.Resize(ref _links, Math.Max(16, Math.Min(keys.Length, _links.Length * 2)));
            _links[dstIndex] = head - 1; //New entry links to the previous head of the chain.
        }

        Unsafe.Add(ref MemoryMarshal.GetArrayDataReference(keys), dstIndex) = key;
        ref var v = ref Unsafe.Add(ref MemoryMarshal.GetArrayDataReference(_vals!), dstIndex);
        v = value;

        bucket = (uint)(dstIndex + 1);
        return ref v;
    }

    ///<summary>Cold path of insertion: the key is known to be new and the table is full.</summary>
    [MethodImpl(MethodImplOptions.NoInlining)]
    private ref V GrowAndAdd(K key, V value)
    {
        Resize(_entries!.Length * 2);
        return ref AddNew(ref GetBucket(Hash(key)), key, value); //buckets were reallocated: re-resolve
    }

    public void Add(K? key, V value)
    {
        if (!TryInsert(key, value, false))
            throw new ArgumentException("An item with the same key has already been added.");
    }

    void ICollection<KeyValuePair<K?, V>>.Add(KeyValuePair<K?, V> item) => Add(item.Key, item.Value);

    public void Clear()
    {
        if (Count == 0)
            return;
        _hasNullKey = false;
        _nullKeyValue = default!;
        if (_buckets != null)
            if ((_loSize + _hiSize) * 8 <= _buckets.Length) //a few entries in a large table: only their buckets ( a map received pack after pack, once large: 1.9 µs -> 20 ns )
            {
                var e = _entries!;
                for (var i = 0; i < _loSize; i++)
                    GetBucket(Hash(e[i])) = 0;
                for (var i = e.Length - _hiSize; i < e.Length; i++)
                    GetBucket(Hash(e[i])) = 0;
            }
            else
                Array.Clear(_buckets, 0, _buckets.Length);
        _loSize = 0;
        _hiSize = 0;
    }

    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    public bool ContainsKey(K? key)
    {
        if (!key.HasValue)
            return _hasNullKey;
        return FindIndex(key.Value) >= 0;
    }

    public bool ContainsValue(V value)
    {
        if (_hasNullKey && EqualityComparer<V>.Default.Equals(_nullKeyValue, value))
            return true;

        //Iterate lo-region
        for (var i = 0; i < _loSize; i++)
            if (EqualityComparer<V>.Default.Equals(_vals![i], value))
                return true;

        if (_hiSize == 0)
            return false;

        //Iterate hi-region
        for (var i = _vals!.Length - _hiSize; i < _vals.Length; i++)
            if (EqualityComparer<V>.Default.Equals(_vals[i], value))
                return true;

        return false;
    }

    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    public bool TryGetValue(K? key, [MaybeNullWhen(false)] out V value)
    {
        if (!key.HasValue)
        {
            if (_hasNullKey)
            {
                value = _nullKeyValue;
                return true;
            }
            value = default;
            return false;
        }
        var i = FindIndex(key.Value);
        if (i < 0)
        {
            value = default;
            return false;
        }
        value = _vals![i];
        return true;
    }
    ///<summary>
    ///Gets a reference to the value associated with the specified key, adding a provided default value if the key does not exist.
    ///</summary>
    ///<param name="key">The key to search for.</param>
    ///<param name="defaultValue">The value to add if the key does not exist.</param>
    ///<param name="exists">When this method returns, contains <c>true</c> if the key already existed; otherwise, <c>false</c>.</param>
    ///<returns>A reference to the value associated with the specified key.</returns>
    ///<remarks>
    ///Note: Do not add or remove items from the map while holding this reference, as triggering a resize of the internal arrays will invalidate it.
    ///</remarks>
    public ref V GetValueRefOrAddDefault(K? key, V defaultValue, out bool exists)
    {
        //1. Handle the null key specifically
        if (!key.HasValue)
        {
            if (_hasNullKey)
            {
                exists = true;
                return ref _nullKeyValue;
            }

            _hasNullKey = true;
            _nullKeyValue = defaultValue;
            exists = false;
            return ref _nullKeyValue;
        }

        var kv = key.Value;

        //2. Hash Table logic for non-null keys
        if (_buckets == null)
            Initialize(DefaultCapacity);

        ref var bucket = ref GetBucket(Hash(kv));

        if (bucket != 0)
        {
            //Collision detected (bucket is not empty). Traverse the chain.
            var i = (int)bucket - 1;
            if (!EqualityComparer<K>.Default.Equals(_entries![i], kv))
                i = _loSize <= i ? -1 : FindInChain(i, kv);
            if (0 <= i)
            {
                //Key found: Return a reference to the existing value.
                exists = true;
                return ref _vals![i];
            }
        }

        exists = false;
        //Initialize the new entry with the provided default value and return a reference to its value.
        if (_entries!.Length <= _loSize + _hiSize)
            return ref GrowAndAdd(kv, defaultValue);
        return ref AddNew(ref bucket, kv, defaultValue);
    }

    ///<summary>Rebuilds into local arrays, growing links on demand, then publishes the completed table.</summary>
    private int Resize(int newSize)
    {
        var oldKeys = _entries!;
        var oldVals = _vals!;
        var oldLoSize = _loSize;
        var oldEnd = oldKeys.Length;
        var oldHiStart = oldEnd - _hiSize;

        var size = GetPowerOfTwo(newSize);
        var bucketCount = BucketsFor(size);
        var buckets = new uint[bucketCount];
        var keys = new K[size];
        var vals = new V[size];
        var links = new uint[LinksFor(size)];
        var mask = (uint)(bucketCount - 1);

        ref var oldKeys0 = ref MemoryMarshal.GetArrayDataReference(oldKeys);
        ref var oldVals0 = ref MemoryMarshal.GetArrayDataReference(oldVals);
        ref var keys0 = ref MemoryMarshal.GetArrayDataReference(keys);
        ref var vals0 = ref MemoryMarshal.GetArrayDataReference(vals);
        ref var links0 = ref MemoryMarshal.GetArrayDataReference(links);
        ref var buckets0 = ref MemoryMarshal.GetArrayDataReference(buckets);
        var loSize = 0;
        var hi = size; //Hi-Region grows down from the end

        //the Lo-Region, then the Hi-Region
        for (int i = 0, end = oldLoSize;; i = oldHiStart, end = oldEnd)
        {
            for (; i < end; i++)
            {
                var key = Unsafe.Add(ref oldKeys0, i);
                ref var bucket = ref Unsafe.Add(ref buckets0, (nint)(Hash(key) & mask));
                var head = bucket;
                int dstIndex;

                if (head == 0)
                    dstIndex = --hi;
                else
                {
                    if (loSize == links.Length)
                    {
                        //Only with a pathological key set: Lo can hold up to every entry.
                        Array.Resize(ref links, Math.Min(size, links.Length * 2));
                        links0 = ref MemoryMarshal.GetArrayDataReference(links);
                    }
                    Unsafe.Add(ref links0, dstIndex = loSize++) = head - 1;
                }

                Unsafe.Add(ref keys0, dstIndex) = key;
                Unsafe.Add(ref vals0, dstIndex) = Unsafe.Add(ref oldVals0, i);
                bucket = (uint)(dstIndex + 1);
            }
            if (end == oldEnd)
                break;
        }

        _buckets = buckets;
        _entries = keys;
        _vals = vals;
        _links = links;
        _mask = mask;
        _loSize = loSize;
        _hiSize = size - hi;
        return size;
    }

    //Moves the entry at src to dst and updates the one pointer to src ( the bucket or a link ).
    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    private void Move(int src, int dst)
    {
        if (src == dst)
            return;

        //Skip the array-bounds checks: src < _entries.Length and the chain-walked
        //indices are bounded by the same. Same trick the BCL uses internally.
        ref var keys0 = ref MemoryMarshal.GetArrayDataReference(_entries!);
        ref var vals0 = ref MemoryMarshal.GetArrayDataReference(_vals!);
        ref var links0 = ref MemoryMarshal.GetArrayDataReference(_links!);
        var srcKey = Unsafe.Add(ref keys0, src);
        ref var srcBucket = ref GetBucket(Hash(srcKey));
        var index = (int)srcBucket - 1;

        if (index == src)
            srcBucket = (uint)(dst + 1);
        else
        {
            ref var link = ref Unsafe.Add(ref links0, index);
            while (link != src)
            {
                index = (int)link;
                link = ref Unsafe.Add(ref links0, index);
            }
            link = (uint)dst;
        }

        if (src < _loSize)
            Unsafe.Add(ref links0, dst) = Unsafe.Add(ref links0, src);

        Unsafe.Add(ref keys0, dst) = srcKey;
        Unsafe.Add(ref vals0, dst) = Unsafe.Add(ref vals0, src);
    }

    ///<summary>
    ///Removes <paramref name="key"/> if present. The common case inline - a key not there, or alone in its bucket ( an
    ///entry of hi ) - the chains in <see cref="RemoveChain"/> ( see PrimitiveKeyMap ).
    ///</summary>
    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    public bool Remove(K? key)
    {
        if (!key.HasValue)
        {
            if (!_hasNullKey)
                return false;
            _hasNullKey = false;
            _nullKeyValue = default!;
            return true;
        }

        var kv = key.Value;
        if (_loSize + _hiSize == 0)
            return false;

        ref var bucket = ref GetBucket(Hash(kv));
        var idx = (int)bucket - 1;
        if (idx < 0)
            return false;

        if (_loSize <= idx)
        {
            if (!EqualityComparer<K>.Default.Equals(Unsafe.Add(ref MemoryMarshal.GetArrayDataReference(_entries!), idx), kv))
                return false;
            Move(_entries!.Length - _hiSize, idx);
            _hiSize--;
            bucket = 0;
            return true;
        }
        return RemoveChain(ref bucket, idx, kv);
    }

    ///<summary><see cref="Remove"/> of a chain that begins in lo.</summary>
    [MethodImpl(MethodImplOptions.NoInlining)]
    private bool RemoveChain(ref uint bucket, int idx, K kv)
    {
        var loSize = _loSize;
        ref var keys0 = ref MemoryMarshal.GetArrayDataReference(_entries!);
        ref var links0 = ref MemoryMarshal.GetArrayDataReference(_links!);
        var prev = -1;
        var prevPrev = -1;

        for (var collisions = 0;
             !EqualityComparer<K>.Default.Equals(Unsafe.Add(ref keys0, idx), kv);
             prevPrev = prev,
                 idx = (int)Unsafe.Add(ref links0, prev = idx))
        {
            if (idx >= loSize)
                return false;
            if (++collisions > loSize)
                ThrowChainTooLong();
        }

        var lastLo = loSize - 1;
        if (idx < loSize)
        {
            //Standard removal: rewire (prev or bucket) → next; compact lo by swap-with-last.
            //Single read of the matched entry's link; both branches consume `next`.
            var next = Unsafe.Add(ref links0, idx);
            if (prev < 0)
                bucket = next + 1;
            else
                Unsafe.Add(ref links0, prev) = next;
            Move(lastLo, idx);
        }
        else
        {
            //Found at hi-terminator with chain length ≥ 2. Migrate prev (lo) into the hi slot
            //so the chain still terminates in hi; prev's lo slot becomes the hole.
            ref var vals0 = ref MemoryMarshal.GetArrayDataReference(_vals!);
            Unsafe.Add(ref keys0, idx) = Unsafe.Add(ref keys0, prev);
            Unsafe.Add(ref vals0, idx) = Unsafe.Add(ref vals0, prev);
            if (prevPrev < 0)
                bucket = (uint)(idx + 1);
            else
                Unsafe.Add(ref links0, prevPrev) = (uint)idx;
            Move(lastLo, prev);
        }

        _loSize = lastLo;
        return true;
    }

    bool ICollection<KeyValuePair<K?, V>>.Remove(KeyValuePair<K?, V> item) => TryGetValue(item.Key, out var value) && EqualityComparer<V>.Default.Equals(value, item.Value) && Remove(item.Key);

    bool ICollection<KeyValuePair<K?, V>>.Contains(KeyValuePair<K?, V> item) { return TryGetValue(item.Key, out var value) && EqualityComparer<V>.Default.Equals(value, item.Value); }

    void ICollection<KeyValuePair<K?, V>>.CopyTo(KeyValuePair<K?, V>[] array, int index)
    {
        ArgumentNullException.ThrowIfNull(array);
        ArgumentOutOfRangeException.ThrowIfGreaterThanOrEqual((uint)index, (uint)array.Length);
        if (array.Length - index < Count)
            throw new ArgumentException("Destination array is not long enough.");

        if (_hasNullKey)
            array[index++] = new KeyValuePair < K ?, V > (null, _nullKeyValue);

        //Copy lo-region
        for (var i = 0; i < _loSize; i++)
            array[index++] = new KeyValuePair < K ?, V > (_entries![i], _vals![i]);

        if (_hiSize == 0)
            return;
        //Copy hi-region
        for (var i = _entries!.Length - _hiSize; i < _entries.Length; i++)
            array[index++] = new KeyValuePair < K ?, V > (_entries[i], _vals![i]);
    }

    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    private static int GetPowerOfTwo(int capacity) => capacity <= DefaultCapacity ? DefaultCapacity : (int)BitOperations.RoundUpToPowerOf2((uint)capacity);

