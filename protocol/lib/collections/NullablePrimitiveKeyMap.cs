    ///<summary>
    ///Internal entry-finder for non-null keys. Returns a ref to the entry on hit, or a null ref on
    ///miss (use <see cref="Unsafe.IsNullRef{T}"/>). Marked AggressiveInlining so callers
    ///(TryGetValue, ContainsKey, indexer) inline the body. Null-key handling is short-circuited at
    ///each public method's entry — this helper handles only the value-key path.
    ///</summary>
    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    private ref Entry FindEntry(K key)
    {
        if (_loSize + _hiSize == 0)
            return ref Unsafe.NullRef<Entry>();

        var i = (int)GetBucket((uint)key.GetHashCode()) - 1;
        if (i == -1)
            return ref Unsafe.NullRef<Entry>();

        ref var entry = ref _entries![i];
        for (var collisions = 0;
             !EqualityComparer<K>.Default.Equals(entry.key, key);
             entry = ref _entries![i = (int)_links![i]])
        {
            if (_loSize <= i)
                return ref Unsafe.NullRef<Entry>();
            if (_loSize < ++collisions)
                throw new InvalidOperationException("Hash collision chain is unexpectedly long. Possible data corruption.");
        }
        return ref entry;
    }

