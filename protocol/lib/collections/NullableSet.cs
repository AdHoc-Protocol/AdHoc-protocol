    ///<summary>
    ///Determines whether the set contains a specific element.
    ///</summary>
    ///<param name="item">The element to locate in the set.</param>
    ///<returns><see langword="true"/> if the set contains the specified element; otherwise, <see langword="false"/>.</returns>
    public bool Contains(K? item)
    {
        if (item == null)
            return _hasNullKey;
        if (_loSize + _hiSize == 0)
            return false;

        var hashCode = GetHashCode(item);
        var i = (int)GetBucket((uint)hashCode) - 1;
        if (i == -1)
            return false;

        ref var entriesRef = ref MemoryMarshal.GetArrayDataReference(_entries!);
        ref var linksRef = ref MemoryMarshal.GetArrayDataReference(_links!);
        var loSize = _loSize;

        for (var collisions = 0;;)
        {
            ref var entry = ref Unsafe.Add(ref entriesRef, i);
            if (entry.hash == hashCode && _comparer.Equals(entry.key, item))
                return true;

            if (loSize <= i)
                return false;

            i = (int)Unsafe.Add(ref linksRef, i);
            if (loSize < ++collisions)
                throw new InvalidOperationException("Hash collision chain is unexpectedly long. Possible data corruption.");
        }
    }

    private int Resize(int newSize)
    {
        _version++;
        var oldEntries = _entries;
        var oldLoSize = _loSize;
        var oldHiSize = _hiSize;
        var oldEnd = oldEntries!.Length;
        var oldHiStart = oldEnd - oldHiSize;

        var totalEntries = oldLoSize + oldHiSize;
        Initialize(newSize, totalEntries);

        ref var oldEntries0 = ref MemoryMarshal.GetArrayDataReference(oldEntries);
        ref var entries0 = ref MemoryMarshal.GetArrayDataReference(_entries!);
        ref var links0 = ref MemoryMarshal.GetArrayDataReference(_links!);
        ref var buckets0 = ref MemoryMarshal.GetArrayDataReference(_buckets!);
        var mask = _mask;
        var newEnd = _entries!.Length;
        var loSize = 0;
        var hiSize = 0;

        for (var i = 0; i < oldLoSize; i++)
        {
            ref var entry = ref Unsafe.Add(ref oldEntries0, i);
            ref var bucket = ref Unsafe.Add(ref buckets0, (nint)((uint)entry.hash & mask));
            var prev = (int)bucket - 1;
            int dstIndex;

            if (prev == -1)
                dstIndex = newEnd - 1 - hiSize++;
            else
            {
                dstIndex = loSize++;
                Unsafe.Add(ref links0, dstIndex) = (uint)prev;
            }

            Unsafe.Add(ref entries0, dstIndex) = entry;
            bucket = (uint)(dstIndex + 1);
        }

        for (var i = oldHiStart; i < oldEnd; i++)
        {
            ref var entry = ref Unsafe.Add(ref oldEntries0, i);
            ref var bucket = ref Unsafe.Add(ref buckets0, (nint)((uint)entry.hash & mask));
            var prev = (int)bucket - 1;
            int dstIndex;

            if (prev == -1)
                dstIndex = newEnd - 1 - hiSize++;
            else
            {
                dstIndex = loSize++;
                Unsafe.Add(ref links0, dstIndex) = (uint)prev;
            }

            Unsafe.Add(ref entries0, dstIndex) = entry;
            bucket = (uint)(dstIndex + 1);
        }

        _loSize = loSize;
        _hiSize = hiSize;
        return newSize;
    }
    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    private void Move(int src, int dst, ref Entry dstEntry)
    {
        //Move is private and called only from Remove (three sites). Centralizing the
        //version bump here removes the duplicated `_version++` from each Remove branch
        //and still bumps once per Remove (including the src == dst early-return case).
        _version++;
        if (src == dst)
            return;

        //Skip the array-bounds checks: src < _entries.Length and the chain-walked
        //indices are bounded by the same. Same trick the BCL uses internally.
        ref var entries0 = ref MemoryMarshal.GetArrayDataReference(_entries!);
        ref var links0 = ref MemoryMarshal.GetArrayDataReference(_links!);
        ref var srcEntry = ref Unsafe.Add(ref entries0, src);
        ref var srcBucket = ref GetBucket((uint)srcEntry.hash);
        var index = (int)srcBucket - 1;

        if (index == src)
            srcBucket = (uint)(dst + 1);
        else
        {
            ref var link = ref Unsafe.Add(ref links0, index);
            while (link != src)
            {
                index = (int)link;
                link = ref Unsafe.Add(ref links0, index);
            }
            link = (uint)dst;
        }

        if (src < _loSize)
            Unsafe.Add(ref links0, dst) = Unsafe.Add(ref links0, src);

        dstEntry = srcEntry;
    }

    ///<summary>
    ///Removes the specified element from the set.
    ///</summary>
    ///<param name="key">The element to remove.</param>
    ///<returns><see langword="true"/> if the element is successfully found and removed; otherwise, <see langword="false"/>.</returns>
    public bool Remove(K? key)
    {
        if (key == null)
        {
            if (!_hasNullKey)
                return false;
            _hasNullKey = false;
            _version++;
            return true;
        }

        if (_loSize + _hiSize == 0)
            return false;

        var hashCode = GetHashCode(key);
        ref var bucket = ref GetBucket((uint)hashCode);
        var idx = (int)bucket - 1;
        if (idx < 0)
            return false;

        var loSize = _loSize;
        ref var entries0 = ref MemoryMarshal.GetArrayDataReference(_entries!);

        ref var e = ref Unsafe.Add(ref entries0, idx);
        if (loSize <= idx)
        {
            if (e.hash != hashCode || !_comparer.Equals(e.key, key))
                return false;
            Move(_entries!.Length - _hiSize, idx, ref e);
            _hiSize--;
            bucket = 0;
            return true;
        }

        ref var links0 = ref MemoryMarshal.GetArrayDataReference(_links!);
        var prev = -1;
        var prevPrev = -1;

        for (var collisions = 0;
             e.hash != hashCode || !_comparer.Equals(e.key, key);
             prevPrev = prev,
                 e = ref Unsafe.Add(ref entries0, idx = (int)Unsafe.Add(ref links0, prev = idx)))
        {
            if (idx >= loSize)
                return false;
            if (++collisions > loSize)
                throw new InvalidOperationException("Hash collision chain is unexpectedly long. Possible data corruption.");
        }

        var lastLo = loSize - 1;
        if (idx < loSize)
        {
            //Standard removal: rewire (prev or bucket) → next; compact lo by swap-with-last.
            //Single read of the matched entry's link; both branches consume `next`.
            var next = Unsafe.Add(ref links0, idx);
            if (prev < 0)
                bucket = next + 1;
            else
                Unsafe.Add(ref links0, prev) = next;
            Move(lastLo, idx, ref e);
        }
        else
        {
            //Found at hi-terminator with chain length ≥ 2. Migrate prev (lo) into the hi slot
            //so the chain still terminates in hi; prev's lo slot becomes the hole.
            ref var prevEntry = ref Unsafe.Add(ref entries0, prev);
            e = prevEntry;
            if (prevPrev < 0)
                bucket = (uint)(idx + 1);
            else
                Unsafe.Add(ref links0, prevPrev) = (uint)idx;
            Move(lastLo, prev, ref prevEntry);
        }

        _loSize = lastLo;
        return true;
    }

    public void CopyTo(K?[] dst, int dstIndex)
    {
        ArgumentNullException.ThrowIfNull(dst);
        ArgumentOutOfRangeException.ThrowIfGreaterThanOrEqual((uint)dstIndex, (uint)dst.Length);
        if (dst.Length - dstIndex < Count)
            throw new ArgumentException("Destination array is not long enough.");

        if (_hasNullKey)
            dst[dstIndex++] = null;

        if (_entries == null)
            return;

        ref var entriesRef = ref MemoryMarshal.GetArrayDataReference(_entries);
        ref var dstRef = ref MemoryMarshal.GetArrayDataReference(dst);

        var loSize = _loSize;
        for (var i = 0; i < loSize; i++)
            Unsafe.Add(ref dstRef, dstIndex++) = Unsafe.Add(ref entriesRef, i).key;
        var hiSize = _hiSize;
        if (hiSize == 0)
            return;
        var len = _entries.Length;
        for (var i = len - hiSize; i < len; i++)
            Unsafe.Add(ref dstRef, dstIndex++) = Unsafe.Add(ref entriesRef, i).key;
    }

    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    private static int GetPowerOfTwo(int capacity) => capacity <= DefaultCapacity ? DefaultCapacity : (int)BitOperations.RoundUpToPowerOf2((uint)capacity);

