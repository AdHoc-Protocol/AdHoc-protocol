    ///<summary>
    ///Adds an element to the set.
    ///</summary>
    ///<param name="item">The element to add to the set.</param>
    ///<returns><see langword="true"/> if the element is added to the set; <see langword="false"/> if the element is already in the set.</returns>
    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    public bool Add(K? item)
    {
        if (item == null)
        {
            if (_hasNullKey)
                return false;
            _hasNullKey = true;
            _version++;
            return true;
        }

        if (_buckets == null)
            Initialize(DefaultCapacity);

        var entries = _entries!;
        if (entries.Length <= _loSize + _hiSize)
        {
            Resize(entries.Length * 2);
            entries = _entries!;
        }

        var hashCode = GetHashCode(item);
        ref var bucket = ref GetBucket((uint)hashCode);
        var index = (int)bucket - 1;

        ref var entriesRef = ref MemoryMarshal.GetArrayDataReference(entries);

        if (index != -1)
        {
            ref var linksRef = ref MemoryMarshal.GetArrayDataReference(_links!);
            var loSize = _loSize;
            for (int i = index, collisions = 0;;)
            {
                ref var entry = ref Unsafe.Add(ref entriesRef, i);
                if (entry.hash == hashCode && _comparer.Equals(entry.key, item))
                    return false; //Already exists

                if (loSize <= i)
                    break;

                i = (int)Unsafe.Add(ref linksRef, i);
                if (loSize + 1 < collisions++)
                    throw new InvalidOperationException("Concurrent operations not supported.");
            }
        }

        int dstIndex;
        if (index == -1)
            dstIndex = entries.Length - 1 - _hiSize++; //Bucket is empty: place new entry in hi-region
        else                                           //Collision: place new entry in lo-region
        {
            if (_links!.Length == (dstIndex = _loSize++))
                Array.Resize(ref _links, Math.Max(16, Math.Min(_buckets!.Length, _links.Length * 2)));
            //Re-fetch links ref (Array.Resize may have allocated a new array).
            Unsafe.Add(ref MemoryMarshal.GetArrayDataReference(_links!), dstIndex) = (uint)index;
        }

        ref var newEntry = ref Unsafe.Add(ref entriesRef, dstIndex);
        newEntry.hash = hashCode;
        newEntry.key = item;

        bucket = (uint)(dstIndex + 1);
        _version++;
        return true;
    }

