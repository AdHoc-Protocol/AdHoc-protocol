///<summary>
///A highly optimized dictionary for nullable 2-byte unmanaged keys (e.g., ushort, char).
///It uses a bitset and a value array ("flat") strategy for dense data and a custom hash table for sparse data.
///This class is not thread-safe.
///
///<para><b>Benchmark vs <c>Dictionary&lt;ushort?,int&gt;</c></b> (N = 50 000 unique ushort keys → flat mode,
///.NET 9, Release):</para>
///<code>
///Insert         Search           Get        Iterate         Delete
///NullableTwoBytesKeyMap&lt;ushort?,int&gt;   57 835 944  1 180 836 707   821 018 062  385 547 477    41 539 082   ops/sec
///Dictionary                                  0.38           0.03          0.05         2.17          0.53   x
///</code>
///<para><b>Memory profile (Insert, 50 000 unique random ushort keys (transitions to flat strategy)):</b>
///<list type="bullet">
///<item><c>NullableTwoBytesKeyMap</c> allocates <b>19.85 B/op</b> (Insert, 50 000 unique random ushort keys (transitions to flat strategy) of 50 000 records)</item>
///<item><c>Dictionary</c> allocates <b>58.18 B/op</b></item>
///<item><c>NullableTwoBytesKeyMap</c> saves <b>~38 330 B per 1 000 records</b> vs Dictionary</item>
///</list>
///</para>
///<para>
///Ratio &gt; 1 ⇒ <c>Dictionary</c> faster, &lt; 1 ⇒ NullableTwoBytesKeyMap faster. In flat mode this
///class is <b>33× faster on Search</b>, 22× on TryGetValue, 2.6× on Insert, 1.9× on Delete.
///Dictionary wins Iterate (2.17×) due to its contiguous entry layout vs flat-bitset scan.
///</para>
///<para>See <c>Tests/Benchmarks/NullableTwoBytesBenchmark.cs</c> for the full scenarios and an HTML report.</para>
///<para>Historical benchmark figures predate hash mixing and two buckets per entry slot.
///Re-run the benchmarks for the current layout; see <c>BucketsFor</c> and <c>LinksFor</c> for tuning.</para>
///</summary>
public class NullableTwoBytesKeyMap<K, V> : IDictionary<K?, V>, IReadOnlyDictionary<K?, V>
