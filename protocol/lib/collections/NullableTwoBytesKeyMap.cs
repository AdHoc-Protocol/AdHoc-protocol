    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    private bool TryInsertKey(K kv, V value, bool overwrite)
    {
        if (IsFlatStrategy)
        {
            var k = toUshort(kv);
            if ((_nulls![k >> 6] & 1UL << k) != 0) //Key exists
            {
                if (!overwrite)
                    return false;
                _flatValues![k] = value;
                return false;
            }

            _nulls[k >> 6] |= 1UL << k;
            _flatValues![k] = value;
            _flatCount++;
            return true;
        }

        if (_buckets == null)
            Initialize(DefaultCapacity);

        ref var bucket = ref GetBucket(toUshort(kv));
        if (bucket != 0)
        {
            var i = bucket - 1;
            if (toUshort(_entries![i]) != toUshort(kv))
                i = _loSize <= i ? -1 : FindInChain(i, toUshort(kv));
            if (0 <= i)
            {
                if (overwrite)
                    _vals![i] = value;
                return false;
            }
        }

        if (_entries!.Length <= _loSize + _hiSize)
            GrowAndAdd(kv, value);
        else
            AddNew(ref bucket, kv, value);
        return true;
    }

    //The key is known to be absent and the table has a free entry slot.
    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    private ref V AddNew(ref ushort bucket, K key, V value)
    {
        var keys = _entries!;
        var head = bucket;
        int dstIndex;
        if (head == 0)
            dstIndex = keys.Length - 1 - _hiSize++;
        else
        {
            if (_links!.Length == (dstIndex = _loSize++))
                Array.Resize(ref _links, Math.Max(16, Math.Min(keys.Length, _links.Length * 2)));
            _links[dstIndex] = (ushort)(head - 1);
        }
        Unsafe.Add(ref MemoryMarshal.GetArrayDataReference(keys), dstIndex) = key;
        ref var v = ref Unsafe.Add(ref MemoryMarshal.GetArrayDataReference(_vals!), dstIndex);
        v = value;
        bucket = (ushort)(dstIndex + 1);
        return ref v;
    }

    [MethodImpl(MethodImplOptions.NoInlining)]
    private ref V GrowAndAdd(K key, V value)
    {
        var newSize = _entries!.Length * 2;
        if (newSize > flatStrategyThreshold && _entries.Length < flatStrategyThreshold)
            newSize = flatStrategyThreshold;
        Resize(newSize);
        if (IsFlatStrategy)
        {
            return ref GetValueRefOrAddDefault(key, value, out _);
        }
        return ref AddNew(ref GetBucket(toUshort(key)), key, value);
    }

    public void Clear()
    {
        if (Count == 0)
            return;

        _hasNullKey = false;
        _nullKeyValue = default!;

        if (IsFlatStrategy)
        {
            _flatCount = 0;
            Array.Clear(_nulls!);
            if (RuntimeHelpers.IsReferenceOrContainsReferences<V>())
                Array.Clear(_flatValues!);
        }
        else
        {
            if (_buckets != null)
                Array.Clear(_buckets);
            if (RuntimeHelpers.IsReferenceOrContainsReferences<V>() && _loSize + _hiSize > 0)
                Array.Clear(_vals!);
            _loSize = 0;
            _hiSize = 0;
        }
    }

    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    public bool ContainsKey(K? key)
    {
        if (!key.HasValue)
            return _hasNullKey;
        var kv = key.Value;
        if (IsFlatStrategy)
        {
            var k = toUshort(kv);
            return (_nulls![k >> 6] & 1UL << k) != 0;
        }
        return FindIndex(toUshort(kv)) >= 0;
    }

    public bool ContainsValue(V value)
    {
        if (_hasNullKey && EqualityComparer<V>.Default.Equals(_nullKeyValue, value))
            return true;

        if (IsFlatStrategy)
        {
            var comparer = EqualityComparer<V>.Default;
            for (var i = 0; i < NULLS_SIZE; i++)
            {
                var bits = _nulls![i];
                if (bits == 0)
                    continue; //Skip empty 64-bit segments

                var baseIndex = i << 6; //i * 64
                while (bits != 0)
                {
                    var bitPos = BitOperations.TrailingZeroCount(bits);
                    var index = baseIndex + bitPos;
                    if (comparer.Equals(_flatValues![index], value))
                        return true;
                    bits &= bits - 1; //Clear the least significant set bit
                }
            }

            return false;
        }

        //Iterate lo-region
        for (var i = 0; i < _loSize; i++)
            if (EqualityComparer<V>.Default.Equals(_vals![i], value))
                return true;
        if (_hiSize == 0)
            return false;

        //Iterate hi-region
        for (var i = _vals!.Length - _hiSize; i < _vals.Length; i++)
            if (EqualityComparer<V>.Default.Equals(_vals[i], value))
                return true;

        return false;
    }

    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    public bool TryGetValue(K? key, [MaybeNullWhen(false)] out V value)
    {
        if (!key.HasValue)
        {
            if (_hasNullKey)
            {
                value = _nullKeyValue;
                return true;
            }
            value = default;
            return false;
        }
        var kv = key.Value;
        if (IsFlatStrategy)
        {
            var k = toUshort(kv);
            if ((_nulls![k >> 6] & 1UL << k) != 0)
            {
                value = _flatValues![k];
                return true;
            }
            value = default;
            return false;
        }
        var i = FindIndex(toUshort(kv));
        if (i < 0)
        {
            value = default;
            return false;
        }
        value = _vals![i];
        return true;
    }

    ///<summary>
    ///Gets a reference to the value associated with the specified key, adding a provided default value if the key does not exist.
    ///</summary>
    ///<param name="key">The key to search for.</param>
    ///<param name="defaultValue">The value to add if the key does not exist.</param>
    ///<param name="exists">When this method returns, contains <c>true</c> if the key already existed; otherwise, <c>false</c>.</param>
    ///<returns>A reference to the value associated with the specified key.</returns>
    ///<remarks>
    ///Note: Do not add or remove items from the map while holding this reference, as triggering a resize of the internal arrays will invalidate it.
    ///</remarks>
    public ref V GetValueRefOrAddDefault(K? key, V defaultValue, out bool exists)
    {
        //1. Handle the null key specifically
        if (!key.HasValue)
        {
            if (_hasNullKey)
            {
                exists = true;
                return ref _nullKeyValue;
            }

            _hasNullKey = true;
            _nullKeyValue = defaultValue;
            exists = false;
            return ref _nullKeyValue;
        }

        var kv = key.Value;

        //Flat Strategy Logic
        if (IsFlatStrategy)
        {
            var k = toUshort(kv);
            if ((_nulls![k >> 6] & 1UL << k) != 0) //Key exists
            {
                exists = true;
                return ref _flatValues![k];
            }

            //Key does not exist: Add it
            _nulls[k >> 6] |= 1UL << k;
            _flatValues![k] = defaultValue;
            _flatCount++;
            exists = false;
            return ref _flatValues[k];
        }

        //Hash Strategy Logic
        if (_buckets == null)
            Initialize(DefaultCapacity);

        ref var bucket = ref GetBucket(toUshort(kv));
        if (bucket != 0)
        {
            var i = bucket - 1;
            if (toUshort(_entries![i]) != toUshort(kv))
                i = _loSize <= i ? -1 : FindInChain(i, toUshort(kv));
            if (0 <= i)
            {
                exists = true;
                return ref _vals![i];
            }
        }
        exists = false;
        if (_entries!.Length <= _loSize + _hiSize)
            return ref GrowAndAdd(kv, defaultValue);
        return ref AddNew(ref bucket, kv, defaultValue);
    }

    public void CopyTo(KeyValuePair<K?, V>[] dst, int dstIndex)
