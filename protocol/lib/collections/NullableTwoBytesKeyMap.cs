    ///<summary>
    ///Internal finder for hash (non-flat) mode with non-null keys: the index of the key, or -1. AggressiveInlining; flat
    ///mode and null-key short-circuit happen at each public method's entry. The bucket mask comes from the bucket array
    ///read and key / link reads keep their bounds checks: a lookup racing a resize stays in bounds. The chain past its
    ///head is <see cref="FindInChain"/>: a thrower called in the loop made the JIT save 7 registers at every lookup.
    ///</summary>
    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    private int FindIndex(ushort kUshort)
    {
        var buckets = _buckets;
        if (buckets == null)
            return -1;

        var i = (int)Unsafe.Add(ref MemoryMarshal.GetArrayDataReference(buckets), (nint)(MixHash(kUshort) & (uint)(buckets.Length - 1))) - 1;
        if (i < 0)
            return -1;
        if (toUshort(_entries![i]) == kUshort)
            return i;
        return _loSize <= i ? -1 : FindInChain(i, kUshort);
    }

    ///<summary>The index of the key in the chain past its lo entry <paramref name="i"/>, or -1.</summary>
    [MethodImpl(MethodImplOptions.NoInlining)]
    private int FindInChain(int i, ushort kUshort)
    {
        var keys = _entries!;
        var links = _links!;
        var loSize = _loSize;
        for (var budget = loSize;;)
        {
            i = links[i];
            if (toUshort(keys[i]) == kUshort)
                return i;
            if (loSize <= i)
                return -1;
            if (--budget < 0)
                ThrowChainTooLong();
        }
    }

