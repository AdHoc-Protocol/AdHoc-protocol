    ///<summary>
    ///High-throughput iterator over the map.
    ///<para><b>Null-key handling.</b> When <c>_hasNullKey</c> is set, the (null, value) pair is yielded
    ///first via a small state machine: <c>NotStarted → NullEmitted → InRegular → Finished</c>.
    ///The state lives in <c>_index</c> alone (-1 = pending null, -2 = finished/initial-no-null).</para>
    ///<para><b>Flat-mode design (cached bitset word).</b> The previous implementation called
    ///<c>next1(_index)</c> on every <see cref="MoveNext"/>, which re-computed the word index
    ///<c>(bit+1) &gt;&gt; 6</c>, re-loaded <c>_nulls[index]</c> from the heap, and re-built the mask
    ///<c>~0UL &lt;&lt; (i &amp; 63)</c>. None of that survives across <see cref="MoveNext"/> calls.
    ///The new design keeps the current word and "bits not yet consumed" in the enumerator
    ///struct: each call is just <c>TrailingZeroCount</c> on a register, then <c>bits &amp;= bits - 1</c>
    ///to clear the lowest set bit. The heap is touched once per word (every ~64 items, on
    ///average) instead of once per item.</para>
    ///<para><b>Hash-mode design.</b> Lo-region and hi-region snapshotted at construction so the
    ///instance fields are never re-read during the walk. <c>Unsafe.Add</c> +
    ///<c>MemoryMarshal.GetArrayDataReference</c> skips the JIT-emitted array-bounds check on
    ///<c>_entries</c>; the lo/hi boundary fold collapses the "have I finished" branch to a single
    ///<c>i &gt;= _hiEnd</c> compare.</para>
    ///<para><b>Concurrent-modification semantics.</b> Matches BCL Dictionary: the version check
    ///lives in <see cref="MoveNext"/>; <see cref="Current"/> is a bare field read.</para>
    ///</summary>
    public struct Enumerator : IEnumerator<KeyValuePair<K?, V>>
    {
        private readonly NullableTwoBytesKeyMap<K, V> _map;
        private readonly int _version;

        //Null-key snapshot.
        private readonly bool _hasNullKey;
        private readonly V _nullKeyValue;

        //Hash-mode snapshot (null in flat mode).
        private readonly Entry[]? _entries;
        private readonly int _loEnd;
        private readonly int _hiStart;
        private readonly int _hiEnd;

        //Flat-mode snapshot (null in hash mode).
        private readonly ulong[]? _nulls;
        private readonly V[]? _flatValues;

        //Iteration state.
        private int _wordIdx;         //flat mode: current word index in _nulls
        private ulong _remainingBits; //flat mode: bits not yet consumed in the current word
        private int _index;           //-1 = null key pending, -2 = finished/no-null-yet, else current bit/index
        private KeyValuePair<K?, V> _current;

        internal Enumerator(NullableTwoBytesKeyMap<K, V> map)
        {
            _map = map;
            _version = map._version;
            _hasNullKey = map._hasNullKey;
            _nullKeyValue = map._nullKeyValue;
            _current = default;
            //-1 = null-key pending (yielded next), -2 = no null key (start in regular)
            _index = _hasNullKey ? -1 : -2;
            _wordIdx = -1;
            _remainingBits = 0;

            if (map.IsFlatStrategy)
            {
                _entries = null;
                _loEnd = 0;
                _hiStart = 0;
                _hiEnd = 0;
                _nulls = map._nulls;
                _flatValues = map._flatValues;
            }
            else
            {
                _entries = map._entries;
                _loEnd = map._loSize;
                _hiEnd = _entries?.Length ?? 0;
                _hiStart = _hiEnd - map._hiSize;
                _nulls = null;
                _flatValues = null;
            }
        }

        [MethodImpl(MethodImplOptions.AggressiveInlining)]
        public bool MoveNext()
        {
            if (_version != _map._version)
                throw new InvalidOperationException("Collection was modified during enumeration.");

            //Yield the null key first (when present).
            if (_index == -1)
            {
                _current = new KeyValuePair < K ?, V > (null, _nullKeyValue);
                _index = -2; //transition: null emitted, regular iteration begins next call
                return true;
            }

            if (_nulls != null)
                return MoveNextFlat();

            //Hash mode: walk lo-region [0..loEnd), then hi-region [hiStart..hiEnd).
            if (_entries == null)
                return false;
            //_index == -2 on first regular call after null (or initial when no null);
            //map -2 to -1 so the +1 below lands at 0.
            var i = (_index == -2 ? -1 : _index) + 1;
            if (i == _loEnd)
                i = _hiStart;
            if (i >= _hiEnd)
                return false;

            ref var entry = ref Unsafe.Add(ref MemoryMarshal.GetArrayDataReference(_entries), i);
            _current = new KeyValuePair < K ?, V > (entry.key, entry.value);
            _index = i;
            return true;
        }

        [MethodImpl(MethodImplOptions.AggressiveInlining)]
        private bool MoveNextFlat()
        {
            var bits = _remainingBits;
            var wordIdx = _wordIdx;

            //Drain remaining set bits in the current word; advance to the next non-zero word
            //only when the current one is exhausted. The heap is touched once per word.
            if (bits == 0)
            {
                ref var nulls0 = ref MemoryMarshal.GetArrayDataReference(_nulls!);
                do
                {
                    if (++wordIdx >= NULLS_SIZE)
                        return false;
                    bits = Unsafe.Add(ref nulls0, wordIdx);
                } while (bits == 0);
            }

            var trailing = BitOperations.TrailingZeroCount(bits);
            var bitPos = (wordIdx << 6) + trailing;
            var key = Unsafe.As<int, K>(ref bitPos);
            var value = Unsafe.Add(ref MemoryMarshal.GetArrayDataReference(_flatValues!), bitPos);
            _current = new KeyValuePair < K ?, V > (key, value);
            _remainingBits = bits & (bits - 1); //clear lowest set bit
            _wordIdx = wordIdx;
            _index = bitPos;
            return true;
        }

        //BCL Dictionary semantics: bare field read, no per-access checks.
        //Concurrent-modification detection lives in MoveNext.
        public KeyValuePair<K?, V> Current
        {
            [MethodImpl(MethodImplOptions.AggressiveInlining)]
            get => _current;
        }

        object? IEnumerator.Current => _current;

        public void Reset()
        {
            if (_version != _map._version)
                throw new InvalidOperationException("Collection was modified during enumeration.");
            _index = _hasNullKey ? -1 : -2;
            _wordIdx = -1;
            _remainingBits = 0;
            _current = default;
        }

        public void Dispose() {}
    }

    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    private static ushort toUshort(K key) => Unsafe.As<K, ushort>(ref key);
#region Flat Strategy Helpers
    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    protected int next1(int bit) => next1(bit, _nulls!);

    protected static int next1(int bit, ulong[] nulls)
    {
        if (0xFFFF <= bit)
            return -1;
        var i = ++bit;
        var index = i >> 6;
        if (index >= nulls.Length)
            return -1;
        var value = nulls[index] & ~0UL << (i & 63);

        while (value == 0)
            if (++index == NULLS_SIZE)
                return -1;
            else
                value = nulls[index];

        return (index << 6) + BitOperations.TrailingZeroCount(value);
    }
