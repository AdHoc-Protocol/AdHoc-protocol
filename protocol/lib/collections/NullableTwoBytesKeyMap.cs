    }

    private void AddRange(IEnumerable<KeyValuePair<K?, V>> enumerable)
    {
        foreach (var pair in enumerable)
            Add(pair.Key, pair.Value);
    }

    public int Count => (IsFlatStrategy ? _flatCount : _loSize + _hiSize) + (_hasNullKey ? 1 : 0);

    public V this[K? key]
    {
        [MethodImpl(MethodImplOptions.AggressiveInlining)]
        get
        {
            if (!key.HasValue)
            {
                if (_hasNullKey)
                    return _nullKeyValue;
                throw new KeyNotFoundException();
            }
            var kv = key.Value;
            //Flat strategy fast path.
            if (IsFlatStrategy)
            {
                var k = toUshort(kv);
                if ((_nulls![k >> 6] & 1UL << k) != 0)
                    return _flatValues![k];
                throw new KeyNotFoundException();
            }
            ref var entry = ref FindEntry(toUshort(kv));
            if (Unsafe.IsNullRef(ref entry))
                throw new KeyNotFoundException();
            return entry.value;
        }
        [MethodImpl(MethodImplOptions.AggressiveInlining)]
        set => TryInsert(key, value, true);
    }

    public void Add(K? key, V value)
    {
        if (!TryInsert(key, value, false))
            throw new ArgumentException("An item with the same key has already been added.");
    }

    void ICollection<KeyValuePair<K?, V>>.Add(KeyValuePair<K?, V> item) => TryInsert(item.Key, item.Value, true);

    ///<summary>Native TryAdd — avoids the BCL IDictionary extension's double dispatch.</summary>
    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    public bool TryAdd(K? key, V value) => TryInsert(key, value, false);

    ///<summary>
    ///Internal entry-finder for hash (non-flat) mode with non-null keys. Returns a ref to the entry
    ///on hit, or a null ref on miss. AggressiveInlining; flat mode and null-key short-circuit
    ///happen at each public method's entry, this helper handles only the chain-walk path.
    ///</summary>
    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    private ref Entry FindEntry(ushort kUshort)
    {
        if (_loSize + _hiSize == 0)
            return ref Unsafe.NullRef<Entry>();

        var i = GetBucket(kUshort) - 1;
        if (i == -1)
            return ref Unsafe.NullRef<Entry>();

        ref var entry = ref _entries![i];
        for (var collisions = 0;
             toUshort(entry.key) != kUshort;
             entry = ref _entries![i = _links![i]])
        {
            if (_loSize <= i)
                return ref Unsafe.NullRef<Entry>();
            if (_loSize < ++collisions)
                throw new InvalidOperationException("Hash collision chain is unexpectedly long. Possible data corruption.");
        }
        return ref entry;
    }

    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    private bool TryInsert(K? key, V value, bool overwrite)
    {
        if (!key.HasValue)
        {
            if (_hasNullKey)
            {
                if (!overwrite)
                    return false;
                _nullKeyValue = value;
                return false;
            }

            _hasNullKey = true;
            _nullKeyValue = value;
            _version++;
            return true;
        }

        while (true)
        {
            var kv = key.Value;

            if (IsFlatStrategy)
            {
                var k = toUshort(kv);
                if ((_nulls![k >> 6] & 1UL << k) != 0) //Key exists
                {
                    if (!overwrite)
                        return false;
                    _flatValues![k] = value;
                    return false;
                }

                _nulls[k >> 6] |= 1UL << k;
                _flatValues![k] = value;
                _flatCount++;
                _version++;
                return true;
            }

            if (_buckets == null)
                Initialize(DefaultCapacity);

            var entries = _entries!;
            if (entries.Length <= _loSize + _hiSize)
            {
                var newSize = entries.Length * 2;
                if (newSize > flatStrategyThreshold && entries.Length < flatStrategyThreshold)
                    newSize = flatStrategyThreshold;
                Resize(newSize);
                if (IsFlatStrategy)
                    continue; //Retry with the new flat strategy
                entries = _entries!;
            }

            var kUshort = toUshort(kv);
            ref var bucket = ref _buckets![(uint)kUshort & _mask];

            int dstIndex;
            if (bucket == 0) //Bucket is empty: Place new entry in the Hi-Region (non-colliding entries).
                dstIndex = entries.Length - 1 - _hiSize++;
            else //Collision detected (bucket is not empty).
            {
                //Traverse a collision chain to check for an existing key or find insertion point.
                for (int i = bucket - 1, collisions = 0;;)
                {
                    ref var entry = ref entries[i];
                    if (toUshort(entry.key) == kUshort)
                    {
                        //Key found: Overwrite if allowed, otherwise return false (add failed).
                        if (!overwrite)
                            return false;
                        entry.value = value;
                        _version++;   //Update version as value changed.
                        return false; //Return false as no *new* entry was added (it was an update).
                    }

                    if (_loSize <= i)
                        break; //the key is not found, jump to the adding the new entry in the collided chain (Lo-Region)

                    i = _links![i];
                    if (_loSize + 1 < collisions++)
                        throw new InvalidOperationException("Concurrent operations not supported.");
                }

                //Key not found in chain: Add new entry to the Lo-Region (colliding entries).
                if (_links!.Length == (dstIndex = _loSize++))
                    Array.Resize(ref _links, Math.Max(16, Math.Min(_buckets!.Length, _links.Length * 2)));
                _links[dstIndex] = (ushort)(bucket - 1); //New entry links to the previous head of the chain.
            }

            ref var newEntry = ref entries[dstIndex];
            newEntry.key = kv;
            newEntry.value = value;

            bucket = (ushort)(dstIndex + 1);
            _version++;  //Update version for successful addition.
            return true; //Item successfully added.
        }
    }

    public void Clear()
    {
        if (Count == 0)
            return;

        _hasNullKey = false;
        _nullKeyValue = default!;
        _version++;

        if (IsFlatStrategy)
        {
            _flatCount = 0;
            Array.Clear(_nulls!);
            if (RuntimeHelpers.IsReferenceOrContainsReferences<V>())
                Array.Clear(_flatValues!);
        }
        else
        {
            if (_buckets != null)
                Array.Clear(_buckets);
            if (RuntimeHelpers.IsReferenceOrContainsReferences<V>() && _loSize + _hiSize > 0)
                Array.Clear(_entries!);
            _loSize = 0;
            _hiSize = 0;
        }
    }

    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    public bool ContainsKey(K? key)
    {
        if (!key.HasValue)
            return _hasNullKey;
        var kv = key.Value;
        if (IsFlatStrategy)
        {
            var k = toUshort(kv);
            return (_nulls![k >> 6] & 1UL << k) != 0;
        }
        return !Unsafe.IsNullRef(ref FindEntry(toUshort(kv)));
    }

    public bool ContainsValue(V value)
    {
        if (_hasNullKey && EqualityComparer<V>.Default.Equals(_nullKeyValue, value))
            return true;

        if (IsFlatStrategy)
        {
            var comparer = EqualityComparer<V>.Default;
            for (var i = 0; i < NULLS_SIZE; i++)
            {
                var bits = _nulls![i];
                if (bits == 0)
                    continue; //Skip empty 64-bit segments

                var baseIndex = i << 6; //i * 64
                while (bits != 0)
                {
                    var bitPos = BitOperations.TrailingZeroCount(bits);
                    var index = baseIndex + bitPos;
                    if (comparer.Equals(_flatValues![index], value))
                        return true;
                    bits &= bits - 1; //Clear the least significant set bit
                }
            }

            return false;
        }

        //Iterate lo-region
        for (var i = 0; i < _loSize; i++)
            if (EqualityComparer<V>.Default.Equals(_entries![i].value, value))
                return true;
        if (_hiSize == 0)
            return false;

        //Iterate hi-region
        for (var i = _entries!.Length - _hiSize; i < _entries.Length; i++)
            if (EqualityComparer<V>.Default.Equals(_entries![i].value, value))
                return true;

        return false;
    }

    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    public bool TryGetValue(K? key, [MaybeNullWhen(false)] out V value)
    {
        if (!key.HasValue)
        {
            if (_hasNullKey)
            {
                value = _nullKeyValue;
                return true;
            }
            value = default;
            return false;
        }
        var kv = key.Value;
        if (IsFlatStrategy)
        {
            var k = toUshort(kv);
            if ((_nulls![k >> 6] & 1UL << k) != 0)
            {
                value = _flatValues![k];
                return true;
            }
            value = default;
            return false;
        }
        ref var entry = ref FindEntry(toUshort(kv));
        if (Unsafe.IsNullRef(ref entry))
        {
            value = default;
            return false;
        }
        value = entry.value;
        return true;
    }

    ///<summary>
    ///Gets a reference to the value associated with the specified key, adding a provided default value if the key does not exist.
    ///</summary>
    ///<param name="key">The key to search for.</param>
    ///<param name="defaultValue">The value to add if the key does not exist.</param>
    ///<param name="exists">When this method returns, contains <c>true</c> if the key already existed; otherwise, <c>false</c>.</param>
    ///<returns>A reference to the value associated with the specified key.</returns>
    ///<remarks>
    ///Note: Do not add or remove items from the map while holding this reference, as triggering a resize of the internal arrays will invalidate it.
    ///</remarks>
    public ref V GetValueRefOrAddDefault(K? key, V defaultValue, out bool exists)
    {
        //1. Handle the null key specifically
        if (!key.HasValue)
        {
            if (_hasNullKey)
            {
                exists = true;
                return ref _nullKeyValue;
            }

            _hasNullKey = true;
            _nullKeyValue = defaultValue;
            _version++;
            exists = false;
            return ref _nullKeyValue;
        }

        //2. Loop to handle transition between Hash and Flat strategies
        while (true)
        {
            var kv = key.Value;

            //Flat Strategy Logic
            if (IsFlatStrategy)
            {
                var k = toUshort(kv);
                if ((_nulls![k >> 6] & 1UL << k) != 0) //Key exists
                {
                    exists = true;
                    return ref _flatValues![k];
                }

                //Key does not exist: Add it
                _nulls[k >> 6] |= 1UL << k;
                _flatValues![k] = defaultValue;
                _flatCount++;
                _version++;
                exists = false;
                return ref _flatValues[k];
            }

            //Hash Strategy Logic
            if (_buckets == null)
                Initialize(DefaultCapacity);

            var entries = _entries!;
            if (entries.Length <= _loSize + _hiSize)
            {
                var newSize = entries.Length * 2;
                if (newSize > flatStrategyThreshold && entries.Length < flatStrategyThreshold)
                    newSize = flatStrategyThreshold;

                Resize(newSize);

                if (IsFlatStrategy)
                    continue; //Retry with the newly activated flat strategy
                entries = _entries!;
            }

            var kUshort = toUshort(kv);
            ref var bucket = ref _buckets![(uint)kUshort & _mask];

            int dstIndex;
            if (bucket == 0) //Bucket is empty: Place new entry in the Hi-Region (non-colliding entries).
                dstIndex = entries.Length - 1 - _hiSize++;
            else //Collision detected (bucket is not empty).
            {
                //Traverse the collision chain to check for an existing key or find insertion point.
                for (int i = bucket - 1, collisions = 0;;)
                {
                    ref var entry = ref entries[i];
                    if (toUshort(entry.key) == kUshort)
                    {
                        //Key found: Return a reference to the existing value.
                        exists = true;
                        return ref entry.value;
                    }

                    if (_loSize <= i)
                        break; //The key is not found, jump to adding the new entry in the collided chain (Lo-Region)

                    i = _links![i];
                    if (_loSize + 1 < collisions++)
                        throw new InvalidOperationException("Concurrent operations not supported.");
                }

                //Key not found in chain: Add new entry to the Lo-Region (colliding entries).
                if (_links!.Length == (dstIndex = _loSize++))
                    Array.Resize(ref _links, Math.Max(16, Math.Min(_buckets!.Length, _links.Length * 2)));
                _links[dstIndex] = (ushort)(bucket - 1); //New entry links to the previous head of the chain.
            }

            //Initialize the new entry with the provided default value
            ref var newEntry = ref entries[dstIndex];
            newEntry.key = kv;
            newEntry.value = defaultValue;

            bucket = (ushort)(dstIndex + 1);
            _version++;
            exists = false;

            //Return a reference to the newly added value
            return ref newEntry.value;
        }
    }

    public void CopyTo(KeyValuePair<K?, V>[] dst, int dstIndex)
    {
        ArgumentNullException.ThrowIfNull(dst);
        ArgumentOutOfRangeException.ThrowIfGreaterThanOrEqual((uint)dstIndex, (uint)dst.Length);
        if (dst.Length - dstIndex < Count)
            throw new ArgumentException("Destination array is not long enough.");

        if (_hasNullKey)
            dst[dstIndex++] = new KeyValuePair < K ?, V > (null, _nullKeyValue);

        if (IsFlatStrategy)
            for (var i = -1; (i = next1(i)) != -1;)
                dst[dstIndex++] = new KeyValuePair < K ?, V > (Unsafe.As<int, K>(ref i), _flatValues![i]);
        else
        {
            for (var i = 0; i < _loSize; i++)
            {
                ref var entry = ref _entries![i];
                dst[dstIndex++] = new KeyValuePair < K ?, V > (entry.key, entry.value);
            }

            for (int i = 0, j = _entries!.Length - _hiSize; i < _hiSize; i++, j++)
            {
                ref var entry = ref _entries![j];
                dst[dstIndex++] = new KeyValuePair < K ?, V > (entry.key, entry.value);
            }
        }
    }

    private int Initialize(int capacity, int linksHint = 16)
    {
        _version++;
        _flatCount = 0;

        if (flatStrategyThreshold < capacity)
        {
            _nulls = new ulong[NULLS_SIZE];
            _flatValues = new V[VALUES_SIZE];
            _buckets = null;
            _entries = null;
            _links = null;
            _loSize = _hiSize = 0;
            return VALUES_SIZE;
        }

        _nulls = null;
        _flatValues = null;

        var size = GetPowerOfTwo(capacity);
        _buckets = new ushort[size];
        _entries = new Entry[size];
        _links = new ushort[Math.Min(size, linksHint)];
        _loSize = _hiSize = 0;
        _mask = (uint)(size - 1);

        return size;
    }

    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    private static int GetPowerOfTwo(int capacity) => capacity <= DefaultCapacity ? DefaultCapacity : (int)BitOperations.RoundUpToPowerOf2((uint)capacity);

    private int Resize(int newSize)
    {
        _version++;

        if (IsFlatStrategy)
        {
            if (flatStrategyThreshold < newSize)
                return newSize;
            var oldNulls = _nulls!;
            var oldFlatValues = _flatValues!;

            Initialize(newSize);
            for (var token = -1; (token = next1(token, oldNulls)) != -1;)
            {
                var k = Unsafe.As<int, K>(ref token);
                ref var bucket = ref GetBucket(toUshort(k));
                var i = bucket - 1;
                int dstIndex;

                if (i == -1)
                    dstIndex = _entries!.Length - 1 - _hiSize++;
                else
                {
                    if (_links!.Length == (dstIndex = _loSize++))
                        Array.Resize(ref _links, Math.Max(16, Math.Min(_buckets!.Length, _links.Length * 2)));
                    _links[dstIndex] = (ushort)i;
                }

                ref var entry = ref _entries![dstIndex];
                entry.key = k;
                entry.value = oldFlatValues[token];
                bucket = (ushort)(dstIndex + 1);
            }

            return newSize;
        }

        if (flatStrategyThreshold < newSize)
        {
            _nulls = new ulong[NULLS_SIZE];
            _flatValues = new V[VALUES_SIZE];

            for (var i = 0; i < _loSize; i++)
            {
                ref var entry = ref _entries![i];
                var index = toUshort(entry.key);
                _nulls[index >> 6] |= 1UL << index;
                _flatValues[index] = entry.value;
            }

            if (0 < _hiSize)
                for (var i = _entries!.Length - _hiSize; i < _entries.Length; i++)
                {
                    ref var entry = ref _entries![i];
                    var index = toUshort(entry.key);
                    _nulls[index >> 6] |= 1UL << index;
                    _flatValues[index] = entry.value;
                }

            _flatCount = _loSize + _hiSize;
            _buckets = null;
            _entries = null;
            _links = null;
            _loSize = 0;
            _hiSize = 0;
            return newSize;
        }

        //Hash-to-hash resize
        var oldEntries = _entries;
        var oldLoSize = _loSize;
        var oldHiSize = _hiSize;
        var oldEnd = oldEntries!.Length;
        var oldHiStart = oldEnd - oldHiSize;

        var totalEntries = oldLoSize + oldHiSize;
        Initialize(newSize, totalEntries);

        ref var oldEntries0 = ref MemoryMarshal.GetArrayDataReference(oldEntries);
        ref var entries0 = ref MemoryMarshal.GetArrayDataReference(_entries!);
        ref var links0 = ref MemoryMarshal.GetArrayDataReference(_links!);
        ref var buckets0 = ref MemoryMarshal.GetArrayDataReference(_buckets!);
        var mask = _mask;
        var newEnd = _entries!.Length;
        var loSize = 0;
        var hiSize = 0;

        for (var i = 0; i < oldLoSize; i++)
        {
            ref var entry = ref Unsafe.Add(ref oldEntries0, i);
            ref var bucket = ref Unsafe.Add(ref buckets0, (nint)((uint)toUshort(entry.key) & mask));
            var prev = (int)bucket - 1;
            int dstIndex;

            if (prev == -1)
                dstIndex = newEnd - 1 - hiSize++;
            else
            {
                dstIndex = loSize++;
                Unsafe.Add(ref links0, dstIndex) = (ushort)prev;
            }

            Unsafe.Add(ref entries0, dstIndex) = entry;
            bucket = (ushort)(dstIndex + 1);
        }

        for (var i = oldHiStart; i < oldEnd; i++)
        {
            ref var entry = ref Unsafe.Add(ref oldEntries0, i);
            ref var bucket = ref Unsafe.Add(ref buckets0, (nint)((uint)toUshort(entry.key) & mask));
            var prev = (int)bucket - 1;
            int dstIndex;

            if (prev == -1)
                dstIndex = newEnd - 1 - hiSize++;
            else
            {
                dstIndex = loSize++;
                Unsafe.Add(ref links0, dstIndex) = (ushort)prev;
            }

            Unsafe.Add(ref entries0, dstIndex) = entry;
            bucket = (ushort)(dstIndex + 1);
        }

        _loSize = loSize;
        _hiSize = hiSize;
        return newSize;
    }

    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    private void Move(int src, int dst, ref Entry dstEntry)
    {
        //Move is private and called only from Remove (three sites). Centralizing the
        //version bump here removes the duplicated `_version++` from each Remove branch
        //and still bumps once per Remove (including the src == dst early-return case).
        _version++;
        if (src == dst)
            return;

        //Skip the array-bounds checks: src < _entries.Length and the chain-walked
        //indices are bounded by the same. Same trick the BCL uses internally.
        ref var entries0 = ref MemoryMarshal.GetArrayDataReference(_entries!);
        ref var links0 = ref MemoryMarshal.GetArrayDataReference(_links!);
        ref var srcEntry = ref Unsafe.Add(ref entries0, src);
        ref var srcBucket = ref GetBucket(toUshort(srcEntry.key));
        var index = srcBucket - 1;

        if (index == src)
            srcBucket = (ushort)(dst + 1);
        else
        {
            ref var link = ref Unsafe.Add(ref links0, index);
            while (link != src)
            {
                index = link;
                link = ref Unsafe.Add(ref links0, index);
            }
            link = (ushort)dst;
        }

        if (src < _loSize)
            Unsafe.Add(ref links0, dst) = Unsafe.Add(ref links0, src);

        dstEntry = srcEntry;
    }

    public bool Remove(K? key)
    {
        if (!key.HasValue)
        {
            if (!_hasNullKey)
                return false;
            _hasNullKey = false;
            _nullKeyValue = default!;
            _version++;
            return true;
        }

        var kv = key.Value;

        if (IsFlatStrategy)
        {
            var k = toUshort(kv);
            ref var bitword = ref _nulls![k >> 6];
            var t = bitword;
            if (t == (bitword &= ~(1UL << k)))
                return false;

            if (RuntimeHelpers.IsReferenceOrContainsReferences<V>())
                _flatValues![k] = default!;
            _flatCount--;
            _version++;
            return true;
        }

        if (_loSize + _hiSize == 0)
            return false;

        var kUshort = toUshort(kv);
        ref var bucket = ref GetBucket(kUshort);
        var idx = bucket - 1;
        if (idx < 0)
            return false;

        var loSize = _loSize;
        ref var entries0 = ref MemoryMarshal.GetArrayDataReference(_entries!);

        ref var e = ref Unsafe.Add(ref entries0, idx);
        if (loSize <= idx)
        {
            if (toUshort(e.key) != kUshort)
                return false;
            Move(_entries!.Length - _hiSize, idx, ref e);
            _hiSize--;
            bucket = 0;
            return true;
        }

        ref var links0 = ref MemoryMarshal.GetArrayDataReference(_links!);
        var prev = -1;
        var prevPrev = -1;

        for (var collisions = 0;
             toUshort(e.key) != kUshort;
             prevPrev = prev,
                 e = ref Unsafe.Add(ref entries0, idx = Unsafe.Add(ref links0, prev = idx)))
        {
            if (idx >= loSize)
                return false;
            if (++collisions > loSize)
                throw new InvalidOperationException("Hash collision chain is unexpectedly long. Possible data corruption.");
        }

        var lastLo = loSize - 1;
        if (idx < loSize)
        {
            //Standard removal: rewire (prev or bucket) → next; compact lo by swap-with-last.
            //Single read of the matched entry's link; both branches consume `next`.
            var next = Unsafe.Add(ref links0, idx);
            if (prev < 0)
                bucket = (ushort)(next + 1);
            else
                Unsafe.Add(ref links0, prev) = next;
            Move(lastLo, idx, ref e);
        }
        else
        {
            //Found at hi-terminator with chain length ≥ 2. Migrate prev (lo) into the hi slot
            //so the chain still terminates in hi; prev's lo slot becomes the hole.
            ref var prevEntry = ref Unsafe.Add(ref entries0, prev);
            e = prevEntry;
            if (prevPrev < 0)
                bucket = (ushort)(idx + 1);
            else
                Unsafe.Add(ref links0, prevPrev) = (ushort)idx;
            Move(lastLo, prev, ref prevEntry);
        }

        _loSize = lastLo;
        return true;
    }

