    public bool IsSubsetOf(IEnumerable<K?> other)
    {
        ArgumentNullException.ThrowIfNull(other);
        if (Count == 0)
            return true;
        var otherAsSet = other as ISet<K?> ?? new HashSet<K?>(other);
        if (Count > otherAsSet.Count)
            return false;

        //Fast path
        if (IsFlatStrategy && other is NullableTwoBytesSet<K> { IsFlatStrategy : true } otherTbs)
        {
            if (_hasNullKey && !otherTbs._hasNullKey)
                return false;
            ref var nullsRef = ref MemoryMarshal.GetArrayDataReference(_nulls!);
            ref var otherNullsRef = ref MemoryMarshal.GetArrayDataReference(otherTbs._nulls!);
            for (var i = 0; i < NULLS_SIZE; i++)
                if ((Unsafe.Add(ref nullsRef, i) & ~Unsafe.Add(ref otherNullsRef, i)) != 0)
                    return false;

            return true;
        }

        foreach (var key in this)
            if (!otherAsSet.Contains(key))
                return false;
        return true;
    }

    public bool IsSupersetOf(IEnumerable<K?> other)
    {
        ArgumentNullException.ThrowIfNull(other);
        if (other is ICollection<K?> { Count : 0 })
            return true;

        //Fast path
        if (IsFlatStrategy && other is NullableTwoBytesSet<K> { IsFlatStrategy : true } otherTbs)
        {
            if (otherTbs._hasNullKey && !_hasNullKey)
                return false;
            ref var nullsRef = ref MemoryMarshal.GetArrayDataReference(_nulls!);
            ref var otherNullsRef = ref MemoryMarshal.GetArrayDataReference(otherTbs._nulls!);
            for (var i = 0; i < NULLS_SIZE; i++)
                if ((Unsafe.Add(ref otherNullsRef, i) & ~Unsafe.Add(ref nullsRef, i)) != 0)
                    return false;

            return true;
        }

        foreach (var key in other)
            if (!Contains(key))
                return false;
        return true;
    }

