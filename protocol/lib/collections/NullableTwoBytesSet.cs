///<summary>
///A highly optimized set for nullable 2-byte unmanaged types (e.g., ushort, char).
///It uses a bitset ("flat") strategy for dense data and a custom hash table for sparse data.
///This class is not thread-safe.
///
///<para><b>Benchmark vs <c>HashSet&lt;ushort?&gt;</c></b> (N = 50 000 unique ushort keys → flat mode,
///.NET 9, Release):</para>
///<code>
///Insert         Search hit    Search miss
///NullableTwoBytesSet&lt;ushort?&gt;   113 477 937    1 011 268 420   ~922 023 182   ops/sec
///HashSet                              0.23            0.04           ~0.04   x
///</code>
///<para><b>Memory profile (Insert, 50 000 unique random ushort keys (transitions to flat strategy)):</b>
///<list type="bullet">
///<item><c>NullableTwoBytesSet</c> allocates <b>6.74 B/op</b> (Insert of 50 000 records)</item>
///<item><c>HashSet</c> allocates <b>46.55 B/op</b></item>
///<item><c>NullableTwoBytesSet</c> saves <b>~39 806 B per 1 000 records</b> vs HashSet</item>
///</list>
///</para>
///<para>
///Ratio &gt; 1 ⇒ <c>HashSet</c> faster, &lt; 1 ⇒ NullableTwoBytesSet faster. Flat mode delivers
///<b>~25× faster Contains</b> than <c>HashSet&lt;ushort?&gt;</c> (single bit-test vs hash + nullable
///wrap), 4.3× faster Insert.
///</para>
///<para>See <c>Tests/Benchmarks/NullableTwoBytesBenchmark.cs</c> for the full scenarios and an HTML report.</para>
///<para>Historical benchmark figures predate hash mixing and two buckets per entry slot.
///Re-run the benchmarks for the current layout; see <c>BucketsFor</c> and <c>LinksFor</c> for tuning.</para>
///</summary>
public class NullableTwoBytesSet<K> : ISet<K?>, IReadOnlySet<K?>
    where K : unmanaged
{
    private ushort[]? _buckets;
    private K[]? _keys;
    private ushort[]? _links; //0-based indices into _keys for collision chains.

    //The _keys array is split into two regions to optimize for non-colliding entries:
    //1. Lo-Region (indices 0 to _loSize-1): Stores keys that have caused a hash collision.
    //2. Hi-Region (indices _keys.Length - _hiSize to _keys.Length-1): Stores keys that have not caused a collision.
    private int _hiSize; //Number of active entries in the high region.
    private int _loSize; //Number of active entries in the low region.

    private int _flatCount;
    private int _version;
    private uint _mask;

    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    private ref ushort GetBucket(uint hashCode) => ref Unsafe.Add(ref MemoryMarshal.GetArrayDataReference(_buckets!), (nint)(MixHash(hashCode) & _mask));

    private bool _hasNullKey;

    private readonly bool _speedUp;

    private const int DefaultCapacity = 4;
    protected const int VALUES_SIZE = 0x10000;         //65536
    protected const int NULLS_SIZE = VALUES_SIZE / 64; //1024
    public const int flatStrategyThreshold = 0x7FFF;   //Max capacity for hash phase

    private ulong[]? _nulls; //Bitset for flat mode. A set bit at index `i` means the value `i` is present.
    public bool IsFlatStrategy => _nulls != null;

    public NullableTwoBytesSet(bool speed_up) : this(0, speed_up) {}

    public NullableTwoBytesSet() : this(0) {}

    public NullableTwoBytesSet(int capacity) : this(capacity, true) {}

    ///<summary>Chooses two buckets per entry slot when <paramref name="speed_up"/> is true, or one to save memory.</summary>
    public NullableTwoBytesSet(int capacity, bool speed_up)
    {
        _speedUp = speed_up;
        ArgumentOutOfRangeException.ThrowIfNegative(capacity);
        if (Unsafe.SizeOf<K>() != 2)
            throw new InvalidOperationException($"The Key type {typeof(K).Name} is {Unsafe.SizeOf<K>()} bytes, but must be 2 bytes.");

        if (capacity > 0)
            Initialize(capacity);
    }

    public NullableTwoBytesSet(IEnumerable<K?> collection) : this(collection, (collection as NullableTwoBytesSet<K>)?._speedUp ?? true) {}

    public NullableTwoBytesSet(IEnumerable<K?> collection, bool speed_up) : this(collection is ICollection<K?> coll ? coll.Count : 0, speed_up)
    {
        ArgumentNullException.ThrowIfNull(collection);
        if (Unsafe.SizeOf<K>() != 2)
            throw new InvalidOperationException($"The Key type {typeof(K).Name} is {Unsafe.SizeOf<K>()} bytes, but must be 2 bytes.");
        AddRange(collection);
    }

    private void AddRange(IEnumerable<K?> enumerable)
    {
        foreach (var key in enumerable)
            Add(key);
    }

    public int Count => (IsFlatStrategy ? _flatCount : _loSize + _hiSize) + (_hasNullKey ? 1 : 0);

    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    public bool Add(K? key) => key.HasValue ? AddKey(key.GetValueOrDefault()) : AddNull();

    ///<summary>Adds the null key. Returns <c>true</c> if it was new.</summary>
    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    public bool AddNull()
    {
        if (_hasNullKey)
            return false;
        _hasNullKey = true;
        _version++;
        return true;
    }

    ///<summary>Whether the set holds the null key.</summary>
    public bool HasNullKey
    {
        [MethodImpl(MethodImplOptions.AggressiveInlining)]
        get => _hasNullKey;
    }

    ///<summary>Adds a non-null key. Returns <c>true</c> if the key was new.</summary>
    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    public bool AddKey(K kv)
    {
        if (IsFlatStrategy)
        {
            var i = toUshort(kv);
            ref var bitword = ref Unsafe.Add(ref MemoryMarshal.GetArrayDataReference(_nulls!), i >> 6);
            var t = bitword;
            if (t == (bitword |= 1UL << i))
                return false;
            _flatCount++;
            _version++;
            return true;
        }

        if (_buckets == null)
            Initialize(DefaultCapacity);

        ref var bucket = ref GetBucket(toUshort(kv));
        if (bucket != 0)
        {
            var keys = _keys!;
            var links = _links!;
            var loSize = _loSize;
            for (int i = (int)bucket - 1, collisions = 0;;)
            {

                if (toUshort(keys[i]) == toUshort(kv))
                {
                    return false;
                }
                if (loSize <= i)
                    break;
                i = (int)links[i];
                if (loSize + 1 < collisions++)
                    ThrowConcurrentOperation();
            }
        }

        if (_keys!.Length <= _loSize + _hiSize)
            GrowAndAdd(kv);
        else
            AddNew(ref bucket, kv);
        return true;
    }

    //The key is known to be absent and the table has a free entry slot.
    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    private void AddNew(ref ushort bucket, K key)
    {
        var keys = _keys!;
        var head = bucket;
        int dstIndex;
        if (head == 0)
            dstIndex = keys.Length - 1 - _hiSize++;
        else
        {
            if (_links!.Length == (dstIndex = _loSize++))
                Array.Resize(ref _links, Math.Max(16, Math.Min(keys.Length, _links.Length * 2)));
            _links[dstIndex] = (ushort)(head - 1);
        }
        keys[dstIndex] = key;

        bucket = (ushort)(dstIndex + 1);
        _version++;
    }

    [MethodImpl(MethodImplOptions.NoInlining)]
    private void GrowAndAdd(K key)
    {
        var newSize = _keys!.Length * 2;
        if (newSize > flatStrategyThreshold && _keys.Length < flatStrategyThreshold)
            newSize = flatStrategyThreshold;
        Resize(newSize);
        if (IsFlatStrategy)
        {
            AddKey(key);
            return;
        }
        AddNew(ref GetBucket(toUshort(key)), key);
    }

    void ICollection<K?>.Add(K? key) => Add(key);

    public void Clear()
    {
        if (Count == 0)
            return;

        _hasNullKey = false;
        _version++;

        if (IsFlatStrategy)
        {
            _flatCount = 0;
            Array.Clear(_nulls!, 0, _nulls!.Length);
        }
        else
        {
            if (_buckets != null)
                Array.Clear(_buckets, 0, _buckets.Length);
            _loSize = 0;
            _hiSize = 0;
        }
    }

    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    public bool Contains(K? key)
    {
        if (!key.HasValue)
            return _hasNullKey;
        var kv = key.Value;
        if (IsFlatStrategy)
            return exists(kv);

        var buckets = _buckets;
        if (buckets == null)
            return false;

        var i = (int)Unsafe.Add(ref MemoryMarshal.GetArrayDataReference(buckets), (nint)(MixHash(toUshort(kv)) & (uint)(buckets.Length - 1))) - 1;
        if (i < 0)
            return false;
        var keys = _keys!;
        if (toUshort(keys[i]) == toUshort(kv))
            return true;
        var loSize = _loSize;
        if (loSize <= i)
            return false;
        var links = _links!;
        for (var budget = loSize;;)
        {
            i = (int)links[i];
            if (toUshort(keys[i]) == toUshort(kv))
                return true;
            if (loSize <= i)
                return false;
            if (--budget < 0)
                ThrowChainTooLong();
        }
    }

    public void CopyTo(K?[] dst, int dstIndex)
    {
        ArgumentNullException.ThrowIfNull(dst);
        ArgumentOutOfRangeException.ThrowIfGreaterThanOrEqual((uint)dstIndex, (uint)dst.Length);
        if (dst.Length - dstIndex < Count)
            throw new ArgumentException("Destination array is not long enough.");

        if (_hasNullKey)
            dst[dstIndex++] = null;

        if (IsFlatStrategy)
            for (var i = -1; (i = next1(i)) != -1;)
                dst[dstIndex++] = Unsafe.As<int, K>(ref i);
        else
        {
            //Copy lo-region
            for (var i = 0; i < _loSize; i++)
                dst[dstIndex++] = _keys[i];
            //Copy hi-region
            for (var i = _keys.Length - _hiSize; i < _keys.Length; i++)
                dst[dstIndex++] = _keys[i];
        }
    }

    //speed_up selects two buckets per entry slot; otherwise one. Links grow on demand.
    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    private int BucketsFor(int size) => _speedUp && size < 1 << 30 ? size << 1 : size;

    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    private static int LinksFor(int size) => Math.Max(Math.Min(size, 16), size >> 2);

    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    private static uint MixHash(uint h) => h ^ (h >> 8) ^ (h >> 13) ^ (h >> 24);

    [DoesNotReturn]
    [MethodImpl(MethodImplOptions.NoInlining)]
    private static void ThrowChainTooLong() => throw new InvalidOperationException("Hash collision chain is unexpectedly long. Possible data corruption.");

    [DoesNotReturn]
    [MethodImpl(MethodImplOptions.NoInlining)]
    private static void ThrowConcurrentOperation() => throw new InvalidOperationException("Concurrent operations not supported.");

    private int Initialize(int capacity)
    {
        _version++;
        _flatCount = 0;

        if (flatStrategyThreshold < capacity)
        {
            _nulls = new ulong[NULLS_SIZE];
            _buckets = null;
            _keys = null;
            _links = null;
            _loSize = _hiSize = 0;
            return VALUES_SIZE;
        }

        _nulls = null;

        var size = GetPowerOfTwo(capacity);
        var bucketCount = BucketsFor(size);
        _buckets = new ushort[bucketCount];
        _keys = new K[size];
        _links = new ushort[LinksFor(size)];
        _loSize = _hiSize = 0;
        _mask = (uint)(bucketCount - 1);

        return size;
    }
    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    private static int GetPowerOfTwo(int capacity) => capacity <= DefaultCapacity ? DefaultCapacity : (int)BitOperations.RoundUpToPowerOf2((uint)capacity);

    //Build both hash and flat representations locally before publishing them.
    private int Resize(int newSize)
    {
        _version++;
        if (flatStrategyThreshold < newSize)
        {
            if (IsFlatStrategy)
                return VALUES_SIZE;
            var nulls = new ulong[NULLS_SIZE];

            var oldData = _keys!;
            for (var i = 0; i < _loSize; i++)
            {
                ref var entry = ref oldData[i];
                var index = toUshort(entry);
                nulls[index >> 6] |= 1UL << index;
            }
            for (var i = oldData.Length - _hiSize; i < oldData.Length; i++)
            {
                ref var entry = ref oldData[i];
                var index = toUshort(entry);
                nulls[index >> 6] |= 1UL << index;
            }
            _flatCount = _loSize + _hiSize;

            _nulls = nulls;
            _buckets = null;
            _keys = null;
            _links = null;
            _loSize = _hiSize = 0;
            return VALUES_SIZE;
        }

        var size = GetPowerOfTwo(newSize);
        var bucketCount = BucketsFor(size);
        var buckets = new ushort[bucketCount];
        var data = new K[size];
        var links = new ushort[LinksFor(size)];
        var mask = (uint)(bucketCount - 1);
        ref var data0 = ref MemoryMarshal.GetArrayDataReference(data);
        ref var links0 = ref MemoryMarshal.GetArrayDataReference(links);
        ref var buckets0 = ref MemoryMarshal.GetArrayDataReference(buckets);
        var loSize = 0;
        var hi = size;
        if (IsFlatStrategy)
        {
            var oldNulls = _nulls!;

            for (var token = -1; (token = next1(token, oldNulls)) != -1;)
            {
                var key = Unsafe.As<int, K>(ref token);
                var entry = key;
                ref var bucket = ref Unsafe.Add(ref buckets0, (nint)(MixHash(toUshort(entry)) & mask));
                var head = bucket;
                int dstIndex;
                if (head == 0)
                    dstIndex = --hi;
                else
                {
                    if (loSize == links.Length)
                    {
                        Array.Resize(ref links, Math.Min(size, links.Length * 2));
                        links0 = ref MemoryMarshal.GetArrayDataReference(links);
                    }
                    Unsafe.Add(ref links0, dstIndex = loSize++) = (ushort)(head - 1);
                }
                Unsafe.Add(ref data0, dstIndex) = entry;
                bucket = (ushort)(dstIndex + 1);
            }
        }
        else
        {
            var oldData = _keys!;
            ref var oldData0 = ref MemoryMarshal.GetArrayDataReference(oldData);
            var oldLoSize = _loSize;
            var oldEnd = oldData.Length;
            var oldHiStart = oldEnd - _hiSize;
            for (var i = 0; i < oldLoSize; i++)
            {
                ref var entry = ref Unsafe.Add(ref oldData0, i);
                ref var bucket = ref Unsafe.Add(ref buckets0, (nint)(MixHash(toUshort(entry)) & mask));
                var head = bucket;
                int dstIndex;
                if (head == 0)
                    dstIndex = --hi;
                else
                {
                    if (loSize == links.Length)
                    {
                        Array.Resize(ref links, Math.Min(size, links.Length * 2));
                        links0 = ref MemoryMarshal.GetArrayDataReference(links);
                    }
                    Unsafe.Add(ref links0, dstIndex = loSize++) = (ushort)(head - 1);
                }
                Unsafe.Add(ref data0, dstIndex) = entry;
                bucket = (ushort)(dstIndex + 1);
            }
            for (var i = oldHiStart; i < oldEnd; i++)
            {
                ref var entry = ref Unsafe.Add(ref oldData0, i);
                ref var bucket = ref Unsafe.Add(ref buckets0, (nint)(MixHash(toUshort(entry)) & mask));
                var head = bucket;
                int dstIndex;
                if (head == 0)
                    dstIndex = --hi;
                else
                {
                    if (loSize == links.Length)
                    {
                        Array.Resize(ref links, Math.Min(size, links.Length * 2));
                        links0 = ref MemoryMarshal.GetArrayDataReference(links);
                    }
                    Unsafe.Add(ref links0, dstIndex = loSize++) = (ushort)(head - 1);
                }
                Unsafe.Add(ref data0, dstIndex) = entry;
                bucket = (ushort)(dstIndex + 1);
            }
        }
        _buckets = buckets;
        _keys = data;
        _links = links;
        _mask = mask;
        _loSize = loSize;
        _hiSize = size - hi;

        _nulls = null;
        _flatCount = 0;
        return size;
    }

    //Moves data from src index to dst index and updates all links pointing to src.
    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    private void Move(int src, int dst, ref K dstKey)
    {
        //Move is private and called only from Remove (three sites). Centralizing the
        //version bump here removes the duplicated `_version++` from each Remove branch
        //and still bumps once per Remove (including the src == dst early-return case).
        _version++;
        if (src == dst)
            return;

        //Skip the array-bounds checks: src < _keys.Length and the chain-walked
        //indices are bounded by the same. Same trick the BCL uses internally.
        ref var keys0 = ref MemoryMarshal.GetArrayDataReference(_keys!);
        ref var links0 = ref MemoryMarshal.GetArrayDataReference(_links!);
        ref var srcKey = ref Unsafe.Add(ref keys0, src);
        ref var srcBucket = ref GetBucket(toUshort(srcKey));
        var index = srcBucket - 1;

        if (index == src)
            srcBucket = (ushort)(dst + 1);
        else
        {
            ref var link = ref Unsafe.Add(ref links0, index);
            while (link != src)
            {
                index = link;
                link = ref Unsafe.Add(ref links0, index);
            }
            link = (ushort)dst;
        }

        if (src < _loSize)
            Unsafe.Add(ref links0, dst) = Unsafe.Add(ref links0, src);

        dstKey = srcKey;
    }

    public bool Remove(K? key)
    {
        if (!key.HasValue)
        {
            if (!_hasNullKey)
                return false;
            _hasNullKey = false;
            _version++;
            return true;
        }

        var kv = key.Value;

        if (IsFlatStrategy)
        {
            var i = toUshort(kv);
            ref var bitword = ref Unsafe.Add(ref MemoryMarshal.GetArrayDataReference(_nulls!), i >> 6);
            var t = bitword;
            if (t == (bitword &= ~(1UL << i)))
                return false;
            _flatCount--;
            _version++;
            return true;
        }

        if (_loSize + _hiSize == 0)
            return false;

        var kUshort = toUshort(kv);
        ref var bucket = ref GetBucket(kUshort);
        var idx = bucket - 1;
        if (idx < 0)
            return false;

        var loSize = _loSize;
        ref var keys0 = ref MemoryMarshal.GetArrayDataReference(_keys!);

        ref var k = ref Unsafe.Add(ref keys0, idx);
        if (loSize <= idx)
        {
            if (toUshort(k) != kUshort)
                return false;
            Move(_keys!.Length - _hiSize, idx, ref k);
            _hiSize--;
            bucket = 0;
            return true;
        }

        ref var links0 = ref MemoryMarshal.GetArrayDataReference(_links!);
        var prev = -1;
        var prevPrev = -1;

        for (var collisions = 0;
             toUshort(k) != kUshort;
             prevPrev = prev,
                 k = ref Unsafe.Add(ref keys0, idx = Unsafe.Add(ref links0, prev = idx)))
        {
            if (idx >= loSize)
                return false;
            if (++collisions > loSize)
                ThrowChainTooLong();
        }

        var lastLo = loSize - 1;
        if (idx < loSize)
        {
            //Standard removal: rewire (prev or bucket) → next; compact lo by swap-with-last.
            //Single read of the matched entry's link; both branches consume `next`.
            var next = Unsafe.Add(ref links0, idx);
            if (prev < 0)
                bucket = (ushort)(next + 1);
            else
                Unsafe.Add(ref links0, prev) = next;
            Move(lastLo, idx, ref k);
        }
        else
        {
            //Found at hi-terminator with chain length ≥ 2. Migrate prev (lo) into the hi slot
            //so the chain still terminates in hi; prev's lo slot becomes the hole.
            ref var prevKey = ref Unsafe.Add(ref keys0, prev);
            k = prevKey;
            if (prevPrev < 0)
                bucket = (ushort)(idx + 1);
            else
                Unsafe.Add(ref links0, prevPrev) = (ushort)idx;
            Move(lastLo, prev, ref prevKey);
        }

        _loSize = lastLo;
        return true;
    }

