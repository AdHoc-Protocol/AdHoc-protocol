using System;
using System.Runtime.CompilerServices;
using System.Runtime.InteropServices;
using System.Threading;

namespace org.unirail.collections;

///<summary>
///Reusable objects for any number of threads: an object is taken and given back at once, never waited for.
///<para>
///Magazines (Bonwick and Adams 2001, the slab allocator of Solaris; jemalloc's tcache does the same): each thread holds two
///magazines of up to 32 objects and takes and gives back with no atomic at all; with the depot of the pool it trades whole
///magazines - a full one for an empty one, one atomic exchange for a magazine. No order (the last given back is the first
///taken: warm in the cache), no cursors, no wait: an empty pool makes a new object with the factory, a full one drops it.
///</para>
///<para>
///A pool is not a queue: the pool before this one was one - two shared cursors, first in first out - and from two threads on
///it was slower than making a new object each time (8 threads, each taking and giving back: 246 ns an object against 18 of
///<c>new</c>; it also lost objects in a race). A thread's magazines are its own by a <see cref="ThreadLocal{T}"/> of the pool:
///those of a thread that ended go with it.
///</para>
///</summary>
///<typeparam name="T">The type of the objects in the pool. Must be a reference type.</typeparam>
public sealed class Pool<T>
    where T : class
{
    ///<summary>Objects a magazine holds at most.</summary>
    const int M = 32;

    ///<summary>A magazine: objects, the first <see cref="count"/> of <see cref="items"/>.</summary>
    sealed class Mag
    {
        public readonly T?[] items;
        public int count;
        public Mag(int m) => items = new T?[m];
    }

    ///<summary>A thread's two magazines: the loaded one, and the one before - full or empty: a thread taking and giving back
    ///in turn at the edge of a magazine does not go to the depot each time.</summary>
    sealed class Local
    {
        public Mag loaded, prev;
        public Local(int m) => (loaded, prev) = (new Mag(m), new Mag(m));
    }

    readonly ThreadLocal<Local> _locals;

    //the depot: full magazines, and empty ones - a place holds a magazine or null
    readonly Mag?[] _full, _empty;

    //objects a magazine holds
    readonly int _m;

    readonly Func<T> _factory;

    ///<summary>A pool whose depot holds <c>2^powerOf2</c> idle objects at most, besides the two magazines of each thread.</summary>
    public Pool(int powerOf2, Func<T> factory)
    {
        if (powerOf2 is < 1 or > 30)
            throw new ArgumentOutOfRangeException(nameof(powerOf2), "powerOf2 must be between 1 and 30");
        ArgumentNullException.ThrowIfNull(factory);
        var capacity = 1 << powerOf2;
        _m = Math.Min(capacity, M);
        _full = new Mag?[capacity / _m];
        _empty = new Mag?[capacity / _m];
        _factory = factory;
        var m = _m;
        _locals = new ThreadLocal<Local>(() => new Local(m));
    }

    ///<summary>An object of this thread's magazines; else of a full magazine of the depot; else a new one.</summary>
    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    public T Acquire()
    {
        var l = _locals.Value!;
        var m = l.loaded;
        if (0 < m.count)
        {
            var item = m.items[--m.count]!;
            m.items[m.count] = null; //the magazine keeps nothing it gave away alive
            return item;
        }
        return AcquireDepot(l);
    }

    ///<summary>The loaded magazine is empty: the one before, if it holds any; else a full one of the depot for it, the empty
    ///one to the depot.</summary>
    [MethodImpl(MethodImplOptions.NoInlining)]
    T AcquireDepot(Local l)
    {
        if (0 < l.prev.count)
            (l.loaded, l.prev) = (l.prev, l.loaded);
        else
        {
            var full = Take(_full);
            if (full == null)
                return _factory();
            Give(_empty, l.loaded); //the empty one: kept for a thread to fill, or dropped
            l.loaded = full;
        }
        var m = l.loaded;
        var item = m.items[--m.count]!;
        m.items[m.count] = null;
        return item;
    }

    ///<summary>Gives <paramref name="item"/> back: into this thread's magazines; a full pool drops it.</summary>
    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    public void Release(T item)
    {
        if (item == null)
            return;
        var l = _locals.Value!;
        var m = l.loaded;
        if (m.count < _m)
            m.items[m.count++] = item;
        else
            ReleaseDepot(l, item);
    }

    ///<summary>The loaded magazine is full: the one before, if it has room; else the one before - full - to the depot and an
    ///empty one in its place.</summary>
    [MethodImpl(MethodImplOptions.NoInlining)]
    void ReleaseDepot(Local l, T item)
    {
        if (l.prev.count < _m)
            (l.loaded, l.prev) = (l.prev, l.loaded);
        else
        {
            if (!Give(_full, l.prev))
                return; //the depot is full: the object dropped
            l.prev = l.loaded;
            l.loaded = Take(_empty) ?? new Mag(_m);
        }
        var m = l.loaded;
        m.items[m.count++] = item;
    }

    ///<summary>A magazine of <paramref name="places"/>, its place left null; null - none there.</summary>
    static Mag? Take(Mag?[] places)
    {
        for (var i = 0; i < places.Length; i++)
            if (Volatile.Read(ref places[i]) != null)
            {
                var m = Interlocked.Exchange(ref places[i], null);
                if (m != null)
                    return m;
            }
        return null;
    }

    ///<summary><paramref name="mag"/> into a null place of <paramref name="places"/>; false - none there.</summary>
    static bool Give(Mag?[] places, Mag mag)
    {
        for (var i = 0; i < places.Length; i++)
            if (Volatile.Read(ref places[i]) == null && Interlocked.CompareExchange(ref places[i], mag, null) == null)
                return true;
        return false;
    }

    ///<summary>Idle objects the depot holds at most; each thread holds two magazines besides.</summary>
    public int Capacity => _full.Length * _m;

    ///<summary>Idle objects in the depot now (its magazines are full), a snapshot; the threads' magazines are not counted.</summary>
    public int Count
    {
        get {
            var n = 0;
            for (var i = 0; i < _full.Length; i++)
                if (Volatile.Read(ref _full[i]) != null)
                    n++;
            return n * _m;
        }
    }
}
