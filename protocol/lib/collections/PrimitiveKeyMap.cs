    ///<summary>Attempts to add the specified key and value. Returns false if the key already exists.</summary>
    ///<remarks>Native implementation. Avoids the BCL <c>IDictionary&lt;K,V&gt;</c> extension method's
    ///double dispatch (ContainsKey + Add).</remarks>
    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    public bool TryAdd(K key, V value) => TryInsert(key, value, false);

    ///<summary>
    ///Internal entry-finder. Returns a ref to the entry on hit, or a null ref on miss.
    ///AggressiveInlining so callers (TryGetValue, ContainsKey, indexer) inline the body — the
    ///indexer was 4× slower than direct TryGetValue without this fix.
    ///</summary>
    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    private ref Entry FindEntry(K key)
    {
        if (_loSize + _hiSize == 0)
            return ref Unsafe.NullRef<Entry>();

        var i = (int)GetBucket((uint)key.GetHashCode()) - 1;
        if (i == -1)
            return ref Unsafe.NullRef<Entry>();

        ref var entry = ref _entries![i];
        for (var collisions = 0; !EqualityComparer<K>.Default.Equals(entry.key, key); entry = ref _entries![i = (int)_links![i]])
        {
            if (_loSize <= i)
                return ref Unsafe.NullRef<Entry>();
            if (_loSize < ++collisions)
                throw new InvalidOperationException("Hash collision chain is unexpectedly long. Possible data corruption.");
        }

        return ref entry;
    }

    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    private bool TryInsert(K key, V value, bool overwrite)
    {
        if (_buckets == null)
            Initialize(DefaultCapacity);

        var entries = _entries!;
        if (entries.Length <= _loSize + _hiSize)
        {
            Resize(entries.Length * 2);
            entries = _entries!;
        }

        ref var bucket = ref GetBucket((uint)key.GetHashCode());
        ref var entries0 = ref MemoryMarshal.GetArrayDataReference(entries);

        int dstIndex;
        if (bucket == 0)
            dstIndex = entries.Length - 1 - _hiSize++; //Empty bucket → place in hi-region.
        else
        {
            //Cache links0 only for the read-only chain walk. The post-walk lo-insert may
            //call Array.Resize(ref _links, ...) which would invalidate this ref, so the
            //write below uses the _links! field directly.
            ref var links0 = ref MemoryMarshal.GetArrayDataReference(_links!);
            var loSize = _loSize;
            for (uint i = bucket - 1, collisions = 0;;)
            {
                ref var entry = ref Unsafe.Add(ref entries0, i);
                if (EqualityComparer<K>.Default.Equals(entry.key, key))
                {
                    if (!overwrite)
                        return false;
                    entry.value = value;
                    _version++;
                    return false;
                }

                if (loSize <= i)
                    break; //Reached hi-region terminator without match.
                i = Unsafe.Add(ref links0, i);
                if (loSize + 1 < collisions++)
                    throw new InvalidOperationException("Concurrent operations not supported.");
            }

            //Push new entry on chain head in lo-region.
            if (_links!.Length == (dstIndex = _loSize++))
                Array.Resize(ref _links, Math.Max(16, Math.Min(_buckets!.Length, _links.Length * 2)));
            _links[dstIndex] = bucket - 1;
        }

        ref var newEntry = ref Unsafe.Add(ref entries0, dstIndex);
        newEntry.key = key;
        newEntry.value = value;
        bucket = (uint)(dstIndex + 1);
        _version++;
        return true;
    }

