    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    private ref uint GetBucket(uint hashCode) => ref Unsafe.Add(ref MemoryMarshal.GetArrayDataReference(_buckets!), hashCode &_mask);

    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    private int Initialize(int capacity, int linksHint = 16)
    {
        _version++;
        var size = GetPowerOfTwo(capacity);
        _buckets = new uint[size];
        _entries = new Entry[size];
        _links = new uint[Math.Min(size, linksHint)];
        _loSize = _hiSize = 0;
        _mask = (uint)(size - 1);
        return size;
    }

    public void Clear()
    {
        if (Count == 0)
            return;
        _version++;
        if (_buckets != null)
            Array.Clear(_buckets, 0, _buckets.Length);
        _loSize = 0;
        _hiSize = 0;
    }

    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    public bool ContainsKey(K key) => !Unsafe.IsNullRef(ref FindEntry(key));

    public bool ContainsValue(V value)
    {
        //Iterate lo-region
        for (var i = 0; i < _loSize; i++)
            if (EqualityComparer<V>.Default.Equals(_entries![i].value, value))
                return true;
        if (_hiSize == 0)
            return false;

        //Iterate hi-region
        for (var i = _entries!.Length - _hiSize; i < _entries.Length; i++)
            if (EqualityComparer<V>.Default.Equals(_entries![i].value, value))
                return true;

        return false;
    }

    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    public bool TryGetValue(K key, [MaybeNullWhen(false)] out V value)
    {
        ref var entry = ref FindEntry(key);
        if (Unsafe.IsNullRef(ref entry))
        {
            value = default;
            return false;
        }

        value = entry.value;
        return true;
    }

    ///<summary>
    ///Gets a reference to the value associated with the specified key, adding a provided default value if the key does not exist.
    ///</summary>
    ///<param name="key">The key to search for.</param>
    ///<param name="defaultValue">The value to add if the key does not exist.</param>
    ///<param name="exists">When this method returns, contains <c>true</c> if the key already existed; otherwise, <c>false</c>.</param>
    ///<returns>A reference to the value associated with the specified key.</returns>
    ///<remarks>
    ///Note: Do not add or remove items from the map while holding this reference, as triggering a resize of the internal arrays will invalidate it.
    ///</remarks>
    public ref V GetValueRefOrAddDefault(K key, V defaultValue, out bool exists)
    {
        if (_buckets == null)
            Initialize(DefaultCapacity);

        var entries = _entries!;
        if (entries.Length <= _loSize + _hiSize)
        {
            Resize(entries.Length * 2);
            entries = _entries!;
        }

        ref var bucket = ref GetBucket((uint)key.GetHashCode());
        ref var entries0 = ref MemoryMarshal.GetArrayDataReference(entries);

        int dstIndex;
        if (bucket == 0)
            dstIndex = entries.Length - 1 - _hiSize++;
        else
        {
            //Cache links0 only for the read-only chain walk. Post-walk insert may
            //Array.Resize(_links) and invalidate this ref, so the write uses _links! directly.
            ref var links0 = ref MemoryMarshal.GetArrayDataReference(_links!);
            var loSize = _loSize;
            for (uint i = bucket - 1, collisions = 0;;)
            {
                ref var entry = ref Unsafe.Add(ref entries0, i);
                if (EqualityComparer<K>.Default.Equals(entry.key, key))
                {
                    exists = true;
                    return ref entry.value;
                }

                if (loSize <= i)
                    break;
                i = Unsafe.Add(ref links0, i);
                if (loSize + 1 < collisions++)
                    throw new InvalidOperationException("Concurrent operations not supported.");
            }

            if (_links!.Length == (dstIndex = _loSize++))
                Array.Resize(ref _links, Math.Max(16, Math.Min(_buckets!.Length, _links.Length * 2)));
            _links[dstIndex] = bucket - 1;
        }

        ref var newEntry = ref Unsafe.Add(ref entries0, dstIndex);
        newEntry.key = key;
        newEntry.value = defaultValue;
        bucket = (uint)(dstIndex + 1);
        _version++;
        exists = false;
        return ref newEntry.value;
    }

    ///<summary>
    ///Rebuilds the table at <paramref name="newSize"/>, re-inserting every old entry.
    ///<para>
    ///<b>Memory win — pre-size <c>_links</c> once.</b> The previous implementation called a per-entry
    ///<c>Copy</c> helper that doubled <c>_links</c> from 16 → 32 → 64 → … → roundUpPowerOf2(N) as
    ///entries streamed in. For a Resize that re-inserts ~75 000 lo-entries (typical at 100k load),
    ///that's ~13 <c>Array.Resize</c> calls allocating cumulatively <b>~1 MB</b> of arrays that all
    ///become garbage, plus the final ~512 KB kept array. By passing the precise <c>linksHint</c> to
    ///<c>Initialize</c>, we make <b>zero</b> intermediate allocations and the kept array is right-sized.
    ///</para>
    ///<para><b>Speed win — hoist hot fields.</b> The per-entry rebuild loop reads <c>_buckets</c>,
    ///<c>_mask</c>, <c>_hiSize</c>, <c>_loSize</c> on every iteration. The JIT cannot hoist them across
    ///the <c>_hiSize++</c>/<c>_loSize++</c> writes (it cannot prove the writes don't alias other field
    ///loads), so they compile to repeated memory loads. We hoist them into locals (<c>buckets0</c>,
    ///<c>mask</c>, <c>hiSize</c>, <c>loSize</c>) and write back at the end. Combined with cached
    ///<c>Unsafe.Add</c> refs and no JIT bounds checks, the loop body reduces to register-only work plus
    ///the unavoidable hash + memory writes.</para>
    ///</summary>
    private int Resize(int newSize)
    {
        _version++;
        var oldEntries = _entries;
        var oldLoSize = _loSize;
        var oldHiSize = _hiSize;
        var oldEnd = oldEntries!.Length;
        var oldHiStart = oldEnd - oldHiSize;

        //Pass the precise linksHint so Initialize sizes _links to fit all surviving entries
        //worst-case (every old entry could re-collide into lo). No throwaway 16-element alloc.
        var totalEntries = oldLoSize + oldHiSize;
        Initialize(newSize, totalEntries);

        ref var oldEntries0 = ref MemoryMarshal.GetArrayDataReference(oldEntries);
        ref var entries0 = ref MemoryMarshal.GetArrayDataReference(_entries!);
        ref var links0 = ref MemoryMarshal.GetArrayDataReference(_links!);
        ref var buckets0 = ref MemoryMarshal.GetArrayDataReference(_buckets!);
        var mask = _mask;
        var newEnd = _entries!.Length;
        var loSize = 0;
        var hiSize = 0;

        //Re-insert lo region [0..oldLoSize)
        for (var i = 0; i < oldLoSize; i++)
        {
            ref var entry = ref Unsafe.Add(ref oldEntries0, i);
            ref var bucket = ref Unsafe.Add(ref buckets0, (nint)((uint)entry.key.GetHashCode() & mask));
            var prev = (int)bucket - 1;
            int dstIndex;

            if (prev == -1)
                dstIndex = newEnd - 1 - hiSize++;
            else
            {
                dstIndex = loSize++; //pre-sized: never resizes here
                Unsafe.Add(ref links0, dstIndex) = (uint)prev;
            }

            Unsafe.Add(ref entries0, dstIndex) = entry;
            bucket = (uint)(dstIndex + 1);
        }

        //Re-insert hi region [oldHiStart..oldEnd)
        for (var i = oldHiStart; i < oldEnd; i++)
        {
            ref var entry = ref Unsafe.Add(ref oldEntries0, i);
            ref var bucket = ref Unsafe.Add(ref buckets0, (nint)((uint)entry.key.GetHashCode() & mask));
            var prev = (int)bucket - 1;
            int dstIndex;

            if (prev == -1)
                dstIndex = newEnd - 1 - hiSize++;
            else
            {
                dstIndex = loSize++;
                Unsafe.Add(ref links0, dstIndex) = (uint)prev;
            }

            Unsafe.Add(ref entries0, dstIndex) = entry;
            bucket = (uint)(dstIndex + 1);
        }

        _loSize = loSize;
        _hiSize = hiSize;
        return newSize;
    }

    //Moves data from src index to dst index and updates all links pointing to src.
    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    private void Move(int src, int dst, ref Entry dstEntry)
    {
        //Move is private and called only from Remove (three sites). Centralizing the
        //version bump here removes the duplicated `_version++` from each Remove branch
        //and still bumps once per Remove (including the src == dst early-return case).
        _version++;
        if (src == dst)
            return;

        //Skip the array-bounds checks: src < _entries.Length and the chain-walked
        //indices are bounded by the same. Same trick the BCL uses internally.
        ref var entries0 = ref MemoryMarshal.GetArrayDataReference(_entries!);
        ref var links0 = ref MemoryMarshal.GetArrayDataReference(_links!);
        ref var srcEntry = ref Unsafe.Add(ref entries0, src);
        ref var srcBucket = ref GetBucket((uint)srcEntry.key.GetHashCode());
        var index = (int)srcBucket - 1;

        if (index == src)
            srcBucket = (uint)(dst + 1);
        else
        {
            ref var link = ref Unsafe.Add(ref links0, index);
            while (link != src)
            {
                index = (int)link;
                link = ref Unsafe.Add(ref links0, index);
            }

            link = (uint)dst;
        }

        if (src < _loSize)
            Unsafe.Add(ref links0, dst) = Unsafe.Add(ref links0, src);

        dstEntry = srcEntry;
    }

    ///<summary>
    ///Removes <paramref name="key"/> if present.
    ///<para>Index-based chain walk (no <c>ref</c> aliasing across iterations) so the JIT can keep
    ///the loop in registers. Tracks the immediate predecessor (<c>prev</c>) and pre-predecessor
    ///(<c>prevPrev</c>) so the hi-terminator migration case rewires the back-pointer in O(1).
    ///Hot fields (<c>_entries</c>, <c>_links</c>, <c>_loSize</c>) are hoisted into locals.</para>
    ///</summary>
    public bool Remove(K key)
    {
        if (_loSize + _hiSize == 0)
            return false;

        ref var bucket = ref GetBucket((uint)key.GetHashCode());
        var idx = (int)bucket - 1;
        if (idx < 0)
            return false;

        var loSize = _loSize;
        ref var entries0 = ref MemoryMarshal.GetArrayDataReference(_entries!);

        //Chain length 1 (entry sits in hi as the original empty-bucket placement).
        ref var e = ref Unsafe.Add(ref entries0, idx);
        if (loSize <= idx)
        {
            if (!EqualityComparer<K>.Default.Equals(e.key, key))
                return false;
            Move(_entries!.Length - _hiSize, idx, ref e);
            _hiSize--;
            bucket = 0;
            return true;
        }

        ref var links0 = ref MemoryMarshal.GetArrayDataReference(_links!);
        var prev = -1;
        var prevPrev = -1;

        for (var collisions = 0;
             !EqualityComparer<K>.Default.Equals(e.key, key);
             prevPrev = prev,
                 e = ref Unsafe.Add(ref entries0, idx = (int)Unsafe.Add(ref links0, prev = idx)))
        {
            if (idx >= loSize)
                return false;
            if (++collisions > loSize)
                throw new InvalidOperationException("Hash collision chain is unexpectedly long. Possible data corruption.");
        }

        var lastLo = loSize - 1;
        if (idx < loSize)
        {
            //Standard removal: rewire (prev or bucket) → next; compact lo by swap-with-last.
            //Single read of the matched entry's link; both branches consume `next`.
            var next = Unsafe.Add(ref links0, idx);
            if (prev < 0)
                bucket = next + 1;
            else
                Unsafe.Add(ref links0, prev) = next;
            Move(lastLo, idx, ref e);
        }
        else
        {
            //Found at hi-terminator with chain length ≥ 2. Migrate prev (lo) into the hi slot
            //so the chain still terminates in hi; prev's lo slot becomes the hole.
            ref var prevEntry = ref Unsafe.Add(ref entries0, prev);
            e = prevEntry;
            if (prevPrev < 0)
                bucket = (uint)(idx + 1);
            else
                Unsafe.Add(ref links0, prevPrev) = (uint)idx;
            Move(lastLo, prev, ref prevEntry);
        }

        _loSize = lastLo;
        return true;
    }

    bool ICollection<KeyValuePair<K, V>>.Remove(KeyValuePair<K, V> item) => TryGetValue(item.Key, out var value) && EqualityComparer<V>.Default.Equals(value, item.Value) && Remove(item.Key);

