    ///<summary>Attempts to add the specified key and value. Returns false if the key already exists.</summary>
    ///<remarks>Native implementation. Avoids the BCL <c>IDictionary&lt;K,V&gt;</c> extension method's
    ///double dispatch (ContainsKey + Add).</remarks>
    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    public bool TryAdd(K key, V value) => TryInsert(key, value, false);

    ///<summary>
    ///Internal finder: the index of the key, or -1. Walks the keys alone.
    ///AggressiveInlining so callers (TryGetValue, ContainsKey, indexer) inline the body — the
    ///indexer was 4× slower than direct TryGetValue without this fix. The chain past its head is
    ///<see cref="FindInChain"/>: its length check calls a thrower, and a call in the loop made the JIT save
    ///7 registers at every lookup ( a hit 3.0 ns against 2.2 ).
    ///</summary>
    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    private int FindIndex(K key)
    {
        var buckets = _buckets;
        if (buckets == null)
            return -1;

        var i = (int)Unsafe.Add(ref MemoryMarshal.GetArrayDataReference(buckets), (nint)(Hash(key) & (uint)(buckets.Length - 1))) - 1; //the mask of the array read, not _mask: a lookup racing a resize stays in bounds
        if (i < 0)
            return -1;
        if (EqualityComparer<K>.Default.Equals(_entries![i], key)) //the reads of a lookup keep their bounds checks: one racing a resize stays in bounds
            return i;
        return _loSize <= i ? -1 : FindInChain(i, key);
    }

    ///<summary>The index of <paramref name="key"/> in the chain past its lo entry <paramref name="i"/>, or -1.</summary>
    [MethodImpl(MethodImplOptions.NoInlining)]
    private int FindInChain(int i, K key)
    {
        var keys = _entries!;
        var links = _links!;
        var loSize = _loSize;
        for (var budget = loSize;;)
        {
            i = (int)links[i];
            if (EqualityComparer<K>.Default.Equals(keys[i], key))
                return i;
            if (loSize <= i)
                return -1;
            if (--budget < 0)
                ThrowChainTooLong();
        }
    }

    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    private bool TryInsert(K key, V value, bool overwrite)
    {
        if (_buckets == null)
            Initialize(DefaultCapacity);

        ref var bucket = ref GetBucket(Hash(key));
        if (bucket != 0)
        {
            var i = (int)bucket - 1;
            if (!EqualityComparer<K>.Default.Equals(_entries![i], key))
                i = _loSize <= i ? -1 : FindInChain(i, key);
            if (0 <= i)
            {
                if (overwrite)
                    Unsafe.Add(ref MemoryMarshal.GetArrayDataReference(_vals!), i) = value;
                return false;
            }
        }

        if (_entries!.Length <= _loSize + _hiSize)
            GrowAndAdd(key, value);
        else
            AddNew(ref bucket, key, value);
        return true;
    }
    //The key is known to be absent and the table has a free entry slot.
    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    private ref V AddNew(ref uint bucket, K key, V value)
    {
        var keys = _entries!;
        var head = bucket;
        int dstIndex;
        if (head == 0)
            dstIndex = keys.Length - 1 - _hiSize++;
        else
        {
            if (_links!.Length == (dstIndex = _loSize++))
                Array.Resize(ref _links, Math.Max(16, Math.Min(keys.Length, _links.Length * 2)));
            _links[dstIndex] = (uint)(head - 1);
        }
        Unsafe.Add(ref MemoryMarshal.GetArrayDataReference(keys), dstIndex) = key;
        ref var v = ref Unsafe.Add(ref MemoryMarshal.GetArrayDataReference(_vals!), dstIndex);
        v = value;
        bucket = (uint)(dstIndex + 1);
        return ref v;
    }

    [MethodImpl(MethodImplOptions.NoInlining)]
    private ref V GrowAndAdd(K key, V value)
    {
        Resize(_entries!.Length * 2);
        return ref AddNew(ref GetBucket(Hash(key)), key, value);
    }

