    public struct Enumerator : IEnumerator<KeyValuePair<K, V>>
    {
        //Snapshot the layout at construction so MoveNext only reads instance fields when
        //version-checking. Field reads on a heap object cost a load + a possible cache miss
        //per call; locals stay in registers across the iteration.
        private readonly PrimitiveKeyMap<K, V> _map;
        private readonly Entry[]? _entries;
        private readonly int _loEnd;
        private readonly int _hiStart;
        private readonly int _hiEnd;
        private readonly int _version;
        private int _index; //-1 = not started, -2 = finished, else current index
        private KeyValuePair<K, V> _current;

        internal Enumerator(PrimitiveKeyMap<K, V> map)
        {
            _map = map;
            _version = map._version;
            _entries = map._entries;
            _loEnd = map._loSize;
            _hiEnd = _entries?.Length ?? 0;
            _hiStart = _hiEnd - map._hiSize;
            _index = -1;
            _current = default;
        }

        [MethodImpl(MethodImplOptions.AggressiveInlining)]
        public bool MoveNext()
        {
            if (_version != _map._version)
                throw new InvalidOperationException("Collection was modified during enumeration.");
            if (_index == -2)
                return false; //already finished — calling MoveNext again is allowed and must keep returning false

            var i = _index + 1;
            if (i == _loEnd)
                i = _hiStart;
            if (i >= _hiEnd)
            {
                _index = -2;
                return false;
            }

            //Skip the array-bounds check: we just verified i < _hiEnd ≤ _entries.Length,
            //so the JIT-generated bounds check on _entries![i] is provably redundant.
            ref var entry = ref Unsafe.Add(ref MemoryMarshal.GetArrayDataReference(_entries!), i);
            _current = new KeyValuePair<K, V>(entry.key, entry.value);
            _index = i;
            return true;
        }

        //BCL Dictionary semantics: bare field read, no per-access checks.
        //Concurrent-modification detection lives in MoveNext.
        public KeyValuePair<K, V> Current
        {
            [MethodImpl(MethodImplOptions.AggressiveInlining)]
            get => _current;
        }

        object? IEnumerator.Current => Current;

        public void Reset()
        {
            if (_version != _map._version)
                throw new InvalidOperationException("Collection was modified during enumeration.");
            _index = -1;
            _current = default;
        }

        public void Dispose() {}
    }

    public int EnsureCapacity(int capacity)
    {
        ArgumentOutOfRangeException.ThrowIfNegative(capacity);
        var currentCapacity = _entries?.Length ?? 0;
        if (currentCapacity >= capacity)
            return currentCapacity;
        _version++;
        if (_buckets == null)
            return Initialize(capacity);
        var newSize = GetPowerOfTwo(capacity);
        Resize(newSize);
        return newSize;
    }

    public void TrimExcess()
    {
        var count = Count;
        if (count == 0)
        {
            Initialize(0);
            return;
        }

        if (_entries == null)
            return;
        var newSize = GetPowerOfTwo(count);
        if (newSize < _entries.Length)
            Resize(newSize);
    }
