///<summary>
///Hash map with primitive (unmanaged) keys, optimized for top throughput and minimal GC pressure.
///<para><b>Storage layout (current — selected design):</b></para>
///<para>
///The keys <c>_entries</c> and the values <c>_vals</c> lie apart, at the same index: a lookup walks the keys alone and reads
///a value on a hit only. Measured against one array of key-value entries ( int -> long, one P-core ): a lookup of 1 000
///keys 2.3-2.7 -> 1.9-2.0 ns, of 100 000 4.8-5.2 -> 4.45-4.55, churn -5%. A filter byte of hash classes per bucket was
///measured too and left out: misses of 100 000 keys twice as cheap, hits and inserts 5-20% dearer.
///The slots are split into two regions to optimize for the common case where most entries do not collide:
///</para>
///<list type="bullet">
///<item><b>Hi-region</b> [<c>_entries.Length - _hiSize .. _entries.Length</c>) — chain terminators
///(entries placed when their bucket was empty). They have no successor; the chain ends there.</item>
///<item><b>Lo-region</b> [<c>0 .. _loSize</c>) — collision-chain elements. Their successor index is
///stored in a separate side array <c>_links</c> sized only to <c>_loSize</c> (not capacity), so the
///memory cost is paid only when collisions actually occur.</item>
///</list>
///<para>
///Chain termination is detected implicitly by the bound <c>_loSize &lt;= i</c> while walking — no
///sentinel and no per-hop region flag are needed. The chain walk reads <c>_entries[i]</c> and, on a
///miss, follows <c>_links[i]</c>; both arrays are touched but <c>_entries</c> is the dominant working
///set and the JIT keeps its reference hot across the loop.
///</para>
///
///<para><b>Alternative considered: Option D — split <c>LoEntry</c>/<c>HiEntry</c> types</b></para>
///<para>
///An obvious "fix" to the second-array fetch on collision walks is to inline the next-pointer into
///each entry, Dictionary-style. To keep the hi-region tight (the merit of the dual-region design),
///the natural answer is two distinct entry types in two arrays:
///</para>
///<code>
///struct LoEntry { uint next; K key; V value; }   // collision-chain elements
///struct HiEntry { K key; V value; }              // chain terminators
///LoEntry[] _loEntries; HiEntry[] _hiEntries;     // bucket value encodes region in its high bit
///</code>
///<para>
///This was prototyped and benchmarked. Result against the current design (random <c>int</c> keys at
///~78% load factor):
///</para>
///<list type="bullet">
///<item><c>Add</c>: +38% (good — chain walk during duplicate detection benefits from one less load).</item>
///<item><c>TryGet</c>: <b>-35%</b> (bad — every lookup pays a region-flag branch, mask/decode of the
///bucket value, and dispatches between two arrays even on the hot length-0/1 path).</item>
///<item><c>foreach</c>: -10% (walks two arrays instead of one).</item>
///</list>
///<para>
///<b>Why Option D was not selected:</b> with a well-distributed hash and a load factor &lt;= 0.75,
///roughly 82% of buckets are length 0 or 1, where the inlined-next saving buys nothing because there
///is no chain hop. Option D's overhead, however, is paid on every lookup. Real workloads are
///lookup-dominated and have rare collisions; the current design's tight hi-region entries plus a
///single shared <c>_entries</c> array win in that regime. Option D would only pay off on adversarial
///hash distributions or sustained load factor &gt; 0.85, neither of which is the target use case.
///</para>
///<para>
///For posterity: a forced-collision benchmark (keys whose hashes all map to one bucket) would expose
///Option D's chain-walk advantage and is the right diagnostic if the workload assumption ever changes.
///</para>
///
///<para><b>Benchmark vs <c>Dictionary&lt;int,int&gt;</c></b> (N = 100 000, random int keys, .NET 9, Release;
///median of 7–10 runs):</para>
///<code>
///Insert       Search          Get          Iterate       Delete       Churn   Insert(N)
///PrimitiveKeyMap&lt;int,int&gt;  46 210 721  189 035 917  157 625 707    1 529 051 988   55 000 000   61 195 230  111 204 664   ops/sec
///Dictionary                      1.10         0.65         0.74             0.85         0.85         0.76         0.73   x
///</code>
///<para><b>Memory profile (grow-from-empty Insert, 100 000 random int keys):</b>
///<list type="bullet">
///<item><c>PrimitiveKeyMap</c> allocates <b>36.71 B/op</b> (grow-from-empty Insert of 100 000 records)</item>
///<item><c>Dictionary</c> allocates <b>60.38 B/op</b></item>
///<item><c>PrimitiveKeyMap</c> saves <b>~23 664 B per 1 000 records</b> vs Dictionary</item>
///</list>
///</para>
///<para>
///Ratio &gt; 1 ⇒ <c>Dictionary</c> faster, &lt; 1 ⇒ <c>PrimitiveKeyMap</c> faster. PrimitiveKeyMap
///is 26–41% faster than Dictionary on every read path (Search/Get/Indexer), <b>~38% faster on
///pre-sized Insert</b> (Insert(N) column), and now beats Dictionary on Iterate, Delete, and Churn.
///The remaining ~10% gap on grow-from-empty Insert is structural: each Resize allocates three
///parallel arrays (<c>_buckets</c>, <c>_entries</c>, <c>_links</c>) where Dictionary allocates two,
///and Resize re-insertions write to two cache lines per entry (entry + link) where Dictionary's
///inline-<c>next</c> Entry hits one. The dual-region layout pays for that on Resize and recovers it
///many times over on every read. The chain-walk speed-up came from skipping JIT-emitted array-bounds
///checks (<c>Unsafe.Add</c> + <c>MemoryMarshal.GetArrayDataReference</c> on
///<c>_entries</c>/<c>_links</c>); the Resize speed-up came from hoisting <c>_buckets</c>,
///<c>_mask</c>, <c>_hiSize</c>, <c>_loSize</c> into locals so the per-entry rebuild loop runs
///entirely from registers, with local arrays published after rebuilding.
///</para>
///<para>See <c>Tests/Benchmarks/PrimitiveKeyMapBenchmark.cs</c> for the full scenarios and an HTML report.</para>
///<para>Historical benchmark figures predate hash mixing and two buckets per entry slot.
///Re-run the benchmarks for the current layout; see <c>BucketsFor</c> and <c>LinksFor</c> for tuning.</para>
///</summary>
///<typeparam name="K">The unmanaged primitive key type.</typeparam>
///<typeparam name="V">The value type.</typeparam>
[DebuggerDisplay("Count = {Count}")]
public class PrimitiveKeyMap<K, V> : IDictionary<K, V>, IReadOnlyDictionary<K, V>
