    public int Count
    {
        [MethodImpl(MethodImplOptions.AggressiveInlining)]
        get => _loSize + _hiSize;
    }

    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    public bool Add(K key)
    {
        if (_buckets == null)
            Initialize(DefaultCapacity);

        var keys = _keys!;
        if (keys.Length <= _loSize + _hiSize)
        {
            Resize(keys.Length * 2);
            keys = _keys!;
        }

        ref var bucket = ref GetBucket((uint)key.GetHashCode());
        var index = (int)bucket - 1;

        ref var keysRef = ref MemoryMarshal.GetArrayDataReference(keys);
        int dstIndex;

        if (index == -1) //Bucket is empty: place new entry in hi-region
            dstIndex = keys.Length - 1 - _hiSize++;
        else
        {
            ref var linksRef = ref MemoryMarshal.GetArrayDataReference(_links!);
            var loSize = _loSize;
            for (int i = index, collisions = 0;;)
            {
                if (EqualityComparer<K>.Default.Equals(Unsafe.Add(ref keysRef, i), key))
                    return false;

                if (loSize <= i)
                    break; //Reached a hi-region entry, end of this chain.
                i = (int)Unsafe.Add(ref linksRef, i);

                if (loSize + 1 < collisions++)
                    throw new InvalidOperationException("Concurrent operations not supported.");
            }

            if (_links!.Length == (dstIndex = _loSize++))
                Array.Resize(ref _links, Math.Max(16, Math.Min(_buckets!.Length, _links.Length * 2)));

            //Re-fetch links ref (Array.Resize may have allocated a new array).
            Unsafe.Add(ref MemoryMarshal.GetArrayDataReference(_links!), dstIndex) = (uint)index;
        }

        Unsafe.Add(ref keysRef, dstIndex) = key;
        bucket = (uint)(dstIndex + 1);
        _version++;
        return true;
    }

    void ICollection<K>.Add(K key) => Add(key);

    public void Clear()
    {
        if (Count == 0)
            return;

        _version++;

        if (_buckets != null)
            Array.Clear(_buckets, 0, _buckets.Length);
        _loSize = 0;
        _hiSize = 0;
    }

    public bool Contains(K key)
    {
        if (_loSize + _hiSize == 0)
            return false;

        var i = (int)GetBucket((uint)key.GetHashCode()) - 1;
        if (i == -1)
            return false;

        ref var keysRef = ref MemoryMarshal.GetArrayDataReference(_keys!);
        ref var linksRef = ref MemoryMarshal.GetArrayDataReference(_links!);
        var loSize = _loSize;

        for (var collisions = 0;;)
        {
            if (EqualityComparer<K>.Default.Equals(Unsafe.Add(ref keysRef, i), key))
                return true;

            if (loSize <= i)
                return false; //Reached end of chain (a hi-region entry)
            i = (int)Unsafe.Add(ref linksRef, i);

            if (loSize < ++collisions)
                throw new InvalidOperationException("Hash collision chain is unexpectedly long. Possible data corruption.");
        }
    }

    public void CopyTo(K[] dst, int dstIndex)
    {
        ArgumentNullException.ThrowIfNull(dst);
        ArgumentOutOfRangeException.ThrowIfGreaterThanOrEqual((uint)dstIndex, (uint)dst.Length);
        if (dst.Length - dstIndex < Count)
            throw new ArgumentException("Destination array is not long enough.");

        //Copy lo-region
        Array.Copy(_keys!, 0, dst, dstIndex, _loSize);
        //Copy hi-region
        Array.Copy(_keys!, _keys!.Length - _hiSize, dst, dstIndex + _loSize, _hiSize);
    }

    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    private int Initialize(int capacity, int linksHint = 16)
    {
        _version++;

        var size = GetPowerOfTwo(capacity);
        _buckets = new uint[size];
        _keys = new K[size];
        _links = new uint[Math.Min(size, linksHint)];
        _loSize = _hiSize = 0;
        _mask = (uint)(size - 1);

        return size;
    }

    private static int GetPowerOfTwo(int capacity) => capacity <= DefaultCapacity ? DefaultCapacity : (int)BitOperations.RoundUpToPowerOf2((uint)capacity);

    ///<summary>
    ///Rebuilds the table at <paramref name="newSize"/>, re-inserting every old key.
    ///<para>
    ///<b>Memory win — pre-size <c>_links</c> once.</b> The previous implementation called a per-entry
    ///<c>Copy</c> helper that doubled <c>_links</c> from 16 → 32 → 64 → … → roundUpPowerOf2(N) as
    ///entries streamed in. By passing the precise <c>linksHint</c> to <c>Initialize</c>, we make
    ///<b>zero</b> intermediate allocations and the kept array is right-sized.
    ///</para>
    ///<para><b>Speed win — hoist hot fields.</b> The per-entry rebuild loop reads <c>_buckets</c>,
    ///<c>_mask</c>, <c>_hiSize</c>, <c>_loSize</c> on every iteration. The JIT cannot hoist them across
    ///the <c>_hiSize++</c>/<c>_loSize++</c> writes, so they compile to repeated memory loads. We hoist
    ///them into locals (<c>buckets0</c>, <c>mask</c>, <c>hiSize</c>, <c>loSize</c>) and write back at
    ///the end. Combined with cached <c>Unsafe.Add</c> refs and no JIT bounds checks, the loop body
    ///reduces to register-only work plus the unavoidable hash + memory writes.</para>
    ///</summary>
    private int Resize(int newSize)
    {
        _version++;
        var oldKeys = _keys;
        var oldLoSize = _loSize;
        var oldHiSize = _hiSize;
        var oldEnd = oldKeys!.Length;
        var oldHiStart = oldEnd - oldHiSize;

        //Pass the precise linksHint so Initialize sizes _links to fit all surviving entries
        //worst-case (every old entry could re-collide into lo). No throwaway 16-element alloc.
        var totalEntries = oldLoSize + oldHiSize;
        Initialize(newSize, totalEntries);

        ref var oldKeys0 = ref MemoryMarshal.GetArrayDataReference(oldKeys);
        ref var keys0 = ref MemoryMarshal.GetArrayDataReference(_keys!);
        ref var links0 = ref MemoryMarshal.GetArrayDataReference(_links!);
        ref var buckets0 = ref MemoryMarshal.GetArrayDataReference(_buckets!);
        var mask = _mask;
        var newEnd = _keys!.Length;
        var loSize = 0;
        var hiSize = 0;

        //Re-insert lo region [0..oldLoSize)
        for (var i = 0; i < oldLoSize; i++)
        {
            var key = Unsafe.Add(ref oldKeys0, i);
            ref var bucket = ref Unsafe.Add(ref buckets0, (nint)((uint)key.GetHashCode() & mask));
            var prev = (int)bucket - 1;
            int dstIndex;

            if (prev == -1)
                dstIndex = newEnd - 1 - hiSize++;
            else
            {
                dstIndex = loSize++; //pre-sized: never resizes here
                Unsafe.Add(ref links0, dstIndex) = (uint)prev;
            }

            Unsafe.Add(ref keys0, dstIndex) = key;
            bucket = (uint)(dstIndex + 1);
        }

        //Re-insert hi region [oldHiStart..oldEnd)
        for (var i = oldHiStart; i < oldEnd; i++)
        {
            var key = Unsafe.Add(ref oldKeys0, i);
            ref var bucket = ref Unsafe.Add(ref buckets0, (nint)((uint)key.GetHashCode() & mask));
            var prev = (int)bucket - 1;
            int dstIndex;

            if (prev == -1)
                dstIndex = newEnd - 1 - hiSize++;
            else
            {
                dstIndex = loSize++;
                Unsafe.Add(ref links0, dstIndex) = (uint)prev;
            }

            Unsafe.Add(ref keys0, dstIndex) = key;
            bucket = (uint)(dstIndex + 1);
        }

        _loSize = loSize;
        _hiSize = hiSize;
        return newSize;
    }

    //Moves data from src index to dst index and updates all links pointing to src.
    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    private void Move(int src, int dst, ref K dstKey)
    {
        //Move is private and called only from Remove (three sites). Centralizing the
        //version bump here removes the duplicated `_version++` from each Remove branch
        //and still bumps once per Remove (including the src == dst early-return case).
        _version++;
        if (src == dst)
            return;

        //Skip the array-bounds checks: src < _keys.Length and the chain-walked
        //indices are bounded by the same. Same trick the BCL uses internally.
        ref var keys0 = ref MemoryMarshal.GetArrayDataReference(_keys!);
        ref var links0 = ref MemoryMarshal.GetArrayDataReference(_links!);
        ref var srcKey = ref Unsafe.Add(ref keys0, src);
        ref var srcBucket = ref GetBucket((uint)srcKey.GetHashCode());
        var index = (int)srcBucket - 1;

        if (index == src)
            srcBucket = (uint)(dst + 1);
        else
        {
            ref var link = ref Unsafe.Add(ref links0, index);
            while (link != src)
            {
                index = (int)link;
                link = ref Unsafe.Add(ref links0, index);
            }
            link = (uint)dst;
        }

        if (src < _loSize)
            Unsafe.Add(ref links0, dst) = Unsafe.Add(ref links0, src);

        dstKey = srcKey;
    }

    ///<summary>
    ///Removes <paramref name="key"/> if present.
    ///<para>Index-based chain walk (no <c>ref</c> aliasing across iterations) so the JIT can keep
    ///the loop in registers. Tracks <c>prev</c>/<c>prevPrev</c> indices so the hi-terminator
    ///migration case rewires the back-pointer in O(1).</para>
    ///</summary>
    public bool Remove(K key)
    {
        if (_loSize + _hiSize == 0)
            return false;

        ref var bucket = ref GetBucket((uint)key.GetHashCode());
        var idx = (int)bucket - 1;
        if (idx < 0)
            return false;

        var loSize = _loSize;
        ref var keys0 = ref MemoryMarshal.GetArrayDataReference(_keys!);

        ref var k = ref Unsafe.Add(ref keys0, idx);
        if (loSize <= idx)
        {
            if (!EqualityComparer<K>.Default.Equals(k, key))
                return false;
            Move(_keys!.Length - _hiSize, idx, ref k);
            _hiSize--;
            bucket = 0;
            return true;
        }

        ref var links0 = ref MemoryMarshal.GetArrayDataReference(_links!);
        var prev = -1;
        var prevPrev = -1;

        for (var collisions = 0;
             !EqualityComparer<K>.Default.Equals(k, key);
             prevPrev = prev,
                 k = ref Unsafe.Add(ref keys0, idx = (int)Unsafe.Add(ref links0, prev = idx)))
        {
            if (idx >= loSize)
                return false;
            if (++collisions > loSize)
                throw new InvalidOperationException("Hash collision chain is unexpectedly long. Possible data corruption.");
        }

        var lastLo = loSize - 1;
        if (idx < loSize)
        {
            //Standard removal: rewire (prev or bucket) → next; compact lo by swap-with-last.
            //Single read of the matched entry's link; both branches consume `next`.
            var next = Unsafe.Add(ref links0, idx);
            if (prev < 0)
                bucket = next + 1;
            else
                Unsafe.Add(ref links0, prev) = next;
            Move(lastLo, idx, ref k);
        }
        else
        {
            //Found at hi-terminator with chain length ≥ 2. Migrate prev (lo) into the hi slot
            //so the chain still terminates in hi; prev's lo slot becomes the hole.
            ref var prevKey = ref Unsafe.Add(ref keys0, prev);
            k = prevKey;
            if (prevPrev < 0)
                bucket = (uint)(idx + 1);
            else
                Unsafe.Add(ref links0, prevPrev) = (uint)idx;
            Move(lastLo, prev, ref prevKey);
        }

        _loSize = lastLo;
        return true;
    }

