    public int Count
    {
        [MethodImpl(MethodImplOptions.AggressiveInlining)]
        get => _loSize + _hiSize;
    }

    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    public bool Add(K key)
    {
        if (_buckets == null)
            Initialize(DefaultCapacity);

        ref var bucket = ref GetBucket(Hash(key));
        if (bucket != 0)
        {
            var keys = _keys!;
            var links = _links!;
            var loSize = _loSize;
            for (int i = (int)bucket - 1, collisions = 0;;)
            {

                if (EqualityComparer<K>.Default.Equals(keys[i], key))
                {
                    return false;
                }
                if (loSize <= i)
                    break;
                i = (int)links[i];
                if (loSize + 1 < collisions++)
                    ThrowConcurrentOperation();
            }
        }

        if (_keys!.Length <= _loSize + _hiSize)
            GrowAndAdd(key);
        else
            AddNew(ref bucket, key);
        return true;
    }
    //The key is known to be absent and the table has a free entry slot.
    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    private void AddNew(ref uint bucket, K key)
    {
        var keys = _keys!;
        var head = bucket;
        int dstIndex;
        if (head == 0)
            dstIndex = keys.Length - 1 - _hiSize++;
        else
        {
            if (_links!.Length == (dstIndex = _loSize++))
                Array.Resize(ref _links, Math.Max(16, Math.Min(keys.Length, _links.Length * 2)));
            _links[dstIndex] = (uint)(head - 1);
        }
        keys[dstIndex] = key;

        bucket = (uint)(dstIndex + 1);
        _version++;
    }

    [MethodImpl(MethodImplOptions.NoInlining)]
    private void GrowAndAdd(K key)
    {
        Resize(_keys!.Length * 2);
        AddNew(ref GetBucket(Hash(key)), key);
    }

    void ICollection<K>.Add(K key) => Add(key);

    public void Clear()
    {
        if (Count == 0)
            return;

        _version++;

        if (_buckets != null)
            if ((_loSize + _hiSize) * 8 <= _buckets.Length) //a few entries in a large table: only their buckets ( a map received pack after pack, once large: 1.9 µs -> 20 ns )
            {
                var k = _keys!;
                for (var i = 0; i < _loSize; i++)
                    GetBucket(Hash(k[i])) = 0;
                for (var i = k.Length - _hiSize; i < k.Length; i++)
                    GetBucket(Hash(k[i])) = 0;
            }
            else
                Array.Clear(_buckets, 0, _buckets.Length);
        _loSize = 0;
        _hiSize = 0;
    }

    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    public bool Contains(K key)
    {
        var buckets = _buckets;
        if (buckets == null)
            return false;

        var i = (int)Unsafe.Add(ref MemoryMarshal.GetArrayDataReference(buckets), (nint)(Hash(key) & (uint)(buckets.Length - 1))) - 1;
        if (i < 0)
            return false;
        var keys = _keys!;
        if (EqualityComparer<K>.Default.Equals(keys[i], key))
            return true;
        var loSize = _loSize;
        if (loSize <= i)
            return false;
        var links = _links!;
        for (var budget = loSize;;)
        {
            i = (int)links[i];
            if (EqualityComparer<K>.Default.Equals(keys[i], key))
                return true;
            if (loSize <= i)
                return false;
            if (--budget < 0)
                ThrowChainTooLong();
        }
    }

    public void CopyTo(K[] dst, int dstIndex)
    {
        ArgumentNullException.ThrowIfNull(dst);
        ArgumentOutOfRangeException.ThrowIfGreaterThanOrEqual((uint)dstIndex, (uint)dst.Length);
        if (dst.Length - dstIndex < Count)
            throw new ArgumentException("Destination array is not long enough.");

        //Copy lo-region
        Array.Copy(_keys!, 0, dst, dstIndex, _loSize);
        //Copy hi-region
        Array.Copy(_keys!, _keys!.Length - _hiSize, dst, dstIndex + _loSize, _hiSize);
    }

    //speed_up selects two buckets per entry slot; otherwise one. Links grow on demand.
    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    private int BucketsFor(int size) => _speedUp && size < 1 << 30 ? size << 1 : size;

    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    private static int LinksFor(int size) => Math.Max(Math.Min(size, 16), size >> 2);

    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    private static uint MixHash(uint h) => h ^ (h >> 8) ^ (h >> 13) ^ (h >> 24);

    [DoesNotReturn]
    [MethodImpl(MethodImplOptions.NoInlining)]
    private static void ThrowChainTooLong() => throw new InvalidOperationException("Hash collision chain is unexpectedly long. Possible data corruption.");

    [DoesNotReturn]
    [MethodImpl(MethodImplOptions.NoInlining)]
    private static void ThrowConcurrentOperation() => throw new InvalidOperationException("Concurrent operations not supported.");

    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    private static uint Hash(K key) => MixHash((uint)key.GetHashCode());

    private int Initialize(int capacity)
    {
        _version++;

        var size = GetPowerOfTwo(capacity);
        var bucketCount = BucketsFor(size);
        _buckets = new uint[bucketCount];
        _keys = new K[size];
        _links = new uint[LinksFor(size)];
        _loSize = _hiSize = 0;
        _mask = (uint)(bucketCount - 1);

        return size;
    }

    private static int GetPowerOfTwo(int capacity) => capacity <= DefaultCapacity ? DefaultCapacity : (int)BitOperations.RoundUpToPowerOf2((uint)capacity);

    ///<summary>Rebuilds into local arrays, growing links on demand, then publishes the completed table.</summary>
    private int Resize(int newSize)
    {
        _version++;
        var oldData = _keys!;
        var oldLoSize = _loSize;
        var oldEnd = oldData.Length;
        var oldHiStart = oldEnd - _hiSize;
        var size = GetPowerOfTwo(newSize);
        var bucketCount = BucketsFor(size);
        var buckets = new uint[bucketCount];
        var data = new K[size];
        var links = new uint[LinksFor(size)];
        var mask = (uint)(bucketCount - 1);
        ref var oldData0 = ref MemoryMarshal.GetArrayDataReference(oldData);
        ref var data0 = ref MemoryMarshal.GetArrayDataReference(data);
        ref var links0 = ref MemoryMarshal.GetArrayDataReference(links);
        ref var buckets0 = ref MemoryMarshal.GetArrayDataReference(buckets);
        var loSize = 0;
        var hi = size;

        for (var i = 0; i < oldLoSize; i++)
        {
            ref var entry = ref Unsafe.Add(ref oldData0, i);
            ref var bucket = ref Unsafe.Add(ref buckets0, (nint)(Hash(entry) & mask));
            var head = bucket;
            int dstIndex;
            if (head == 0)
                dstIndex = --hi;
            else
            {
                if (loSize == links.Length)
                {
                    Array.Resize(ref links, Math.Min(size, links.Length * 2));
                    links0 = ref MemoryMarshal.GetArrayDataReference(links);
                }
                Unsafe.Add(ref links0, dstIndex = loSize++) = (uint)(head - 1);
            }
            Unsafe.Add(ref data0, dstIndex) = entry;
            bucket = (uint)(dstIndex + 1);
        }

        for (var i = oldHiStart; i < oldEnd; i++)
        {
            ref var entry = ref Unsafe.Add(ref oldData0, i);
            ref var bucket = ref Unsafe.Add(ref buckets0, (nint)(Hash(entry) & mask));
            var head = bucket;
            int dstIndex;
            if (head == 0)
                dstIndex = --hi;
            else
            {
                if (loSize == links.Length)
                {
                    Array.Resize(ref links, Math.Min(size, links.Length * 2));
                    links0 = ref MemoryMarshal.GetArrayDataReference(links);
                }
                Unsafe.Add(ref links0, dstIndex = loSize++) = (uint)(head - 1);
            }
            Unsafe.Add(ref data0, dstIndex) = entry;
            bucket = (uint)(dstIndex + 1);
        }

        _buckets = buckets;
        _keys = data;
        _links = links;
        _mask = mask;
        _loSize = loSize;
        _hiSize = size - hi;
        return size;
    }

    //Moves data from src index to dst index and updates all links pointing to src.
    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    private void Move(int src, int dst, ref K dstKey)
    {
        //Move is private and called only from Remove (three sites). Centralizing the
        //version bump here removes the duplicated `_version++` from each Remove branch
        //and still bumps once per Remove (including the src == dst early-return case).
        _version++;
        if (src == dst)
            return;

        //Skip the array-bounds checks: src < _keys.Length and the chain-walked
        //indices are bounded by the same. Same trick the BCL uses internally.
        ref var keys0 = ref MemoryMarshal.GetArrayDataReference(_keys!);
        ref var links0 = ref MemoryMarshal.GetArrayDataReference(_links!);
        ref var srcKey = ref Unsafe.Add(ref keys0, src);
        ref var srcBucket = ref GetBucket(Hash(srcKey));
        var index = (int)srcBucket - 1;

        if (index == src)
            srcBucket = (uint)(dst + 1);
        else
        {
            ref var link = ref Unsafe.Add(ref links0, index);
            while (link != src)
            {
                index = (int)link;
                link = ref Unsafe.Add(ref links0, index);
            }
            link = (uint)dst;
        }

        if (src < _loSize)
            Unsafe.Add(ref links0, dst) = Unsafe.Add(ref links0, src);

        dstKey = srcKey;
    }

    ///<summary>
    ///Removes <paramref name="key"/> if present.
    ///<para>Index-based chain walk (no <c>ref</c> aliasing across iterations) so the JIT can keep
    ///the loop in registers. Tracks <c>prev</c>/<c>prevPrev</c> indices so the hi-terminator
    ///migration case rewires the back-pointer in O(1).</para>
    ///</summary>
    public bool Remove(K key)
    {
        if (_loSize + _hiSize == 0)
            return false;

        ref var bucket = ref GetBucket(Hash(key));
        var idx = (int)bucket - 1;
        if (idx < 0)
            return false;

        var loSize = _loSize;
        ref var keys0 = ref MemoryMarshal.GetArrayDataReference(_keys!);

        ref var k = ref Unsafe.Add(ref keys0, idx);
        if (loSize <= idx)
        {
            if (!EqualityComparer<K>.Default.Equals(k, key))
                return false;
            Move(_keys!.Length - _hiSize, idx, ref k);
            _hiSize--;
            bucket = 0;
            return true;
        }

        ref var links0 = ref MemoryMarshal.GetArrayDataReference(_links!);
        var prev = -1;
        var prevPrev = -1;

        for (var collisions = 0;
             !EqualityComparer<K>.Default.Equals(k, key);
             prevPrev = prev,
                 k = ref Unsafe.Add(ref keys0, idx = (int)Unsafe.Add(ref links0, prev = idx)))
        {
            if (idx >= loSize)
                return false;
            if (++collisions > loSize)
                ThrowChainTooLong();
        }

        var lastLo = loSize - 1;
        if (idx < loSize)
        {
            //Standard removal: rewire (prev or bucket) → next; compact lo by swap-with-last.
            //Single read of the matched entry's link; both branches consume `next`.
            var next = Unsafe.Add(ref links0, idx);
            if (prev < 0)
                bucket = next + 1;
            else
                Unsafe.Add(ref links0, prev) = next;
            Move(lastLo, idx, ref k);
        }
        else
        {
            //Found at hi-terminator with chain length ≥ 2. Migrate prev (lo) into the hi slot
            //so the chain still terminates in hi; prev's lo slot becomes the hole.
            ref var prevKey = ref Unsafe.Add(ref keys0, prev);
            k = prevKey;
            if (prevPrev < 0)
                bucket = (uint)(idx + 1);
            else
                Unsafe.Add(ref links0, prevPrev) = (uint)idx;
            Move(lastLo, prev, ref prevKey);
        }

        _loSize = lastLo;
        return true;
    }

