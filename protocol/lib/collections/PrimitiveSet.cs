///<summary>
///Represents a set of unique primitive values of type <typeparamref name="K"/>.
///This set implementation uses a hash table and is optimized for primitive types.
///<para><b>Storage layout:</b> dual-region <c>_keys</c> array (lo-region for collision-chain entries,
///hi-region for chain terminators), plus a side <c>_links</c> array sized only to the lo-region —
///memory paid only for actual collisions. See <see cref="PrimitiveKeyMap{K,V}"/> for the full
///discussion of why this layout was selected over inlined-next variants.</para>
///
///<para><b>Benchmark vs <c>HashSet&lt;int&gt;</c></b> (N = 100 000, random int keys, .NET 9, Release):</para>
///<code>
///Insert       Search          Get          Iterate        Delete         Churn
///PrimitiveSet&lt;int&gt;  49 011 714  144 035 886  133 485 889      809 903 969    18 997 476    18 163 325   ops/sec
///HashSet                 0.87         0.70         0.64             1.30          2.09          2.30   x
///</code>
///<para><b>Memory profile (grow-from-empty Insert, 100 000 random int keys):</b>
///<list type="bullet">
///<item><c>PrimitiveSet</c> allocates <b>26.23 B/op</b> (grow-from-empty Insert, 100 000 random int keys of 100 000 records)</item>
///<item><c>HashSet</c> allocates <b>48.30 B/op</b></item>
///<item><c>PrimitiveSet</c> saves <b>~22 077 B per 1 000 records</b> vs HashSet</item>
///</list>
///</para>
///<para>
///Ratio &gt; 1 ⇒ <c>HashSet</c> faster, &lt; 1 ⇒ <c>PrimitiveSet</c> faster. PrimitiveSet wins on
///Insert (1.15× on grow / 1.51× pre-sized) and on every read path (1.4–1.55×); HashSet wins on
///Iterate (its single contiguous entry array enjoys better cache flow than our dual-region split)
///and on Remove (~2× — the structural cost of dual-region compaction).
///</para>
///<para>See <c>Tests/Benchmarks/PrimitiveSetBenchmark.cs</c> for the full scenarios and an HTML report.</para>
///</summary>
///<typeparam name="K">The type of the primitive values in the set. Must be an unmanaged type.</typeparam>
public class PrimitiveSet<K> : ISet<K>, IReadOnlyCollection<K>
    where K : unmanaged
{
    private uint[]? _buckets;
    private K[]? _keys;
    private uint[]? _links; //0-based indices into _keys for collision chains.

    //The _keys array is split into two regions to optimize for non-colliding entries:
    //1. Lo-Region (indices 0 to _loSize-1): Stores keys that have caused a hash collision.
    //2. Hi-Region (indices _keys.Length - _hiSize to _keys.Length-1): Stores keys that have not caused a collision.
    private int _hiSize; //Number of active entries in the high region.
    private int _loSize; //Number of active entries in the low region.

    private int _version;
    private uint _mask;

    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    private ref uint GetBucket(uint hashCode) => ref Unsafe.Add(ref MemoryMarshal.GetArrayDataReference(_buckets!), hashCode &_mask);

    private const int DefaultCapacity = 4;

    public PrimitiveSet() : this(0) {}

    public PrimitiveSet(int capacity)
