using System.Diagnostics.CodeAnalysis;
using System.Runtime.CompilerServices;
using System.Runtime.InteropServices;
using System.Threading;

namespace org.unirail.collections;

///<summary>The head and the tail of a <see cref="RingBuffer{T}"/>, each alone on a cache line - padded on both sides,
///whatever the runtime lays out around the struct - as <c>PaddedHeadAndTail</c> of .NET's <c>ConcurrentQueue</c>: 128
///bytes, the line of Apple silicon and the pair of lines Intel's spatial prefetcher fetches together. Not nested in the
///generic class: a type nested in a generic one is generic, and the runtime refuses an explicit layout to generics.</summary>
[StructLayout(LayoutKind.Explicit, Size = 3 * 128)]
internal struct PaddedHeadAndTail
{
    [FieldOffset(128)]
    public ulong Head;
    [FieldOffset(256)]
    public ulong Tail;
}

///<summary>
///A fixed-size queue for any number of producers and consumers (MPMC), without a lock: Dmitry Vyukov's bounded MPMC queue
///(https://www.1024cores.net/home/lock-free-algorithms/queues/bounded-mpmc-queue), as the segments of .NET's
///<c>ConcurrentQueue</c> have it. Every member is thread-safe; nothing is allocated.
///</summary>
///<remarks>
///<para>Each slot carries a sequence number that says whose turn it is - the producer of lap <c>n</c> or its consumer - so
///a put is one CAS on the tail, a take one CAS on the head, and a value is taken only once it is written.</para>
///<para><see cref="TryGet"/>, <see cref="TryPut"/> and <see cref="PutPosition"/> never wait: a slot its producer has
///claimed and not yet written reads as empty, a slot its consumer has claimed and not yet released reads as full. A
///producer that finds the head on the position its put took (<see cref="PutPosition"/> <c>==</c> <see cref="Head"/>)
///knows the consumer found the queue empty or passed its value by, and wakes it - the transmit queue of a connection
///works so. <see cref="Clear()"/> waits for a value its producer is writing: nothing is left behind when a queue is
///emptied for good.</para>
///<para>The same queue as <c>org.unirail.collections.RingBuffer</c> of the Java runtime, in the idiom of .NET: <c>Try</c>
///methods with an <c>out</c> value, so that an empty queue of a value type is not mistaken for a default value.</para>
///<para>Against <c>ConcurrentQueue&lt;object&gt;</c> (.NET 10, i9-13900HX P-cores, M operations a second, the best of 3):</para>
///<code>
///RingBuffer (1024)    ConcurrentQueue
///1 thread, put + get                95                  85
///4 producers, 1 consumer            8.0 - 8.6           8.5 - 9.1   and 0.5 - 1 MB allocated
///4 producers, 4 consumers           8.0 - 8.8           8.6 - 9.0   and 0.5 - 8 MB allocated
///1 producer, 1 consumer            14                  33 - 55      and 150 MB allocated
///</code>
///<para>Many producers - a transmit queue - run as fast, with nothing allocated. One producer outruns one consumer in
///<c>ConcurrentQueue</c> by growing it without end - 10 million values ahead, 150 MB - which a bounded queue must not do:
///a full one refuses, and its producer waits.</para>
///</remarks>
///<typeparam name="T">The type of the values.</typeparam>
public class RingBuffer<T>
{
    ///<summary>What <see cref="PutPosition"/> returns when the queue is full.</summary>
    public const ulong FULL = ulong.MaxValue;

    //the slots: a value and its turn side by side, in one cache line - as the Slot of ConcurrentQueue's segments. In two
    //arrays each operation touched two lines, both moving between the cores (1 producer to 1 consumer: 13.6 against 15.7 M/s).
    readonly Slot[] _slots;

    struct Slot
    {
        //by value: the value queued, cleared when taken if T holds references - the queue keeps nothing it gave away alive.
        //In place: what is queued at the slot - its Own, or what was put whole; default: the slot was given up
        public T Item;

        //in place: the value of the slot for good, made by the wrapper when the slot is claimed for the first time
        public T? Own;

        //the turn: slot i of lap n is free for the put of position i + n * Length when it equals that position, and holds
        //its value for the take of that position when it equals the position + 1
        public ulong Sequence;
    }

    readonly ulong _mask;

    //the position of the next take and of the next put, each on a cache line of its own
    PaddedHeadAndTail _positions;

    //in place: what has to be free before a producer that found the queue full claims again - a quarter
    readonly ulong _part;

    //in place: makes the value of a slot, once, when the slot is claimed for the first time
    readonly Func<T>? _wrapper;

    bool _blocked;       //a producer found the queue full (a heuristic)
    ulong _taken = FULL; //in place: the position of the slot the consumer holds, FULL: none - the consumer's alone

    ///<summary>In place: the consumer found the queue empty and stopped - the producer of the next value is to wake it.</summary>
    volatile bool _idle = true;

    ///<summary>A queue of 2<sup><paramref name="capacityPowerOfTwo"/></sup> values, two at least: with one slot a value
    ///queued and a slot free are the same turn.</summary>
    ///<param name="capacityPowerOfTwo">the power of two of the capacity</param>
    ///<param name="wrapper">for the in-place side (<see cref="Claim"/>, <see cref="Own"/>): makes the value of a slot, once,
    ///when the slot is claimed for the first time</param>
    ///<exception cref="ArgumentOutOfRangeException"><paramref name="capacityPowerOfTwo"/> is negative or above 30.</exception>
    public RingBuffer(int capacityPowerOfTwo, Func<T>? wrapper = null)
    {
        ArgumentOutOfRangeException.ThrowIfNegative(capacityPowerOfTwo);
        ArgumentOutOfRangeException.ThrowIfGreaterThan(capacityPowerOfTwo, 30);
        var capacity = 1 << Math.Max(1, capacityPowerOfTwo);
        _mask = (ulong)(capacity - 1);
        _part = (ulong)Math.Max(1, capacity >> 2);
        _wrapper = wrapper;
        _slots = new Slot[capacity];
        for (var i = 0; i < capacity; i++)
            _slots[i].Sequence = (ulong)i;
    }

    ///<summary>The capacity: how many values the queue holds at most.</summary>
    public int Length => _slots.Length;

    ///<summary>The consumer: the position of the value it took last and holds until <see cref="Free"/>, <see cref="FULL"/> - none.</summary>
    public ulong Taken => _taken;

    ///<summary>How many values are in the queue: a snapshot, stale once other threads move on.</summary>
    public int Size
    {
        get {
            var head = Volatile.Read(ref _positions.Head); //before the tail: puts in between make it larger, never negative
            var tail = Volatile.Read(ref _positions.Tail);
            return head < tail ? (int)Math.Min(tail - head, (ulong)_slots.Length) : 0;
        }
    }

    ///<summary>No value in the queue: a snapshot.</summary>
    public bool IsEmpty => Volatile.Read(ref _positions.Tail) <= Volatile.Read(ref _positions.Head);

    ///<summary>No room in the queue: a snapshot.</summary>
    public bool IsFull => Size == _slots.Length;

    ///<summary>The position of the next take: compared with what <see cref="PutPosition"/> returned, it tells a producer
    ///that the consumer is to be woken.</summary>
    public ulong Head => Volatile.Read(ref _positions.Head);

    ///<summary>Takes the value at the head. Never waits.</summary>
    ///<param name="value">The value taken; <c>default</c> when there is none.</param>
    ///<returns><c>false</c>: the queue is empty - or the value at its head is claimed by a producer and not yet written,
    ///and that producer wakes the consumer once it is (see <see cref="PutPosition"/>).</returns>
    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    public bool TryGet([MaybeNullWhen(false)] out T value)
    {
        var pos = ClaimHead(false);
        if (pos == FULL)
        {
            value = default;
            return false;
        }
        value = TakeValue(pos);
        return true;
    }

    ///<summary>Takes the value at the head, as <see cref="TryGet"/>: for a queue of references, where <c>null</c> means
    ///"nothing". Never waits.</summary>
    ///<returns>The value taken, or <paramref name="empty"/>.</returns>
    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    public T? Get(T? empty = default) => TryGet(out var value) ? value : empty;

    ///<summary>Puts <paramref name="value"/> at the tail. Never waits.</summary>
    ///<returns><c>false</c>: the queue is full.</returns>
    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    public bool TryPut(T value) => PutPosition(value) != FULL;

    ///<summary>Puts <paramref name="value"/> at the tail, as <see cref="TryPut"/>, and tells the position it took.
    ///Never waits.</summary>
    ///<returns>The position of the value - when <see cref="Head"/> equals it after the put, the consumer found the queue
    ///empty or passed the value by while it was being written, and is to be woken - or <see cref="FULL"/>.</returns>
    public ulong PutPosition(T value)
    {
        var pos = ClaimTail();
        if (pos == FULL)
            return FULL;
        ref var slot = ref SlotAt(pos);
        slot.Item = value;
        Volatile.Write(ref slot.Sequence, pos + 1); //a release: the value is seen with the sequence
        return pos;
    }

    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    ref Slot SlotAt(ulong pos) => ref Unsafe.Add(ref MemoryMarshal.GetArrayDataReference(_slots), (nint)(pos & _mask));

    ///<summary>Moves the tail on by one.</summary>
    ///<returns>The position claimed, or <see cref="FULL"/>: the slot holds the value of the lap before, or its consumer has
    ///not released it yet.</returns>
    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    ulong ClaimTail()
    {
        //one try: a put with no other producer in the way. A lost race goes on in ClaimContended - its loop, kept out of
        //here, made this path slower (12 -> 18 ns with one producer)
        var pos = Volatile.Read(ref _positions.Tail);
        var dif = (long)(Volatile.Read(ref SlotAt(pos).Sequence) - pos);
        if (dif == 0 && Interlocked.CompareExchange(ref _positions.Tail, pos + 1, pos) == pos)
            return pos;
        return dif < 0 ? FULL : ClaimContended();
    }

    ///<summary><see cref="ClaimTail"/> after a lost race: each next try after a wait of <c>2^step</c> spins, the step
    ///growing up to 6 (as crossbeam's <c>Backoff.spin</c>) - producers retrying at once keep the cache line of the tail
    ///moving between cores: with 2 producers a value cost 3 times as much.</summary>
    [MethodImpl(MethodImplOptions.NoInlining)]
    ulong ClaimContended()
    {
        for (var step = 0;; step += step < 6 ? 1 : 0)
        {
            Thread.SpinWait(1 << step);
            var pos = Volatile.Read(ref _positions.Tail);
            var dif = (long)(Volatile.Read(ref SlotAt(pos).Sequence) - pos);
            if (dif == 0)
            {
                if (Interlocked.CompareExchange(ref _positions.Tail, pos + 1, pos) == pos)
                    return pos;
            }
            else if (dif < 0)
                return FULL;
            //another producer took this position: wait, then the next
        }
    }

    ///<summary>Takes and drops every value there is.</summary>
    ///<returns>This queue.</returns>
    public RingBuffer<T> Clear()
    {
        for (ulong pos; (pos = ClaimHead(true)) != FULL;)
            TakeValue(pos);
        return this;
    }

    ///<summary>Takes every value there is and hands each to <paramref name="onClear"/>, oldest first.</summary>
    ///<remarks>A slot is emptied and freed before its value is handed on: <paramref name="onClear"/> may throw or take its
    ///time without holding the producers up. A value it puts into this queue is taken again: it must not.</remarks>
    ///<returns>This queue.</returns>
    public RingBuffer<T> Clear(Action<T> onClear)
    {
        for (ulong pos; (pos = ClaimHead(true)) != FULL;)
            onClear(TakeValue(pos));
        return this;
    }

    ///<summary>As <see cref="Clear(Action{T})"/>, with a state of the caller's. With a <c>static</c> lambda nothing is
    ///allocated: no closure, and the delegate is cached by the compiler.</summary>
    ///<returns>This queue.</returns>
    public RingBuffer<T> Clear<S>(S state, Action<S, T> onClear)
    {
        for (ulong pos; (pos = ClaimHead(true)) != FULL;)
            onClear(state, TakeValue(pos));
        return this;
    }

    public override string ToString() => $"RingBuffer{{Length={Length}, Size={Size}, Head={Volatile.Read(ref _positions.Head)}, Tail={Volatile.Read(ref _positions.Tail)}}}";
#region in place
    //The sending queue of a connection: every slot keeps a value of its own for good - made by the wrapper the first time the
    //slot is claimed - a producer fills it in place and publishes it, one consumer reads it in place while it serializes the
    //pack and frees it. Nothing allocated a value, nothing moved between threads but the turn of the slot.
    // - A put reads nothing the consumer writes at every value: the consumer that finds the queue empty says so (_idle), and
    //   the producer of the next value learns from Publish that it is to wake it.
    // - A producer that found the queue full claims nothing until a quarter of it is free: a full queue has its producers
    //   and its consumer at the same slot, a line of the cache going to and fro at every value.
    // - A slot taken stays taken until Free(): its value is the consumer's while the pack is serialized.
    //A queue is used in place or by value, not both.

    ///<summary>A producer: the next slot is its own.</summary>
    ///<returns>
    ///The position of the slot - its value is <see cref="Own"/>, to be filled and published (or given up:
    ///<see cref="Cancel"/>); <c>-1</c>: the queue is full, or was and less than a quarter of it is free yet.
    ///</returns>
    public long Claim()
    {
        if (_blocked)
        {
            var ahead = Volatile.Read(ref _positions.Tail) + _part - 1;
            if (Volatile.Read(ref SlotAt(ahead).Sequence) != ahead)
                return -1;
            _blocked = false;
        }
        var pos = ClaimTail();
        if (pos != FULL)
            return (long)pos;
        _blocked = true;
        return -1;
    }

    ///<summary>The value of the slot claimed at <paramref name="pos"/>, to be filled in place: made by the wrapper the first
    ///time the slot is claimed.</summary>
    public T Own(long pos)
    {
        ref var slot = ref SlotAt((ulong)pos);
        if (slot.Own is null)
            slot.Own = _wrapper!(); //the slot is of the producer that claimed it: nobody else is here
        return slot.Own;
    }

    ///<summary>The value of the slot claimed at <paramref name="pos"/> is filled: it is queued.</summary>
    ///<returns>The consumer sleeps: it is to be woken.</returns>
    public bool Publish(long pos)
    {
        ref var slot = ref SlotAt((ulong)pos);
        slot.Item = slot.Own!;
        return Turn(ref slot, pos);
    }

    ///<summary><paramref name="whole"/> takes the slot claimed at <paramref name="pos"/> in place of its value.</summary>
    ///<returns>The consumer sleeps: it is to be woken.</returns>
    public bool Publish(long pos, T whole)
    {
        ref var slot = ref SlotAt((ulong)pos);
        slot.Item = whole;
        return Turn(ref slot, pos);
    }

    ///<summary>The producer of the slot claimed at <paramref name="pos"/> gives it up: the consumer passes it by.</summary>
    ///<returns>The consumer sleeps: it is to be woken - what is queued behind the slot waited for it.</returns>
    public bool Cancel(long pos)
    {
        ref var slot = ref SlotAt((ulong)pos);
        slot.Item = default!;
        return Turn(ref slot, pos);
    }

    bool Turn(ref Slot slot, long pos)
    {
        Interlocked.Exchange(ref slot.Sequence, (ulong)pos + 1); //a full fence: the word of the consumer is read after the consumer sees the value
        if (!_idle)
            return false;
        _idle = false;
        return true;
    }

    ///<summary>The consumer: what is queued next. Its slot stays taken until <see cref="Free()"/>.</summary>
    ///<returns>
    ///<c>null</c>: nothing is queued - or the slot at the head is claimed and not published yet - and the producer of the
    ///next value wakes the consumer.
    ///</returns>
    public T? Take()
    {
        var v = Next();
        if (v is not null)
            return v;
        _idle = true;
        Interlocked.MemoryBarrier(); //a full fence: what is queued is looked for after the producers see the word
        if ((v = Next()) is not null)
            _idle = false;
        return v;
    }

    T? Next()
    {
        for (;;)
        {
            var pos = ClaimHead(false);
            if (pos == FULL)
                return default;
            var v = SlotAt(pos).Item;
            if (v is null)
            { //given up by its producer
                Release(pos);
                continue;
            }
            _taken = pos;
            return v;
        }
    }

    ///<summary>The consumer is done with what it took: the slot is free for the producers.</summary>
    public void Free()
    {
        var pos = _taken;
        if (pos == FULL)
            return;
        _taken = FULL;
        Release(pos);
    }

    //frees the slot of the taken position: what was put whole is not kept, the value of the slot stays where it is
    void Release(ulong pos)
    {
        ref var slot = ref SlotAt(pos);
        if (!ReferenceEquals(slot.Item, slot.Own))
            slot.Item = default!;
        Volatile.Write(ref slot.Sequence, pos + (ulong)_slots.Length);
    }

    ///<summary>
    ///Takes everything queued in place - from any thread, the consumer may run meanwhile: what it holds is left to it. A slot
    ///claimed and not published yet is waited for: nothing is left behind when a queue is emptied for good. The producer of
    ///the next value wakes the consumer.
    ///</summary>
    ///<param name="state">goes to <paramref name="on_clear"/> as it is: a lambda without a capture allocates nothing</param>
    ///<param name="on_clear">takes each of them, oldest first, before its slot is freed - the value of the slot is what it
    ///reads; <c>null</c> - they are dropped</param>
    public void ClearInPlace<S>(S state, Action<S, T>? on_clear)
    {
        for (ulong pos; (pos = ClaimHead(true)) != FULL;)
            try
            {
                var v = SlotAt(pos).Item;
                if (v is not null)
                    on_clear?.Invoke(state, v);
            }
            finally
            {
                Release(pos); //after the callback, a throw out of it too: one left taken would hold the queue full for good
            }

        _idle = true; //emptied, and not by the consumer: the producer of the next value wakes it
        Interlocked.MemoryBarrier();
    }
#endregion

    ///<summary>Moves the head on by one.</summary>
    ///<param name="wait">Wait for a producer that has claimed the slot at the head and not yet written it.</param>
    ///<returns>The position taken, or <see cref="FULL"/>: nothing to take - empty (or, without <paramref name="wait"/>, not
    ///yet written).</returns>
    ulong ClaimHead(bool wait)
    {
        var spinner = new SpinWait();
        for (;;)
        {
            var pos = Volatile.Read(ref _positions.Head);
            var dif = (long)(Volatile.Read(ref SlotAt(pos).Sequence) - (pos + 1));
            if (dif == 0)
            {
                if (Interlocked.CompareExchange(ref _positions.Head, pos + 1, pos) == pos)
                    return pos;
                continue; //another consumer took this position: try the next
            }
            if (dif < 0)
            {
                if (!wait || Volatile.Read(ref _positions.Tail) <= pos)
                    return FULL;      //empty
                spinner.SpinOnce(-1); //claimed by a producer that is writing it: a few instructions away
            }
            //else another consumer took this position: try the next
        }
    }

    ///<summary>Reads the value at a claimed position and frees its slot for the next lap.</summary>
    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    T TakeValue(ulong pos)
    {
        ref var slot = ref SlotAt(pos);
        var value = slot.Item;
        if (RuntimeHelpers.IsReferenceOrContainsReferences<T>())
            slot.Item = default!;                                      //a JIT-time constant: nothing written for values without references
        Volatile.Write(ref slot.Sequence, pos + (ulong)_slots.Length); //a release: the read above comes first
        return value;
    }
}
