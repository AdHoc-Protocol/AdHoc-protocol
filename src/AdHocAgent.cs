        public static int exit(string banner, int code = 1)
        {
            var text = banner.Replace("{", "{{").Replace("}", "}}"); // the banner is text, not a template: its braces are its own
            TaskProgress.end();
            if( 0 < banner.Length )
                if( code == 0 )
                    LOG.Information(text);
                else
                    LOG.Error(text);

            if( !Console.IsInputRedirected ) // a window opened by a double click stays until it is read; a script or a pipe is not held
            {
                Console.Out.WriteLine(ansi("Press ENTER to exit", "2"));
                try { Console.In.ReadLine(); }
                catch( IOException ) { }
            }

            Environment.Exit(code);
            return code;
        }

