        /// Serilog enricher that adds the agent's own source line that wrote the message. Only for agent developers:
        /// with <c>ADHOC_TRACE=1</c>; a user sees what is wrong in the description, not where in the agent it was noticed.
        /// </summary>
        class CallerEnricher : ILogEventEnricher{
            public void Enrich(LogEvent logEvent, ILogEventPropertyFactory propertyFactory)
            {
                // the first frame with a file is the caller: the enricher and Serilog come without one
                var frame = new StackTrace(true).GetFrames().Skip(1).FirstOrDefault(f => f.GetFileName() != null);
                if( frame != null )
                    logEvent.AddPropertyIfAbsent(new LogEventProperty("FileLine", new ScalarValue($"{frame.GetFileName()}:line {frame.GetFileLineNumber()}")));
            }
        }

        static readonly bool trace = Environment.GetEnvironmentVariable("ADHOC_TRACE") == "1";

        /// <summary>
        /// The console of AdHocAgent. `[time LVL]` - the time dim, the level in its colour: errors red, warnings yellow, the rest
        /// cyan - then the message: the names it is given in bold, `code` in cyan, "line N" in yellow. The lines after the first
        /// stand under the text of the first. Without colours - NO_COLOR, or the output going to a file - it is the same text, plain.
        /// </summary>
        sealed class Console_ : ILogEventSink{
            // a place in a file - `D:\dir\File.cs:13`, `/dir/File.cs(12,36)`: a link the terminal opens on a click -, `code`, "line N"
            static readonly Regex marks = new(@"(?:[A-Za-z]:[\\/]|(?<![\w.])/)[^\s""'`()\u0001\u0002]+\.\w+(?::\d+|\(\d+,\d+\))?|`[^`\n]+`|\bline \d+\b", RegexOptions.Compiled);

            const char open = '\u0001', close = '\u0002'; // around a value of the message, until the colours are put in

            public void Emit(LogEvent e)
            {
                var (tag, colour) = e.Level switch
                                    {
                                        LogEventLevel.Error or LogEventLevel.Fatal => ("ERR", "1;31"),
                                        LogEventLevel.Warning                      => ("WRN", "1;33"),
                                        LogEventLevel.Information                  => ("INF", "1;36"),
                                        _                                          => ("DBG", "2")
                                    };

                var sb = new StringBuilder();
                foreach( var token in e.MessageTemplate.Tokens )
                    if( token is PropertyToken p && e.Properties.TryGetValue(p.PropertyName, out var value) )
                    {
                        var text = value is ScalarValue { Value: string s } ? s : value.ToString(); // a string as it is, no quotes
                        if( 60 < text.Length || text.Contains('\n') || value is ScalarValue { Value: not string } ) sb.Append(text); // a block, a sentence or a number: as text
                        else sb.Append(open).Append(text).Append(close);                                                            // a name
                    }
                    else sb.Append(token is TextToken t ? t.Text : token.ToString());

                if( trace && e.Properties.TryGetValue("FileLine", out var at) ) sb.Append("   (").Append(((ScalarValue)at).Value).Append(')');

                var head   = $"[{e.Timestamp:HH:mm:ss} {tag}] ";
                var line   = sb.ToString().Replace("\n", "\n" + new string(' ', head.Length)); // the next lines under the text
                var styled = color_ok ?
                                 marks.Replace(line, m => ansi(m.Value, m.Value[0] == '`' ? "36" : m.Value.StartsWith("line ") ? "33" : "4;36"))
                                      .Replace(open.ToString(), "\u001b[1m").Replace(close.ToString(), "\u001b[22m") :
                                 line.Replace(open.ToString(), "").Replace(close.ToString(), "");

                TaskProgress.hide(); // outside the lock of the console: the progress takes its own and then writes
                lock( Console.Out )
                {
                    Console.Out.WriteLine(ansi($"[{e.Timestamp:HH:mm:ss} ", "2") + ansi(tag, colour) + ansi("] ", "2") + styled);
                    if( e.Exception != null ) Console.Out.WriteLine(e.Exception);
                }
            }
        }

