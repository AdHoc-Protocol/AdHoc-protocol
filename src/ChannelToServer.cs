        // The domain of the generator servers, and the name whose TXT record lists them, each as `label:port`: `us:8443,cn:443,tw:4567`.
        const string SERVERS_DOMAIN = "unirail.org";
        const string SERVERS_RECORD = "agent." + SERVERS_DOMAIN;

        // The addresses to try: the `server` key in its order, or the TXT record with the fastest server first. The configuration of the
        // network changes without a release. DNS proves nothing about its answer, so a record names labels of our domain only, and the certificate of `wss` checks the rest.
        // The `server` key is only for the stand: it points the agent at the local server there. The users are not told of it: they use the public servers.
        static async Task<string[]> servers()
        {
            if( settings_of("server") is { } own ) return own;

            const string how = "Check that this computer is connected to the internet, and run again.";

            var records = AdHoc.value(SERVERS_RECORD);
            if( records == null || records.Length == 0 ) exit($"Cannot read the list of servers: neither public DNS servers nor those of this computer gave a TXT record of {SERVERS_RECORD}. {how}");
            if( 1 < records!.Length ) exit($"Cannot read the list of servers: {SERVERS_RECORD} has {records.Length} TXT records, one is expected. {how}");

            var text = System.Text.Encoding.ASCII.GetString(records[0].Span);
            return await fastest_first(text.Split(',', StringSplitOptions.RemoveEmptyEntries | StringSplitOptions.TrimEntries)
                       .Select(entry =>
                               {
                                   var colon = entry.IndexOf(':');
                                   if( 0 < colon && entry[..colon].All(c => char.IsAsciiLetterOrDigit(c) || c == '-') && ushort.TryParse(entry[(colon + 1)..], out var port) && 0 < port )
                                       return $"wss://{entry[..colon]}.{SERVERS_DOMAIN}:{port}";
                                   exit($"Cannot read the list of servers: the TXT record of {SERVERS_RECORD} is `{text}`, and `{entry}` is not `label:port`. {how}");
                                   return "";
                               })
                       .ToArray());
        }

        // The server that opens a WebSocket first goes first, the others stay in their order: a race of the whole path - TLS and, behind Cloudflare, the
        // tunnel to the server - as a nearby edge of Cloudflare says nothing of the server behind it. Nobody answers in the time of a connect - the order stays, and the rounds report why.
        static async Task<string[]> fastest_first(string[] urls)
        {
            if( urls.Length < 2 ) return urls;

            using var stop = new System.Threading.CancellationTokenSource(10_000);
            var races = urls.Select(async url =>
                                    {
                                        using var socket = new System.Net.WebSockets.ClientWebSocket();
                                        var       start  = System.Diagnostics.Stopwatch.GetTimestamp();
                                        await socket.ConnectAsync(new Uri(url), stop.Token);
                                        socket.Abort();
                                        return (url, System.Diagnostics.Stopwatch.GetElapsedTime(start));
                                    })
                            .ToList();

            while( 0 < races.Count )
            {
                var race = await Task.WhenAny(races);
                races.Remove(race);
                if( !race.IsCompletedSuccessfully ) continue;

                stop.Cancel();
                var (fastest, time) = race.Result;
                DETAIL($"The fastest of {urls.Length} servers is {fastest}: {(long)time.TotalMilliseconds} ms");
                return urls.OrderBy(url => url != fastest).ToArray();
            }

            return urls;
        }

        // The addresses are tried in order, round after round, until one of them answers as a generator.
        static async Task Start()
        {
            var urls = await servers();
            if( urls.Length == 0 ) exit("No servers in " + (settings_of("server") != null ? app_props_file : "the TXT record of " + SERVERS_RECORD));
            for( var round = 0;; round++ )
            {
                if( round > 0 )
                {
                    WRN($"None of the servers answered - the next round in 5 s");
                    await Task.Delay(5_000);
                }

                if( await Round(urls) ) return;
            }
        }

        // One pass over the addresses. true - a generator answered and the exchange ended there.
        static async Task<bool> Round(string[] urls)
        {
            foreach( var url in urls )
            {
                done     = new TaskCompletionSource<bool>();
                answered = false;
                INF($"Connecting to {url}");
                Connection connection = null;

                // A refused/unreachable server must only cost us THIS url: both clients report a failed connect by
                // throwing (the WebSocket one completes its task with the exception, the TCP one re-throws), so an
                // uncaught attempt would escape Main and the remaining urls would never be tried. The try wraps the
                // connect ALONE — a failure after this point is a protocol problem, not a reason to try elsewhere.
                try
                {
                    var connected = new TaskCompletionSource<Connection?>(TaskCreationOptions.RunContinuationsAsynchronously);
                    Action<Connection?, Exception?> report = (c, e) => { if (e == null) connected.TrySetResult(c); else connected.TrySetException(e); };
                    if( url.StartsWith("ws:", StringComparison.OrdinalIgnoreCase) || url.StartsWith("wss:", StringComparison.OrdinalIgnoreCase) )
                        new Network.TCP.WebSocket.Client<Connection>("http_client", (ext) => new Connection(), Network.TCP.onFailurePrintConsole, 1024, mux: true).Connect(new Uri(url), 10_000, report);
                    else
                    {
                        var uri       = new Uri("http://" + url);
                        var ipAddress = IPAddress.Loopback;

                        if( !uri.Host.Equals("localhost", StringComparison.OrdinalIgnoreCase) )
                            try
                            {
                                var addresses = (await Dns.GetHostAddressesAsync(uri.Host));
                                if( addresses.Length == 0 )
                                {
                                    WRN($"No IP address found for host {uri.Host}.");
                                    continue;
                                }

                                ipAddress = addresses[random.Next(addresses.Length)];
                            }
                            catch( SocketException ex )
                            {
                                WRN($"DNS lookup failed for {uri.Host}: {ex.Message}");
                                continue;
                            }

                        new Network.TCP.Client<Connection>("tcp_client", (ext) => new Connection(), Network.TCP.onFailurePrintConsole, 1024, mux: true).Connect(new IPEndPoint(ipAddress, uri.Port), 10_000, report);
                    }
                    connection = await connected.Task;
                }
                catch( Exception ex ) //refused, unreachable, connect timeout, bad url — all mean "try the next one"
                {
                    WRN($"The connection to {url} has failed: {ex.Message}");
                    continue;
                }

                if( connection == null ) //the older clients signalled failure with null instead of an exception
                {
                    WRN($"The connection to {url} has failed.");
                    continue;
                }

                DETAIL($"Connected to {url}");
                current = connection; //before the Version: a server that closes at once must end this attempt

                Actor0.State.O.transmitter.send(new AdHocProtocol.Agent_.Version
                                                {
                                                    LCID = (byte)CultureInfo.CurrentUICulture.LCID,
                                                    zone = (byte)(TimeZoneInfo.Local.BaseUtcOffset.TotalMinutes / 15),
                                                    uid  = (ushort)VER
                                                }, connection);
                // a server that accepts and stays silent is not a generator either
                var silence = Task.Delay(15_000);
                if( await Task.WhenAny(done.Task, silence) == silence && !answered )
                {
                    WRN($"{url} did not answer in 15 s - not a generator; trying the next one");
                    current = null;
                    connection.ext_connection.Close();
                    continue;
                }

                var received = await done.Task;
                if( answered && !received && !result_delivered ) // a generator answered, and the code did not come: a failed run, not a success
                    exit("Nothing is generated: the connection ended before the result came. Run AdHocAgent again.");
                if( answered || result_delivered ) return true;
                WRN($"{url} closed the connection without answering - not a generator; trying the next one");
            }

            return false;
        }


