            /// <summary>
            /// Compiles the C# of `block`, a step of `md_path`, as a C# script whose globals are a <see cref="StepContext"/>: an expression, statements, or a class `Program`
            /// with `Main(string[] args)` - called with the file then. The lines in quotes of an earlier AdHocAgent at its top are left out: the assemblies of .NET are
            /// referenced anyway. A step compiled before is taken from the cache, by the hash of its code. A compile error stops the deployment, at its line of the file.
            /// </summary>
            internal static CSharpStep compile_step(Block block, string md_path)
            {
                var code = Regex.Replace(block.body, @"^(?:[ \t]*""[^""\n]+""[ \t]*\n)+", m => new string('\n', m.Value.Count(c => c == '\n'))); // the old references: blank lines, the numbering kept
                var text = $"#line {block.line} \"{md_path}\"\n{code}";
                var tree = CSharpSyntaxTree.ParseText(Microsoft.CodeAnalysis.Text.SourceText.From(text, Encoding.UTF8), new CSharpParseOptions(LanguageVersion.Latest, kind: SourceCodeKind.Script), md_path);
                var root = tree.GetCompilationUnitRoot();

                // a program of its own, nothing around it: it is called with the file, as an earlier AdHocAgent called it
                if( !root.Members.OfType<GlobalStatementSyntax>().Any() &&
                    root.DescendantNodes().OfType<ClassDeclarationSyntax>().FirstOrDefault(c => c.Identifier.Text == "Program") is { } program &&
                    program.Members.OfType<MethodDeclarationSyntax>().Any(m => m.Identifier.Text == "Main" && m.Modifiers.Any(SyntaxKind.StaticKeyword)) )
                {
                    tree = tree.WithChangedText(tree.GetText().WithChanges(new Microsoft.CodeAnalysis.Text.TextChange(new Microsoft.CodeAnalysis.Text.TextSpan(tree.Length, 0), "\nProgram.Main(new[] { path });\n")));
                    root = tree.GetCompilationUnitRoot();
                }

                var once = root.DescendantNodes().OfType<IdentifierNameSyntax>().Any(n => n.Identifier.Text == "files" && !(n.Parent is MemberAccessExpressionSyntax ma && ma.Name == n));

                var resolver = new StepReferences(Path.GetDirectoryName(md_path)!);
                var hash     = Convert.ToHexString(SHA256.HashData(Encoding.UTF8.GetBytes(tree.GetText() + "\0" + typeof(StepContext).Assembly.ManifestModule.ModuleVersionId)))[..32];
                var cache    = Path.Combine(Path.GetTempPath(), "AdHocAgent", "csharp-steps");
                var dll      = Path.Combine(cache, hash + ".dll");
                var pdb      = Path.Combine(cache, hash + ".pdb");
                var refs     = Path.Combine(cache, hash + ".refs");
                var entry    = Path.Combine(cache, hash + ".entry");

                if( !File.Exists(dll) || !File.Exists(entry) )
                {
                    var compilation = CSharpCompilation.CreateScriptCompilation("step_" + hash,
                                                                                tree,
                                                                                framework,
                                                                                new CSharpCompilationOptions(OutputKind.DynamicallyLinkedLibrary,
                                                                                                             usings: step_usings,
                                                                                                             optimizationLevel: OptimizationLevel.Release,
                                                                                                             metadataReferenceResolver: resolver,
                                                                                                             nullableContextOptions: NullableContextOptions.Disable),
                                                                                returnType: typeof(object),
                                                                                globalsType: typeof(StepContext));
                    using var dll_bytes = new MemoryStream();
                    using var pdb_bytes = new MemoryStream();
                    var       result    = compilation.Emit(dll_bytes, pdb_bytes, options: new EmitOptions(debugInformationFormat: DebugInformationFormat.PortablePdb));
                    if( !result.Success )
                    {
                        // each error at its place in the instructions file: `#line` maps the step onto it
                        var errors = string.Join("\n", result.Diagnostics.Where(d => d.Severity == DiagnosticSeverity.Error)
                                                             .Select(d => d.Location.GetMappedLineSpan() is var at && at.IsValid ?
                                                                              $"  {at.Path}:{at.StartLinePosition.Line + 1}:{at.StartLinePosition.Character + 1}: {d.Id} {d.GetMessage()}" :
                                                                              $"  {d.Id} {d.GetMessage()}"));
                        ERR($"A C# step of {md_path} does not compile:\n{errors}");
                        exit("Nothing is deployed. Fix the step and deploy again.");
                    }

                    Directory.CreateDirectory(cache);
                    File.WriteAllBytes(pdb, pdb_bytes.ToArray());
                    File.WriteAllLines(refs, resolver.paths);
                    // the factory of the script: its type and method, as the compiler named them
                    var factory_of = compilation.GetEntryPoint(default)!;
                    File.WriteAllLines(entry, [factory_of.ContainingType.MetadataName, factory_of.MetadataName]);
                    File.WriteAllBytes(dll, dll_bytes.ToArray()); // last: a .dll in the cache is a whole entry
                }

                var libraries = File.Exists(refs) ?
                                    File.ReadAllLines(refs).Where(l => 0 < l.Length).ToList() :
                                    [];
                foreach( var library in libraries ) Assembly.LoadFrom(library);
                if( 0 < libraries.Count )
                    AppDomain.CurrentDomain.AssemblyResolve += (_, e) => libraries.Select(l => Path.Combine(Path.GetDirectoryName(l)!, new AssemblyName(e.Name).Name + ".dll"))
                                                                                  .Where(File.Exists)
                                                                                  .Select(Assembly.LoadFrom)
                                                                                  .FirstOrDefault();

                var assembly = Assembly.Load(File.ReadAllBytes(dll), File.ReadAllBytes(pdb));
                // a script is a class with a factory: it takes the states of the submissions - the globals first - and runs the script
                var names   = File.ReadAllLines(entry);
                var factory = assembly.GetType(names[0], true)!.GetMethod(names[1], BindingFlags.Public | BindingFlags.NonPublic | BindingFlags.Static)!;
                return new CSharpStep(ctx => ((Task<object>)factory.Invoke(null, [new object?[] { ctx, null }])!).GetAwaiter().GetResult(), once);
            }

            /// <summary>Runs a C# step over `files`: once with all of them when it names `files`, else for each - writing back what it changed.</summary>
            internal static void run_csharp(CSharpStep step, List<StepFile> files, string md_path)
            {
                if( step.once )
                {
                    TaskProgress.step($"C# step, {files.Count} files");
                    invoke(new StepContext { received = raw_files_dir_path, files = files }, null);
                    return;
                }

                foreach( var f in files )
                {
                    TaskProgress.step("C# step " + Path.GetFileName(f.path));
                    var before = read_text(f.path);
                    var ctx    = new StepContext { text = before, path = f.path, relative = f.relative, language = f.language, host = f.host, received = raw_files_dir_path, files = files };
                    var after  = invoke(ctx, f) as string ?? ctx.text;
                    if( after != before && after != null ) write_text(f.path, after);
                }

                object? invoke(StepContext ctx, StepFile? f)
                {
                    try { return step.run(ctx); }
                    catch( Exception e )
                    {
                        var inner = e is TargetInvocationException { InnerException: { } i } ?
                                        i :
                                        e;
                        // the frames of the step: their lines are the lines of the instructions file
                        var at = string.Join("\n", (inner.StackTrace ?? "").Split('\n').Where(l => l.Contains(md_path)).Select(l => "  " + l.Trim()));
                        ERR($"The C# step of {md_path} failed{(f == null ? "" : " on " + f.relative)}: {inner.GetType().Name}: {inner.Message}{(at.Length == 0 ? "" : "\n" + at)}");
                        exit("Nothing is deployed. Fix the step and deploy again.");
                        return null;
                    }
                }
            }

            /// <summary>
            /// The `#r` of a C# step: `#r "lib/My.dll"` - a library, its path from the folder of the instructions file or full; `#r "nuget: Name, 1.2.3"` - a package
            /// of nuget.org, its library for the newest framework it has, downloaded once into the cache. The dependencies of a package are not fetched: name each with
            /// a `#r` of its own.
            /// </summary>
            sealed class StepReferences(string folder) : MetadataReferenceResolver{
                /// <summary>The libraries resolved: loaded before the step runs.</summary>
                public readonly List<string> paths = [];

                public override ImmutableArray<PortableExecutableReference> ResolveReference(string reference, string? baseFilePath, MetadataReferenceProperties properties)
                {
                    var found = reference.StartsWith("nuget:", StringComparison.OrdinalIgnoreCase) ?
                                    nuget(reference[6..]) :
                                    Path.GetFullPath(reference, folder) is var p && File.Exists(p) ?
                                        [p] :
                                        [];
                    paths.AddRange(found);
                    return [..found.Select(p => MetadataReference.CreateFromFile(p, properties))];
                }

                public override bool Equals(object? other) => ReferenceEquals(this, other);
                public override int GetHashCode() => folder.GetHashCode();
                public override bool ResolveMissingAssemblies => false;

                /// <summary>The libraries of the package `Name, 1.2.3`: its folder `lib/<framework>` for the newest framework .NET 10 runs, from the cache or from nuget.org.</summary>
                static List<string> nuget(string spec)
                {
                    var parts = spec.Split(',', StringSplitOptions.TrimEntries | StringSplitOptions.RemoveEmptyEntries);
                    if( parts.Length != 2 )
                    {
                        ERR($"`#r \"nuget: {spec}\"`: a package is named with its version, `#r \"nuget: Humanizer, 2.14.1\"`");
                        return [];
                    }

                    var (id, version) = (parts[0].ToLowerInvariant(), parts[1].ToLowerInvariant());
                    var folder        = Path.Combine(Path.GetTempPath(), "AdHocAgent", "nuget", id, version);
                    if( !Directory.Exists(folder) )
                        try
                        {
                            using var http = new HttpClient();
                            var       nupkg = http.GetByteArrayAsync($"https://api.nuget.org/v3-flatcontainer/{id}/{version}/{id}.{version}.nupkg").GetAwaiter().GetResult();
                            var       tmp   = folder + ".tmp";
                            if( Directory.Exists(tmp) ) Directory.Delete(tmp, true);
                            new ZipArchive(new MemoryStream(nupkg)).ExtractToDirectory(tmp);
                            Directory.Move(tmp, folder);
                        }
                        catch( Exception e )
                        {
                            ERR($"The package {parts[0]} {parts[1]} is not downloaded from nuget.org: {e.Message}");
                            return [];
                        }

                    var lib = Path.Combine(folder, "lib");
                    if( !Directory.Exists(lib) ) return [];
                    // the newest framework first: net10.0 ... net5.0, then netstandard2.1, netstandard2.0
                    var best = Directory.GetDirectories(lib)
                                        .Select(d => (d, name: Path.GetFileName(d).ToLowerInvariant()))
                                        .Select(t => (t.d, rank: Regex.Match(t.name, @"^net(\d+)\.(\d+)$") is { Success: true } m && int.Parse(m.Groups[1].Value) <= 10 ?
                                                                     1000 + int.Parse(m.Groups[1].Value) * 10 + int.Parse(m.Groups[2].Value) :
                                                                     t.name switch { "netstandard2.1" => 21, "netstandard2.0" => 20, _ => -1 }))
                                        .Where(t => 0 <= t.rank)
                                        .OrderByDescending(t => t.rank)
                                        .Select(t => t.d)
                                        .FirstOrDefault();
                    return best == null ?
                               [] :
                               [..Directory.GetFiles(best, "*.dll")];
                }
            }

            // ======================== The instructions of an earlier AdHocAgent, written in the new form once

            /// <summary>
            /// Rewrites the steps and hooks of an earlier AdHocAgent in the form of steps of one block: a ```regexp block and the ```shell or ```csharp block after it -
            /// one ```shell re:… or ```csharp re:… block; `regexp-off` - a block `shell-off`, `csharp-off`, which does not run; a hook link - a ```before or ```after
            /// block. Formatter steps and the region-marker step go: AdHocAgent does both itself. The section of formatters an earlier AdHocAgent wrote becomes the
            /// one it writes now. Null - nothing of the old form.
            /// </summary>
            internal static string? migrated(string md, out List<string> dropped)
            {
                dropped = [];
                var nl = md.Contains("\r\n") ?
                             "\r\n" :
                             "\n";
                var s = md.Replace("\r\n", "\n");

                // the section an earlier AdHocAgent wrote: the formatters, switched off, and the region-marker step - up to the end of
                // that last step: what the user wrote after it stays
                if( s.IndexOf("## Formatting the code\n\nThe code arrives unformatted.", StringComparison.Ordinal) is var section and >= 0 &&
                    s.IndexOf("### Every file: no indentation before region markers", section, StringComparison.Ordinal) is var last and >= 0 &&
                    s.IndexOf("\n```csharp\n", last, StringComparison.Ordinal) is var code and >= 0 &&
                    s.IndexOf("\n```", code + 10, StringComparison.Ordinal) is var closing and >= 0 )
                {
                    var end      = closing + 4; // past the closing fence
                    var template = DeploymentText.FOOTER.Replace("\r\n", "\n");
                    var now      = template[template.IndexOf("## Formatting the code\n", StringComparison.Ordinal)..template.IndexOf("\n---\n\nAll of this in full:", StringComparison.Ordinal)];
                    s = s[..section] + now + s[end..];
                    dropped.Add("the formatter steps and the region-marker step of the generated instructions");
                }

                var formatters = new[] { "clang-format", "prettier", "rustfmt", "gofmt", "astyle", "ruff", "black", "swift-format" };
                var list       = dropped;
                var t = Regex.Replace(s, @"```(regexp|regexp-off)[ \t]*\n(.+?)\n```\s*```(shell|csharp)[ \t]*\n([\s\S]*?)\n```", m =>
                                                                                                                                   {
                                                                                                                                       var off  = m.Groups[1].Value == "regexp-off";
                                                                                                                                       var mask = "re:" + m.Groups[2].Value.Trim();
                                                                                                                                       var kind = m.Groups[3].Value;
                                                                                                                                       var body = m.Groups[4].Value;
                                                                                                                                       if( kind == "csharp" && body.Contains("(?=//#region|//#endregion") )
                                                                                                                                       {
                                                                                                                                           list.Add("the region-marker step");
                                                                                                                                           return "";
                                                                                                                                       }

                                                                                                                                       if( kind == "shell" )
                                                                                                                                       {
                                                                                                                                           // the lines of an old shell block made one command; a path of the received folder lost its leading /
                                                                                                                                           body = Regex.Replace(Regex.Replace(body.Trim(), @"\s*\n\s*", " "), @"(?<=^|\s|"")[\\/](?=(InCPP|InCS|InC|InGO|InJAVA|InRS|InTS|InSwift|InDart|InPy)[\\/])", "");
                                                                                                                                           var program = Path.GetFileNameWithoutExtension(body.Split(' ')[0].Trim('"')).ToLowerInvariant();
                                                                                                                                           if( !off && formatters.Contains(program) )
                                                                                                                                           {
                                                                                                                                               list.Add($"the formatter step `{body}`: AdHocAgent.toml sets the formatters");
                                                                                                                                               return "";
                                                                                                                                           }
                                                                                                                                       }

                                                                                                                                       return $"```{kind}{(off ? "-off" : "")} {mask}\n{body}\n```";
                                                                                                                                   });
                t = Regex.Replace(t, @"(?<!\\)\[(before|after) deployment\]\(([^\n]+?)\)(?=\s*$|\s)", m => $"\n```{m.Groups[1].Value}\n{m.Groups[2].Value}\n```\n", RegexOptions.Multiline);
                if( t == md.Replace("\r\n", "\n") ) return null;
                return Regex.Replace(t, @"\n{3,}", "\n\n").Replace("\n", nl);
            }
        }
    }
