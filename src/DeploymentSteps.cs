            /// <summary>A glob as a regular expression over a path with `/`: `**/` any folders, `**` anything, `*` and `?` within a name, `{a,b}` either.</summary>
            internal static Regex glob(string mask)
            {
                var re     = new StringBuilder("^");
                var braces = 0;
                for( var i = 0; i < mask.Length; i++ )
                    switch( mask[i] )
                    {
                        case '*' when i + 2 < mask.Length && mask[i + 1] == '*' && mask[i + 2] == '/':
                            re.Append("(?:.*/)?");
                            i += 2;
                            break;
                        case '*' when i + 1 < mask.Length && mask[i + 1] == '*':
                            re.Append(".*");
                            i++;
                            break;
                        case '*':
                            re.Append("[^/]*");
                            break;
                        case '?':
                            re.Append("[^/]");
                            break;
                        case '{':
                            re.Append("(?:");
                            braces++;
                            break;
                        case '}' when 0 < braces:
                            re.Append(')');
                            braces--;
                            break;
                        case ',' when 0 < braces:
                            re.Append('|');
                            break;
                        case '\\':
                            re.Append('/');
                            break;
                        default:
                            re.Append(Regex.Escape(mask[i].ToString()));
                            break;
                    }

                return new Regex(re.Append('$').ToString(), RegexOptions.IgnoreCase);
            }

