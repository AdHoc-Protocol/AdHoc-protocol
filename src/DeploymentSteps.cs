            /// <summary>The fenced blocks at the top level of `md`, as CommonMark reads them: a block inside another is its text.</summary>
            internal static List<Block> blocks_of(string md)
            {
                var blocks = new List<Block>();
                var lines  = md.Replace("\r\n", "\n").Split('\n');
                for( var i = 0; i < lines.Length; i++ )
                {
                    if( fence(lines[i]) is not { } open ) continue;
                    var body  = new StringBuilder();
                    var start = i + 1;
                    for( i++; i < lines.Length; i++ )
                    {
                        if( fence(lines[i]) is { } close && close.mark == open.mark && open.length <= close.length && close.info.Length == 0 ) break;
                        body.Append(lines[i]).Append('\n');
                    }

                    blocks.Add(new Block(open.info, body.ToString(), start + 1));
                }

                return blocks;

                // a line opening or closing a fence: ``` or ~~~, three at least, indented three spaces at most; backticks have none in their info
                static (char mark, int length, string info)? fence(string line)
                {
                    var at = 0;
                    while( at < line.Length && at < 4 && line[at] == ' ' ) at++;
                    if( 3 < at || line.Length <= at || line[at] is not ('`' or '~') ) return null;
                    var mark = line[at];
                    var n    = 0;
                    while( at + n < line.Length && line[at + n] == mark ) n++;
                    if( n < 3 ) return null;
                    var info = line[(at + n)..].Trim();
                    if( mark == '`' && info.Contains('`') ) return null;
                    return (mark, n, info);
                }
            }

