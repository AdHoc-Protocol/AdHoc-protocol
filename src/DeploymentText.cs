## What a deployment does

1. It compares the list with what arrived. When they differ - a host added, a host gone - it says what changed and where the
   new files would go, and asks whether to deploy now. Lines that still match keep their routes and notes.
2. It runs the `before deployment` commands, then the steps below, on the received files.
3. It copies every file it is about to overwrite or delete into a numbered folder next to this file (`{received}_1`,
   `{received}_2`, ...). `restore.bat`, `restore.ps1` or `restore.sh` in that folder put everything back.
4. It writes the files to their destinations, with your code in them, and reports where each one went.
5. It runs the `after deployment` commands: a build or a test run sees the deployed files.

The numbered folder also keeps, in `.description`, the description the deployed code came from. `AdHocAgent MyProtocol.cs~`
compares the one you are editing with it and reports which hosts the changes reach.

## Your code inside generated files

Generated files contain injection points: regions whose content survives every regeneration.

```text
//#region > Connection receiving
    your code
//#endregion > ǺÿÿČ.Project.Connection receiving     <- never edit, move or copy this line: its id finds your code
```

(C# uses `#region` / `#endregion`.) Inside a region, the blocks between `//🌭<` and `//🌭/>` are generated: one you
leave as it is follows the generator, one you edit - change it, comment it out - is yours and stays as you left it;
delete a block to have the generator's version back. Leave the markers alone. After an update the agent marks what
needs a look with `//todo 🔴`. If a region you wrote code in is gone from the new code, the agent shows that code and
asks before dropping it.

## Formatting the code

The code arrives unformatted. The formatters below are switched off, because a step whose program is not installed stops
the deployment: to switch one on, install it and change its `regexp-off` to `regexp`.

A step runs on the received files before anything is copied. It is two fenced blocks, one right after the other: a `regexp`
block that selects files by their full path, then a `shell` or a `csharp` block. Steps run in the order they appear; Markdown
files are never processed.

- `shell`: one command per line; a line that starts with a space or a tab continues the one above. `FILE_PATH` is replaced
  with the path of each selected file.
- `csharp`: a class `Program` with `public static void Main(string[] args)`; `args[0]` is the file. Lines in quotes at the top,
  such as `"System.Text.RegularExpressions"`, add assembly references.
- A path that starts with a language folder, such as `/InCS/`, is a path inside the received folder.

To run a command once, before or after the whole deployment, write a link whose text is `before deployment` or
`after deployment` and whose target is the command: `［before deployment](dotnet format "/InCS/MyHost")`. Written with `［`, a
full-width bracket, as here, it does nothing; with an ordinary `[` it runs, wherever in this file it stands.

### Java, C#, C++: clang-format

```regexp-off
\.(java|cs|cpp|h)$
```

