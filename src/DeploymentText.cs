## What a deployment does

1. It compares the list with what arrived. When they differ - a host added, a host gone - it says what changed and where the
   new files would go, and asks whether to deploy now. Lines that still match keep their routes and notes.
2. It runs the `before deployment` commands, then the steps below, on the received files.
3. It copies every file it is about to overwrite or delete into a numbered folder next to this file (`{received}_1`,
   `{received}_2`, ...). `restore.bat`, `restore.ps1` or `restore.sh` in that folder put everything back.
4. It writes the files to their destinations, with your code in them, and reports where each one went.
5. It runs the `after deployment` commands: a build or a test run sees the deployed files.

The numbered folder also keeps, in `.description`, the description the deployed code came from. `AdHocAgent MyProtocol.cs~`
compares the one you are editing with it and reports which hosts the changes reach.

## Your code inside generated files

Generated files contain injection points: regions whose content survives every regeneration.

```text
//#region > Connection receiving
    your code
//#endregion > ǺÿÿČ.Project.Connection receiving     <- never edit, move or copy this line: its id finds your code
```

(C# uses `#region` / `#endregion`.) Inside a region, the blocks between `//🌭<` and `//🌭/>` are generated: one you
leave as it is follows the generator, one you edit - change it, comment it out - is yours and stays as you left it;
delete a block to have the generator's version back. Leave the markers alone. After an update the agent marks what
needs a look with `//todo 🔴`. If a region you wrote code in is gone from the new code, the agent shows that code and
asks before dropping it.

## Formatting the code

The agent formats the received code itself, before anything is copied: each language by its formatter, set in
`AdHocAgent.toml` beside the agent - clang-format, prettier, rustfmt, gofmt, ruff, dart format, swift-format. Give a
formatter that is not on the PATH its full path there. One that is not installed is skipped with a warning, and its files
go as they came.

## Steps of your own

A step runs a tool or a piece of code of yours on the received files, after the formatting and before anything is copied.
It is one fenced block: its first line names what runs and on which files.

````text
```shell InTS/**/*.ts
prettier --check FILES
```

```csharp InCS/**/*.cs
text.Replace("\t", "    ")
```
````

- What runs: `shell` (cmd on Windows, sh elsewhere), `cmd`, `sh`, `bash`, `pwsh`, `powershell`, or `csharp`.
- On which files: a mask of the path inside the received folder - `InCS/**/*.cs`, `**/*.{java,cs}`, `InTS/Browser/*` -
  or `re:` and a regular expression over the full path.
- A shell block is a script of its shell, run in the received folder: one command a line. `FILES` is replaced with the
  files it selects, as many as a command line takes; `FILE_PATH` with each one, a run a file; with neither it runs once.
  `RECEIVED` is the received folder.
- A `csharp` block is C# as you would paste it, the usual usings in place:
  - an expression - the new text of each file;
  - statements - `text`, `path`, `relative`, `language`, `host` at hand; set `text`, and the file is written;
  - code that names `files` runs once, with all the selected files, each with its `text`;
  - a class `Program` with `Main(string[] args)` is called with each file;
  - `#r "lib/My.dll"` and `#r "nuget: Humanizer, 2.14.1"` reference libraries.
- Steps run in the order they stand. A block inside another - an example in a ````text block, as here - does not run;
  `shell-off`, `csharp-off` switch a step off.

