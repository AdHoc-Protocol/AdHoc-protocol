using System;
using System.Collections.Generic;
using System.Text;
using System.Text.RegularExpressions;

namespace org.unirail;

/// <summary>
/// The documentation of an entity as the Server takes it: ready, one representation a language, so that the Server
/// only picks its own - no parsing and no escaping there.
/// <code>
/// [count][len 0][len 1]...  representation 0  representation 1 ...
/// </code>
/// Every number is one char. The representations go in the order the Server numbers the languages: 0 Java, 1 TypeScript, 2 C#;
/// then 3 - plain text, no comment around it and code between backticks, for the reflection of the generated code ( Meta_ ).
/// The format is set by the pair: <c>Entity.doc</c> of the Server (Generator.scala) reads what is written here.
/// <para>
/// Until the project is ready the documentation of an entity is text with the marks of <c>ToIntermediateFormat</c>:
/// the filters <c>[KeepDoc]</c> / <c>[SkipDoc]</c> read it. It is made ready last, by <see cref="for_languages"/>.
/// </para>
/// </summary>
public static class Docs{
    const int Java = 0, TypeScript = 1, CSharp = 2, Plain = 3;

    static readonly Regex marks = new(@"@@(SUMMARY|REMARKS|PARA|CODE)_(START|END)@@", RegexOptions.Compiled);

    // Code inside a sentence is put between spaces; what is left over of them is removed: runs of spaces, the space between
    // the code and the mark of punctuation after it, the space between an opening bracket and the code.
    static readonly Regex spaces      = new(@"[ \t]{2,}", RegexOptions.Compiled);
    static readonly Regex before_mark = new(@"(</c>|</code>|`) (?=[,.;:!?)])", RegexOptions.Compiled);
    static readonly Regex after_open  = new(@"\( (?=<c>|<code>|`)", RegexOptions.Compiled);

    /// <summary>What goes to the Server in place of <paramref name="doc"/>. What is ready already stays as it is.</summary>
    public static string? for_languages(string? doc)
    {
        // The Observer is not the Server: for it `get_doc` has made the documentation HTML already, and it shows that as it is.
        if( AdHocAgent.is_diagramming ) return doc;

        if( string.IsNullOrWhiteSpace(doc) || ready(doc) ) return doc;

        var java = render(doc, Java);
        var ts   = render(doc, TypeScript);
        var cs   = render(doc, CSharp);
        var text = render(doc, Plain);

        // a length is one char: it has to be a char that goes through UTF-8, and the whole has to fit the field
        if( 0xD800 <= java.Length || 0xD800 <= ts.Length || 0xD800 <= cs.Length || 0xD800 <= text.Length || 65000 < 5 + java.Length + ts.Length + cs.Length + text.Length ) return plain(doc);

        return new StringBuilder(5 + java.Length + ts.Length + cs.Length + text.Length)
               .Append((char)4).Append((char)java.Length).Append((char)ts.Length).Append((char)cs.Length).Append((char)text.Length)
               .Append(java).Append(ts).Append(cs).Append(text)
               .ToString();
    }

    /// <summary>The check the Server makes: the lengths of the head add up to the rest of the text.</summary>
    static bool ready(string doc)
    {
        int count = doc[0];
        if( count < 1 || 8 < count || doc.Length < 1 + count ) return false;
        var sum = 0;
        for( var i = 0; i < count; i++ ) sum += doc[1 + i];
        return 1 + count + sum == doc.Length;
    }

    /// <summary>The text without the marks: what the Server prints as it is when the documentation is too long to be made ready.</summary>
    static string plain(string doc) => marks.Replace(doc, " ").Trim();

    // a section of the documentation: the text of it is in the target language already
    sealed class Section(string kind){
        public readonly string        kind = kind; // "summary", "remarks", "" - what stands outside of both
        public readonly StringBuilder text = new();
    }

    static string render(string doc, int lang)
    {
        var sections = new List<Section>();
        var section  = new Section("");
        var code     = false;
        var at       = 0;

        void text(string s)
        {
            if( s.Length == 0 ) return;
            if( code ) section.text.Append(inline_code(s.Trim(), lang));
            else section.text.Append(escaped(s, lang));
        }

        void close(string next)
        {
            if( 0 < section.text.ToString().Trim().Length ) sections.Add(section);
            section = new Section(next);
        }

        foreach( Match m in marks.Matches(doc) )
        {
            text(doc[at..m.Index]);
            at = m.Index + m.Length;
            var start = m.Groups[2].Value == "START";
            switch( m.Groups[1].Value )
            {
                case "SUMMARY":
                    close(start ? "summary" : "");
                    break;
                case "REMARKS":
                    close(start ? "remarks" : "");
                    break;
                case "CODE":
                    code = start;
                    break;
                case "PARA":
                    section.text.Append(lang switch
                                        {
                                            Java                => start ? "\n<p>\n" : "\n",
                                            TypeScript or Plain => start ? "\n\n" : "\n",
                                            _                   => start ? "\n<para>" : "</para>\n"
                                        });
                    break;
            }
        }

        text(doc[at..]);
        close("");
        if( sections.Count == 0 ) return "";

        var dst = new StringBuilder();
        if( lang == Plain ) // the lines as they are, a section from the next by an empty line
        {
            for( var i = 0; i < sections.Count; i++ )
            {
                if( 0 < i ) dst.Append("\n\n");
                dst.Append(string.Join("\n", lines(sections[i].text.ToString())));
            }

            return dst.ToString();
        }

        if( lang == CSharp )
        {
            // A declaration has one summary: the first section is it, whatever it was, the rest are remarks.
            // A line starts with a space: a formatter leaves a comment of the first column where it is.
            for( var i = 0; i < sections.Count; i++ )
            {
                var tag = i == 0 ? "summary" : "remarks";
                dst.Append(" /// <").Append(tag).Append(">\n");
                foreach( var line in lines(sections[i].text.ToString()) ) dst.Append(line.Length == 0 ? " ///\n" : " /// " + line + "\n");
                dst.Append(" /// </").Append(tag).Append(">\n");
            }

            return dst.ToString();
        }

        dst.Append("/**\n");
        for( var i = 0; i < sections.Count; i++ )
        {
            if( 0 < i ) dst.Append(lang == Java ? " * <p>\n" : " *\n");
            foreach( var line in lines(sections[i].text.ToString()) ) dst.Append(line.Length == 0 ? " *\n" : " * " + line + "\n");
        }

        return dst.Append(" */\n").ToString();
    }

    /// <summary>The lines of a section: trimmed, no empty line at the ends and no two of them in a row.</summary>
    static List<string> lines(string text)
    {
        var dst = new List<string>();
        foreach( var raw in text.Replace("\r\n", "\n").Replace('\r', '\n').Split('\n') )
        {
            var line = after_open.Replace(before_mark.Replace(spaces.Replace(raw.Trim(), " "), "$1"), "(");
            if( line.Length == 0 && (dst.Count == 0 || dst[^1].Length == 0) ) continue;
            dst.Add(line);
        }

        while( 0 < dst.Count && dst[^1].Length == 0 ) dst.RemoveAt(dst.Count - 1);
        return dst;
    }

    /// <summary>Text that cannot end the comment it stands in, start a tag of it or break its markup.</summary>
    static string escaped(string text, int lang)
    {
        switch( lang )
        {
            case CSharp:
                return text.Replace("&", "&amp;").Replace("<", "&lt;").Replace(">", "&gt;");
            case Java:
                // `\` as an entity: Java decodes `\uXXXX` before it lexes, inside a comment too
                return text.Replace("&", "&amp;").Replace("<", "&lt;").Replace(">", "&gt;").Replace("*/", "*&#47;").Replace("@", "&#64;").Replace("\\", "&#92;");
            case Plain:
                return text; // a value of a string, not a comment: nothing in it can end anything
            default:
                return text.Replace("*/", "*\\/");
        }
    }

    static string inline_code(string code, int lang)
    {
        if( code.Length == 0 ) return "";
        switch( lang )
        {
            case CSharp:
                return " <c>" + escaped(code, CSharp) + "</c> ";
            case Java:
                return " <code>" + escaped(code, Java) + "</code> ";
            case Plain:
                var t = code.Contains('`') ? "``" : "`";
                return " " + t + code + t + " ";
            default:
                var tick = code.Contains('`') ? "``" : "`";
                return " " + tick + code.Replace("*/", "*\\/") + tick + " ";
        }
    }
}
