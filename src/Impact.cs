        static string words(string s) => string.Join(' ', s.Split((char[]?)null, StringSplitOptions.RemoveEmptyEntries));

        static T attempt<T>(Func<T> get, T otherwise)
        {
            try { return get(); }
            catch( Exception ) { return otherwise; }
