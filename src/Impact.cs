            }

            /// <summary>The declaration of a changed entity, quoted: new, gone, edited line by line, or as it stands when the change is not in its text.</summary>
            List<Row> quote(Change c)
            {
                var before = c.was is { own: true } ? was.decls.GetValueOrDefault(c.was.decl!) : null;
                var after  = c.now is { own: true } ? now.decls.GetValueOrDefault(c.now.decl!) : null;

                var lines = c.was == null ? rows(null, null, after) :
                            c.now == null ? rows(null, null, null, before) :
                            c.code        ? rows(before, after, null) :
                            rows(null, after, null);

                // a new or a gone entity: its members are its text as well, a step in under its heading
                if( c.was == null || c.now == null )
                    foreach( var m in c.item.members.Where(m => m.own).Select(m => (c.now != null ? now : was).decls.GetValueOrDefault(m.decl!)).Where(m => m != null).DistinctBy(m => (m!.first, m.code)).OrderBy(m => m!.first) )
                        lines.AddRange((c.now != null ? rows(null, null, m) : rows(null, null, null, m)).Select(r => r with { text = "    " + r.text }));

                return lines;
            }

            Dictionary<string, List<Change>>? causes;

            /// <summary>
            /// The edits of declarations that are no entities - a pack set, a type alias, a template - which the text of
            /// <paramref name="d"/> names: what a change of an entity comes from when its own text is as it was.
            /// </summary>
            IEnumerable<Change> causes_of(Decl d)
            {
                if( causes == null )
                {
                    causes = new Dictionary<string, List<Change>>();
                    foreach( var c in x.loose )
                    {
                        var parts = c.item.decl!.Split('.');
                        // a member is reached by the name of its type: a field typed `max_1_000_chars` names the alias, not its TYPEDEF
                        foreach( var part in c.item.kind == "Member" && 1 < parts.Length ? parts[^2..] : parts[^1..] )
                        {
                            var name = part.Split('`', '(')[0];
                            if( !causes.TryGetValue(name, out var list) ) causes[name] = list = [];
                            list.Add(c);
                        }
                    }
                }

                return d.tokens.Split(' ').Distinct().Where(causes.ContainsKey).SelectMany(token => causes[token]).Distinct();
            }

            /// <summary>A line of a quote: ' ' as it is, '+' new, '-' gone; of the current description - with the place to open.</summary>
            readonly record struct Row(char op, string text, int line, string? file, int lo = 0, int hi = 0); // lo..hi - the part of the line that differs

            /// <summary>
            /// The lines of a quote. <paramref name="context"/> - the declaration as it is; <paramref name="added"/> /
            /// <paramref name="removed"/> - one that came or went; <paramref name="before"/> with <paramref name="context"/> -
            /// the two texts of an edited one, line by line.
            /// </summary>
            static List<Row> rows(Decl? before, Decl? context, Decl? added, Decl? removed = null)
            {
                var dst = new List<Row>();

                void all(Decl d, char op, bool current)
                {
                    var lines = d.code.Split('\n');
                    for( var i = 0; i < lines.Length; i++ ) dst.Add(new Row(op, lines[i], d.first + i, current ? d.file : null));
                }

                if( added   != null ) all(added, '+', true);
                if( removed != null ) all(removed, '-', false);
                if( context == null ) return dst;

                if( before == null )
                {
                    all(context, ' ', true);
                    return dst;
                }

                var a   = before.code.Split('\n');
                var b   = context.code.Split('\n');
                var lcs = new int[a.Length + 1, b.Length + 1];
                for( var i = a.Length - 1; 0 <= i; i-- )
                    for( var j = b.Length - 1; 0 <= j; j-- )
                        lcs[i, j] = a[i] == b[j] ? lcs[i + 1, j + 1] + 1 : Math.Max(lcs[i + 1, j], lcs[i, j + 1]);

                for( int i = 0, j = 0; i < a.Length || j < b.Length; )
                    if( i < a.Length && j < b.Length && a[i] == b[j] )
                    {
                        dst.Add(new Row(' ', b[j], context.first + j, context.file));
                        i++;
                        j++;
                    }
                    else if( i < a.Length && (j == b.Length || lcs[i, j + 1] <= lcs[i + 1, j]) ) dst.Add(new Row('-', a[i], before.first + i++, null));
                    else dst.Add(new Row('+', b[j], context.first + j++, context.file));

                // one line replaced by one line: mark what differs inside it
                for( var k = 0; k + 1 < dst.Count; k++ )
                    if( dst[k].op == '-' && dst[k + 1].op == '+' && (k == 0 || dst[k - 1].op == ' ') && (k + 2 == dst.Count || dst[k + 2].op == ' ') )
                    {
                        var (s, t) = (dst[k].text, dst[k + 1].text);
                        var head   = 0;
                        while( head < s.Length && head < t.Length && s[head] == t[head] ) head++;
                        var tail = 0;
                        while( tail < s.Length - head && tail < t.Length - head && s[^(tail + 1)] == t[^(tail + 1)] ) tail++;

                        dst[k]     = dst[k] with { lo = head, hi = s.Length     - tail };
                        dst[k + 1] = dst[k + 1] with { lo = head, hi = t.Length - tail };
                    }

                return dst;
            }

