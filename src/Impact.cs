#region declarations
            static string key_of(SyntaxNode node)
            {
                var parts = new List<string>();
                for( var n = node; n != null; n = n.Parent )
                    switch( n )
                    {
                        case VariableDeclaratorSyntax v:        parts.Add(v.Identifier.ValueText); break;
                        case EnumMemberDeclarationSyntax m:     parts.Add(m.Identifier.ValueText); break;
                        case PropertyDeclarationSyntax p:       parts.Add(p.Identifier.ValueText); break;
                        case MethodDeclarationSyntax m:         parts.Add(m.Identifier.ValueText + "()"); break;
                        case EnumDeclarationSyntax e:           parts.Add(e.Identifier.ValueText); break;
                        case TypeDeclarationSyntax t:           parts.Add(t.Identifier.ValueText + (t.TypeParameterList == null ? "" : "`" + t.TypeParameterList.Parameters.Count)); break;
                        case BaseNamespaceDeclarationSyntax ns: parts.Add(ns.Name.ToString()); break;
                    }

                parts.Reverse();
                return string.Join('.', parts);
            }

            void read_declarations()
            {
                foreach( var file in files )
                {
                    var src  = File.ReadAllText(file);
                    var tree = CSharpSyntaxTree.ParseText(src, path: file);

                    foreach( var node in tree.GetRoot().DescendantNodes(n => n is CompilationUnitSyntax or BaseNamespaceDeclarationSyntax or BaseTypeDeclarationSyntax) )
                        switch( node )
                        {
                            case BaseTypeDeclarationSyntax type:
                                add(type, type, type.Identifier, type.OpenBraceToken.IsKind(SyntaxKind.OpenBraceToken) ?
                                                                     type.OpenBraceToken.SpanStart :
                                                                     type.Span.End, false);
                                break;
                            case EnumMemberDeclarationSyntax member: add(member,   member,   member.Identifier,   member.Span.End,   true); break;
                            case PropertyDeclarationSyntax property: add(property, property, property.Identifier, property.Span.End, true); break;
                            case MethodDeclarationSyntax method:     add(method,   method,   method.Identifier,   method.Span.End,   true); break;
                            case FieldDeclarationSyntax field:
                                foreach( var variable in field.Declaration.Variables ) add(variable, field, variable.Identifier, field.Span.End, true);
                                break;
                        }

                    void add(SyntaxNode node, SyntaxNode whole, SyntaxToken name, int end, bool member)
                    {
                        var key = key_of(node);
                        if( decls.ContainsKey(key) ) return; // an overload, a part of a partial type: the first stands for all

                        var at    = name.GetLocation().GetLineSpan().StartLinePosition;
                        var first = whole.GetLocation().GetLineSpan().StartLinePosition;

                        var decl = decls[key] = new Decl
                                                {
                                                    key    = key,
                                                    name   = key[(key.LastIndexOf('.') + 1)..],
                                                    file   = file,
                                                    line   = at.Line        + 1,
                                                    col    = at.Character   + 1,
                                                    first  = first.Line     + 1,
                                                    member = member,
                                                    code   = tidy(src[whole.SpanStart..end], first.Character),
                                                    tokens = string.Join(' ', whole.DescendantTokens().TakeWhile(t => t.SpanStart < end).Select(t => t.Text)),
                                                    doc    = comments(whole, end)
                                                };

                        if( !member || key.Length == decl.name.Length ) return;
                        var parent = key[..(key.Length - decl.name.Length - 1)];
                        if( !members.TryGetValue(parent, out var list) ) members[parent] = list = [];
                        list.Add(decl);
                    }
                }
            }

            /// <summary>The text of a declaration for a quote: the agent's marks out, the indent of its first line off every line.</summary>
            static string tidy(string code, int indent)
            {
                var lines = uid_mark.Replace(code, "").Replace("\r", "").Split('\n');
                for( var i = 0; i < lines.Length; i++ )
                {
                    var line = lines[i].TrimEnd();
                    var cut  = 0;
                    if( 0 < i )
                        while( cut < indent && cut < line.Length && line[cut] is ' ' or '\t' )
                            cut++;
                    lines[i] = line[cut..];
                }

                return string.Join('\n', lines).TrimEnd();
            }

            /// <summary>
            /// The comments of a declaration - above it, between its attributes, after it on its line - as one line of
            /// words: everything written in its text ( up to <paramref name="end"/> ) that is not a token. The numbers
            /// tables are the agent's, not comments.
            /// </summary>
            static string comments(SyntaxNode node, int end)
            {
                var sb = new StringBuilder();

                void take(SyntaxTriviaList trivia)
                {
                    foreach( var t in trivia )
                        if( t.IsKind(SyntaxKind.SingleLineCommentTrivia) || t.IsKind(SyntaxKind.MultiLineCommentTrivia) ||
                            t.GetStructure() is DocumentationCommentTriviaSyntax doc && ProjectImpl.numbers_table(doc) == null )
                            sb.Append(t.ToFullString()).Append('\n');
                }

                foreach( var token in node.DescendantTokens().TakeWhile(t => t.SpanStart < end) )
                {
                    take(token.LeadingTrivia);
                    take(token.TrailingTrivia);
                }

                return words(uid_mark.Replace(sb.ToString(), ""));
            }
