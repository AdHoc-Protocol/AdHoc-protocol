            /// <summary>The two texts of an edited comment: only where they part, with a few words around - a comment may run for a page.</summary>
            void comment(Change c)
            {
                // as written at the declaration; what the generator is given is the same comment put into its own form
                var before = c.was is { own: true } ? was.decls.GetValueOrDefault(c.was.decl!) : null;
                var after  = c.now is { own: true } ? now.decls.GetValueOrDefault(c.now.decl!) : null;

                var (s, t) = before != null && after != null && before.doc != after.doc ? (before.doc, after.doc) : (c.was!.doc, c.now!.doc);
                var head   = 0;
                while( head < s.Length && head < t.Length && s[head] == t[head] ) head++;
                var tail = 0;
                while( tail < s.Length - head && tail < t.Length - head && s[^(tail + 1)] == t[^(tail + 1)] ) tail++;

                const int AROUND = 70;

                string part(string doc)
                {
                    var start = Math.Max(0, head - AROUND);
                    var end   = Math.Min(doc.Length, doc.Length - tail + AROUND);
                    return (0 < start ? "… " : "") + esc(doc[start..head]) + "<mark>" + esc(doc[head..(doc.Length - tail)]) + "</mark>" + esc(doc[(doc.Length - tail)..end]) + (end < doc.Length ? " …" : "");
                }

                o.Append("<div class=docs>");
                if( 0 < s.Length ) o.Append($"<div class=\"docline del\">{part(s)}</div>");
                if( 0 < t.Length ) o.Append($"<div class=\"docline add\">{part(t)}</div>");
                o.Append("</div>");
            }

            /// <summary>What differs in an entity or a member: its properties and the quote of its declaration.</summary>
            void body(Change c, bool member = false)
            {
                if( 0 < c.props.Count )
                {
                    o.Append("<ul class=diffs>");
                    foreach( var p in c.props )
                    {
                        o.Append($"<li><span class=p>{esc(p.name)}</span>");
                        switch( p.kind )
                        {
                            case Prop.SET:
                                foreach( var v in p.was ) o.Append($"<span class=\"v del\">− {esc(v)}</span>");
                                foreach( var v in p.now ) o.Append($"<span class=\"v add\">+ {esc(v)}</span>");
                                break;
                            case Prop.ORDER:
                                o.Append($"<span class=\"v del\">{esc(string.Join(", ", p.was))}</span><span class=arrow>→</span><span class=\"v add\">{esc(string.Join(", ", p.now))}</span>");
                                break;
                            default:
                                o.Append(p.was.Length == 0 ? "<span class=\"v none\">not set</span>" : $"<span class=\"v del\">{esc(p.was[0])}</span>");
                                o.Append("<span class=arrow>→</span>");
                                o.Append(p.now.Length == 0 ? "<span class=\"v none\">not set</span>" : $"<span class=\"v add\">{esc(p.now[0])}</span>");
                                break;
                        }

                        o.Append("</li>");
                    }

                    o.Append("</ul>");
                }

                var lines = quote(c);

                // fields that changed places: the place is the quote - the fields as they stand now, under the heading of their pack
                foreach( var p in c.props.Where(p => p.kind == Prop.ORDER) )
                    foreach( var name in p.now )
                        if( c.now!.members.FirstOrDefault(m => m.name == name) is { own: true } moved && now.decls.GetValueOrDefault(moved.decl!) is { } d )
                            lines.AddRange(rows(null, d, null).Select(r => r with { text = "    " + r.text }));

                code(lines);

                if( c.props.Any(p => p.kind == Prop.ORDER) )
                    o.Append("<p class=note>Fields travel in the order they are declared - the primitive ones as well: the generator writes each sequence of fields as it stands in the description. Fields of one sequence that changed places are another pack on the wire, for every host that sends or receives it.</p>");

                // The properties differ and its own text does not: the edit is in a declaration it is built with.
                if( c is not { was: not null, now: not null, code: false } || c.props.All(p => p.kind == Prop.ORDER) ) return;

                var after = c.now.own ? now.decls.GetValueOrDefault(c.now.decl!) : null;
                var from  = after == null ? [] : causes_of(after).Take(3).ToList();

                foreach( var cause in from )
                {
                    o.Append($"<div class=cause><div class=mhead><span class=kind>comes from</span>{name_link(cause)}</div>");
                    if( quoted.Add(cause) ) code(quote(cause)); // quoted once in a card: several fields of a pack follow one alias
                    o.Append("</div>");
                }

                if( from.Count == 0 && !member )
                    o.Append(after == null ?
                                 "<p class=note>It has no declaration of its own: the description makes it out of the declarations around it.</p>" :
