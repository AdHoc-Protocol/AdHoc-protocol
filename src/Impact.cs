    /// <summary>
    /// What a change of the protocol description reaches: <c>AdHocAgent MyProtocol.cs~</c>.
    /// <para>
    /// Two versions of a description are read by the parser the code generation uses, and each is reduced to what the
    /// generator is given: hosts, packs with their fields and constants, connections with their actors and states,
    /// multiplexers - every reference by name, never by an index, since indices shift when anything is added. Beside
    /// that stands the text of every declaration, token by token, so an edit the model does not explain is still seen.
    /// </para>
    /// <para>
    /// A host has to be updated when anything its generated code is made of differs: its own declaration, a connection
    /// it is a party of, a pack it sends or receives there, a type one of those packs is built from. An edited comment
    /// is not such a thing: it changes the documentation of the generated code and nothing a host does, so it is never
    /// a reason - the page lists the edited comments apart, at its end. The order of a pack's fields is such a thing,
    /// the order of primitive fields too: the generator writes fields as they are declared.
    /// </para>
    /// <para>
    /// The result is one HTML page with one purpose - to say which hosts to update. They are what it opens with; why
    /// each is reached, the declarations quoted, every quote a link into the current description
    /// (<c>vscode://file/…</c>), is folded under them. The same answer is in the page for a program: one line of JSON
    /// in an element that is not shown, <c>&lt;script type="application/json" id="adhoc-impact"&gt;</c>.
    /// </para>
    /// </summary>
