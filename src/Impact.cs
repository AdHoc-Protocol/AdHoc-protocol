                if( d != null ) o.Append($"<a class=at href=\"{href(d.file, d.line, d.col)}\">{esc(Path.GetFileName(d.file))}:{d.line}</a>");
                o.Append("</header><p class=note>Its declaration is as it was. What changed is who handles it: a branch, a pack set or a field of another pack now brings it to this host, or no longer does.</p>");
