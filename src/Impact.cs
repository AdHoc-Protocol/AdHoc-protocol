#region the model
            void read_model(ProjectImpl root)
            {
                project = root._name;

                var by_idx = new Dictionary<int, PackImpl>();
                foreach( var p in root.packs ) by_idx[p.idx] = p;

                // A transform chain is a container pack holding a sub-pack per stage, and is referred to by index.
                // It is no entity of the description: it is told where it is used, as text.
                var chains = ProjectImpl.stream_chains.Values.ToHashSet();
                var stages = new HashSet<PackImpl>();
                foreach( var link in chains.SelectMany(chain => chain._constants_) )
                    if( link._value_int is { } i && by_idx.TryGetValue((int)i, out var stage) )
                        stages.Add(stage);

                string chain_text(PackImpl chain) => string.Join(" | ", chain._constants_.Select(link =>
                                                                                                   {
                                                                                                       if( link._value_int is not { } i || !by_idx.TryGetValue((int)i, out var stage) ) return link._name;
                                                                                                       if( stage._constants_.Count == 0 ) return stage._name;

                                                                                                       // a trim's constants are the legs it cuts, as connection indices: their names say the same and do not shift
                                                                                                       var trim = stage._name is "ToStream" or "FromStream";
                                                                                                       return $"{stage._name}({string.Join(", ", stage._constants_.Select(p => trim ? p._name : $"{p._name}={value(p)}"))})";
                                                                                                   }));

                string pack_name(PackImpl p) => attempt(() => p.full_path, p._name);

                string type_name(int t) => (int)DataType.t_subpack <= t ? ((DataType)t).ToString()[2..] :
                                           !by_idx.TryGetValue(t, out var p) ? "#" + t :
                                           chains.Contains(p) ? "chain " + chain_text(p) :
                                           pack_name(p);

                string value(ConstantImpl c) => c._array_ != null ? "[" + string.Join(", ", c._array_.Cast<object?>().Select(e => e == null ? "null" : text(e))) + "]" :
                                                c._value_string != null ? "\"" + c._value_string + "\"" :
                                                c._value_int    != null ? text(c._value_int) :
                                                c._value_double != null ? text(c._value_double) :
                                                "null";

                string? decl_of(HasDocs e)
                {
                    var symbol = e is Entity entity ? (ISymbol?)entity.symbol ?? e.symbol : e.symbol;
                    var node   = symbol?.DeclaringSyntaxReferences.FirstOrDefault()?.GetSyntax();
                    if( node == null ) return null;
                    var key = key_of(node);
                    return decls.ContainsKey(key) ? key : null;
                }

                // `home` - the entity a declaration-less one borrows its place in the description from
                Item add(Item it, HasDocs? e, Item? home = null, bool member = false)
                {
                    if( e != null )
                    {
                        it.decl = decl_of(e);
                        it.doc  = words(e._doc + " " + e._inline_doc);
                    }

                    it.own  =   it.decl != null && it.decl != home?.decl;
                    it.decl ??= home?.decl;

                    if( member ) home!.members.Add(it);
                    else
                    {
                        it.under = home?.id;
                        items.TryAdd(it.id, it);
                    }

                    return it;
                }

                void constants(Item it, HasDocs e, params ConstantImpl[] skip)
                {
                    foreach( var c in e._constants_ )
                        if( !skip.Contains(c) )
                            add(new Item(it.id + "." + c._name, it.kind == "Enum" ? "Enum member" : "Constant", c._name), c, it, true)
                                .set("type", type_name(c._exT))
                                .set("value", value(c));
                }

                void describe(FieldImpl f, Item it, string of)
                {
                    var exT = attempt(() => (int)f._exT, -1);
                    var inT = attempt(() => (int?)f._inT, null);

                    it.set(of + "type", exT < 0 ? "?" : type_name(exT));
                    if( inT != null && inT != exT )
                        if( by_idx.TryGetValue(inT.Value, out var chain) && chains.Contains(chain) ) it.set(of + "chain", chain_text(chain));
                        else it.set(of + "stored as", type_name(inT.Value));

                    it.set(of + "array", f._exT_array);
                    if( f.is_Map ) it.set(of + "collection", "map");
                    else if( f.is_Set ) it.set(of + "collection", "set");
                    if( f.dims is { Length: > 0 } ) it.set(of + "dimensions", string.Join(", ", f.dims));
                    it.set(of + "map/set length", f._map_set_len);
                    it.set(of + "map/set array",  f._map_set_array);
                    it.set(of + "min",            f._min_value);
                    it.set(of + "max",            f._max_value);
                    if( f._dir != Project.Host.Pack.Field._dir__.NULL ) it.set(of + "varint", f._dir < 0 ? "V" : f._dir == 0 ? "X" : "A");
                    it.set(of + "min (float)", f._min_valueD);
                    it.set(of + "max (float)", f._max_valueD);
                    if( f._bits != Project.Host.Pack.Field._bits__.NULL ) it.set(of + "bits", f._bits);
                    it.set(of + "null value", f._null_value);
                }

                // The order fields are declared in is the order they travel in, group by group. The generator splits the
                // fields of a pack with stable partitions ( Generator.scala, `fields_exT_by_ref` and its neighbours ) and
                // its emitters write each group in the order it came out, which is the order of the declaration:
                //   - strings, fields typed with a pack, collections - and with them every nullable field, whose null
                //     bits are written in the same sequence;
                //   - single primitive fields: numbers, booleans, enums, Value packs. Only a pack made of nothing else
                //     has them sorted, the widest first, and fields of one width stay as declared even there.
                // So two fields of one group swapped is another pack on the wire, and a primitive field moved past a
                // string is not. The test of the first group is the generator's own: `!is_single || !exT.is_primitive_or_value`.
                bool by_reference(FieldImpl f)
                {
                    if( f.dims is { Length: > 0 } || f._exT_array != null || f.is_Map || f.is_Set || f._map_set_len != null || f._map_set_array != null ) return true; // a collection
                    if( f.exT_primitive is { } primitive ) return primitive <= (int)DataType.t_string;

                    var type = attempt(() => f.get_exT_pack, null);
                    return type != null && type._id <= (int)DataType.t_string && !attempt(() => type.IsValuePack(), false);
                }

                string host_id(HostImpl h)                                                                     => "host:" + h.full_path;
                string pack_id(PackImpl p)                                                                     => "pack:" + pack_name(p);
                string connection_id(ConnectionImpl c)                                                         => "connection:" + c.full_path;
                string actor_id(ConnectionImpl c, ConnectionImpl.ActorImpl a)                                  => "actor:" + c.full_path + "/" + a._name;
                string state_id(ConnectionImpl c, ConnectionImpl.ActorImpl a, ConnectionImpl.StateImpl s)      => "state:" + c.full_path + "/" + a._name + "/" + s._name;

                string short_name(ISymbol symbol) => Entity.entities.TryGetValue(symbol, out var e) ? e.full_path :
                                                     symbol.ContainingType == null ? symbol.Name :
                                                     short_name(symbol.ContainingType) + "." + symbol.Name;

                // An entity's number is what it keeps through a rename - when it is written in the description, in a
                // numbers table or as a mark beside the name. A number given in this run may be the one a removed
                // entity has left, and says nothing of who the entity was.
                void number(Item it, Entity e)
                {
                    if( e.uid == ulong.MaxValue ) return;
                    it.set("uid", e.uid);

                    var symbol = (ISymbol?)e.symbol ?? ((HasDocs)e).symbol;
                    if( 0 < e.uid_marks.Count || symbol != null && ProjectImpl.projects.Any(p => p.numbers.TryGetValue(symbol, out var read) && read.numbers.Length != 0 && read.numbers[0] == e.uid) )
                        it.uid = e.uid;
                }

                // --- the project
                var prj = add(new Item("project:", "Project", root._name), root);
                prj.set("namespace", root._namespacE);
                number(prj, root);
                constants(prj, root);
                if( prj.decl != null ) name_root = prj.decl + ".";

                // --- hosts
                var live = root.hosts.Where(h => !attempt(() => h.IsModifier, false)).ToList();
                foreach( var h in live )
                {
                    var it = add(new Item(host_id(h), "Host", h._name), h);
                    number(it, h);
                    it.set("languages", langs(h._langs));
                    it.set("implementation by default", $"0x{h._default_impl_hash_equal:X8}");
                    foreach( var (symbol, config) in h.pack_impl.OrderBy(e => e.Key.ToString()) ) it.set("implementation of " + short_name(symbol), $"0x{config:X8}");
                    foreach( var (symbol, config) in h.field_impl.OrderBy(e => e.Key.ToString()) ) it.set("implementation of the field " + short_name(symbol), langs(config));
                    it.list("constants", h.const_enum_packs.Select(pack_name).Order());
                    constants(it, h);
                    hosts.Add(it.id);
                }

                // --- packs: the transmitted ones, enums, constant sets, headers
                var packs = new Dictionary<string, PackImpl>();
                foreach( var p in root.packs )
                {
                    if( chains.Contains(p) || stages.Contains(p) || !packs.TryAdd(pack_id(p), p) ) continue;

                    var resumable = p as ProjectImpl.ResumableImpl;
                    var it = add(new Item(pack_id(p), ProjectImpl.projects.Any(x => x.proxy == p) ? "Imported project" :
                                                      resumable != null                            ? "Guaranteed delivery" :
                                                      p.is_enum                                    ? "Enum" :
                                                      p.is_constants_set                           ? "Constants" :
                                                      p.is_Header                                  ? "Header" :
                                                      p.is_Stream                                  ? "Stream pack" :
                                                      p.is_File                                    ? "File pack" :
                                                      "Pack", pack_name(p)), p);

                    if( p.is_explicitly_transmittable ) it.set("id", p._id);
                    else if( p._id != (int)DataType.t_subpack ) it.set("form", ((DataType)p._id).ToString()[2..]);
                    number(it, p);
                    if( p._link != ushort.MaxValue && by_idx.TryGetValue(p._link, out var chain) ) it.set("chain", chain_text(chain));
                    if( p._stream_max != 0 ) it.set("stream max", p._stream_max);
                    if( p._nested_max != 0 ) it.set("nested max", p._nested_max);
                    if( p._referred ) it.set("used as a field type", true);

                    if( resumable != null )
                    {
                        it.set("guards", $"what {resumable.host?._name} sends over {resumable.connection?._name}");
                        it.set("journal, MB", resumable.resumable_megabytes);
                        if( resumable.target_packs != null ) it.list("packs", resumable.target_packs.Select(pack_name).Order());
                        constants(it, p, resumable.Host, resumable.Conn); // these two are indices
                    }
                    else constants(it, p);

                    it.list("order of the strings, non-primitive and nullable fields", p.fields.Where(f => by_reference(f) || f.nullable).Select(f => f._name), Prop.ORDER);
                    it.list("order of the primitive fields", p.fields.Where(f => !by_reference(f)).Select(f => f._name), Prop.ORDER);
                    foreach( var f in p.fields )
                    {
                        var fld = add(new Item(it.id + "." + f._name, "Field", f._name), f, it, true);
                        describe(f, fld, "");
                        if( f.V != null ) describe(f.V, fld, "value ");
                    }
                }

                // --- connections, their actors and states
                var connections = root.connections.Where(c => c.hostL != null && c.hostR != null && !c.is_Modifier).ToList();
                foreach( var c in connections )
                {
                    var it = add(new Item(connection_id(c), c.is_virtual ? "Virtual connection" : "Connection", c._name), c);
                    it.set("connects", $"{c.hostL!._name} ↔ {c.hostR!._name}");
                    number(it, c);
                    if( c._id < (int)DataType.t_subpack ) it.set("tunnel id", c._id);
                    if( 0 < c.viaPath.Length ) it.set("route", string.Join(" → ", c.viaPath.Select(i => connections.FirstOrDefault(x => x.idx == i)?._name ?? "#" + i)));
                    if( c.relay_carrier != null ) it.set("relayed over", c.relay_carrier._name);
                    // Which connections share a port is the business of the host the port is on. The host that dials
                    // opens its socket with its own number, whatever else the port serves: for it the port is a
                    // property of its connection.
                    if( root.multiplexes.FirstOrDefault(m => m.connections.Contains(c)) is { hosts.Count: > 0 } port ) it.set("multiplexed", $"on the port of {port.hosts[0]._name}");
                    if( c._link != ushort.MaxValue && by_idx.TryGetValue(c._link, out var chain) ) it.set("chain", chain_text(chain));
                    if( c.is_virtual )
                    {
                        it.set("MaxTunnels",          c._MaxTunnels);
                        it.set("MaxStream_KiloBytes", c._MaxStream_KiloBytes);
                    }

                    constants(it, c);

                    foreach( var a in c.actors )
                    {
                        var actor = add(new Item(actor_id(c, a), "Actor", c._name + "." + a._name), a, it);
                        number(actor, a);
                        actor.set("MaxActiveInstances", a._MaxActiveInstances);
                        if( a._Multicasting ) actor.set("multicasting", true);
                        constants(actor, a);

                        foreach( var s in a.states )
                        {
                            var state = add(new Item(state_id(c, a, s), "State", c._name + "." + (a._name == "Actor0" ? "" : a._name + ".") + s._name), s, actor);
                            number(state, s);

                            string branch(ConnectionImpl.BranchImpl b) => (b.packs.Count == 0 ? "nothing" : string.Join(", ", b.packs.Select(pack_name).Order())) + "  →  " +
                                                                           (b.goto_state == null                            ? "?" :
                                                                            b.goto_state == ConnectionImpl.StateImpl.Close ? "Close" :
                                                                            b.goto_state == ConnectionImpl.StateImpl.End   ? "End" :
                                                                            b.goto_state == s                              ? "stays" :
                                                                            b.goto_state._name);

                            state.list($"{c.hostL._name} sends", s.branchesL.Select(branch));
                            state.list($"{c.hostR._name} sends", s.branchesR.Select(branch));
                            state.doc = words(state.doc + " " + string.Join(' ', s.branchesL.Concat(s.branchesR).Select(b => b._doc)));
                            constants(state, s);
                        }
                    }
                }

                // --- multiplexers
                foreach( var m in root.multiplexes )
                {
                    if( m.hosts.Count == 0 ) continue;
                    var it = add(new Item("multiplex:" + m.full_path, "Multiplexer", m._name), m);
                    number(it, m);
                    it.set("port of", m.hosts[0]._name);
                    it.list("connections", m.connections.Select((c, i) => i + 1 < m.hosts.Count ? $"{c._name}, dialed by {m.hosts[i + 1]._name}" : c._name));
                    constants(it, m);
                }

                // --- what is written in an entity's body and is no field or constant of the model: a property that
                //     tunes it, an RPC method. Carried as a member, so that an edit there is an edit of the entity.
                foreach( var it in items.Values )
                    if( it.own && members.TryGetValue(it.decl!, out var written) )
                    {
                        var known = it.members.Where(m => m.own).Select(m => m.decl).ToHashSet();
                        foreach( var d in written.Where(d => !known.Contains(d.key)) )
                            it.members.Add(new Item(it.id + "." + d.name, "Declaration", d.name) { decl = d.key, own = true, doc = d.doc });
                    }

                // --- who a change of each entity reaches
                foreach( var h in live )
                {
                    var mine = uses[host_id(h)] = new Dictionary<string, List<Use>>();

                    void use(string id, string how, string group, string role = "")
                    {
                        if( !items.ContainsKey(id) ) return;
                        if( !mine.TryGetValue(id, out var list) ) mine[id] = list = [];
                        if( list.All(u => u.how != how) ) list.Add(new Use(how, group, role));
                    }

                    use(host_id(h), "the host itself", HOST);
                    use("project:", "the project", HOST);

                    foreach( var c in connections )
                    {
                        var L = c.hostL == h;
                        var R = c.hostR == h;

                        if( !L && !R )
                        {
                            // a host on the route of a virtual connection carries its bytes without reading them
                            if( c.viaPath.Select(i => connections.FirstOrDefault(x => x.idx == i)).Any(leg => leg != null && (leg.hostL == h || leg.hostR == h)) )
                                use(connection_id(c), "relays it", $"Connection {c._name} · relayed");
                            continue;
                        }

                        var peer  = L && R ? "itself" : (L ? c.hostR! : c.hostL!)._name;
                        var group = $"Connection {c._name} · with {peer}";

                        void sends(IEnumerable<PackImpl> list)
                        {
                            foreach( var p in list ) use(pack_id(p), $"sends to {peer} over {c._name}", group, "sends");
                        }

                        void takes(IEnumerable<PackImpl> list)
                        {
                            foreach( var p in list ) use(pack_id(p), $"receives from {peer} over {c._name}", group, "receives");
                        }

                        use(connection_id(c), $"its connection with {peer}", group);

                        foreach( var a in c.actors )
                        {
                            use(actor_id(c, a), $"an actor of {c._name}", group);
                            foreach( var s in a.states ) use(state_id(c, a, s), $"a state of {c._name}", group);

                            // the packs a side transmits and what they are built of - both sides have code for them
                            if( L )
                            {
                                sends(a.hostL_directly_transmitting_packs.Concat(a.hostL_indirectly_transmitting_packs));
                                takes(a.hostR_directly_transmitting_packs.Concat(a.hostR_indirectly_transmitting_packs));
                            }

                            if( R )
                            {
                                sends(a.hostR_directly_transmitting_packs.Concat(a.hostR_indirectly_transmitting_packs));
                                takes(a.hostL_directly_transmitting_packs.Concat(a.hostL_indirectly_transmitting_packs));
                            }
                        }

                        // and what a trim leaves to one side only: the payload it serializes while the peer keeps bytes,
                        // the payload it rebuilds out of the bytes the peer sent. The sets are the generator's `pkT` and `pkR` of a host.
                        if( L )
                        {
                            sends(c.toL);
                            takes(c.fromR);
                        }

                        if( R )
                        {
                            sends(c.toR);
                            takes(c.fromL);
                        }
                    }

                    foreach( var r in root.resumables )
                        if( r.connection != null && (r.connection.hostL == h || r.connection.hostR == h) )
                            use(pack_id(r), $"guaranteed delivery over {r.connection._name}", $"Connection {r.connection._name} · with {(r.connection.hostL == h ? r.connection.hostR : r.connection.hostL)?._name}");

                    foreach( var m in root.multiplexes )
                        if( 0 < m.hosts.Count && m.hosts[0] == h )
                            use("multiplex:" + m.full_path, "its multiplexed port", HOST);

                    foreach( var p in h.const_enum_packs ) use(pack_id(p), "its constants", TYPES);

                    // what the packs it handles are built of: the type of a field is a pack, an enum, a constant set
                    var todo = new Queue<string>(mine.Keys.Where(packs.ContainsKey));
                    while( todo.TryDequeue(out var id) )
                    {
                        var pack = packs[id];
                        foreach( var f in pack.fields )
                            foreach( var part in f.V == null ? new[] { f } : new[] { f, f.V } )
                            {
                                var type = attempt(() => part.get_exT_pack, null);
                                if( type == null || mine.ContainsKey(pack_id(type)) || !items.ContainsKey(pack_id(type)) ) continue;
                                use(pack_id(type), $"the type of {pack_name(pack)}.{f._name}", TYPES);
                                todo.Enqueue(pack_id(type));
                            }
                    }
                }
            }

            static string langs(Project.Host.Langs l) => (ushort)l == 0xFFFF ? "all" :
                                                         (ushort)l == 0      ? "none" :
                                                         string.Join(", ", Enum.GetValues<Project.Host.Langs>().Where(x => (ushort)x != 0xFFFF && (ushort)x != 0 && (l & x) == x).Select(x => x.ToString()));
#endregion
        }
