        /// <summary>
        /// <c>AdHocAgent Current.cs~ [Previous.cs~ | folder~] [imported .cs / .csproj …] [output folder]</c>.
        /// The previous version is the second argument marked with <c>~</c>: a description file, a folder that holds one
        /// under the same name, or a backup folder of a deployment. Without it the description saved by the last
        /// deployment is taken (<see cref="Deployment.DESCRIPTION"/> in the backup folder).
        /// </summary>
        public static void report(string[] args)
        {
            is_comparing = true;

            var previous = args.FirstOrDefault(a => a.EndsWith('~'));
            set_provided_paths(args.Where(a => !a.EndsWith('~')).ToArray());
            provided_paths = provided_paths.Select(Path.GetFullPath)
                                           .Where(p => !p.Equals(provided_path, StringComparison.OrdinalIgnoreCase))
                                           .Distinct(StringComparer.OrdinalIgnoreCase)
                                           .ToArray();

            if( !File.Exists(provided_path) ) exit($"There is no description file {provided_path}. Check the path.");

            var current = (main: provided_path, imports: provided_paths);
            var (main, imports, origin) = previous == null ?
                                              saved_by_deployment() :
                                              given(Path.GetFullPath(previous[..^1]));

            INF($"Comparing {current.main} with its previous version {main}");

            // The parser keeps one description at a time in its statics, so each version is reduced to plain data
            // before the next one is read.
            (provided_path, provided_paths) = (main, imports);
            var was = Version.read(ProjectImpl.init());

            (provided_path, provided_paths) = current;
            var now = Version.read(ProjectImpl.init());

            var comparison = new Comparison(was, now);
            var file       = Path.Combine(destination_dir_path, Path.GetFileNameWithoutExtension(provided_path) + ".changes.html");
            File.WriteAllText(file, new Page(comparison).render(origin), Deployment.UTF8_NO_BOM);

            var W = Console.Out;
            W.WriteLine();
            foreach( var (verdict, title) in new[] { (Verdict.NEW, "new"), (Verdict.UPDATE, "have to be updated"), (Verdict.GONE, "removed"), (Verdict.SAME, "not reached") } )
            {
                var hosts = comparison.hosts.Where(h => h.verdict == verdict).Select(h => h.name).ToArray();
                if( 0 < hosts.Length ) W.WriteLine($"  {title} ({hosts.Length}): {string.Join(", ", hosts)}");
            }

            W.WriteLine();
            INF($"The report is in {file}");

            if( Console.IsOutputRedirected ) return; // a scripted run reads the file, it does not want a browser
            try { Process.Start(new ProcessStartInfo { FileName = file, UseShellExecute = true }); }
            catch( Exception e ) { WRN($"Cannot open the report: {e.Message}"); }
        }

        /// <summary>The description saved by the last deployment: in the newest backup folder beside the deployment instructions file.</summary>
        static (string main, string[] imports, string origin) saved_by_deployment()
        {
            var name = Path.GetFileName(provided_path);
            var stem = Path.GetFileNameWithoutExtension(provided_path);

            // A backup folder is `<stem>_<n>`, beside the instructions file - which is in the output folder or in the working one.
            var places = new[] { destination_dir_path, Directory.GetCurrentDirectory() }.Select(Path.GetFullPath).Distinct(StringComparer.OrdinalIgnoreCase).Where(Directory.Exists).ToArray();
            var backups = places.SelectMany(dir => Directory.GetDirectories(dir, stem + "_*"))
                                .Where(dir => int.TryParse(Path.GetFileName(dir)[(stem.Length + 1)..], out _) && File.Exists(Path.Join(dir, Deployment.DESCRIPTION, name)))
                                .OrderByDescending(Directory.GetCreationTimeUtc)
                                .ToList();

            if( backups.Count == 0 )
                exit($"No previous version of {name} is found: no backup folder `{stem}_<n>` in {string.Join(" or ", places)} holds a `{Deployment.DESCRIPTION}`. " +
                     "Every deployment saves the description there; a backup made by an earlier AdHocAgent has none. Name the previous version yourself:\n\n" +
                     $"        AdHocAgent \"{provided_path}~\" \"<the previous {name}>~\"\n");

            // Right after a deployment its backup holds the very description that is on disk, and comparing with it
            // says nothing: the version before it is the newest one that differs.
            var files       = new[] { provided_path }.Concat(provided_paths).ToArray();
            var backup      = backups.FirstOrDefault(dir => !same(Path.Join(dir, Deployment.DESCRIPTION), files)) ?? backups[0];
            var description = Path.Join(backup, Deployment.DESCRIPTION);
            var main        = Path.Join(description, name);

            return (main, Directory.GetFiles(description, "*.cs").Where(f => !f.Equals(main, StringComparison.OrdinalIgnoreCase)).ToArray(), $"saved by the deployment backed up in {backup}");
        }

        static bool same(string description, string[] files) =>
            Directory.GetFiles(description, "*.cs").Length == files.Length &&
            Deployment.flat(files).All(f => File.Exists(Path.Join(description, f.name)) && File.ReadAllBytes(Path.Join(description, f.name)).AsSpan().SequenceEqual(File.ReadAllBytes(f.path)));

        /// <summary>The previous version named on the command line: a file, a folder with the description in it, or a backup folder.</summary>
        static (string main, string[] imports, string origin) given(string path)
        {
            var name = Path.GetFileName(provided_path);
            var dir  = path;
            var main = path;

            if( Directory.Exists(path) )
            {
                if( !File.Exists(Path.Join(path, name)) ) dir = Path.Join(path, Deployment.DESCRIPTION); // a backup folder of a deployment
                main = Path.Join(dir, name);
                if( !File.Exists(main) ) exit($"The folder {path} holds no {name}, neither itself nor in its `{Deployment.DESCRIPTION}`.");
            }
            else
            {
                if( !File.Exists(path) ) exit($"Cannot find the previous version of the protocol description {path}");
                dir = Path.GetDirectoryName(path)!;
            }

            // A saved description is complete in itself. Beside a lone file, a file named as a current import is that
            // import's previous version; an import with no such file there has not changed.
            var imports = Path.GetFileName(dir) == Deployment.DESCRIPTION ?
                              Directory.GetFiles(dir, "*.cs").Where(f => !f.Equals(main, StringComparison.OrdinalIgnoreCase)).ToArray() :
                              provided_paths.Select(now =>
                                                    {
                                                        var then = Path.Join(dir, Path.GetFileName(now));
                                                        return File.Exists(then) && !then.Equals(main, StringComparison.OrdinalIgnoreCase) ?
                                                                   then :
                                                                   now;
                                                    }).ToArray();

            return (main, imports, "named on the command line");
        }
