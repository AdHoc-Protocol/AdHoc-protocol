#region comparison
        /// <summary>The differing values of a property: of a set - what left and what came, of an order - the two orders of what is in both.</summary>
        sealed record PropDiff(string name, string[] was, string[] now, char kind){
            public static PropDiff? of(string name, Prop? a, Prop? b)
            {
                var kind = (b ?? a)!.kind;
                var x    = a?.values ?? [];
                var y    = b?.values ?? [];

                switch( kind )
                {
                    case Prop.VALUE: return x.SequenceEqual(y) ? null : new PropDiff(name, x, y, kind);
                    case Prop.SET:
                        var left = x.Except(y).ToArray();
                        var came = y.Except(x).ToArray();
                        return left.Length + came.Length == 0 ? null : new PropDiff(name, left, came, kind);
                    default:
                        var before = x.Intersect(y).ToArray();
                        var after  = y.Intersect(x).ToArray();
                        return before.SequenceEqual(after) ? null : new PropDiff(name, before, after, kind);
                }
            }
        }

        /// <summary>What differs in one entity between the versions. <c>was == null</c> - it is new, <c>now == null</c> - it is gone.</summary>
        sealed class Change(Item? was, Item? now){
            public readonly Item? was = was, now = now;

            public bool renamed; // the same entity, by its number, under another name
            public bool code;    // its declaration is written differently
            public bool doc;     // its comments differ

            public readonly List<PropDiff> props   = [];
            public readonly List<Change>   members = [];

            public Item item => now ?? was!;

            /// <summary>Differs in what the generated code is made of, not only in comments.</summary>
            public bool protocol => was == null || now == null || renamed || code || 0 < props.Count || members.Any(m => m.protocol);

            public bool any => protocol || doc || members.Any(m => m.any);
        }

        enum Verdict{ NEW, UPDATE, GONE, SAME }

        /// <summary>
        /// One reason a host has to be updated: an entity it depends on changed, or the entity is the same and the host's
        /// part in it is not. An edited comment is never a reason: it changes nothing a host does.
        /// </summary>
        sealed class Reason{
            public Change? change;           // null - the entity itself is as it was
            public Item    item = null!;
            public Use[]   was = [], now = [];
            public string  group = "";
        }

        sealed class HostReport{
            public string  id   = "";
            public string  name = "";
            public Item?   was, now;
            public Verdict verdict;

            public readonly List<Reason> reasons = [];
        }

        sealed class Comparison{
            public readonly Version was, now;

            public readonly Dictionary<string, string> renamed = new(); // the id an entity had -> the id it has
            public readonly Dictionary<string, string> named   = new(); // and back

            public readonly List<Change>               changes = []; // of entities: in the order of the current description, then the gone ones
            public readonly Dictionary<string, Change> by_now  = new();
            public readonly Dictionary<string, Change> by_was  = new();

            public readonly List<HostReport> hosts = [];
            public readonly List<Change>     loose = []; // edits of declarations that are no entity: a pack set, a template, a modifier

            public Comparison(Version was, Version now)
            {
                this.was = was;
                this.now = now;

                // An entity keeps its number through a rename, and whatever lives in a renamed entity moves with it.
                foreach( var kind in new[] { "host:", "pack:", "connection:", "actor:", "state:" } ) pair(kind);

                // What refers to a renamed entity names it anew, and that is the rename told once, on the entity: the
                // old properties are read with the new names. The longest first - a pack is named through its host.
                foreach( var (old, id) in renamed.Where(r => !r.Key.StartsWith("actor:") && !r.Key.StartsWith("state:")).OrderByDescending(r => was.items[r.Key].name.Length) )
                    if( was.items[old].name != now.items[id].name )
                        carried.Add((new Regex(@"(?<![\w.])" + Regex.Escape(was.items[old].name) + @"(?!\w)"), now.items[id].name));

                foreach( var it in now.items.Values )
                {
                    var old = was.items.GetValueOrDefault(named.GetValueOrDefault(it.id, it.id));
                    if( old != null && renamed.ContainsKey(old.id) && renamed[old.id] != it.id ) old = null; // its name is taken by another entity now
                    if( compare(old, it) is not { } change ) continue;
                    changes.Add(change);
                    by_now[it.id] = change;
                    if( old != null ) by_was[old.id] = change;
                }

                foreach( var old in was.items.Values )
                    if( !now.items.ContainsKey(old.id) && !renamed.ContainsKey(old.id) )
                        changes.Add(by_was[old.id] = new Change(old, null));

                read_hosts();
                read_loose();
            }

            void pair(string kind)
            {
                var gone  = was.items.Values.Where(i => i.id.StartsWith(kind) && !now.items.ContainsKey(i.id)).ToList();
                var fresh = now.items.Values.Where(i => i.id.StartsWith(kind) && !was.items.ContainsKey(i.id)).ToList();

                foreach( var old in gone )
                {
                    // where it lives now: the entity it lived in, under whatever name that has
                    var home = old.under == null ? null : now.items.ContainsKey(old.under) ? old.under : renamed.GetValueOrDefault(old.under);
                    if( old.under != null && home == null ) continue;

                    var there = fresh.Where(f => f.under == home && !named.ContainsKey(f.id)).ToList();

                    var match = old.under != null ? there.FirstOrDefault(f => local(f.name) == local(old.name)) : null; // moved with its home, the name kept
                    if( match == null && old.uid != ulong.MaxValue && gone.Count(g => g.under == old.under && g.uid == old.uid) == 1 && there.Count(f => f.uid == old.uid) == 1 )
                        match = there.First(f => f.uid == old.uid);
                    if( match == null ) continue;

                    renamed[old.id] = match.id;
                    named[match.id] = old.id;
                }
            }

            static string local(string name) => name[(name.LastIndexOf('.') + 1)..];

            // a reference in a comment with the sign that follows it: `<see cref='InJAVA'/>+-`, `<see cref='Pack'/>-`
            static readonly Regex see = new(@"<see\s+cref\s*=\s*['""][^'""]*['""]\s*/>\s*[-+]*", RegexOptions.Compiled);

            static string refs(string doc) => string.Join(' ', see.Matches(doc).Select(m => words(m.Value)));

            readonly List<(Regex find, string name)> carried = []; // the name a renamed entity had -> the name it has

            string carry(string s)
            {
                foreach( var (find, name) in carried ) s = find.Replace(s, _ => name);
                return s;
            }

            Change? compare(Item? a, Item? b)
            {
                var change = new Change(a, b);
                if( a == null || b == null ) return change;

                // by its own name: what lives in a renamed entity is not renamed with it
                change.renamed = local(a.name) != local(b.name);

                var before = carried.Count == 0 ? a.props : a.props.Select(p => p with { name = carry(p.name), values = p.values.Select(carry).ToArray() }).ToList();

                foreach( var name in b.props.Select(p => p.name).Concat(before.Select(p => p.name)).Distinct() )
                    if( PropDiff.of(name, before.FirstOrDefault(p => p.name == name), b.props.FirstOrDefault(p => p.name == name)) is { } diff )
                        change.props.Add(diff);

                if( a.own && b.own ) change.code = was.decls[a.decl!].tokens != now.decls[b.decl!].tokens;
                // a comment: as it is written at the declaration, and as the generator is given it
                change.doc = a.doc != b.doc || a.own && b.own && was.decls[a.decl!].doc != now.decls[b.decl!].doc;

                // members by name; the n-th of a name with the n-th of it
                static Dictionary<string, Item> index(List<Item> members)
                {
                    var dst = new Dictionary<string, Item>();
                    foreach( var m in members )
                    {
                        var key = m.name;
                        for( var n = 2; !dst.TryAdd(key, m); n++ ) key = m.name + "#" + n;
                    }

                    return dst;
                }

                var olds = index(a.members);
                var news = index(b.members);

                foreach( var (key, member) in news )
                    if( compare(olds.GetValueOrDefault(key), member) is { } diff )
                        change.members.Add(diff);
                foreach( var (key, member) in olds )
                    if( !news.ContainsKey(key) )
                        change.members.Add(new Change(member, null));

                // a rename alone rewrites the name in the declaration: that is the rename, not one more edit
                if( change.renamed && change.code && was.decls[a.decl!].tokens.Replace(was.decls[a.decl!].name, now.decls[b.decl!].name) == now.decls[b.decl!].tokens ) change.code = false;

                return change.any ? change : null;
            }

            void read_hosts()
            {
                foreach( var id in now.hosts )
                {
                    var old_id = named.GetValueOrDefault(id, id);
                    var host   = new HostReport { id = id, name = now.items[id].name, now = now.items[id], was = was.hosts.Contains(old_id) ? was.items[old_id] : null };
                    hosts.Add(host);

                    if( host.was == null )
                    {
                        // everything a new host handles is new to it: only what changed with it is told
                        host.verdict = Verdict.NEW;
                        foreach( var (item, how) in now.uses[id] )
                            if( by_now.GetValueOrDefault(item) is { protocol: true } change )
                                host.reasons.Add(new Reason { change = change, item = now.items[item], now = how.ToArray(), group = how[0].group });
                        continue;
                    }

                    var uses_now = now.uses[id];
                    var uses_was = was.uses[old_id];
                    var seen     = new HashSet<string>();

                    foreach( var (item, how) in uses_now )
                    {
                        var before = named.GetValueOrDefault(item, item);
                        var then   = uses_was.GetValueOrDefault(before);
                        if( then != null ) seen.Add(before);

                        var change = by_now.GetValueOrDefault(item) is { protocol: true } real ? real : null; // comments edited: the entity is as it was

                        // the entity is as it was: a reason only when the host's part in it is not - it handles it now, or
                        // has to serialize what it only parsed
                        if( change == null && then != null && then.Select(u => u.role).Distinct().Order().SequenceEqual(how.Select(u => u.role).Distinct().Order()) ) continue;

                        host.reasons.Add(new Reason { change = change, item = now.items[item], was = then?.ToArray() ?? [], now = how.ToArray(), group = how[0].group });
                    }

                    foreach( var (item, how) in uses_was )
                        if( !seen.Contains(item) )
                            host.reasons.Add(new Reason
                                             {
                                                 change = by_was.GetValueOrDefault(item) is { now: null } removed ? removed : null, // gone altogether, or only from this host
                                                 item   = now.items.GetValueOrDefault(renamed.GetValueOrDefault(item, item)) ?? was.items[item],
                                                 was    = how.ToArray(),
                                                 group  = how[0].group
                                             });

                    host.verdict = 0 < host.reasons.Count ? Verdict.UPDATE : Verdict.SAME;
                }

                foreach( var id in was.hosts )
                    if( !renamed.ContainsKey(id) && !now.hosts.Contains(id) )
                    {
                        var host = new HostReport { id = id, name = was.items[id].name, was = was.items[id], verdict = Verdict.GONE };
                        hosts.Add(host);
                        foreach( var (item, how) in was.uses[id] )
                            if( by_was.GetValueOrDefault(item) is { now: null } change ) // what went with it; the rest lives on for the other hosts and is told there
                                host.reasons.Add(new Reason { change = change, item = change.item, was = how.ToArray(), group = how[0].group });
                    }
            }

            void read_loose()
            {
                var owned_was = was.owned();
                var owned_now = now.owned();

                Item item(Version v, Decl d) => new(d.key, d.member ? "Member" : "Declaration", d.key.StartsWith(v.name_root) ? d.key[v.name_root.Length..] : d.key) { decl = d.key, own = true, doc = d.doc };

                foreach( var d in now.decls.Values.Where(d => !owned_now.Contains(d.key)) )
                    if( !was.decls.TryGetValue(d.key, out var old) )
                    {
                        if( !owned_was.Contains(d.key) ) loose.Add(new Change(null, item(now, d)));
                    }
                    else if( !owned_was.Contains(d.key) && (old.tokens != d.tokens || old.doc != d.doc) )
                        // The `<see cref=…/>` lines of a comment are not a comment: on a modifier they are what it adds,
                        // removes and configures. Whatever else is written around them is.
                        loose.Add(new Change(item(was, old), item(now, d)) { code = old.tokens != d.tokens || refs(old.doc) != refs(d.doc), doc = old.doc != d.doc });

                foreach( var d in was.decls.Values )
                    if( !owned_was.Contains(d.key) && !now.decls.ContainsKey(d.key) )
                        loose.Add(new Change(item(was, d), null));

                // a member of a declaration that came or went whole says nothing its declaration has not said
                var whole = loose.Where(c => c.was == null || c.now == null).Select(c => c.item.decl!).ToHashSet();
                loose.RemoveAll(c =>
                                {
                                    var dot = c.item.decl!.LastIndexOf('.');
                                    return 0 < dot && whole.Contains(c.item.decl[..dot]);
                                });
            }
        }
