using System;
using System.Diagnostics;
using System.Text;
using System.Threading;
using org.unirail.Agent;
using static org.unirail.AdHocAgent;
using Progress = org.unirail.Agent.AdHocProtocol.Server_.Progress;

namespace org.unirail{
    /// <summary>
    /// What the Server says it is doing with the task - `Server.Progress` - on the console.
    ///
    /// A terminal gets a block redrawn in place: a line of the task - its testing level, the time it takes, how far it
    /// is - and a line per language: the pass that runs, what is being done, how far the language is.
    ///
    ///     AdHocProtocol · testing level: full · 00:41 · 29%
    ///       Java   pass 2 of 4   running tests     ███████░░░░░░░░░  43%
    ///       C#     pass 2 of 4   compiling         █████░░░░░░░░░░░  31%
    ///       TS     pass 1 of 4   compiling         ██░░░░░░░░░░░░░░  12%
    ///
    /// A redirected output - the log of a CI run - gets plain lines instead, and only what stays true: the task is
    /// taken, a pass of a language is done, the result is on its way.
    ///
    /// The pack carries numbers; the texts are the constants of the pack in the protocol description. A number this
    /// agent has no text for - a newer Server - is shown as a number.
    ///
    /// The deployment is shown here too: a line of the stage that runs, redrawn in place, and a line left by each stage done.
    ///
    ///       ✔ run the custom steps   1605   02:11
    ///     AdHocProtocol · 02:33 · step 3 of 6 · merge your code  ███████░░░░░░░░░  43%  690 of 1605 · Tasks.cs
    ///
    /// Anything the log prints takes the place of the line, and the next step draws it again under what was printed.
    /// A redirected output gets a plain line per stage.
    /// </summary>
    public static class TaskProgress{
        const int Accepted = 0, Done = 4, Delivering = 5; //indexes in Progress.TEXT
        const int BAR      = 16;

        //The brand colours of the languages, by the number of the language: the order of Progress.LANG. A bar has its language's colour until it reaches 100%, then green.
        static readonly string[] BRAND = {
            "38;2;0;89;156",    //C++
            "38;2;206;66;43",   //Rust
            "38;2;81;43;212",   //C#
            "38;2;237;139;0",   //Java
            "38;2;0;173;216",   //Go
            "38;2;49;120;198",  //TS
            "38;2;240;81;56",   //Swift
            "38;2;168;185;204", //C
            "38;2;1;117;194",   //Dart
            "38;2;55;118;171"   //Python
        };

        struct Line{
            public byte what, pass, passes, percent;
        }

        static readonly Line[] lines = new Line[Progress.lang__.MAX + 1]; //by the number of the language
        static readonly byte[] order = new byte[Progress.lang__.MAX + 1]; //the languages in the order they were first spoken of
        static          int    langs;

        static string project = "";
        static int    level   = -1; //not told yet
        static bool   delivering;

        static readonly Stopwatch     time = new();
        static readonly StringBuilder sb   = new();
        static readonly object        gate = new(); //the receiving thread and the clock
        static          Timer?        clock;
        static          int           drawn; //the lines of the block on the screen

        /// <summary>A terminal: the block is redrawn in place. Otherwise plain lines.</summary>
        internal static bool live = !Console.IsOutputRedirected;

        /// <summary>The task has gone to the Server.</summary>
        public static void begin(string name){
            lock( gate ){
                project    = name;
                level      = -1;
                delivering = false;
                langs      = 0;
                drawn      = 0;
                time.Restart();
            }
        }

        public static void show(Progress p){
            lock( gate ){
                if( !time.IsRunning ) time.Start();
                switch( p.what ){
                    case Accepted:
                        level = p.level;
                        if( !live ) LOG.Information("The task is accepted. Testing level: {level:l}", text(Progress.LEVEL, level));
                        break;
                    case Delivering:
                        delivering = true;
                        if( !live ) LOG.Information("Delivering the result");
                        break;
                    default:
                        var i = 0;
                        while( i < langs && order[i] != p.lang ) i++;
                        if( i == langs ) order[langs++] = p.lang;
                        ref var l = ref lines[p.lang];
                        l.what    = p.what;
                        l.pass    = p.pass;
                        l.passes  = p.passes;
                        l.percent = p.percent;
                        if( !live && p.what == Done ) LOG.Information("{lang:l}: pass {pass} of {passes} is done", text(Progress.LANG, p.lang), p.pass, p.passes);
                        break;
                }

                if( !live ) return;
                draw();
                clock ??= new Timer(static _ => {
                                        lock( gate )
                                            if( 0 < drawn ) draw();
                                    }, null, 1000, 1000);
            }
        }

        /// <summary>The Server's answer is here, or the connection is gone: the block stays as it is, what is printed next goes below it.</summary>
        public static void end(){
            lock( gate ){
                hide();
                stage_what = null;
                clock?.Dispose();
                clock = null;
                time.Stop();
                drawn = 0;
            }
        }

        static string? stage_what; //the stage of the deployment that runs; null - none
        static string  stage_item = "";
        static int     stage_no, stages, stage_done, stage_total;
        static long    stage_drawn_at;

        static readonly Stopwatch stage_time = new();

        /// <summary>The deployment starts: `count` stages are ahead.</summary>
        public static void deploying(string name, int count){
            lock( gate ){
                project    = name;
                level      = -1;
                delivering = false;
                langs      = 0;
                drawn      = 0;
                stage_what = null;
                stage_no   = 0;
                stages     = count;
                time.Restart();
            }
        }

        /// <summary>The next stage of the deployment, of `total` steps. The one before it is done.</summary>
        public static void stage(string what, int total){
            lock( gate ){
                stage_end();
                stage_what  = what;
                stage_item  = "";
                stage_done  = 0;
                stage_total = total;
                stage_no++;
                stage_time.Restart();

                if( !live ){
                    LOG.Information("Step {no} of {count}: {what:l}", stage_no, stages, what);
                    return;
                }

                draw();
                clock ??= new Timer(static _ => {
                                        lock( gate )
                                            if( 0 < drawn ) draw();
                                    }, null, 1000, 1000);
            }
        }

        /// <summary>The next step of the stage starts, on `item`. A terminal is redrawn ten times a second at most: a step can take less than a console write.</summary>
        public static void step(string item){
            lock( gate ){
                if( stage_what == null ) return;
                stage_item = item;
                stage_done++;
                if( !live || 0 < drawn && Environment.TickCount64 - stage_drawn_at < 100 ) return;
                draw();
            }
        }

        /// <summary>The stage that runs is done: its line stays on the screen.</summary>
        public static void stage_end(){
            lock( gate ){
                if( stage_what == null ) return;
                hide();
                stage_time.Stop();
                if( live ){
                    var s = (int)stage_time.Elapsed.TotalSeconds;
                    Console.Out.WriteLine(ansi("  ✔ ", "32") + stage_what + "   " + stage_total + "   " + s / 60 / 10 + s / 60 % 10 + ':' + s % 60 / 10 + s % 60 % 10);
                }
                stage_what = null;
            }
        }

        /// <summary>Something is about to be printed: the line of the stage gives up its place on the screen. The next step draws it again.</summary>
        public static void hide(){
            lock( gate ){
                if( stage_what == null || drawn == 0 ) return;
                Console.Out.Write("\u001b[1A\r\u001b[2K");
                Console.Out.Flush();
                drawn = 0;
            }
        }

        //Under the gate.
        static void draw_stage(int width){
            sb.Clear();
            if( 0 < drawn ) sb.Append("\u001b[").Append(drawn).Append('A');

            var at = sb.Length;
            var s  = (int)time.Elapsed.TotalSeconds;
            sb.Append(ansi(project, "1")).Append(" · ").Append(s / 60 / 10).Append(s / 60 % 10).Append(':').Append(s % 60 / 10).Append(s % 60 % 10);
            sb.Append(" · step ").Append(stage_no).Append(" of ").Append(stages).Append(" · ").Append(stage_what).Append("  ");

            var percent = stage_total == 0 ? 0 : Math.Min(stage_done * 100 / stage_total, 100);
            var full    = percent * BAR / 100;
            sb.Append(ansi(new string('█', full), "32")).Append(ansi(new string('░', BAR - full), "2")).Append(' ');
            if( percent < 100 ) sb.Append(' ');
            if( percent < 10 ) sb.Append(' ');
            sb.Append(percent).Append("%  ").Append(stage_done).Append(" of ").Append(stage_total);
            if( 0 < stage_item.Length ) sb.Append(" · ").Append(stage_item);
            line(at, width);

            drawn          = 1;
            stage_drawn_at = Environment.TickCount64;
            Console.Out.Write(sb);
            Console.Out.Flush();
        }

        static string text(string[] of, int i) => i < of.Length ? of[i] : i.ToString();

        //Under the gate. The cursor is on the line after the block: it goes back up by the lines drawn and every line is written over.
        static void draw(){
            var width = 0;
            try{ width = Console.WindowWidth - 1; } catch( Exception ){ } //no window: nothing to fit into

            if( stage_what != null ){
                draw_stage(width);
                return;
            }

            sb.Clear();
            if( 0 < drawn ) sb.Append("\u001b[").Append(drawn).Append('A');

            var sum = 0;
            for( var i = 0; i < langs; i++ ) sum += lines[order[i]].percent;

            var at = sb.Length;
            sb.Append(ansi(project, "1"));
            if( -1 < level ) sb.Append(" · testing level: ").Append(text(Progress.LEVEL, level));
            var s = (int)time.Elapsed.TotalSeconds;
            sb.Append(" · ").Append(s / 60 / 10).Append(s / 60 % 10).Append(':').Append(s % 60 / 10).Append(s % 60 % 10);
            if( 0 < langs ) sb.Append(" · ").Append(sum / langs).Append('%');
            if( delivering ) sb.Append(" · ").Append(text(Progress.TEXT, Delivering));
            line(at, width);

            for( var i = 0; i < langs; i++ ){
                ref var l = ref lines[order[i]];
                at = sb.Length;
                sb.Append("  ").Append(text(Progress.LANG, order[i]).PadRight(6));
                sb.Append(" pass ").Append(l.pass).Append(" of ").Append(l.passes).Append("   ");
                sb.Append(text(Progress.TEXT, l.what).PadRight(17)).Append(' ');
                var full = l.percent * BAR / 100;
                sb.Append(ansi(new string('█', full), l.percent < 100 && order[i] < BRAND.Length ? BRAND[order[i]] : "32")).Append(ansi(new string('░', BAR - full), "2"));
                sb.Append(' ');
                if( l.percent < 100 ) sb.Append(' ');
                if( l.percent < 10 ) sb.Append(' ');
                sb.Append(l.percent).Append('%');
                line(at, width);
            }

            drawn = langs + 1;
            Console.Out.Write(sb);
            Console.Out.Flush();
        }

        static readonly System.Text.RegularExpressions.Regex sgr = new(@"\u001b\[[0-9;]*m");

        //Ends the line that starts at `at`: no longer than the window is wide - a wrapped line would take two, and the way back up would be short.
        //The colours take no room on the screen; a line too wide loses them and is cut as plain text.
        static void line(int at, int width){
            var text = sb.ToString(at, sb.Length - at);
            var plain = sgr.Replace(text, "");
            if( 0 < width && width < plain.Length ){
                sb.Length = at;
                sb.Append(plain, 0, width);
            }
            sb.Insert(at, "\r\u001b[2K").Append('\n');
        }
    }
}
